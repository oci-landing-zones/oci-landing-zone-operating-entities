-- One COPY_DATA operation and one row-resolution cycle per failed file.
-- Run for one FOCUS load pipeline at a time; the staging table is shared.
SET DEFINE OFF
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

CREATE OR REPLACE FUNCTION OCI_FOCUS_REMED_NUMBER(P_VALUE VARCHAR2)
  RETURN NUMBER DETERMINISTIC AUTHID DEFINER IS
BEGIN
  IF TRIM(P_VALUE) IS NULL THEN RETURN NULL; END IF;
  RETURN TO_NUMBER(TRIM(P_VALUE), NULL, 'NLS_NUMERIC_CHARACTERS=''.,''');
END;
/

CREATE OR REPLACE FUNCTION OCI_FOCUS_REMED_TIMESTAMP(P_VALUE VARCHAR2)
  RETURN TIMESTAMP DETERMINISTIC AUTHID DEFINER IS
  L_VALUE VARCHAR2(32767) := TRIM(P_VALUE);
  L_NORMAL VARCHAR2(32767);
  L_RESULT TIMESTAMP;
BEGIN
  IF L_VALUE IS NULL THEN RETURN NULL; END IF;
  L_NORMAL := REPLACE(REPLACE(L_VALUE, 'T', ' '), 'Z', ' UTC');
  IF REGEXP_LIKE(L_VALUE, '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}Z$') THEN
    SELECT SYS_EXTRACT_UTC(TO_TIMESTAMP_TZ(
      L_NORMAL, 'YYYY-MM-DD HH24:MI TZR'))
      INTO L_RESULT FROM DUAL;
  ELSIF REGEXP_LIKE(L_VALUE,
    '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z$') THEN
    SELECT SYS_EXTRACT_UTC(TO_TIMESTAMP_TZ(
      L_NORMAL, 'YYYY-MM-DD HH24:MI:SS TZR'))
      INTO L_RESULT FROM DUAL;
  ELSIF REGEXP_LIKE(L_VALUE,
    '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}\.[0-9]+Z$') THEN
    SELECT SYS_EXTRACT_UTC(TO_TIMESTAMP_TZ(
      L_NORMAL, 'YYYY-MM-DD HH24:MI:SS.FF9 TZR'))
      INTO L_RESULT FROM DUAL;
  ELSE
    RAISE_APPLICATION_ERROR(-20810,
      'Unsupported FOCUS timestamp: ' || SUBSTR(L_VALUE, 1, 150));
  END IF;
  RETURN L_RESULT;
END;
/

-- Remediate queued files for an approved OCI landing target. Optional exact
-- source-name selection permits a controlled single-file diagnostic.
SET DEFINE OFF
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

CREATE OR REPLACE PROCEDURE OCI_FOCUS_REMEDIATE_FILES(
  P_PIPELINE_NAME IN VARCHAR2,
  P_MAX_FILES IN PLS_INTEGER DEFAULT 1,
  P_SOURCE_NAME IN VARCHAR2 DEFAULT NULL
) AUTHID CURRENT_USER IS
  L_PIPELINE VARCHAR2(128) := UPPER(TRIM(P_PIPELINE_NAME));
  L_GENERATION NUMBER;
  L_STATUS_TABLE VARCHAR2(128);
  L_PIPELINE_STATUS VARCHAR2(30);
  L_TARGET VARCHAR2(128);
  L_CREDENTIAL VARCHAR2(256);
  L_LOCATION CLOB;
  L_URI_PREFIX VARCHAR2(4000);
  L_FORMAT CLOB;
  L_FIELD_LIST CLOB := TO_CLOB('');
  L_COPY_OPERATION_ID NUMBER;
  L_COPY_SESSION_SID NUMBER;
  L_COPY_SESSION_SERIAL NUMBER;
  L_COPY_STATUS VARCHAR2(30);
  L_COPY_ROWS NUMBER;
  L_STAGE_COUNT NUMBER;
  L_STATUS_COUNT NUMBER;
  L_INSERTED NUMBER;
  L_MANUAL NUMBER;
  L_ERROR_CODE NUMBER;
  L_ERROR_MESSAGE VARCHAR2(4000);
  L_RUN_ID NUMBER;
  L_HANDLED NUMBER := 0;
  L_FILE_STATE VARCHAR2(20);
BEGIN
  OCI_FOCUS_REMED_MUTEX.ENTER;
  IF L_PIPELINE IS NULL OR LENGTH(L_PIPELINE) > 128 OR
     NOT REGEXP_LIKE(L_PIPELINE, '^[A-Z][A-Z0-9_$#]*$') THEN
    RAISE_APPLICATION_ERROR(-20820, 'Invalid FOCUS pipeline name');
  END IF;
  IF P_MAX_FILES IS NULL OR P_MAX_FILES NOT BETWEEN 1 AND 2000 THEN
    RAISE_APPLICATION_ERROR(-20811, 'P_MAX_FILES must be between 1 and 2000');
  END IF;
  IF P_SOURCE_NAME IS NOT NULL AND LENGTH(P_SOURCE_NAME) > 4000 THEN
    RAISE_APPLICATION_ERROR(-20835, 'Source name is too long');
  END IF;

  SELECT STATUS, STATUS_TABLE
    INTO L_PIPELINE_STATUS, L_STATUS_TABLE
    FROM USER_CLOUD_PIPELINES
   WHERE PIPELINE_NAME = L_PIPELINE AND PIPELINE_TYPE = 'LOAD';
  L_STATUS_TABLE := DBMS_ASSERT.SIMPLE_SQL_NAME(L_STATUS_TABLE);

  SELECT DBMS_ASSERT.SIMPLE_SQL_NAME(
           DBMS_LOB.SUBSTR(ATTRIBUTE_VALUE, 128, 1))
    INTO L_TARGET
    FROM USER_CLOUD_PIPELINE_ATTRIBUTES
   WHERE PIPELINE_NAME = L_PIPELINE AND ATTRIBUTE_NAME = 'table_name';
  SELECT COUNT(*) INTO L_STAGE_COUNT
    FROM OCI_FOCUS_REMED_TARGET_CONFIG
   WHERE TARGET_TABLE = L_TARGET AND ENABLED = 'Y';
  IF L_STAGE_COUNT <> 1 THEN
    RAISE_APPLICATION_ERROR(-20821, 'Landing target is not approved for remediation');
  END IF;
  SELECT COUNT(*) INTO L_STAGE_COUNT
    FROM USER_TAB_COLUMNS T
   WHERE T.TABLE_NAME = L_TARGET
     AND EXISTS (
       SELECT 1 FROM USER_TAB_COLUMNS S
        WHERE S.TABLE_NAME = 'OCI_FOCUS_REMED_STAGE'
          AND S.COLUMN_NAME = T.COLUMN_NAME);
  IF L_STAGE_COUNT <> 49 THEN
    RAISE_APPLICATION_ERROR(-20822, 'Target must contain all 49 FOCUS columns');
  END IF;

  SELECT GENERATION_NO INTO L_GENERATION
    FROM OCI_FOCUS_FAIL_SCAN_CURSOR
   WHERE PIPELINE_NAME = L_PIPELINE
     AND STATUS_TABLE = L_STATUS_TABLE;

  SELECT DBMS_LOB.SUBSTR(ATTRIBUTE_VALUE, 256, 1)
    INTO L_CREDENTIAL
    FROM USER_CLOUD_PIPELINE_ATTRIBUTES
   WHERE PIPELINE_NAME = L_PIPELINE AND ATTRIBUTE_NAME = 'credential_name';
  SELECT ATTRIBUTE_VALUE INTO L_FORMAT
    FROM USER_CLOUD_PIPELINE_ATTRIBUTES
   WHERE PIPELINE_NAME = L_PIPELINE AND ATTRIBUTE_NAME = 'format';
  SELECT ATTRIBUTE_VALUE INTO L_LOCATION
    FROM USER_CLOUD_PIPELINE_ATTRIBUTES
   WHERE PIPELINE_NAME = L_PIPELINE AND ATTRIBUTE_NAME = 'location';
  L_URI_PREFIX := OCI_FOCUS_SOURCE_PREFIX(L_LOCATION);
  -- COPY_DATA receives a single concrete URI. The pipeline's regexuri=true
  -- selects a range of files; it must not reinterpret this concrete URI.
  SELECT JSON_MERGEPATCH(L_FORMAT, '{"regexuri":false}' RETURNING CLOB)
    INTO L_FORMAT FROM DUAL;

  -- All source fields remain text in staging; conversion happens per row.
  FOR C IN (
    SELECT COLUMN_NAME
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = L_TARGET
     ORDER BY COLUMN_ID
  ) LOOP
    IF L_FIELD_LIST IS NOT NULL AND DBMS_LOB.GETLENGTH(L_FIELD_LIST) > 0 THEN
      L_FIELD_LIST := L_FIELD_LIST || ',';
    END IF;
    L_FIELD_LIST := L_FIELD_LIST || '"' || C.COLUMN_NAME || '" CHAR(' ||
      CASE WHEN C.COLUMN_NAME = 'TAGS' THEN '200000000' ELSE '32767' END || ')';
  END LOOP;

  SELECT COUNT(ROWID) INTO L_STAGE_COUNT FROM OCI_FOCUS_REMED_STAGE;
  IF L_STAGE_COUNT <> 0 THEN
    RAISE_APPLICATION_ERROR(-20813,
      'Staging contains rows from an interrupted file; inspect before restarting');
  END IF;
  SELECT COUNT(*) INTO L_STAGE_COUNT FROM OCI_FOCUS_REMED_FILE
   WHERE STATE IN ('COPYING', 'STAGED', 'PROCESSING');
  IF L_STAGE_COUNT <> 0 THEN
    RAISE_APPLICATION_ERROR(-20814,
      'An interrupted or active file needs reconciliation');
  END IF;

  OCI_FOCUS_FILL_SOURCE_URIS(L_PIPELINE);

  INSERT INTO OCI_FOCUS_REMED_RUN (PIPELINE_NAME)
  VALUES (L_PIPELINE) RETURNING RUN_ID INTO L_RUN_ID;
  COMMIT;

  FOR F IN (
    SELECT Q.GENERATION_NO, Q.SOURCE_NAME_HASH,
           Q.SOURCE_NAME, Q.SOURCE_URI
      FROM OCI_FOCUS_FAIL_FILE Q
     WHERE Q.PIPELINE_NAME = L_PIPELINE
       AND Q.GENERATION_NO = L_GENERATION
       AND Q.FILE_STATE = 'NEW'
       AND (P_SOURCE_NAME IS NULL OR Q.SOURCE_NAME = P_SOURCE_NAME)
       AND NOT EXISTS (
         SELECT 1 FROM OCI_FOCUS_REMED_FILE R
          WHERE R.PIPELINE_NAME = Q.PIPELINE_NAME
            AND R.GENERATION_NO = Q.GENERATION_NO
            AND R.SOURCE_NAME_HASH = Q.SOURCE_NAME_HASH)
     ORDER BY Q.FIRST_SEEN_AT, Q.SOURCE_NAME
  ) LOOP
    EXIT WHEN L_HANDLED >= P_MAX_FILES;
    L_HANDLED := L_HANDLED + 1;

    IF SUBSTR(F.SOURCE_NAME, -7) <> '.csv.gz' OR
       INSTR(F.SOURCE_NAME, '..') > 0 OR
       INSTR(F.SOURCE_NAME, '/') = 0 OR
       SUBSTR(F.SOURCE_NAME, 1, 1) = '/' OR
       INSTR(F.SOURCE_NAME, '*') > 0 OR
       INSTR(F.SOURCE_NAME, '?') > 0 OR
       INSTR(F.SOURCE_NAME, ',') > 0 THEN
      RAISE_APPLICATION_ERROR(-20815, 'Unexpected relative source name');
    END IF;
    IF F.SOURCE_URI IS NULL OR
       SUBSTR(F.SOURCE_URI, 1, LENGTH(L_URI_PREFIX)) <> L_URI_PREFIX THEN
      RAISE_APPLICATION_ERROR(-20826, 'Stored source URI is missing or outside location');
    END IF;
    -- Oracle's generated status table is read only. Our ledgers own the
    -- remediation outcome even when Oracle's file status remains FAILED.
    EXECUTE IMMEDIATE
      'SELECT COUNT(*) FROM ' || L_STATUS_TABLE ||
      ' WHERE NAME = :n AND STATUS = ''FAILED'''
      INTO L_STATUS_COUNT USING F.SOURCE_NAME;
    IF L_STATUS_COUNT <> 1 THEN
      RAISE_APPLICATION_ERROR(-20816,
        'Source is no longer uniquely FAILED in the current status table');
    END IF;

    -- Persist the caller session before COPY_DATA. An interrupted COPY may
    -- never return its operation ID to PL/SQL; recovery must still be able
    -- to prove that this session has ended before retrying the source.
    SELECT SID, SERIAL# INTO L_COPY_SESSION_SID, L_COPY_SESSION_SERIAL
      FROM V$SESSION
     WHERE SID = TO_NUMBER(SYS_CONTEXT('USERENV', 'SID'));
    INSERT INTO OCI_FOCUS_REMED_FILE
      (PIPELINE_NAME, GENERATION_NO, SOURCE_NAME_HASH, STATE,
       COPY_SESSION_SID, COPY_SESSION_SERIAL)
    VALUES (L_PIPELINE, F.GENERATION_NO, F.SOURCE_NAME_HASH, 'COPYING',
            L_COPY_SESSION_SID, L_COPY_SESSION_SERIAL);
    UPDATE OCI_FOCUS_FAIL_FILE SET FILE_STATE = 'IN_PROGRESS'
     WHERE PIPELINE_NAME = L_PIPELINE
       AND GENERATION_NO = F.GENERATION_NO
       AND SOURCE_NAME_HASH = F.SOURCE_NAME_HASH;
    COMMIT;

    BEGIN
      DBMS_CLOUD.COPY_DATA(
        TABLE_NAME      => 'OCI_FOCUS_REMED_STAGE',
        CREDENTIAL_NAME => L_CREDENTIAL,
        FILE_URI_LIST   => F.SOURCE_URI,
        FORMAT          => L_FORMAT,
        FIELD_LIST      => L_FIELD_LIST,
        OPERATION_ID    => L_COPY_OPERATION_ID
      );
      SELECT COUNT(ROWID) INTO L_STAGE_COUNT FROM OCI_FOCUS_REMED_STAGE;
      IF L_STAGE_COUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20817, 'COPY_DATA loaded no data rows');
      END IF;
      SELECT STATUS, ROWS_LOADED INTO L_COPY_STATUS, L_COPY_ROWS
        FROM USER_LOAD_OPERATIONS WHERE ID = L_COPY_OPERATION_ID;
      IF NVL(L_COPY_STATUS, '?') <> 'COMPLETED' OR
         NVL(L_COPY_ROWS, -1) <> L_STAGE_COUNT THEN
        RAISE_APPLICATION_ERROR(-20823,
          'COPY_DATA operation status or row count does not match staging');
      END IF;
      UPDATE OCI_FOCUS_REMED_FILE
         SET STATE = 'STAGED', STAGED_ROWS = L_STAGE_COUNT,
             COPY_OPERATION_ID = L_COPY_OPERATION_ID
       WHERE PIPELINE_NAME = L_PIPELINE
         AND GENERATION_NO = F.GENERATION_NO
         AND SOURCE_NAME_HASH = F.SOURCE_NAME_HASH;
      COMMIT;
    EXCEPTION WHEN OTHERS THEN
      L_ERROR_MESSAGE := SUBSTR(SQLERRM, 1, 4000);
      DELETE FROM OCI_FOCUS_REMED_STAGE;
      UPDATE OCI_FOCUS_REMED_FILE
         SET STATE = 'ERROR', ERROR_MESSAGE = L_ERROR_MESSAGE,
             COPY_OPERATION_ID = L_COPY_OPERATION_ID,
             FINISHED_AT = SYSTIMESTAMP
       WHERE PIPELINE_NAME = L_PIPELINE
         AND GENERATION_NO = F.GENERATION_NO
         AND SOURCE_NAME_HASH = F.SOURCE_NAME_HASH;
      UPDATE OCI_FOCUS_FAIL_FILE SET FILE_STATE = 'ERROR'
       WHERE PIPELINE_NAME = L_PIPELINE
         AND GENERATION_NO = F.GENERATION_NO
         AND SOURCE_NAME_HASH = F.SOURCE_NAME_HASH;
      UPDATE OCI_FOCUS_REMED_RUN SET FILES_ERROR = FILES_ERROR + 1
       WHERE RUN_ID = L_RUN_ID;
      COMMIT;
      DBMS_OUTPUT.PUT_LINE('COPY_DATA failed: ' || L_ERROR_MESSAGE);
      CONTINUE;
    END;

    UPDATE OCI_FOCUS_REMED_FILE SET STATE = 'PROCESSING'
     WHERE PIPELINE_NAME = L_PIPELINE
       AND GENERATION_NO = F.GENERATION_NO
       AND SOURCE_NAME_HASH = F.SOURCE_NAME_HASH;
    COMMIT;

    FOR S IN (SELECT ROWIDTOCHAR(ROWID) AS STAGE_ROWID
                FROM OCI_FOCUS_REMED_STAGE ORDER BY ROWID) LOOP
      SAVEPOINT REMED_ROW;
      BEGIN
        EXECUTE IMMEDIATE 'INSERT INTO ' || L_TARGET || q'~ (
          AVAILABILITYZONE,BILLEDCOST,BILLINGACCOUNTID,BILLINGACCOUNTNAME,
          BILLINGCURRENCY,BILLINGPERIODEND,BILLINGPERIODSTART,CHARGECATEGORY,
          CHARGEDESCRIPTION,CHARGEFREQUENCY,CHARGEPERIODEND,CHARGEPERIODSTART,
          CHARGESUBCATEGORY,COMMITMENTDISCOUNTCATEGORY,COMMITMENTDISCOUNTID,
          COMMITMENTDISCOUNTNAME,COMMITMENTDISCOUNTTYPE,EFFECTIVECOST,
          INVOICEISSUER,LISTCOST,LISTUNITPRICE,PRICINGCATEGORY,
          PRICINGQUANTITY,PRICINGUNIT,PROVIDER,PUBLISHER,REGION,RESOURCEID,
          RESOURCENAME,RESOURCETYPE,SERVICECATEGORY,SERVICENAME,SKUID,
          SKUPRICEID,SUBACCOUNTID,SUBACCOUNTNAME,TAGS,USAGEQUANTITY,
          USAGEUNIT,OCI_REFERENCENUMBER,OCI_COMPARTMENTID,OCI_COMPARTMENTNAME,
          OCI_OVERAGEFLAG,OCI_UNITPRICEOVERAGE,OCI_BILLEDQUANTITYOVERAGE,
          OCI_COSTOVERAGE,OCI_ATTRIBUTEDUSAGE,OCI_ATTRIBUTEDCOST,
          OCI_BACKREFERENCENUMBER
        )
        SELECT
          TRIM(AVAILABILITYZONE),OCI_FOCUS_REMED_NUMBER(BILLEDCOST),
          TRIM(BILLINGACCOUNTID),TRIM(BILLINGACCOUNTNAME),TRIM(BILLINGCURRENCY),
          OCI_FOCUS_REMED_TIMESTAMP(BILLINGPERIODEND),
          OCI_FOCUS_REMED_TIMESTAMP(BILLINGPERIODSTART),
          TRIM(CHARGECATEGORY),TRIM(CHARGEDESCRIPTION),TRIM(CHARGEFREQUENCY),
          OCI_FOCUS_REMED_TIMESTAMP(CHARGEPERIODEND),
          OCI_FOCUS_REMED_TIMESTAMP(CHARGEPERIODSTART),
          TRIM(CHARGESUBCATEGORY),TRIM(COMMITMENTDISCOUNTCATEGORY),
          TRIM(COMMITMENTDISCOUNTID),TRIM(COMMITMENTDISCOUNTNAME),
          TRIM(COMMITMENTDISCOUNTTYPE),OCI_FOCUS_REMED_NUMBER(EFFECTIVECOST),
          TRIM(INVOICEISSUER),OCI_FOCUS_REMED_NUMBER(LISTCOST),
          OCI_FOCUS_REMED_NUMBER(LISTUNITPRICE),TRIM(PRICINGCATEGORY),
          OCI_FOCUS_REMED_NUMBER(PRICINGQUANTITY),TRIM(PRICINGUNIT),
          TRIM(PROVIDER),TRIM(PUBLISHER),TRIM(REGION),TRIM(RESOURCEID),
          TRIM(RESOURCENAME),TRIM(RESOURCETYPE),TRIM(SERVICECATEGORY),
          TRIM(SERVICENAME),TRIM(SKUID),TRIM(SKUPRICEID),TRIM(SUBACCOUNTID),
          TRIM(SUBACCOUNTNAME),JSON(TAGS),
          OCI_FOCUS_REMED_NUMBER(USAGEQUANTITY),TRIM(USAGEUNIT),
          TRIM(OCI_REFERENCENUMBER),TRIM(OCI_COMPARTMENTID),
          TRIM(OCI_COMPARTMENTNAME),TRIM(OCI_OVERAGEFLAG),
          OCI_FOCUS_REMED_NUMBER(OCI_UNITPRICEOVERAGE),
          OCI_FOCUS_REMED_NUMBER(OCI_BILLEDQUANTITYOVERAGE),
          OCI_FOCUS_REMED_NUMBER(OCI_COSTOVERAGE),
          OCI_FOCUS_REMED_NUMBER(OCI_ATTRIBUTEDUSAGE),
          OCI_FOCUS_REMED_NUMBER(OCI_ATTRIBUTEDCOST),
          TRIM(OCI_BACKREFERENCENUMBER)
        FROM OCI_FOCUS_REMED_STAGE WHERE ROWID = CHARTOROWID(:stage_rowid)~'
        USING S.STAGE_ROWID;
        IF SQL%ROWCOUNT <> 1 THEN
          RAISE_APPLICATION_ERROR(-20827, 'Expected one landing insert');
        END IF;
      EXCEPTION WHEN OTHERS THEN
        L_ERROR_CODE := SQLCODE;
        L_ERROR_MESSAGE := SUBSTR(SQLERRM, 1, 4000);
        ROLLBACK TO REMED_ROW;
        INSERT INTO OCI_FOCUS_REMED_MANUAL
          (PIPELINE_NAME, GENERATION_NO, SOURCE_NAME_HASH, STAGE_ROWID,
           ERROR_CODE, ERROR_MESSAGE, RAW_ROW_JSON)
        SELECT L_PIPELINE, F.GENERATION_NO, F.SOURCE_NAME_HASH,
               S.STAGE_ROWID,
               L_ERROR_CODE, L_ERROR_MESSAGE, JSON_OBJECT(* RETURNING CLOB)
          FROM OCI_FOCUS_REMED_STAGE
         WHERE ROWID = CHARTOROWID(S.STAGE_ROWID);
        IF SQL%ROWCOUNT <> 1 THEN
          RAISE_APPLICATION_ERROR(-20829, 'Expected one manual-review row');
        END IF;
        DELETE FROM OCI_FOCUS_REMED_STAGE
         WHERE ROWID = CHARTOROWID(S.STAGE_ROWID);
        IF SQL%ROWCOUNT <> 1 THEN
          RAISE_APPLICATION_ERROR(-20834, 'Expected one staged row removal');
        END IF;
        UPDATE OCI_FOCUS_REMED_FILE SET MANUAL_ROWS = MANUAL_ROWS + 1
         WHERE PIPELINE_NAME = L_PIPELINE
           AND GENERATION_NO = F.GENERATION_NO
           AND SOURCE_NAME_HASH = F.SOURCE_NAME_HASH;
        IF SQL%ROWCOUNT <> 1 THEN
          RAISE_APPLICATION_ERROR(-20836, 'Expected one manual file counter update');
        END IF;
        COMMIT;
        CONTINUE;
      END;
      -- Only a landing INSERT failure belongs in manual review. If stage
      -- deletion or ledger accounting fails, the outer exception rolls this
      -- uncommitted landing INSERT back and leaves the stage row for recovery.
      DELETE FROM OCI_FOCUS_REMED_STAGE
       WHERE ROWID = CHARTOROWID(S.STAGE_ROWID);
      IF SQL%ROWCOUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20828, 'Expected one staged row removal');
      END IF;
      UPDATE OCI_FOCUS_REMED_FILE SET INSERTED_ROWS = INSERTED_ROWS + 1
       WHERE PIPELINE_NAME = L_PIPELINE
         AND GENERATION_NO = F.GENERATION_NO
         AND SOURCE_NAME_HASH = F.SOURCE_NAME_HASH;
      IF SQL%ROWCOUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20837, 'Expected one inserted file counter update');
      END IF;
      COMMIT;
    END LOOP;

    SELECT INSERTED_ROWS, MANUAL_ROWS INTO L_INSERTED, L_MANUAL
      FROM OCI_FOCUS_REMED_FILE
     WHERE PIPELINE_NAME = L_PIPELINE
       AND GENERATION_NO = F.GENERATION_NO
       AND SOURCE_NAME_HASH = F.SOURCE_NAME_HASH;
    SELECT COUNT(ROWID) INTO L_STAGE_COUNT FROM OCI_FOCUS_REMED_STAGE;
    IF L_STAGE_COUNT <> 0 OR L_INSERTED + L_MANUAL = 0 THEN
      RAISE_APPLICATION_ERROR(-20818, 'Row accounting is incomplete');
    END IF;
    L_FILE_STATE := CASE WHEN L_MANUAL = 0 THEN 'FULL' ELSE 'PARTIAL' END;
    UPDATE OCI_FOCUS_REMED_FILE
       SET STATE = L_FILE_STATE, FINISHED_AT = SYSTIMESTAMP
     WHERE PIPELINE_NAME = L_PIPELINE
       AND GENERATION_NO = F.GENERATION_NO
       AND SOURCE_NAME_HASH = F.SOURCE_NAME_HASH
       AND STAGED_ROWS = L_INSERTED + L_MANUAL;
    IF SQL%ROWCOUNT <> 1 THEN
      RAISE_APPLICATION_ERROR(-20819, 'Staged row count differs from outcomes');
    END IF;
    UPDATE OCI_FOCUS_FAIL_FILE SET FILE_STATE = L_FILE_STATE
     WHERE PIPELINE_NAME = L_PIPELINE
       AND GENERATION_NO = F.GENERATION_NO
       AND SOURCE_NAME_HASH = F.SOURCE_NAME_HASH;
    IF SQL%ROWCOUNT <> 1 THEN
      RAISE_APPLICATION_ERROR(-20838, 'Expected one failed-file queue finalization');
    END IF;
    IF L_FILE_STATE = 'FULL' THEN
      UPDATE OCI_FOCUS_REMED_RUN SET FILES_FULL = FILES_FULL + 1
       WHERE RUN_ID = L_RUN_ID;
    ELSE
      UPDATE OCI_FOCUS_REMED_RUN SET FILES_PARTIAL = FILES_PARTIAL + 1
       WHERE RUN_ID = L_RUN_ID;
    END IF;
    IF SQL%ROWCOUNT <> 1 THEN
      RAISE_APPLICATION_ERROR(-20839, 'Expected one remediation run update');
    END IF;
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('file=' || F.SOURCE_NAME || ' result=' ||
      L_FILE_STATE || ' inserted=' || L_INSERTED || ' manual=' || L_MANUAL);
  END LOOP;

  UPDATE OCI_FOCUS_REMED_RUN SET FINISHED_AT = SYSTIMESTAMP
   WHERE RUN_ID = L_RUN_ID;
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('run_id=' || L_RUN_ID || ' files_handled=' || L_HANDLED);
  OCI_FOCUS_REMED_MUTEX.LEAVE;
EXCEPTION WHEN OTHERS THEN
  L_ERROR_MESSAGE := SUBSTR(SQLERRM, 1, 4000);
  ROLLBACK;
  IF L_RUN_ID IS NOT NULL THEN
    UPDATE OCI_FOCUS_REMED_RUN
       SET FINISHED_AT = SYSTIMESTAMP, ERROR_MESSAGE = L_ERROR_MESSAGE
     WHERE RUN_ID = L_RUN_ID;
    COMMIT;
  END IF;
  OCI_FOCUS_REMED_MUTEX.LEAVE;
  RAISE;
END;
