SELECT NAME, TYPE, LINE, POSITION, TEXT FROM USER_ERRORS
 WHERE NAME IN ('OCI_FOCUS_REMED_NUMBER','OCI_FOCUS_REMED_TIMESTAMP',
                'OCI_FOCUS_REMEDIATE_FILES')
 ORDER BY NAME, SEQUENCE;

DECLARE
  L_ERRORS NUMBER;
BEGIN
  SELECT COUNT(*) INTO L_ERRORS FROM USER_ERRORS
   WHERE NAME IN ('OCI_FOCUS_REMED_NUMBER','OCI_FOCUS_REMED_TIMESTAMP',
                  'OCI_FOCUS_REMEDIATE_FILES');
  IF L_ERRORS <> 0 THEN
    RAISE_APPLICATION_ERROR(-20841, 'Remediation objects have compile errors');
  END IF;
END;
