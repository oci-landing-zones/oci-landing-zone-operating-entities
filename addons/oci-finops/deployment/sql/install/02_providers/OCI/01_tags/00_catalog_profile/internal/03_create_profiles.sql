-- Immutable profile revisions and one current reporting selection.
SET DEFINE OFF SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE TABLE OCI_TAG_PROFILE (
  PROFILE_NAME VARCHAR2(128) NOT NULL,
  PROFILE_VERSION NUMBER(8) NOT NULL,
  TAG_NAMESPACE_ID VARCHAR2(255),
  PROFILE_KIND VARCHAR2(10) NOT NULL,
  SPEC_JSON CLOB NOT NULL CHECK (SPEC_JSON IS JSON),
  CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT OCI_TAG_PROFILE_PK PRIMARY KEY
    (PROFILE_NAME,PROFILE_VERSION),
  CONSTRAINT OCI_TAG_PROFILE_NS_FK FOREIGN KEY (TAG_NAMESPACE_ID)
    REFERENCES OCI_TAG_NAMESPACE(TAG_NAMESPACE_ID),
  CONSTRAINT OCI_TAG_PROFILE_KIND_CK CHECK
    (PROFILE_KIND IN ('DEFAULT','CUSTOM','MIXED')),
  CONSTRAINT OCI_TAG_PROFILE_VERSION_CK CHECK (PROFILE_VERSION > 0)
);

CREATE TABLE OCI_TAG_PROFILE_ITEM (
  PROFILE_NAME VARCHAR2(128) NOT NULL,
  PROFILE_VERSION NUMBER(8) NOT NULL,
  DISPLAY_ORDER NUMBER(4) NOT NULL,
  LOGICAL_TAG_NAME VARCHAR2(256) NOT NULL,
  IS_ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N')),
  TAG_NAMESPACE_ID VARCHAR2(255) NOT NULL,
  TAG_NAME VARCHAR2(100) NOT NULL,
  CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT OCI_TAG_PROFILE_ITEM_PK PRIMARY KEY
    (PROFILE_NAME,PROFILE_VERSION,TAG_NAMESPACE_ID,TAG_NAME),
  CONSTRAINT OCI_TAG_PROFILE_ITEM_ORDER_UQ UNIQUE
    (PROFILE_NAME,PROFILE_VERSION,DISPLAY_ORDER),
  CONSTRAINT OCI_TAG_PROFILE_ITEM_LOGICAL_UQ UNIQUE
    (PROFILE_NAME,PROFILE_VERSION,LOGICAL_TAG_NAME),
  CONSTRAINT OCI_TAG_PROFILE_ITEM_PROFILE_FK FOREIGN KEY
    (PROFILE_NAME,PROFILE_VERSION)
    REFERENCES OCI_TAG_PROFILE(PROFILE_NAME,PROFILE_VERSION),
  CONSTRAINT OCI_TAG_PROFILE_ITEM_DEF_FK FOREIGN KEY
    (TAG_NAMESPACE_ID,TAG_NAME)
    REFERENCES OCI_TAG_DEFINITION(TAG_NAMESPACE_ID,TAG_NAME)
);

CREATE TABLE OCI_TAG_PROFILE_SELECTION (
  SELECTION_ID NUMBER(1) DEFAULT 1 NOT NULL,
  PROFILE_NAME VARCHAR2(128) NOT NULL,
  PROFILE_VERSION NUMBER(8) NOT NULL,
  SELECTED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT OCI_TAG_PROFILE_SELECTION_PK PRIMARY KEY (SELECTION_ID),
  CONSTRAINT OCI_TAG_PROFILE_SELECTION_ONE_CK CHECK (SELECTION_ID=1),
  CONSTRAINT OCI_TAG_PROFILE_SELECTION_FK FOREIGN KEY
    (PROFILE_NAME,PROFILE_VERSION)
    REFERENCES OCI_TAG_PROFILE(PROFILE_NAME,PROFILE_VERSION)
);

CREATE OR REPLACE PACKAGE OCI_TAG_PROFILE_API AUTHID DEFINER AS
  PROCEDURE APPLY_SPEC(P_SPEC IN CLOB);
  PROCEDURE INSTALL_DEFAULT;
  PROCEDURE SWITCH_NAMESPACE(P_NAMESPACE_NAME IN VARCHAR2);
  PROCEDURE REFRESH_ACTIVE;
END OCI_TAG_PROFILE_API;
/
CREATE OR REPLACE PACKAGE BODY OCI_TAG_PROFILE_API AS
  PROCEDURE SELECT_PROFILE(P_NAME VARCHAR2,P_VERSION NUMBER) IS
  BEGIN
    MERGE INTO OCI_TAG_PROFILE_SELECTION S
    USING (SELECT P_NAME N,P_VERSION V FROM DUAL) X ON (S.SELECTION_ID=1)
    WHEN MATCHED THEN UPDATE SET S.PROFILE_NAME=X.N,S.PROFILE_VERSION=X.V,S.SELECTED_AT=SYSTIMESTAMP
    WHEN NOT MATCHED THEN INSERT(SELECTION_ID,PROFILE_NAME,PROFILE_VERSION) VALUES(1,X.N,X.V);
  END;

  PROCEDURE APPLY_SPEC(P_SPEC IN CLOB) IS
    D JSON_OBJECT_T; O JSON_OBJECT_T; A JSON_ARRAY_T; K JSON_KEY_LIST;
    L_NAME VARCHAR2(128); L_MODE VARCHAR2(20); L_NS VARCHAR2(100); L_NS_ID VARCHAR2(255);
    L_VERSION NUMBER; L_OLD NUMBER; L_MAX_SLOT NUMBER:=0; L_N NUMBER:=0; L_COUNT NUMBER;
    L_KIND VARCHAR2(10); L_ACTIVE CHAR(1); L_CHANGED BOOLEAN:=FALSE;
    L_PREV CLOB; L_PREV_DOC JSON_OBJECT_T; L_STORED_SPEC CLOB;
    L_LOCK NUMBER:=DBMS_UTILITY.GET_HASH_VALUE('OCI_TAG_PROFILE_APPLY:'||USER,0,1073741823);
    L_RC NUMBER; L_LOCKED BOOLEAN:=FALSE;
    TYPE TAG_REC IS RECORD(NS_ID VARCHAR2(255),NS_NAME VARCHAR2(100),TAG_NAME VARCHAR2(100),SLOT NUMBER);
    TYPE TAG_LIST IS TABLE OF TAG_REC INDEX BY PLS_INTEGER;
    TYPE SLOT_MAP IS TABLE OF PLS_INTEGER INDEX BY VARCHAR2(512);
    T TAG_LIST; W SLOT_MAP; S SLOT_MAP;
    FUNCTION KEY_OF(P_ID VARCHAR2,P_TAG VARCHAR2) RETURN VARCHAR2 IS
    BEGIN RETURN P_ID||CHR(1)||P_TAG; END;
    PROCEDURE ADD_TAG(P_NS VARCHAR2,P_TAG VARCHAR2) IS
      V_ID VARCHAR2(255); V_KEY VARCHAR2(512); V_COUNT NUMBER;
    BEGIN
      SELECT COUNT(*),MAX(N.TAG_NAMESPACE_ID) INTO V_COUNT,V_ID
        FROM OCI_TAG_NAMESPACE N JOIN OCI_TAG_DEFINITION F ON F.TAG_NAMESPACE_ID=N.TAG_NAMESPACE_ID
       WHERE N.NAMESPACE_NAME=P_NS AND N.IS_CURRENT='Y' AND N.LIFECYCLE_STATE='ACTIVE'
         AND F.TAG_NAME=P_TAG AND F.IS_CURRENT='Y' AND F.LIFECYCLE_STATE='ACTIVE';
      IF V_COUNT<>1 THEN RAISE_APPLICATION_ERROR(-20944,'Exactly one active tag is required: '||P_NS||'.'||P_TAG); END IF;
      V_KEY:=KEY_OF(V_ID,P_TAG);
      IF W.EXISTS(V_KEY) THEN RAISE_APPLICATION_ERROR(-20944,'Duplicate tag: '||P_NS||'.'||P_TAG); END IF;
      L_N:=L_N+1;
      IF L_N>9999 THEN RAISE_APPLICATION_ERROR(-20944,'At most 9999 tag positions are supported'); END IF;
      W(V_KEY):=L_N; T(L_N).NS_ID:=V_ID; T(L_N).NS_NAME:=P_NS; T(L_N).TAG_NAME:=P_TAG;
    END;
  BEGIN
    D:=JSON_OBJECT_T.PARSE(P_SPEC);
    D.ON_ERROR(1);
    IF D.GET_NUMBER('schema_version')<>1 THEN RAISE_APPLICATION_ERROR(-20944,'Unsupported tag specification version'); END IF;
    K:=D.GET_KEYS;
    FOR I IN 1..K.COUNT LOOP
      IF K(I) NOT IN ('schema_version','profile_name','mode','namespace','tags') THEN
        RAISE_APPLICATION_ERROR(-20944,'Unknown tag specification field: '||K(I));
      END IF;
    END LOOP;
    L_NAME:=D.GET_STRING('profile_name'); L_MODE:=D.GET_STRING('mode');
    IF L_NAME IS NULL OR NOT REGEXP_LIKE(L_NAME,'^[A-Z][A-Z0-9_]{0,127}$','c') OR
       L_MODE IS NULL OR L_MODE NOT IN ('NAMESPACE','TAG_LIST') THEN
      RAISE_APPLICATION_ERROR(-20944,'Provide profile_name and mode NAMESPACE or TAG_LIST');
    END IF;
    IF (L_MODE='NAMESPACE' AND (NOT D.HAS('namespace') OR D.HAS('tags'))) OR
       (L_MODE='TAG_LIST' AND (NOT D.HAS('tags') OR D.HAS('namespace'))) THEN
      RAISE_APPLICATION_ERROR(-20944,'Provide namespace OR tags, never both');
    END IF;
    L_RC:=DBMS_LOCK.REQUEST(L_LOCK,DBMS_LOCK.X_MODE,0,FALSE);
    IF L_RC<>0 THEN RAISE_APPLICATION_ERROR(-20944,'Another tag-profile operation is active'); END IF;
    L_LOCKED:=TRUE;
    OCI_TAG_SYNC_CATALOG;
    IF L_MODE='NAMESPACE' THEN
      L_NS:=D.GET_STRING('namespace');
      SELECT COUNT(*),MAX(TAG_NAMESPACE_ID) INTO L_COUNT,L_NS_ID FROM OCI_TAG_NAMESPACE
       WHERE NAMESPACE_NAME=L_NS AND IS_CURRENT='Y' AND LIFECYCLE_STATE='ACTIVE';
      IF L_COUNT<>1 THEN RAISE_APPLICATION_ERROR(-20944,'Exactly one existing active namespace is required'); END IF;
      FOR R IN (SELECT TAG_NAME FROM OCI_TAG_DEFINITION
                 WHERE TAG_NAMESPACE_ID=L_NS_ID AND IS_CURRENT='Y' AND LIFECYCLE_STATE='ACTIVE'
                 ORDER BY CASE WHEN L_NAME='DEFAULT_COST_GOVERNANCE' THEN
                   CASE TAG_NAME WHEN 'tag-lz-cost-center' THEN 1 WHEN 'tag-lz-platform' THEN 2
                     WHEN 'tag-lz-environment' THEN 3 WHEN 'tag-lz-owner' THEN 4
                     WHEN 'tag-lz-business-unit' THEN 5 WHEN 'tag-lz-project' THEN 6 ELSE 7 END
                   ELSE 0 END,TAG_NAME) LOOP ADD_TAG(L_NS,R.TAG_NAME); END LOOP;
    ELSE
      A:=D.GET_ARRAY('tags');
      FOR I IN 0..A.GET_SIZE-1 LOOP
        O:=TREAT(A.GET(I) AS JSON_OBJECT_T); O.ON_ERROR(1); K:=O.GET_KEYS;
        IF K.COUNT<>2 OR NOT O.HAS('namespace') OR NOT O.HAS('tag') THEN
          RAISE_APPLICATION_ERROR(-20944,'Each list entry requires namespace and tag only');
        END IF;
        ADD_TAG(O.GET_STRING('namespace'),O.GET_STRING('tag'));
      END LOOP;
    END IF;
    IF L_N=0 THEN RAISE_APPLICATION_ERROR(-20944,'Select at least one active defined tag'); END IF;
    IF L_NAME='DEFAULT_COST_GOVERNANCE' THEN
      IF L_MODE<>'NAMESPACE' OR L_NS<>'tagns-lz-cost-governance' THEN
        RAISE_APPLICATION_ERROR(-20944,'The default governance profile identity is reserved');
      END IF;
      SELECT COUNT(*) INTO L_COUNT FROM OCI_TAG_DEFINITION
       WHERE TAG_NAMESPACE_ID=L_NS_ID AND IS_CURRENT='Y' AND LIFECYCLE_STATE='ACTIVE'
         AND TAG_NAME IN ('tag-lz-cost-center','tag-lz-platform','tag-lz-environment',
                          'tag-lz-owner','tag-lz-business-unit','tag-lz-project');
      IF L_COUNT<>6 THEN RAISE_APPLICATION_ERROR(-20944,'Governance profile requires its six standard active tags'); END IF;
    END IF;
    SELECT NVL(MAX(PROFILE_VERSION),0) INTO L_OLD FROM OCI_TAG_PROFILE WHERE PROFILE_NAME=L_NAME;
    IF L_OLD=0 THEN L_CHANGED:=TRUE;
    ELSE
      SELECT SPEC_JSON INTO L_PREV FROM OCI_TAG_PROFILE WHERE PROFILE_NAME=L_NAME AND PROFILE_VERSION=L_OLD;
      L_PREV_DOC:=JSON_OBJECT_T.PARSE(L_PREV);
      IF L_PREV_DOC.GET_STRING('mode')<>L_MODE OR
         NVL(L_PREV_DOC.GET_STRING('namespace'),CHR(1))<>NVL(L_NS,CHR(1)) THEN L_CHANGED:=TRUE; END IF;
    END IF;
    FOR R IN (SELECT * FROM OCI_TAG_PROFILE_ITEM WHERE PROFILE_NAME=L_NAME AND PROFILE_VERSION=L_OLD) LOOP
      S(KEY_OF(R.TAG_NAMESPACE_ID,R.TAG_NAME)):=R.DISPLAY_ORDER;
      L_MAX_SLOT:=GREATEST(L_MAX_SLOT,R.DISPLAY_ORDER);
      IF W.EXISTS(KEY_OF(R.TAG_NAMESPACE_ID,R.TAG_NAME)) THEN L_ACTIVE:='Y'; ELSE L_ACTIVE:='N'; END IF;
      IF L_ACTIVE<>R.IS_ACTIVE THEN L_CHANGED:=TRUE; END IF;
    END LOOP;
    FOR I IN 1..L_N LOOP
      IF S.EXISTS(KEY_OF(T(I).NS_ID,T(I).TAG_NAME)) THEN
        T(I).SLOT:=S(KEY_OF(T(I).NS_ID,T(I).TAG_NAME));
      ELSE L_MAX_SLOT:=L_MAX_SLOT+1; T(I).SLOT:=L_MAX_SLOT; L_CHANGED:=TRUE;
      END IF;
    END LOOP;
    IF L_MAX_SLOT>9999 THEN RAISE_APPLICATION_ERROR(-20944,'Reserved and active slots exceed 9999'); END IF;
    IF NOT L_CHANGED THEN
      SELECT_PROFILE(L_NAME,L_OLD); COMMIT;
      L_RC:=DBMS_LOCK.RELEASE(L_LOCK); L_LOCKED:=FALSE;
      DBMS_OUTPUT.PUT_LINE('Profile unchanged; existing tag positions retained'); RETURN;
    END IF;
    L_VERSION:=L_OLD+1;
    L_KIND:=CASE WHEN L_NAME='DEFAULT_COST_GOVERNANCE' THEN 'DEFAULT'
                 WHEN L_MODE='TAG_LIST' THEN 'MIXED' ELSE 'CUSTOM' END;
    L_STORED_SPEC:=D.TO_CLOB;
    INSERT INTO OCI_TAG_PROFILE(PROFILE_NAME,PROFILE_VERSION,TAG_NAMESPACE_ID,PROFILE_KIND,SPEC_JSON)
      VALUES(L_NAME,L_VERSION,L_NS_ID,L_KIND,L_STORED_SPEC);
    FOR R IN (SELECT * FROM OCI_TAG_PROFILE_ITEM WHERE PROFILE_NAME=L_NAME AND PROFILE_VERSION=L_OLD) LOOP
      IF W.EXISTS(KEY_OF(R.TAG_NAMESPACE_ID,R.TAG_NAME)) THEN L_ACTIVE:='Y'; ELSE L_ACTIVE:='N'; END IF;
      INSERT INTO OCI_TAG_PROFILE_ITEM(PROFILE_NAME,PROFILE_VERSION,DISPLAY_ORDER,LOGICAL_TAG_NAME,IS_ACTIVE,TAG_NAMESPACE_ID,TAG_NAME)
      VALUES(L_NAME,L_VERSION,R.DISPLAY_ORDER,R.LOGICAL_TAG_NAME,L_ACTIVE,R.TAG_NAMESPACE_ID,R.TAG_NAME);
    END LOOP;
    FOR I IN 1..L_N LOOP
      IF NOT S.EXISTS(KEY_OF(T(I).NS_ID,T(I).TAG_NAME)) THEN
        INSERT INTO OCI_TAG_PROFILE_ITEM(PROFILE_NAME,PROFILE_VERSION,DISPLAY_ORDER,LOGICAL_TAG_NAME,IS_ACTIVE,TAG_NAMESPACE_ID,TAG_NAME)
        VALUES(L_NAME,L_VERSION,T(I).SLOT,T(I).NS_NAME||'_'||T(I).TAG_NAME,'Y',T(I).NS_ID,T(I).TAG_NAME);
      END IF;
    END LOOP;
    SELECT_PROFILE(L_NAME,L_VERSION); COMMIT;
    L_RC:=DBMS_LOCK.RELEASE(L_LOCK); L_LOCKED:=FALSE;
    DBMS_OUTPUT.PUT_LINE('Selected profile='||L_NAME||' version='||L_VERSION||' active_tags='||L_N||' reserved_slots='||L_MAX_SLOT);
    DBMS_OUTPUT.PUT_LINE('Published MV unchanged; build a candidate and publish it explicitly when ready');
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    IF L_LOCKED THEN L_RC:=DBMS_LOCK.RELEASE(L_LOCK); END IF;
    RAISE;
  END;

  PROCEDURE INSTALL_DEFAULT IS
  BEGIN
    APPLY_SPEC('{"schema_version":1,"profile_name":"DEFAULT_COST_GOVERNANCE","mode":"NAMESPACE","namespace":"tagns-lz-cost-governance"}');
  END;
  PROCEDURE SWITCH_NAMESPACE(P_NAMESPACE_NAME IN VARCHAR2) IS
    D JSON_OBJECT_T:=JSON_OBJECT_T();
  BEGIN
    D.PUT('schema_version',1);
    D.PUT('profile_name','NS_'||SUBSTR(REGEXP_REPLACE(UPPER(P_NAMESPACE_NAME),'[^A-Z0-9_]','_'),1,80)||'_'||
      TO_CHAR(DBMS_UTILITY.GET_HASH_VALUE(P_NAMESPACE_NAME,0,1073741823),'FM0000000000'));
    D.PUT('mode','NAMESPACE'); D.PUT('namespace',P_NAMESPACE_NAME);
    APPLY_SPEC(D.TO_CLOB);
  END;
  PROCEDURE REFRESH_ACTIVE IS
    V_SPEC CLOB;
  BEGIN
    SELECT P.SPEC_JSON INTO V_SPEC FROM OCI_TAG_PROFILE_SELECTION S JOIN OCI_TAG_PROFILE P
      ON P.PROFILE_NAME=S.PROFILE_NAME AND P.PROFILE_VERSION=S.PROFILE_VERSION WHERE S.SELECTION_ID=1;
    APPLY_SPEC(V_SPEC);
  END;
END OCI_TAG_PROFILE_API;
