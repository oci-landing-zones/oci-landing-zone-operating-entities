-- Read-only installation and operating-state gate.
SET ECHO OFF VERIFY OFF DEFINE OFF FEEDBACK ON SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 190 PAGESIZE 100
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

COLUMN OBJECT_TYPE FORMAT A19
COLUMN OBJECT_NAME FORMAT A38
COLUMN STATUS FORMAT A10
COLUMN JOB_NAME FORMAT A28
COLUMN ENABLED FORMAT A8
COLUMN REPEAT_INTERVAL FORMAT A46
COLUMN NEXT_RUN FORMAT A28
COLUMN NEXT_DAY FORMAT A20

PROMPT === OCI tag-value module objects ===
SELECT OBJECT_TYPE,OBJECT_NAME,STATUS FROM USER_OBJECTS
 WHERE OBJECT_NAME LIKE 'OCI_TAG_VALUE%'
 ORDER BY OBJECT_TYPE,OBJECT_NAME;

PROMPT === Bounded worker configuration ===
SELECT CONFIG_ID,TO_CHAR(NEXT_DAY,'YYYY-MM-DD') NEXT_DAY,
       MAX_ROWS_PER_RUN,UPDATED_AT
  FROM OCI_TAG_VALUE_CONFIG;

PROMPT === Scheduler ===
SELECT JOB_NAME,ENABLED,REPEAT_INTERVAL,
       TO_CHAR(NEXT_RUN_DATE,'YYYY-MM-DD HH24:MI TZR') NEXT_RUN
  FROM USER_SCHEDULER_JOBS
 WHERE JOB_NAME='OCI_TAG_VALUE_HOURLY';

PROMPT === Latest completed/background runs, if any ===
SELECT RUN_ID,TO_CHAR(WINDOW_START,'YYYY-MM-DD') WINDOW_DAY,
       STATUS,ROWS_PROCESSED,VALUES_INSERTED,
       TO_CHAR(STARTED_AT,'YYYY-MM-DD HH24:MI') STARTED_AT
  FROM OCI_TAG_VALUE_RUN
 ORDER BY RUN_ID DESC FETCH FIRST 5 ROWS ONLY;

DECLARE
  L_TABLES NUMBER;
  L_TEMP NUMBER;
  L_PARTITIONS NUMBER;
  L_CODE NUMBER;
  L_INVALID NUMBER;
  L_CONFIG NUMBER;
  L_JOB VARCHAR2(5);
  L_INTERVAL VARCHAR2(200);
BEGIN
  SELECT COUNT(*) INTO L_TABLES FROM USER_TABLES
   WHERE TABLE_NAME IN ('OCI_TAG_VALUE','OCI_TAG_VALUE_PROCESSING',
     'OCI_TAG_VALUE_WORK_KEYS','OCI_TAG_VALUE_CONFIG','OCI_TAG_VALUE_RUN');
  SELECT COUNT(*) INTO L_TEMP FROM USER_TABLES
   WHERE TABLE_NAME='OCI_TAG_VALUE_WORK_KEYS' AND TEMPORARY='Y';
  SELECT COUNT(*) INTO L_PARTITIONS FROM USER_PART_TABLES
   WHERE TABLE_NAME IN ('OCI_TAG_VALUE','OCI_TAG_VALUE_PROCESSING');
  SELECT COUNT(*) INTO L_CODE FROM USER_OBJECTS
   WHERE OBJECT_NAME='OCI_TAG_VALUE_API'
     AND OBJECT_TYPE IN ('PACKAGE','PACKAGE BODY') AND STATUS='VALID';
  SELECT COUNT(*) INTO L_INVALID FROM USER_OBJECTS
   WHERE OBJECT_NAME LIKE 'OCI_TAG_VALUE%' AND STATUS<>'VALID';
  SELECT COUNT(*) INTO L_CONFIG FROM OCI_TAG_VALUE_CONFIG
   WHERE CONFIG_ID=1 AND MAX_ROWS_PER_RUN=10000;
  SELECT ENABLED,REPEAT_INTERVAL INTO L_JOB,L_INTERVAL
    FROM USER_SCHEDULER_JOBS WHERE JOB_NAME='OCI_TAG_VALUE_HOURLY';
  DBMS_OUTPUT.PUT_LINE('tables='||L_TABLES||' temporary_work_table='||L_TEMP||
    ' partitioned_tables='||L_PARTITIONS||' valid_code='||L_CODE||
    ' invalid='||L_INVALID);
  DBMS_OUTPUT.PUT_LINE('config_rows='||L_CONFIG||
    ' hourly_job_enabled='||L_JOB);
  IF L_TABLES<>5 OR L_TEMP<>1 OR L_PARTITIONS<>2 OR
     L_CODE<>2 OR L_INVALID<>0 OR L_CONFIG<>1 OR L_JOB<>'TRUE' OR
     L_INTERVAL<>'FREQ=HOURLY;BYMINUTE=00;BYSECOND=00' THEN
    RAISE_APPLICATION_ERROR(-20968,
      'OCI tag-value extraction installation gate failed');
  END IF;
  DBMS_OUTPUT.PUT_LINE('OCI TAG VALUE EXTRACTION VERIFICATION PASS');
END;
