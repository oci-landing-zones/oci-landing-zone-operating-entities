-- Shared operation for SQL*Plus and Python; no MV build or synonym cutover.
SET DEFINE OFF ECHO OFF VERIFY OFF SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'FOCUSPLATFORM' THEN
    RAISE_APPLICATION_ERROR(-20944,'Connect as FOCUSPLATFORM');
  END IF;
  OCI_TAG_PROFILE_API.APPLY_SPEC(JSON_QUERY(:fp_install_config,'$.tag_profile' RETURNING CLOB ERROR ON ERROR));
END;
