-- Read-only structural and configuration gate.
SET VERIFY OFF DEFINE OFF SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 190 PAGESIZE 100
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
PROMPT === OCI Budgets objects ===
COLUMN OBJECT_TYPE FORMAT A18
COLUMN OBJECT_NAME FORMAT A42
COLUMN STATUS FORMAT A10
SELECT OBJECT_TYPE,OBJECT_NAME,STATUS FROM USER_OBJECTS
 WHERE OBJECT_NAME LIKE 'OCI_BUDGET_%' OR OBJECT_NAME='OCI_SYNC_BUDGETS'
 ORDER BY OBJECT_TYPE,OBJECT_NAME;
PROMPT === OCI Budgets schedule ===
COLUMN JOB_NAME FORMAT A28
COLUMN REPEAT_INTERVAL FORMAT A62
SELECT JOB_NAME,ENABLED,REPEAT_INTERVAL FROM USER_SCHEDULER_JOBS
 WHERE JOB_NAME='OCI_BUDGET_DAILY';
DECLARE T NUMBER; V NUMBER; P NUMBER; J NUMBER; C NUMBER; I NUMBER;
BEGIN
  SELECT COUNT(*) INTO T FROM USER_OBJECTS WHERE OBJECT_TYPE='TABLE' AND OBJECT_NAME LIKE 'OCI_BUDGET_%';
  SELECT COUNT(*) INTO V FROM USER_OBJECTS WHERE OBJECT_TYPE='VIEW' AND OBJECT_NAME LIKE 'OCI_BUDGET_%';
  SELECT COUNT(*) INTO P FROM USER_OBJECTS WHERE OBJECT_TYPE='PROCEDURE'
    AND OBJECT_NAME='OCI_SYNC_BUDGETS' AND STATUS='VALID';
  SELECT COUNT(*) INTO J FROM USER_SCHEDULER_JOBS WHERE JOB_NAME='OCI_BUDGET_DAILY'
    AND ENABLED='TRUE' AND REPEAT_INTERVAL='FREQ=DAILY;BYHOUR=08;BYMINUTE=15;BYSECOND=00';
  SELECT COUNT(*) INTO C FROM OCI_BUDGET_CONFIG WHERE IS_SYNC_ENABLED='Y'
    AND TENANCY_OCID LIKE 'ocid1.tenancy.%';
  SELECT COUNT(*) INTO I FROM USER_OBJECTS WHERE STATUS<>'VALID'
    AND (OBJECT_NAME LIKE 'OCI_BUDGET_%' OR OBJECT_NAME='OCI_SYNC_BUDGETS');
  DBMS_OUTPUT.PUT_LINE('tables='||T||' views='||V||' valid_procedure='||P||
    ' enabled_job='||J||' source_rows='||C||' invalid='||I);
  IF T<>4 OR V<>4 OR P<>1 OR J<>1 OR C<>1 OR I<>0 THEN
    RAISE_APPLICATION_ERROR(-20771,'OCI Budgets installation gate failed');
  END IF;
  DBMS_OUTPUT.PUT_LINE('OCI BUDGETS VERIFICATION PASS');
END;
