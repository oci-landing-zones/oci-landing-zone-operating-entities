-- Optional, on-demand replacement of the published OAC OCI cost-detail MV.
-- Run as FOCUSPLATFORM. The build runs in Scheduler; the old synonym target
-- remains published until a new MV is fully populated and validated.
SET ECHO OFF VERIFY OFF DEFINE OFF SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 220 PAGESIZE 100
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
PROMPT OPTIONAL OAC COST DETAIL MV REBUILD

DECLARE
  L_COLUMN NUMBER;
  L_REQUIRED NUMBER;
  L_SLOT_VIEW NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'FOCUSPLATFORM' THEN
    RAISE_APPLICATION_ERROR(-20630,'Connect as FOCUSPLATFORM');
  END IF;
  SELECT COUNT(*) INTO L_REQUIRED FROM USER_TABLES
   WHERE TABLE_NAME IN ('OAC_OCI_FOCUS_COST_DETAIL_RUN',
                        'OAC_OCI_FOCUS_COST_DETAIL_TAG_COLUMN',
                        'MV_CAPABILITIES_TABLE');
  IF L_REQUIRED<>3 THEN
    RAISE_APPLICATION_ERROR(-20643,'Install the OAC cost-detail module first');
  END IF;
  SELECT COUNT(*) INTO L_SLOT_VIEW FROM USER_OBJECTS
   WHERE OBJECT_NAME='OAC_OCI_FOCUS_TAG_SLOT_V'
     AND OBJECT_TYPE='VIEW' AND STATUS='VALID';
  IF L_SLOT_VIEW<>1 THEN
    RAISE_APPLICATION_ERROR(-20644,
      'Install or upgrade the stable tag-slot OAC module first');
  END IF;
  SELECT COUNT(*) INTO L_COLUMN FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME='OAC_OCI_FOCUS_COST_DETAIL_RUN'
     AND COLUMN_NAME='SOURCE_TABLE';
  IF L_COLUMN=0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE OAC_OCI_FOCUS_COST_DETAIL_RUN '||
      'ADD SOURCE_TABLE VARCHAR2(128)';
  END IF;
END;
/

CREATE OR REPLACE PROCEDURE OAC_OCI_FOCUS_COST_DETAIL_REBUILD(
  P_SOURCE_TABLE IN VARCHAR2) AUTHID DEFINER AS
  L_SOURCE VARCHAR2(128) := UPPER(TRIM(P_SOURCE_TABLE));
  L_LOCK_ID INTEGER := DBMS_UTILITY.GET_HASH_VALUE(
    'OAC_OCI_FOCUS_COST_DETAIL:'||SYS_CONTEXT('USERENV','CURRENT_USER'),
    1,1073741823);
  L_LOCK_RESULT INTEGER;
  L_LOCKED BOOLEAN := FALSE;
  L_RUN_ID NUMBER;
  L_MV VARCHAR2(128);
  L_PROFILE VARCHAR2(128);
  L_PROFILE_VERSION NUMBER;
  L_CURRENT_PROFILE VARCHAR2(128);
  L_CURRENT_VERSION NUMBER;
  L_SOURCE_COUNT NUMBER;
  L_PK_COUNT NUMBER;
  L_COL_COUNT NUMBER := 0;
  L_TAG_COUNT NUMBER := 0;
  L_MAX_SLOT NUMBER;
  L_HAS_TAGS NUMBER;
  L_HAS_MV_LOG NUMBER;
  L_BAD_TYPES NUMBER;
  L_FAST NUMBER;
  L_INSERT NUMBER;
  L_VALID NUMBER;
  L_ROWS NUMBER;
  L_SQL VARCHAR2(32767) := 'select';
  L_DDL VARCHAR2(32767);
  L_ALIAS VARCHAR2(128);
  L_PATH VARCHAR2(4000);
  L_STMT_ID VARCHAR2(30);
  L_COMPILE_STATE VARCHAR2(30);
  L_ERROR_CODE NUMBER;
  L_ERROR_MESSAGE VARCHAR2(4000);
  L_PUBLISHED NUMBER;
  TYPE T_NAMES IS TABLE OF BOOLEAN INDEX BY VARCHAR2(128);
  L_SEEN T_NAMES;
BEGIN
  IF L_SOURCE IS NULL OR L_SOURCE<>DBMS_ASSERT.SIMPLE_SQL_NAME(L_SOURCE) THEN
    RAISE_APPLICATION_ERROR(-20630,'Provide a simple local landing table name');
  END IF;
  SELECT COUNT(*) INTO L_SOURCE_COUNT FROM USER_TABLES
   WHERE TABLE_NAME=L_SOURCE AND TEMPORARY='N';
  IF L_SOURCE_COUNT<>1 THEN
    RAISE_APPLICATION_ERROR(-20631,'The source must be a permanent table owned by FOCUSPLATFORM');
  END IF;
  SELECT COUNT(*) INTO L_PK_COUNT FROM USER_CONSTRAINTS
   WHERE TABLE_NAME=L_SOURCE AND CONSTRAINT_TYPE='P' AND STATUS='ENABLED';
  IF L_PK_COUNT<>1 THEN
    RAISE_APPLICATION_ERROR(-20632,'The source needs an enabled primary key for FAST refresh');
  END IF;
  SELECT COUNT(*) INTO L_BAD_TYPES FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME=L_SOURCE AND COLUMN_NAME<>'TAGS'
     AND NOT (DATA_TYPE IN ('VARCHAR2','CHAR','NVARCHAR2','NCHAR','NUMBER',
                            'BINARY_FLOAT','BINARY_DOUBLE','DATE','RAW')
              OR DATA_TYPE LIKE 'TIMESTAMP%');
  IF L_BAD_TYPES>0 THEN
    RAISE_APPLICATION_ERROR(-20633,
      'Source contains unsupported non-TAGS columns; inspect USER_TAB_COLUMNS');
  END IF;
  SELECT COUNT(*) INTO L_HAS_TAGS FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME=L_SOURCE AND COLUMN_NAME='TAGS'
     AND DATA_TYPE IN ('JSON','CLOB','VARCHAR2');
  IF L_HAS_TAGS=0 THEN
    SELECT COUNT(*) INTO L_SOURCE_COUNT FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME=L_SOURCE AND COLUMN_NAME='TAGS';
    IF L_SOURCE_COUNT>0 THEN
      RAISE_APPLICATION_ERROR(-20634,'TAGS must be JSON, CLOB or VARCHAR2');
    END IF;
  END IF;
  L_LOCK_RESULT := DBMS_LOCK.REQUEST(ID=>L_LOCK_ID,
    LOCKMODE=>DBMS_LOCK.X_MODE,TIMEOUT=>0,RELEASE_ON_COMMIT=>FALSE);
  IF L_LOCK_RESULT<>0 THEN
    RAISE_APPLICATION_ERROR(-20635,'Another OAC cost-detail build or refresh is active');
  END IF;
  L_LOCKED := TRUE;
  UPDATE OAC_OCI_FOCUS_COST_DETAIL_RUN R SET STATUS='COMPLETE',
    FINISHED_AT=SYSTIMESTAMP
   WHERE R.RUN_KIND='BUILD' AND R.STATUS='READY'
     AND EXISTS (SELECT 1 FROM USER_SYNONYMS S
                  WHERE S.SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL'
                    AND S.TABLE_NAME=R.MV_NAME);
  UPDATE OAC_OCI_FOCUS_COST_DETAIL_RUN SET STATUS='ERROR',
    FINISHED_AT=SYSTIMESTAMP,ERROR_CODE=-20614,
    ERROR_MESSAGE='Prepared candidate was not published before session ended'
   WHERE RUN_KIND='BUILD' AND STATUS='READY';
  UPDATE OAC_OCI_FOCUS_COST_DETAIL_RUN SET STATUS='ERROR',
    FINISHED_AT=SYSTIMESTAMP,ERROR_CODE=-20614,
    ERROR_MESSAGE='Previous build or refresh session ended before completion'
   WHERE STATUS='RUNNING';
  COMMIT;
  SELECT PROFILE_NAME,PROFILE_VERSION INTO L_PROFILE,L_PROFILE_VERSION
    FROM OCI_TAG_PROFILE_SELECTION WHERE SELECTION_ID=1;
  INSERT INTO OAC_OCI_FOCUS_COST_DETAIL_RUN
    (RUN_KIND,STATUS,PROFILE_NAME,PROFILE_VERSION,SOURCE_TABLE)
    VALUES ('BUILD','RUNNING',L_PROFILE,L_PROFILE_VERSION,L_SOURCE)
    RETURNING RUN_ID INTO L_RUN_ID;
  L_MV := 'OAC_OCI_FOCUS_COST_DETAIL_MV_V'||TO_CHAR(L_RUN_ID,'FM9999999990');
  L_STMT_ID := 'OAC_COST_DETAIL_'||TO_CHAR(L_RUN_ID,'FM9999999990');
  UPDATE OAC_OCI_FOCUS_COST_DETAIL_RUN SET MV_NAME=L_MV WHERE RUN_ID=L_RUN_ID;
  COMMIT;

  FOR C IN (SELECT COLUMN_NAME FROM USER_TAB_COLUMNS
             WHERE TABLE_NAME=L_SOURCE AND COLUMN_NAME<>'TAGS'
             ORDER BY COLUMN_ID) LOOP
    IF L_COL_COUNT>0 THEN L_SQL:=L_SQL||','; END IF;
    L_SQL:=L_SQL||CHR(10)||'  L.'||DBMS_ASSERT.ENQUOTE_NAME(C.COLUMN_NAME,FALSE);
    L_SEEN(C.COLUMN_NAME):=TRUE;
    L_COL_COUNT:=L_COL_COUNT+1;
  END LOOP;
  IF L_COL_COUNT=0 THEN
    RAISE_APPLICATION_ERROR(-20636,'The source has no eligible scalar columns');
  END IF;
  -- The candidate contains exactly one slot per tag in the selected profile.
  -- DISPLAY_ORDER determines ordering; dense slots map that order to TAG_1..TAG_N.
  SELECT COUNT(*) INTO L_MAX_SLOT FROM OCI_TAG_PROFILE_ITEM
   WHERE PROFILE_NAME=L_PROFILE AND PROFILE_VERSION=L_PROFILE_VERSION;
  IF L_MAX_SLOT=0 THEN
    RAISE_APPLICATION_ERROR(-20635,'Selected profile contains no tag slots');
  END IF;
  FOR T IN (
    SELECT I.DISPLAY_ORDER,
           I.LOGICAL_TAG_NAME,
           I.TAG_NAMESPACE_ID,I.TAG_NAME,I.IS_ACTIVE,N.NAMESPACE_NAME
      FROM OCI_TAG_PROFILE_ITEM I
      JOIN OCI_TAG_NAMESPACE N ON N.TAG_NAMESPACE_ID=I.TAG_NAMESPACE_ID
     WHERE I.PROFILE_NAME=L_PROFILE AND I.PROFILE_VERSION=L_PROFILE_VERSION
     ORDER BY I.DISPLAY_ORDER
  ) LOOP
    L_ALIAS:='TAG_'||TO_CHAR(T.DISPLAY_ORDER,'FM9999');
    IF L_SEEN.EXISTS(L_ALIAS) THEN
      RAISE_APPLICATION_ERROR(-20637,
        'Source scalar column conflicts with reserved tag slot: '||L_ALIAS);
    END IF;
    IF L_HAS_TAGS=0 OR T.TAG_NAME IS NULL OR T.IS_ACTIVE='N' THEN
      L_SQL:=L_SQL||','||CHR(10)||
        '  CAST(NULL AS VARCHAR2(4000)) AS '||L_ALIAS;
    ELSE
      L_PATH:='$.'||'"'||REPLACE(REPLACE(
        T.NAMESPACE_NAME||'.'||T.TAG_NAME,
        CHR(92),CHR(92)||CHR(92)),
        '"',CHR(92)||'"')||'"';
      L_SQL:=L_SQL||','||CHR(10)||
        '  JSON_VALUE(L.TAGS, '''||REPLACE(L_PATH,'''','''''')||
        ''' RETURNING VARCHAR2(4000) NULL ON EMPTY NULL ON ERROR) AS '||L_ALIAS;
    END IF;
      INSERT INTO OAC_OCI_FOCUS_COST_DETAIL_TAG_COLUMN
        (RUN_ID,DISPLAY_ORDER,LOGICAL_TAG_NAME,MV_COLUMN_NAME,
         TAG_NAMESPACE_ID,TAG_NAME)
      VALUES (L_RUN_ID,T.DISPLAY_ORDER,T.LOGICAL_TAG_NAME,L_ALIAS,
              T.TAG_NAMESPACE_ID,T.TAG_NAME);
      L_TAG_COUNT:=L_TAG_COUNT+1;
    IF LENGTHB(L_SQL)>28000 THEN
      RAISE_APPLICATION_ERROR(-20638,'Projection exceeds the MV SQL length limit');
    END IF;
  END LOOP;
  UPDATE OAC_OCI_FOCUS_COST_DETAIL_RUN SET TAG_COLUMNS=L_TAG_COUNT
   WHERE RUN_ID=L_RUN_ID;
  COMMIT;
  L_SQL:=L_SQL||CHR(10)||'from '||DBMS_ASSERT.ENQUOTE_NAME(L_SOURCE,FALSE)||' L';
  IF LENGTHB(L_SQL)>29000 THEN
    RAISE_APPLICATION_ERROR(-20638,'Projection exceeds the MV SQL length limit');
  END IF;
  SELECT COUNT(*) INTO L_HAS_MV_LOG FROM USER_MVIEW_LOGS WHERE MASTER=L_SOURCE;
  IF L_HAS_MV_LOG=0 THEN
    EXECUTE IMMEDIATE 'CREATE MATERIALIZED VIEW LOG ON '||
      DBMS_ASSERT.ENQUOTE_NAME(L_SOURCE,FALSE)||
      ' WITH PRIMARY KEY, ROWID, SEQUENCE INCLUDING NEW VALUES';
  END IF;
  DBMS_MVIEW.EXPLAIN_MVIEW(L_SQL,L_STMT_ID);
  SELECT COUNT(*) INTO L_FAST FROM MV_CAPABILITIES_TABLE
   WHERE STATEMENT_ID=L_STMT_ID AND CAPABILITY_NAME='REFRESH_FAST'
     AND POSSIBLE='Y';
  SELECT COUNT(*) INTO L_INSERT FROM MV_CAPABILITIES_TABLE
   WHERE STATEMENT_ID=L_STMT_ID AND CAPABILITY_NAME='REFRESH_FAST_AFTER_INSERT'
     AND POSSIBLE='Y';
  COMMIT;
  IF L_FAST=0 OR L_INSERT=0 THEN
    RAISE_APPLICATION_ERROR(-20639,
      'FAST refresh unsupported; inspect MV_CAPABILITIES_TABLE for '||L_STMT_ID);
  END IF;
  L_DDL:='CREATE MATERIALIZED VIEW '||DBMS_ASSERT.ENQUOTE_NAME(L_MV,FALSE)||
    ' BUILD DEFERRED REFRESH FAST ON DEMAND WITH PRIMARY KEY AS '||L_SQL;
  EXECUTE IMMEDIATE L_DDL;
  DBMS_MVIEW.REFRESH(L_MV,'C');
  SELECT M.COMPILE_STATE INTO L_COMPILE_STATE FROM USER_MVIEWS M
   WHERE M.MVIEW_NAME=L_MV;
  IF L_COMPILE_STATE='NEEDS_COMPILE' THEN
    EXECUTE IMMEDIATE 'ALTER MATERIALIZED VIEW '||
      DBMS_ASSERT.ENQUOTE_NAME(L_MV,FALSE)||' COMPILE';
  END IF;
  SELECT COUNT(*) INTO L_VALID FROM USER_MVIEWS M JOIN USER_OBJECTS O
    ON O.OBJECT_NAME=M.MVIEW_NAME AND O.OBJECT_TYPE='MATERIALIZED VIEW'
   WHERE M.MVIEW_NAME=L_MV AND M.REFRESH_METHOD='FAST'
     AND M.STALENESS<>'UNUSABLE' AND O.STATUS='VALID';
  IF L_VALID<>1 THEN
    RAISE_APPLICATION_ERROR(-20640,'Candidate MV is not a usable FAST-refresh MV');
  END IF;
  EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM '||DBMS_ASSERT.ENQUOTE_NAME(L_MV,FALSE)
    INTO L_ROWS;
  SELECT PROFILE_NAME,PROFILE_VERSION INTO L_CURRENT_PROFILE,L_CURRENT_VERSION
    FROM OCI_TAG_PROFILE_SELECTION WHERE SELECTION_ID=1;
  IF L_HAS_TAGS=1 AND (L_CURRENT_PROFILE<>L_PROFILE OR
                       L_CURRENT_VERSION<>L_PROFILE_VERSION) THEN
    RAISE_APPLICATION_ERROR(-20641,
      'Tag profile changed during build; candidate retained without cutover');
  END IF;
  UPDATE OAC_OCI_FOCUS_COST_DETAIL_RUN SET STATUS='READY',MV_ROWS=L_ROWS,FINISHED_AT=SYSTIMESTAMP
   WHERE RUN_ID=L_RUN_ID;
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('READY candidate run='||L_RUN_ID||' '||L_MV||' from '||L_SOURCE||
    ' rows='||L_ROWS||' tag_columns='||L_TAG_COUNT);
  L_LOCK_RESULT:=DBMS_LOCK.RELEASE(ID=>L_LOCK_ID);
  L_LOCKED:=FALSE;
EXCEPTION WHEN OTHERS THEN
  L_ERROR_CODE:=SQLCODE;
  L_ERROR_MESSAGE:=SQLERRM;
  ROLLBACK;
  IF L_RUN_ID IS NOT NULL THEN
    SELECT COUNT(*) INTO L_PUBLISHED FROM USER_SYNONYMS
     WHERE SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL'
       AND TABLE_NAME=L_MV;
    UPDATE OAC_OCI_FOCUS_COST_DETAIL_RUN
       SET STATUS=CASE WHEN L_PUBLISHED=1 THEN 'COMPLETE' ELSE 'ERROR' END,
           FINISHED_AT=SYSTIMESTAMP,
           ERROR_CODE=CASE WHEN L_PUBLISHED=1 THEN NULL ELSE L_ERROR_CODE END,
           ERROR_MESSAGE=CASE WHEN L_PUBLISHED=1 THEN NULL
                              ELSE SUBSTR(L_ERROR_MESSAGE,1,4000) END
     WHERE RUN_ID=L_RUN_ID;
    COMMIT;
  END IF;
  IF L_LOCKED THEN L_LOCK_RESULT:=DBMS_LOCK.RELEASE(ID=>L_LOCK_ID); END IF;
  RAISE;
END OAC_OCI_FOCUS_COST_DETAIL_REBUILD;
