SHOW ERRORS PROCEDURE OAC_OCI_FOCUS_COST_DETAIL_REBUILD

DECLARE
  L_VALID NUMBER;
BEGIN
  SELECT COUNT(*) INTO L_VALID FROM USER_OBJECTS
   WHERE OBJECT_NAME='OAC_OCI_FOCUS_COST_DETAIL_REBUILD'
     AND OBJECT_TYPE='PROCEDURE' AND STATUS='VALID';
  IF L_VALID<>1 THEN
    RAISE_APPLICATION_ERROR(-20642,'Auxiliary rebuild procedure did not compile');
  END IF;
END;
/

DECLARE
  L_SOURCE VARCHAR2(128) := UPPER(NVL(JSON_VALUE(:fp_install_config,'$.source_table' ERROR ON ERROR),'OCI_FOCUS_REPORTS'));
  L_JOB VARCHAR2(128) := 'OAC_OCI_COST_REBUILD_'||SUBSTR(RAWTOHEX(SYS_GUID()),1,16);
  L_COUNT NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'FOCUSPLATFORM' THEN
    RAISE_APPLICATION_ERROR(-20630,'Connect as FOCUSPLATFORM');
  END IF;
  IF L_SOURCE IS NULL OR L_SOURCE<>DBMS_ASSERT.SIMPLE_SQL_NAME(L_SOURCE) THEN
    RAISE_APPLICATION_ERROR(-20630,'Provide a simple local landing table name');
  END IF;
  SELECT COUNT(*) INTO L_COUNT FROM USER_TABLES WHERE TABLE_NAME=L_SOURCE;
  IF L_COUNT<>1 THEN
    RAISE_APPLICATION_ERROR(-20631,'Landing table not found in FOCUSPLATFORM');
  END IF;
  DBMS_SCHEDULER.CREATE_JOB(
    JOB_NAME=>L_JOB,JOB_TYPE=>'STORED_PROCEDURE',
    JOB_ACTION=>'OAC_OCI_FOCUS_COST_DETAIL_REBUILD',
    NUMBER_OF_ARGUMENTS=>1,START_DATE=>SYSTIMESTAMP+INTERVAL '10' SECOND,
    ENABLED=>FALSE,AUTO_DROP=>FALSE,
    COMMENTS=>'Optional full candidate build; publish OAC synonym only after validation');
  DBMS_SCHEDULER.SET_JOB_ARGUMENT_VALUE(L_JOB,1,L_SOURCE);
  DBMS_SCHEDULER.ENABLE(L_JOB);
  DBMS_OUTPUT.PUT_LINE('Background rebuild requested job='||L_JOB||
    ' source='||L_SOURCE);
  DBMS_OUTPUT.PUT_LINE('Current OAC synonym remains unchanged. Publish the validated READY candidate explicitly.');
END;
/
PROMPT === Background rebuild request ===
SELECT JOB_NAME,ENABLED,STATE,NEXT_RUN_DATE
  FROM USER_SCHEDULER_JOBS
 WHERE JOB_NAME LIKE 'OAC_OCI_COST_REBUILD_%'
 ORDER BY JOB_NAME DESC
 FETCH FIRST 3 ROWS ONLY;
