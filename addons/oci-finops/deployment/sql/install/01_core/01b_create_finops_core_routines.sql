-- Provider API contract, installed by each provider module, not by this script:
-- PACKAGE <PPP>_... AS
--   PROCEDURE RUN(P_CORE_RUN_ID NUMBER, P_MAX_FILES_PER_PIPELINE NUMBER);
--   FUNCTION REPORT RETURN CLOB;  -- read-only, current provider status
-- END;
-- RUN inserts one FINOPS_CORE_PIPELINE_RUN row per handled pipeline.
CREATE OR REPLACE PACKAGE FINOPS_CORE_SCHEDULE_API AUTHID DEFINER AS
  FUNCTION LOCAL_START_DATE RETURN TIMESTAMP WITH TIME ZONE;
END FINOPS_CORE_SCHEDULE_API;
/

CREATE OR REPLACE PACKAGE BODY FINOPS_CORE_SCHEDULE_API AS
  FUNCTION LOCAL_START_DATE RETURN TIMESTAMP WITH TIME ZONE IS
    L_TIME_ZONE VARCHAR2(64);
  BEGIN
    SELECT TIME_ZONE INTO L_TIME_ZONE
      FROM FINOPS_CORE_SCHEDULE_CONFIG WHERE CONFIG_ID = 1;
    RETURN SYSTIMESTAMP AT TIME ZONE L_TIME_ZONE;
  END LOCAL_START_DATE;
END FINOPS_CORE_SCHEDULE_API;
/

CREATE OR REPLACE FUNCTION FINOPS_CORE_REPORT(
  P_RUN_ID IN NUMBER DEFAULT NULL
) RETURN CLOB AUTHID DEFINER IS
  L_RUN_ID NUMBER := P_RUN_ID;
  L_STATUS VARCHAR2(20);
  L_STARTED TIMESTAMP WITH TIME ZONE;
  L_FINISHED TIMESTAMP WITH TIME ZONE;
  L_EMAIL VARCHAR2(20);
  L_TEXT CLOB := TO_CLOB('FOCUS provider ingestion report' || CHR(10));
  L_PROVIDER_REPORT CLOB;
  L_PACKAGE VARCHAR2(128);
BEGIN
  IF L_RUN_ID IS NULL THEN
    SELECT MAX(RUN_ID) INTO L_RUN_ID FROM FINOPS_CORE_RUN;
  END IF;
  IF L_RUN_ID IS NULL THEN
    L_TEXT := L_TEXT || 'No coordinator execution has been recorded.' || CHR(10);
  ELSE
    SELECT STATUS, STARTED_AT, FINISHED_AT, EMAIL_STATUS
      INTO L_STATUS, L_STARTED, L_FINISHED, L_EMAIL
      FROM FINOPS_CORE_RUN WHERE RUN_ID = L_RUN_ID;
    L_TEXT := L_TEXT || 'Run ' || L_RUN_ID || ': ' || L_STATUS ||
      '; started ' || TO_CHAR(L_STARTED, 'YYYY-MM-DD HH24:MI:SS TZH:TZM') ||
      '; finished ' || NVL(TO_CHAR(L_FINISHED,
        'YYYY-MM-DD HH24:MI:SS TZH:TZM'), 'IN PROGRESS') ||
      '; email ' || L_EMAIL || CHR(10);
    FOR R IN (
      SELECT PROVIDER_CODE, STATUS, PIPELINES_FOUND, PIPELINES_ERROR,
             FILES_FULL, FILES_PARTIAL, FILES_ERROR, PIPELINES_AT_LIMIT,
             ERROR_MESSAGE
        FROM FINOPS_CORE_PROVIDER_RUN WHERE RUN_ID = L_RUN_ID
       ORDER BY PROVIDER_CODE
    ) LOOP
      L_TEXT := L_TEXT || R.PROVIDER_CODE || ': ' || R.STATUS ||
        '; pipelines=' || R.PIPELINES_FOUND ||
        '; pipeline_errors=' || R.PIPELINES_ERROR ||
        '; full=' || R.FILES_FULL || '; partial=' || R.FILES_PARTIAL ||
        '; file_errors=' || R.FILES_ERROR ||
        '; at_limit=' || R.PIPELINES_AT_LIMIT ||
        CASE WHEN R.ERROR_MESSAGE IS NOT NULL
          THEN '; error=' || R.ERROR_MESSAGE ELSE '' END || CHR(10);
    END LOOP;
    FOR R IN (
      SELECT PROVIDER_CODE, PIPELINE_NAME, PIPELINE_STATUS,
             PROCESS_STATUS, FILES_FULL, FILES_PARTIAL, FILES_ERROR,
             QUEUED_AFTER, OPEN_FILE_ERRORS, MANUAL_PENDING_ROWS,
             LIMIT_REACHED, ERROR_MESSAGE
        FROM FINOPS_CORE_PIPELINE_RUN WHERE RUN_ID = L_RUN_ID
       ORDER BY PROVIDER_CODE, PIPELINE_NAME
    ) LOOP
      L_TEXT := L_TEXT || '  ' || R.PROVIDER_CODE || '/' ||
        R.PIPELINE_NAME || ': source=' || NVL(R.PIPELINE_STATUS, 'UNKNOWN') ||
        '; run=' || R.PROCESS_STATUS || '; full=' || R.FILES_FULL ||
        '; partial=' || R.FILES_PARTIAL ||
        '; file_errors=' || R.FILES_ERROR ||
        '; queued=' || R.QUEUED_AFTER ||
        '; open_file_errors=' || R.OPEN_FILE_ERRORS ||
        '; manual_rows=' || R.MANUAL_PENDING_ROWS ||
        '; limit=' || R.LIMIT_REACHED ||
        CASE WHEN R.ERROR_MESSAGE IS NOT NULL
          THEN '; error=' || R.ERROR_MESSAGE ELSE '' END || CHR(10);
    END LOOP;
  END IF;
  L_TEXT := L_TEXT || 'Current provider status:' || CHR(10);
  FOR P IN (
    SELECT PROVIDER_CODE, API_PACKAGE, ENABLED
      FROM FINOPS_CORE_PROVIDER ORDER BY PROVIDER_CODE
  ) LOOP
    IF P.ENABLED = 'N' THEN
      L_TEXT := L_TEXT || P.PROVIDER_CODE || ': DISABLED' || CHR(10);
    ELSE
      BEGIN
        L_PACKAGE := DBMS_ASSERT.SIMPLE_SQL_NAME(P.API_PACKAGE);
        IF NOT REGEXP_LIKE(L_PACKAGE,
               '^' || P.PROVIDER_CODE || '_[A-Z0-9_$#]+$') THEN
          RAISE_APPLICATION_ERROR(-20901,
            'Provider API package name does not match its code');
        END IF;
        EXECUTE IMMEDIATE 'BEGIN :x := ' || L_PACKAGE || '.REPORT; END;'
          USING OUT L_PROVIDER_REPORT;
        L_TEXT := L_TEXT || P.PROVIDER_CODE || ': ' ||
          NVL(L_PROVIDER_REPORT, TO_CLOB('No status returned')) || CHR(10);
      EXCEPTION WHEN OTHERS THEN
        L_TEXT := L_TEXT || P.PROVIDER_CODE ||
          ': REPORT ERROR ' || SUBSTR(SQLERRM, 1, 1000) || CHR(10);
      END;
    END IF;
  END LOOP;
  RETURN L_TEXT;
END FINOPS_CORE_REPORT;
/

CREATE OR REPLACE PROCEDURE FINOPS_CORE_RUN_DAILY(
  P_SEND_EMAIL IN CHAR DEFAULT 'Y'
) AUTHID DEFINER IS
  L_LOCK_ID INTEGER;
  L_LOCK_RESULT INTEGER;
  L_LOCKED BOOLEAN := FALSE;
  L_RUN_ID NUMBER;
  L_PACKAGE VARCHAR2(128);
  L_PACKAGE_COUNT NUMBER;
  L_PIPELINES NUMBER;
  L_PROVIDER_COUNT NUMBER;
  L_PIPELINE_ERRORS NUMBER;
  L_FULL NUMBER;
  L_PARTIAL NUMBER;
  L_FILE_ERRORS NUMBER;
  L_AT_LIMIT NUMBER;
  L_PROVIDER_ERRORS NUMBER;
  L_TOPIC VARCHAR2(255);
  L_NOTIFY_ENABLED CHAR(1);
  L_BODY CLOB;
  L_FAILURE VARCHAR2(4000);
  L_EMAIL_FAILED BOOLEAN := FALSE;
BEGIN
  IF P_SEND_EMAIL IS NULL OR P_SEND_EMAIL NOT IN ('Y','N') THEN
    RAISE_APPLICATION_ERROR(-20902, 'P_SEND_EMAIL must be Y or N');
  END IF;
  L_LOCK_ID := DBMS_UTILITY.GET_HASH_VALUE(
    SYS_CONTEXT('USERENV', 'CURRENT_USER') || '.FINOPS_CORE_RUN_DAILY',
    0, 1073741823);
  L_LOCK_RESULT := DBMS_LOCK.REQUEST(
    ID => L_LOCK_ID, LOCKMODE => DBMS_LOCK.X_MODE,
    TIMEOUT => 0, RELEASE_ON_COMMIT => FALSE);
  IF L_LOCK_RESULT = 1 THEN
    -- An initial or manual run is still active. Skip this occurrence;
    -- the daily schedule remains unchanged and will try again tomorrow.
    DBMS_OUTPUT.PUT_LINE('FINOPS_CORE skipped: another run is active');
    RETURN;
  END IF;
  IF L_LOCK_RESULT <> 0 THEN
    RAISE_APPLICATION_ERROR(-20903,
      'Core execution lock request failed, code=' || L_LOCK_RESULT);
  END IF;
  L_LOCKED := TRUE;

  -- An expired session cannot retain the DBMS_LOCK lock. A previous RUNNING
  -- audit row is therefore an interruption, not another active execution.
  UPDATE FINOPS_CORE_PROVIDER_RUN SET STATUS = 'INTERRUPTED',
         FINISHED_AT = SYSTIMESTAMP,
         ERROR_MESSAGE = NVL(ERROR_MESSAGE, 'Coordinator interrupted')
   WHERE STATUS = 'RUNNING';
  UPDATE FINOPS_CORE_RUN SET STATUS = 'INTERRUPTED',
         FINISHED_AT = SYSTIMESTAMP,
         ERROR_MESSAGE = NVL(ERROR_MESSAGE, 'Coordinator interrupted')
   WHERE STATUS = 'RUNNING';
  INSERT INTO FINOPS_CORE_RUN (STATUS) VALUES ('RUNNING')
    RETURNING RUN_ID INTO L_RUN_ID;
  COMMIT;

  FOR P IN (
    SELECT PROVIDER_CODE, LANDING_TABLE, API_PACKAGE,
           MAX_FILES_PER_PIPELINE
      FROM FINOPS_CORE_PROVIDER WHERE ENABLED = 'Y'
     ORDER BY PROVIDER_CODE
  ) LOOP
    INSERT INTO FINOPS_CORE_PROVIDER_RUN
      (RUN_ID, PROVIDER_CODE, LANDING_TABLE)
    VALUES (L_RUN_ID, P.PROVIDER_CODE, P.LANDING_TABLE);
    COMMIT;
    BEGIN
      L_PACKAGE := DBMS_ASSERT.SIMPLE_SQL_NAME(P.API_PACKAGE);
      IF NOT REGEXP_LIKE(L_PACKAGE,
             '^' || P.PROVIDER_CODE || '_[A-Z0-9_$#]+$') THEN
        RAISE_APPLICATION_ERROR(-20904,
          'Provider API package name does not match its code');
      END IF;
      SELECT COUNT(*) INTO L_PACKAGE_COUNT FROM USER_OBJECTS
       WHERE OBJECT_NAME = L_PACKAGE AND OBJECT_TYPE = 'PACKAGE'
         AND STATUS = 'VALID';
      IF L_PACKAGE_COUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20905,
          'Provider API package is missing or invalid');
      END IF;
      EXECUTE IMMEDIATE 'BEGIN ' || L_PACKAGE || '.RUN(:run_id,:max_files); END;'
        USING L_RUN_ID, P.MAX_FILES_PER_PIPELINE;
      SELECT COUNT(*),
             NVL(SUM(CASE WHEN PROCESS_STATUS = 'ERROR' THEN 1 ELSE 0 END),0),
             NVL(SUM(FILES_FULL),0), NVL(SUM(FILES_PARTIAL),0),
             NVL(SUM(FILES_ERROR),0),
             NVL(SUM(CASE WHEN LIMIT_REACHED = 'Y' THEN 1 ELSE 0 END),0)
        INTO L_PIPELINES, L_PIPELINE_ERRORS, L_FULL, L_PARTIAL,
             L_FILE_ERRORS, L_AT_LIMIT
        FROM FINOPS_CORE_PIPELINE_RUN
       WHERE RUN_ID = L_RUN_ID AND PROVIDER_CODE = P.PROVIDER_CODE;
      UPDATE FINOPS_CORE_PROVIDER_RUN
         SET STATUS = CASE WHEN L_PIPELINE_ERRORS = 0
                           THEN 'COMPLETE' ELSE 'ERROR' END,
             FINISHED_AT = SYSTIMESTAMP,
             PIPELINES_FOUND = L_PIPELINES,
             PIPELINES_ERROR = L_PIPELINE_ERRORS,
             FILES_FULL = L_FULL, FILES_PARTIAL = L_PARTIAL,
             FILES_ERROR = L_FILE_ERRORS, PIPELINES_AT_LIMIT = L_AT_LIMIT,
             ERROR_MESSAGE = CASE WHEN L_PIPELINE_ERRORS > 0
               THEN L_PIPELINE_ERRORS || ' pipeline(s) failed' END
       WHERE RUN_ID = L_RUN_ID AND PROVIDER_CODE = P.PROVIDER_CODE;
      COMMIT;
    EXCEPTION WHEN OTHERS THEN
      L_FAILURE := SUBSTR(SQLERRM, 1, 4000);
      ROLLBACK;
      UPDATE FINOPS_CORE_PROVIDER_RUN
         SET STATUS = 'ERROR', FINISHED_AT = SYSTIMESTAMP,
             ERROR_MESSAGE = L_FAILURE
       WHERE RUN_ID = L_RUN_ID AND PROVIDER_CODE = P.PROVIDER_CODE;
      COMMIT;
    END;
  END LOOP;

  SELECT COUNT(*),
         NVL(SUM(CASE WHEN STATUS = 'ERROR' THEN 1 ELSE 0 END),0)
    INTO L_PROVIDER_COUNT, L_PROVIDER_ERRORS
    FROM FINOPS_CORE_PROVIDER_RUN WHERE RUN_ID = L_RUN_ID;
  SELECT COUNT(*),
         NVL(SUM(CASE WHEN PROCESS_STATUS = 'ERROR' THEN 1 ELSE 0 END),0),
         NVL(SUM(FILES_FULL),0), NVL(SUM(FILES_PARTIAL),0),
         NVL(SUM(FILES_ERROR),0),
         NVL(SUM(CASE WHEN LIMIT_REACHED = 'Y' THEN 1 ELSE 0 END),0)
    INTO L_PIPELINES, L_PIPELINE_ERRORS, L_FULL, L_PARTIAL,
         L_FILE_ERRORS, L_AT_LIMIT
    FROM FINOPS_CORE_PIPELINE_RUN WHERE RUN_ID = L_RUN_ID;
  UPDATE FINOPS_CORE_RUN
     SET STATUS = CASE WHEN L_PROVIDER_ERRORS = 0
                       THEN 'COMPLETE' ELSE 'ERROR' END,
         FINISHED_AT = SYSTIMESTAMP,
         PROVIDERS_FOUND = L_PROVIDER_COUNT,
         PROVIDERS_ERROR = L_PROVIDER_ERRORS,
         PIPELINES_FOUND = L_PIPELINES,
         PIPELINES_ERROR = L_PIPELINE_ERRORS,
         FILES_FULL = L_FULL, FILES_PARTIAL = L_PARTIAL,
         FILES_ERROR = L_FILE_ERRORS, PIPELINES_AT_LIMIT = L_AT_LIMIT,
         EMAIL_STATUS = CASE WHEN P_SEND_EMAIL = 'N'
                             THEN 'SKIPPED' ELSE 'PENDING' END,
         ERROR_MESSAGE = CASE WHEN L_PROVIDER_ERRORS > 0
           THEN L_PROVIDER_ERRORS || ' provider(s) failed' END
   WHERE RUN_ID = L_RUN_ID;
  COMMIT;

  IF P_SEND_EMAIL = 'Y' THEN
    BEGIN
      SELECT TOPIC_OCID, ENABLED INTO L_TOPIC, L_NOTIFY_ENABLED
        FROM FINOPS_CORE_NOTIFY_CONFIG WHERE CONFIG_ID = 1;
      IF L_NOTIFY_ENABLED = 'N' AND L_TOPIC IS NULL THEN
        UPDATE FINOPS_CORE_RUN SET EMAIL_STATUS = 'SKIPPED'
         WHERE RUN_ID = L_RUN_ID;
        COMMIT;
      ELSIF L_NOTIFY_ENABLED <> 'Y' OR L_TOPIC IS NULL OR
            NOT REGEXP_LIKE(L_TOPIC, '^ocid1\.onstopic\.') THEN
        RAISE_APPLICATION_ERROR(-20906,
          'Common Notifications configuration is inconsistent or invalid');
      ELSE
        L_BODY := FINOPS_CORE_REPORT(L_RUN_ID);
        IF DBMS_LOB.GETLENGTH(L_BODY) > 28000 THEN
          L_BODY := DBMS_LOB.SUBSTR(L_BODY, 12000, 1) || CHR(10) ||
            '[Report shortened; query FINOPS_CORE_RUN and provider manual ' ||
            'review tables in ADB for the complete state.]';
        END IF;
        DBMS_CLOUD_NOTIFICATION.SEND_MESSAGE(
          PROVIDER => 'oci',
          CREDENTIAL_NAME => 'OCI$RESOURCE_PRINCIPAL',
          MESSAGE => L_BODY,
          PARAMS => JSON_OBJECT(
            'topic_ocid' VALUE L_TOPIC,
            'title' VALUE 'FOCUS ingestion daily report'));
        UPDATE FINOPS_CORE_RUN SET EMAIL_STATUS = 'SENT'
         WHERE RUN_ID = L_RUN_ID;
        COMMIT;
      END IF;
    EXCEPTION WHEN OTHERS THEN
      L_FAILURE := SUBSTR(SQLERRM, 1, 4000);
      ROLLBACK;
      L_EMAIL_FAILED := TRUE;
      UPDATE FINOPS_CORE_RUN SET STATUS = 'ERROR',
             EMAIL_STATUS = 'ERROR', EMAIL_ERROR = L_FAILURE,
             ERROR_MESSAGE = NVL(ERROR_MESSAGE, L_FAILURE)
       WHERE RUN_ID = L_RUN_ID;
      COMMIT;
    END;
  END IF;

  L_LOCK_RESULT := DBMS_LOCK.RELEASE(ID => L_LOCK_ID);
  L_LOCKED := FALSE;
  IF L_LOCK_RESULT <> 0 THEN
    RAISE_APPLICATION_ERROR(-20907,
      'Core execution lock release failed, code=' || L_LOCK_RESULT);
  END IF;
  DBMS_OUTPUT.PUT_LINE('FINOPS_CORE run=' || L_RUN_ID ||
    ' providers=' || L_PROVIDER_COUNT);
  IF L_PROVIDER_ERRORS > 0 OR L_EMAIL_FAILED THEN
    RAISE_APPLICATION_ERROR(-20908,
      'Core run has provider or email errors; inspect FINOPS_CORE_RUN');
  END IF;
EXCEPTION WHEN OTHERS THEN
  IF L_RUN_ID IS NOT NULL THEN
    L_FAILURE := SUBSTR(SQLERRM, 1, 4000);
    ROLLBACK;
    UPDATE FINOPS_CORE_RUN
       SET STATUS = 'ERROR', FINISHED_AT = NVL(FINISHED_AT, SYSTIMESTAMP),
           ERROR_MESSAGE = NVL(ERROR_MESSAGE, L_FAILURE)
     WHERE RUN_ID = L_RUN_ID;
    COMMIT;
  END IF;
  IF L_LOCKED THEN
    L_LOCK_RESULT := DBMS_LOCK.RELEASE(ID => L_LOCK_ID);
  END IF;
  RAISE;
END FINOPS_CORE_RUN_DAILY;
/
