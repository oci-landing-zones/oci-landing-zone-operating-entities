-- Module 00 read-only FOCUSPLATFORM schema verification. Run as ADMIN.
-- This script does not create, alter, or grant anything.
SET ECHO OFF VERIFY OFF FEEDBACK ON SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 180 PAGESIZE 100
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

COLUMN OWNER FORMAT A22
COLUMN TABLE_NAME FORMAT A44
COLUMN PRIVILEGE FORMAT A12
COLUMN USERNAME FORMAT A20
COLUMN ACCOUNT_STATUS FORMAT A24
COLUMN GRANTED_ROLE FORMAT A20
COLUMN TABLESPACE_NAME FORMAT A16
COLUMN CREDENTIAL_NAME FORMAT A30

PROMPT === Schema ===
SELECT USERNAME, ACCOUNT_STATUS FROM DBA_USERS
 WHERE USERNAME IN ('FOCUSPLATFORM', 'OAC_FOCUS_READER')
 ORDER BY USERNAME;

PROMPT === OAC reader schema access ===
SELECT GRANTEE, SCHEMA, PRIVILEGE, ADMIN_OPTION FROM DBA_SCHEMA_PRIVS
 WHERE GRANTEE = 'OAC_FOCUS_READER' AND SCHEMA = 'FOCUSPLATFORM';

PROMPT === Roles ===
SELECT GRANTED_ROLE FROM DBA_ROLE_PRIVS
 WHERE GRANTEE = 'FOCUSPLATFORM'
   AND GRANTED_ROLE IN ('CONNECT', 'DWROLE')
 ORDER BY GRANTED_ROLE;

PROMPT === FOCUSPLATFORM direct grants, including DBMS_CLOUD implementation ===
SELECT OWNER, TABLE_NAME, PRIVILEGE FROM DBA_TAB_PRIVS
 WHERE GRANTEE = 'FOCUSPLATFORM'
   AND (TABLE_NAME IN ('DBMS_CLOUD', 'DBMS_CLOUD_NOTIFICATION',
                       'DATA_PUMP_DIR',
                       'DBMS_LOCK', 'V_$SESSION', 'V_$PDBS')
        OR TABLE_NAME LIKE 'DBMS_CLOUD$PDBCS%')
 ORDER BY TABLE_NAME, OWNER;

PROMPT === DATA quota ===
SELECT TABLESPACE_NAME, MAX_BYTES FROM DBA_TS_QUOTAS
 WHERE USERNAME = 'FOCUSPLATFORM' AND TABLESPACE_NAME = 'DATA';

PROMPT === ADMIN resource principal credential ===
SELECT OWNER, CREDENTIAL_NAME FROM DBA_CREDENTIALS
 WHERE OWNER = 'ADMIN' AND CREDENTIAL_NAME = 'OCI$RESOURCE_PRINCIPAL';

PROMPT === Direct OAC object and Scheduler creation privileges ===
SELECT PRIVILEGE FROM DBA_SYS_PRIVS
 WHERE GRANTEE='FOCUSPLATFORM'
   AND PRIVILEGE IN ('CREATE TABLE','CREATE MATERIALIZED VIEW','CREATE SYNONYM','CREATE JOB')
 ORDER BY PRIVILEGE;

DECLARE
  L_USER NUMBER;
  L_ROLES NUMBER;
  L_DIRECT NUMBER;
  L_CLOUD NUMBER;
  L_PIPELINE NUMBER;
  L_QUOTA NUMBER;
  L_ADMIN_PRINCIPAL NUMBER;
  L_PRINCIPAL NUMBER;
  L_MVIEW_ACCESS NUMBER;
  L_OAC_DDL NUMBER;
  L_COPY_DIR NUMBER;
  L_READER NUMBER;
  L_READER_GRANT NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'ADMIN' THEN
    RAISE_APPLICATION_ERROR(-20900, 'Connect as ADMIN to verify the schema');
  END IF;
  SELECT COUNT(*) INTO L_USER FROM DBA_USERS
   WHERE USERNAME = 'FOCUSPLATFORM' AND ACCOUNT_STATUS = 'OPEN';
  SELECT COUNT(DISTINCT GRANTED_ROLE) INTO L_ROLES FROM DBA_ROLE_PRIVS
   WHERE GRANTEE = 'FOCUSPLATFORM'
     AND GRANTED_ROLE IN ('CONNECT', 'DWROLE');
  SELECT COUNT(DISTINCT TABLE_NAME) INTO L_DIRECT FROM DBA_TAB_PRIVS
   WHERE GRANTEE = 'FOCUSPLATFORM'
     AND ((PRIVILEGE = 'EXECUTE' AND TABLE_NAME IN
             ('DBMS_CLOUD_NOTIFICATION', 'DBMS_LOCK'))
       OR (PRIVILEGE = 'SELECT' AND TABLE_NAME IN
             ('V_$SESSION', 'V_$PDBS')));
  SELECT COUNT(*) INTO L_CLOUD FROM DBA_TAB_PRIVS
   WHERE GRANTEE = 'FOCUSPLATFORM' AND PRIVILEGE = 'EXECUTE'
     AND (TABLE_NAME = 'DBMS_CLOUD'
       OR TABLE_NAME LIKE 'DBMS_CLOUD$PDBCS%');
  SELECT COUNT(*) INTO L_PIPELINE FROM DBA_TAB_PRIVS
   WHERE GRANTEE IN ('FOCUSPLATFORM', 'DWROLE', 'PUBLIC')
     AND TABLE_NAME = 'DBMS_CLOUD_PIPELINE' AND PRIVILEGE = 'EXECUTE';
  SELECT COUNT(*) INTO L_QUOTA FROM DBA_TS_QUOTAS
   WHERE USERNAME = 'FOCUSPLATFORM' AND TABLESPACE_NAME = 'DATA'
     AND MAX_BYTES = -1;
  SELECT COUNT(*) INTO L_ADMIN_PRINCIPAL FROM DBA_CREDENTIALS
   WHERE OWNER = 'ADMIN' AND CREDENTIAL_NAME = 'OCI$RESOURCE_PRINCIPAL';
  SELECT COUNT(*) INTO L_PRINCIPAL FROM DBA_TAB_PRIVS
   WHERE GRANTEE = 'FOCUSPLATFORM' AND OWNER = 'ADMIN'
     AND TABLE_NAME = 'OCI$RESOURCE_PRINCIPAL';
  SELECT COUNT(*) INTO L_MVIEW_ACCESS
    FROM DBA_SYNONYMS S JOIN DBA_TAB_PRIVS P
      ON P.OWNER=S.TABLE_OWNER AND P.TABLE_NAME=S.TABLE_NAME
   WHERE S.OWNER='PUBLIC' AND S.SYNONYM_NAME='DBMS_MVIEW'
     AND S.TABLE_OWNER='SYS' AND S.TABLE_NAME='DBMS_SNAPSHOT'
     AND P.PRIVILEGE='EXECUTE'
     AND P.GRANTEE IN ('PUBLIC','FOCUSPLATFORM');
  SELECT COUNT(*) INTO L_OAC_DDL FROM DBA_SYS_PRIVS
   WHERE GRANTEE='FOCUSPLATFORM'
     AND PRIVILEGE IN ('CREATE TABLE','CREATE MATERIALIZED VIEW','CREATE SYNONYM','CREATE JOB');
  SELECT COUNT(DISTINCT PRIVILEGE) INTO L_COPY_DIR FROM DBA_TAB_PRIVS
   WHERE GRANTEE='FOCUSPLATFORM' AND OWNER='SYS'
     AND TABLE_NAME='DATA_PUMP_DIR'
     AND PRIVILEGE IN ('READ','WRITE');
  SELECT COUNT(*) INTO L_READER FROM DBA_USERS
   WHERE USERNAME='OAC_FOCUS_READER' AND ACCOUNT_STATUS='OPEN';
  SELECT COUNT(*) INTO L_READER_GRANT FROM DBA_SCHEMA_PRIVS
   WHERE GRANTEE='OAC_FOCUS_READER' AND SCHEMA='FOCUSPLATFORM'
     AND PRIVILEGE='SELECT ANY TABLE' AND ADMIN_OPTION='NO';

  DBMS_OUTPUT.PUT_LINE('user=' || L_USER || ' roles=' || L_ROLES ||
    ' direct=' || L_DIRECT || ' cloud=' || L_CLOUD ||
    ' pipeline=' || L_PIPELINE || ' quota=' || L_QUOTA ||
    ' admin_principal=' || L_ADMIN_PRINCIPAL ||
    ' principal=' || L_PRINCIPAL || ' mview_access=' || L_MVIEW_ACCESS ||
    ' oac_direct_ddl=' || L_OAC_DDL || ' copy_dir=' || L_COPY_DIR ||
    ' oac_reader=' || L_READER || ' oac_reader_grant=' || L_READER_GRANT);
  IF L_USER <> 1 OR L_ROLES <> 2 OR L_DIRECT <> 4 OR L_CLOUD = 0 OR
     L_PIPELINE = 0 OR L_QUOTA <> 1 OR L_ADMIN_PRINCIPAL <> 1 OR
     L_PRINCIPAL = 0 OR
     L_MVIEW_ACCESS = 0 OR L_OAC_DDL <> 4 OR L_COPY_DIR <> 2 OR
     L_READER <> 1 OR L_READER_GRANT <> 1 THEN
    RAISE_APPLICATION_ERROR(-20902, 'FOCUSPLATFORM schema verification failed');
  END IF;
  DBMS_OUTPUT.PUT_LINE('FOCUSPLATFORM SCHEMA VERIFICATION PASS');
END;
