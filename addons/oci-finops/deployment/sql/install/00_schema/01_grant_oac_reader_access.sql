-- Run as ADMIN after FOCUSPLATFORM and OAC_FOCUS_READER exist.
-- See design/00-schema-bootstrap.md for the reader access contract.
SET ECHO OFF VERIFY OFF DEFINE OFF SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE
WHENEVER OSERROR EXIT FAILURE

DECLARE
  l_count PLS_INTEGER;
BEGIN
  IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'ADMIN' THEN
    RAISE_APPLICATION_ERROR(-20001, 'Run this script as ADMIN.');
  END IF;
  SELECT COUNT(*) INTO l_count FROM DBA_USERS
  WHERE USERNAME IN ('FOCUSPLATFORM', 'OAC_FOCUS_READER');
  IF l_count <> 2 THEN
    RAISE_APPLICATION_ERROR(-20002, 'Create FOCUSPLATFORM and OAC_FOCUS_READER first.');
  END IF;
END;
/

GRANT SELECT ANY TABLE ON SCHEMA FOCUSPLATFORM TO OAC_FOCUS_READER;

DECLARE
  l_count PLS_INTEGER;
BEGIN
  SELECT COUNT(*) INTO l_count FROM DBA_SCHEMA_PRIVS
  WHERE GRANTEE = 'OAC_FOCUS_READER'
    AND SCHEMA = 'FOCUSPLATFORM'
    AND PRIVILEGE = 'SELECT ANY TABLE'
    AND ADMIN_OPTION = 'NO';
  IF l_count <> 1 THEN
    RAISE_APPLICATION_ERROR(-20003, 'Expected schema read grant without ADMIN OPTION.');
  END IF;
  DBMS_OUTPUT.PUT_LINE('OAC READER SCHEMA ACCESS PASS');
END;
/
