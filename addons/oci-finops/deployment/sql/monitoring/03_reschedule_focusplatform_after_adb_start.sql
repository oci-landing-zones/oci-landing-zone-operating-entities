-- Run as FOCUSPLATFORM after the database has restarted. This reschedules the
-- existing jobs in the configured installation time zone; it creates no job.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 220 PAGESIZE 100 TRIMSPOOL ON
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
  L_FOUND   PLS_INTEGER;
  L_RUNNING PLS_INTEGER;
  L_TIME_ZONE VARCHAR2(64);
BEGIN
  SELECT TIME_ZONE INTO L_TIME_ZONE
    FROM FINOPS_CORE_SCHEDULE_CONFIG WHERE CONFIG_ID=1;
  SELECT COUNT(*) INTO L_FOUND
    FROM USER_SCHEDULER_JOBS
   WHERE JOB_NAME IN ('OCI_TAG_CATALOG_DAILY',
                      'OCI_ACCOUNT_CONTEXT_DAILY',
                      'OAC_OCI_FOCUS_COST_DETAIL_REFRESH_2H')
     AND ENABLED = 'TRUE';
  SELECT COUNT(*) INTO L_RUNNING
    FROM USER_SCHEDULER_RUNNING_JOBS
   WHERE JOB_NAME IN ('OCI_TAG_CATALOG_DAILY',
                      'OCI_ACCOUNT_CONTEXT_DAILY',
                      'OAC_OCI_FOCUS_COST_DETAIL_REFRESH_2H');
  IF L_FOUND <> 3 OR L_RUNNING <> 0 THEN
    RAISE_APPLICATION_ERROR(-20981,
      'Expected three enabled, idle FOCUSPLATFORM jobs; found='||L_FOUND||
      ' running='||L_RUNNING);
  END IF;

  DBMS_SCHEDULER.SET_ATTRIBUTE(
    NAME => 'OCI_TAG_CATALOG_DAILY',
    ATTRIBUTE => 'start_date',
    VALUE => FINOPS_CORE_SCHEDULE_API.LOCAL_START_DATE());
  DBMS_SCHEDULER.SET_ATTRIBUTE(
    NAME => 'OCI_TAG_CATALOG_DAILY',
    ATTRIBUTE => 'repeat_interval',
    VALUE => 'FREQ=DAILY;BYHOUR=03;BYMINUTE=00;BYSECOND=00');

  DBMS_SCHEDULER.SET_ATTRIBUTE(
    NAME => 'OCI_ACCOUNT_CONTEXT_DAILY',
    ATTRIBUTE => 'start_date',
    VALUE => FINOPS_CORE_SCHEDULE_API.LOCAL_START_DATE());
  DBMS_SCHEDULER.SET_ATTRIBUTE(
    NAME => 'OCI_ACCOUNT_CONTEXT_DAILY',
    ATTRIBUTE => 'repeat_interval',
    VALUE => 'FREQ=DAILY;BYHOUR=03;BYMINUTE=15;BYSECOND=00');

  DBMS_SCHEDULER.SET_ATTRIBUTE(
    NAME => 'OAC_OCI_FOCUS_COST_DETAIL_REFRESH_2H',
    ATTRIBUTE => 'start_date',
    VALUE => FINOPS_CORE_SCHEDULE_API.LOCAL_START_DATE());
  DBMS_SCHEDULER.SET_ATTRIBUTE(
    NAME => 'OAC_OCI_FOCUS_COST_DETAIL_REFRESH_2H',
    ATTRIBUTE => 'repeat_interval',
    VALUE => 'FREQ=HOURLY;INTERVAL=2;BYMINUTE=30;BYSECOND=00');
  DBMS_OUTPUT.PUT_LINE('FOCUSPLATFORM POST-START RESCHEDULE APPLIED in '||L_TIME_ZONE);
END;
/

COLUMN JOB_NAME FORMAT A47
COLUMN ENABLED FORMAT A7
COLUMN STATE FORMAT A12
COLUMN REPEAT_INTERVAL FORMAT A55
COLUMN START_ZONE FORMAT A24
COLUMN NEXT_RUN FORMAT A30
SELECT JOB_NAME, ENABLED, STATE, REPEAT_INTERVAL,
       TO_CHAR(START_DATE,'TZR') START_ZONE,
       TO_CHAR(NEXT_RUN_DATE,'YYYY-MM-DD HH24:MI TZH:TZM') NEXT_RUN
  FROM USER_SCHEDULER_JOBS
 WHERE JOB_NAME IN ('OCI_TAG_CATALOG_DAILY',
                    'OCI_ACCOUNT_CONTEXT_DAILY',
                    'OAC_OCI_FOCUS_COST_DETAIL_REFRESH_2H')
 ORDER BY JOB_NAME;

DECLARE
  L_VALID PLS_INTEGER;
  L_TIME_ZONE VARCHAR2(64);
BEGIN
  SELECT UPPER(TIME_ZONE) INTO L_TIME_ZONE
    FROM FINOPS_CORE_SCHEDULE_CONFIG WHERE CONFIG_ID=1;
  SELECT COUNT(*) INTO L_VALID
    FROM USER_SCHEDULER_JOBS
   WHERE ENABLED = 'TRUE'
     AND UPPER(TO_CHAR(START_DATE,'TZR')) = L_TIME_ZONE
     AND ((JOB_NAME = 'OCI_TAG_CATALOG_DAILY' AND
           REPEAT_INTERVAL = 'FREQ=DAILY;BYHOUR=03;BYMINUTE=00;BYSECOND=00')
       OR (JOB_NAME = 'OCI_ACCOUNT_CONTEXT_DAILY' AND
           REPEAT_INTERVAL = 'FREQ=DAILY;BYHOUR=03;BYMINUTE=15;BYSECOND=00')
       OR (JOB_NAME = 'OAC_OCI_FOCUS_COST_DETAIL_REFRESH_2H' AND
           REPEAT_INTERVAL = 'FREQ=HOURLY;INTERVAL=2;BYMINUTE=30;BYSECOND=00'));
  IF L_VALID <> 3 THEN
    RAISE_APPLICATION_ERROR(-20982,
      'Post-start schedule verification failed; valid jobs='||L_VALID);
  END IF;
  DBMS_OUTPUT.PUT_LINE('FOCUSPLATFORM POST-START SCHEDULE PASS in '||L_TIME_ZONE);
END;
/
