-- Read-only OCI Identity inventory. The local catalog retains retired entries.
SET DEFINE OFF SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE OR REPLACE PROCEDURE OCI_TAG_SYNC_CATALOG AUTHID DEFINER AS
  L_REGION VARCHAR2(64);
  L_TENANCY VARCHAR2(512);
  L_BASE VARCHAR2(500);
  L_URI VARCHAR2(4000);
  L_PAGE VARCHAR2(1000);
  L_NS_PAGE VARCHAR2(1000);
  L_NS_ID VARCHAR2(255);
  L_RESPONSE DBMS_CLOUD_TYPES.RESP;
  L_HEADERS JSON_OBJECT_T;
  L_NAMESPACES JSON_ARRAY_T;
  L_TAGS JSON_ARRAY_T;
  L_NAMESPACE JSON_OBJECT_T;
  L_TAG JSON_OBJECT_T;
  L_SEEN_AT TIMESTAMP(6) WITH TIME ZONE := SYSTIMESTAMP;
  L_NS_COUNT NUMBER := 0;
  L_TAG_COUNT NUMBER := 0;

  FUNCTION BOOLEAN_TEXT(P_OBJECT JSON_OBJECT_T, P_KEY VARCHAR2)
    RETURN VARCHAR2 IS
  BEGIN
    IF NOT P_OBJECT.HAS(P_KEY) THEN RETURN NULL; END IF;
    IF P_OBJECT.GET_BOOLEAN(P_KEY) THEN RETURN 'true'; END IF;
    RETURN 'false';
  END;

  PROCEDURE GET_PAGE(P_URI VARCHAR2, P_NEXT_PAGE OUT VARCHAR2,
                     P_CONTENT OUT JSON_ARRAY_T) IS
  BEGIN
    L_RESPONSE := DBMS_CLOUD.SEND_REQUEST(
      CREDENTIAL_NAME => 'OCI' || CHR(36) || 'RESOURCE_PRINCIPAL',
      URI => P_URI, METHOD => DBMS_CLOUD.METHOD_GET, TIMEOUT => 120);
    IF DBMS_CLOUD.GET_RESPONSE_STATUS_CODE(L_RESPONSE) <> 200 THEN
      RAISE_APPLICATION_ERROR(-20940,
        'OCI defined-tag catalog GET failed: HTTP ' ||
        DBMS_CLOUD.GET_RESPONSE_STATUS_CODE(L_RESPONSE) || ' at ' ||
        SUBSTR(P_URI, 1, 1000));
    END IF;
    P_CONTENT := JSON_ARRAY_T.PARSE(DBMS_CLOUD.GET_RESPONSE_TEXT(L_RESPONSE));
    L_HEADERS := DBMS_CLOUD.GET_RESPONSE_HEADERS(L_RESPONSE);
    IF L_HEADERS.HAS('opc-next-page') THEN
      P_NEXT_PAGE := L_HEADERS.GET_STRING('opc-next-page');
    ELSE
      P_NEXT_PAGE := NULL;
    END IF;
  END;

  PROCEDURE SAVE_NAMESPACE(P_NAMESPACE JSON_OBJECT_T) IS
    L_NAME VARCHAR2(100) := P_NAMESPACE.GET_STRING('name');
    L_DESCRIPTION VARCHAR2(400) := P_NAMESPACE.GET_STRING('description');
    L_STATE VARCHAR2(30) := P_NAMESPACE.GET_STRING('lifecycleState');
    L_RETIRED VARCHAR2(5) := BOOLEAN_TEXT(P_NAMESPACE,'isRetired');
    L_CREATED VARCHAR2(40) := P_NAMESPACE.GET_STRING('timeCreated');
    L_UPDATED VARCHAR2(40) := P_NAMESPACE.GET_STRING('timeUpdated');
  BEGIN
    L_NS_ID := P_NAMESPACE.GET_STRING('id');
    IF L_NS_ID IS NULL OR L_NAME IS NULL THEN
      RAISE_APPLICATION_ERROR(-20941, 'OCI returned a namespace without id/name');
    END IF;
    MERGE INTO OCI_TAG_NAMESPACE D
    USING (SELECT L_NS_ID ID, L_NAME NAME,
                  L_DESCRIPTION DESCRIPTION,
                  L_STATE STATE,
                  L_RETIRED RETIRED,L_CREATED CREATED,L_UPDATED UPDATED
             FROM DUAL) S
    ON (D.TAG_NAMESPACE_ID = S.ID)
    WHEN MATCHED THEN UPDATE SET
      D.NAMESPACE_NAME = S.NAME, D.DESCRIPTION = S.DESCRIPTION,
      D.LIFECYCLE_STATE = S.STATE, D.IS_RETIRED = S.RETIRED,
      D.OCI_TIME_CREATED = S.CREATED, D.OCI_TIME_UPDATED = S.UPDATED,
      D.IS_CURRENT = 'Y', D.LAST_SEEN_AT = L_SEEN_AT,
      D.NO_LONGER_SEEN_AT = NULL
    WHEN NOT MATCHED THEN INSERT
      (TAG_NAMESPACE_ID,NAMESPACE_NAME,DESCRIPTION,LIFECYCLE_STATE,
       IS_RETIRED,OCI_TIME_CREATED,OCI_TIME_UPDATED,IS_CURRENT,
       FIRST_SEEN_AT,LAST_SEEN_AT)
    VALUES (S.ID,S.NAME,S.DESCRIPTION,S.STATE,S.RETIRED,
            S.CREATED,S.UPDATED,'Y',
            L_SEEN_AT,L_SEEN_AT);
    L_NS_COUNT := L_NS_COUNT + 1;
  END;

  PROCEDURE SAVE_TAG(P_TAG JSON_OBJECT_T) IS
    L_NAME VARCHAR2(100) := P_TAG.GET_STRING('name');
    L_DESCRIPTION VARCHAR2(400) := P_TAG.GET_STRING('description');
    L_STATE VARCHAR2(30) := P_TAG.GET_STRING('lifecycleState');
    L_RETIRED VARCHAR2(5) := BOOLEAN_TEXT(P_TAG,'isRetired');
    L_COST_TRACKING VARCHAR2(5) := BOOLEAN_TEXT(P_TAG,'isCostTracking');
    L_CREATED VARCHAR2(40) := P_TAG.GET_STRING('timeCreated');
    L_UPDATED VARCHAR2(40) := P_TAG.GET_STRING('timeUpdated');
  BEGIN
    IF L_NAME IS NULL THEN
      RAISE_APPLICATION_ERROR(-20942, 'OCI returned a tag without name');
    END IF;
    MERGE INTO OCI_TAG_DEFINITION D
    USING (SELECT L_NS_ID NS_ID, L_NAME NAME,
                  L_DESCRIPTION DESCRIPTION,
                  L_STATE STATE,
                  L_RETIRED RETIRED,
                  L_COST_TRACKING COST_TRACKING,
                  L_CREATED CREATED,L_UPDATED UPDATED
             FROM DUAL) S
    ON (D.TAG_NAMESPACE_ID = S.NS_ID AND D.TAG_NAME = S.NAME)
    WHEN MATCHED THEN UPDATE SET
      D.DESCRIPTION = S.DESCRIPTION, D.LIFECYCLE_STATE = S.STATE,
      D.IS_RETIRED = S.RETIRED, D.IS_COST_TRACKING = S.COST_TRACKING,
      D.OCI_TIME_CREATED = S.CREATED, D.OCI_TIME_UPDATED = S.UPDATED,
      D.IS_CURRENT = 'Y', D.LAST_SEEN_AT = L_SEEN_AT,
      D.NO_LONGER_SEEN_AT = NULL
    WHEN NOT MATCHED THEN INSERT
      (TAG_NAMESPACE_ID,TAG_NAME,DESCRIPTION,LIFECYCLE_STATE,IS_RETIRED,
       IS_COST_TRACKING,OCI_TIME_CREATED,OCI_TIME_UPDATED,IS_CURRENT,
       FIRST_SEEN_AT,LAST_SEEN_AT)
    VALUES (S.NS_ID,S.NAME,S.DESCRIPTION,S.STATE,S.RETIRED,
            S.COST_TRACKING,S.CREATED,S.UPDATED,'Y',L_SEEN_AT,L_SEEN_AT);
    L_TAG_COUNT := L_TAG_COUNT + 1;
  END;
BEGIN
  SELECT LOWER(JSON_VALUE(CLOUD_IDENTITY, '$.TENANT_OCID')),
         LOWER(JSON_VALUE(CLOUD_IDENTITY, '$.REGION'))
    INTO L_TENANCY, L_REGION
    FROM V$PDBS
   WHERE CON_ID = TO_NUMBER(SYS_CONTEXT('USERENV','CON_ID'));
  IF NOT REGEXP_LIKE(L_TENANCY, '^ocid1\.tenancy\.') OR
     NOT REGEXP_LIKE(L_REGION, '^[a-z0-9]+(-[a-z0-9]+)+$') THEN
    RAISE_APPLICATION_ERROR(-20943,
      'V$PDBS.CLOUD_IDENTITY lacks a valid tenancy OCID or region');
  END IF;
  L_BASE := 'https://identity.' || L_REGION ||
            '.oci.'||FINOPS_CORE_ENDPOINT_DOMAIN()||'/20160918';
  L_NS_PAGE := NULL;
  LOOP
    L_URI := L_BASE || '/tagNamespaces?compartmentId=' ||
      UTL_URL.ESCAPE(L_TENANCY, TRUE, 'AL32UTF8') ||
      '&includeSubcompartments=true&limit=1000';
    IF L_NS_PAGE IS NOT NULL THEN
      L_URI := L_URI || '&page=' ||
        UTL_URL.ESCAPE(L_NS_PAGE, TRUE, 'AL32UTF8');
    END IF;
    GET_PAGE(L_URI,L_NS_PAGE,L_NAMESPACES);
    FOR I IN 0 .. L_NAMESPACES.GET_SIZE - 1 LOOP
      L_NAMESPACE := TREAT(L_NAMESPACES.GET(I) AS JSON_OBJECT_T);
      SAVE_NAMESPACE(L_NAMESPACE);
      L_PAGE := NULL;
      LOOP
        L_URI := L_BASE || '/tagNamespaces/' ||
          UTL_URL.ESCAPE(L_NS_ID, TRUE, 'AL32UTF8') || '/tags?limit=1000';
        IF L_PAGE IS NOT NULL THEN
          L_URI := L_URI || '&page=' ||
            UTL_URL.ESCAPE(L_PAGE, TRUE, 'AL32UTF8');
        END IF;
        GET_PAGE(L_URI,L_PAGE,L_TAGS);
        FOR J IN 0 .. L_TAGS.GET_SIZE - 1 LOOP
          L_TAG := TREAT(L_TAGS.GET(J) AS JSON_OBJECT_T);
          SAVE_TAG(L_TAG);
        END LOOP;
        EXIT WHEN L_PAGE IS NULL;
      END LOOP;
    END LOOP;
    EXIT WHEN L_NS_PAGE IS NULL;
  END LOOP;
  UPDATE OCI_TAG_DEFINITION SET IS_CURRENT='N',
    NO_LONGER_SEEN_AT=COALESCE(NO_LONGER_SEEN_AT,L_SEEN_AT)
   WHERE LAST_SEEN_AT < L_SEEN_AT;
  UPDATE OCI_TAG_NAMESPACE SET IS_CURRENT='N',
    NO_LONGER_SEEN_AT=COALESCE(NO_LONGER_SEEN_AT,L_SEEN_AT)
   WHERE LAST_SEEN_AT < L_SEEN_AT;
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('catalog_namespaces_seen=' || L_NS_COUNT ||
    ' catalog_defined_tags_seen=' || L_TAG_COUNT);
EXCEPTION WHEN OTHERS THEN
  ROLLBACK;
  RAISE;
END;
