-- Run as FOCUSPLATFORM from deployment/sql/install. Uses OCI Usage API native forecast.
SET ECHO OFF VERIFY OFF DEFINE OFF FEEDBACK ON SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 190 PAGESIZE 100
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
PROMPT OCI NATIVE FORECAST INSTALLATION

DECLARE N NUMBER; C NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'FOCUSPLATFORM' THEN
    RAISE_APPLICATION_ERROR(-20760,'Connect as FOCUSPLATFORM');
  END IF;
  SELECT COUNT(*) INTO C FROM USER_OBJECTS
   WHERE OBJECT_NAME='FINOPS_CORE_RUN_DAILY' AND STATUS='VALID';
  SELECT COUNT(*) INTO N FROM USER_OBJECTS
   WHERE OBJECT_NAME LIKE 'OCI_FORECAST_%' OR OBJECT_NAME='OCI_SYNC_FORECAST';
  IF C<>1 OR N<>0 THEN
    RAISE_APPLICATION_ERROR(-20760,
      'Install common core first; forecast module must be clean');
  END IF;
  DBMS_OUTPUT.PUT_LINE('Native forecast module preflight passed');
END;
/

@02_providers/OCI/06_forecast/internal/00_preflight_oci_forecast_source.sql
@02_providers/OCI/06_forecast/internal/01_create_oci_forecast_model.sql

INSERT INTO OCI_FORECAST_CONFIG(CONFIG_ID,TENANCY_OCID,ENDPOINT_REGION,ENDPOINT_DOMAIN,IS_SYNC_ENABLED)
VALUES(1,:source_tenancy_ocid,:source_home_region,FINOPS_CORE_ENDPOINT_DOMAIN(),'Y');
COMMIT;

@02_providers/OCI/06_forecast/internal/02_create_oci_forecast_sync.sql

BEGIN
  DBMS_SCHEDULER.CREATE_JOB(
    JOB_NAME=>'OCI_FORECAST_DAILY',JOB_TYPE=>'STORED_PROCEDURE',
    JOB_ACTION=>'OCI_SYNC_FORECAST',
    START_DATE=>FINOPS_CORE_SCHEDULE_API.LOCAL_START_DATE(),
    REPEAT_INTERVAL=>'FREQ=DAILY;BYHOUR=07;BYMINUTE=15;BYSECOND=00',
    ENABLED=>TRUE,COMMENTS=>'OCI Usage API daily actuals and native forecast');
END;
/

@02_providers/OCI/06_forecast/verify/06_verify_oci_forecast.sql

BEGIN
  DBMS_SCHEDULER.RUN_JOB('OCI_FORECAST_DAILY',USE_CURRENT_SESSION=>FALSE);
  DBMS_OUTPUT.PUT_LINE('Initial native forecast sync requested in background');
END;
/
DECLARE N NUMBER;
BEGIN
  FOR I IN 1..12 LOOP
    SELECT COUNT(*) INTO N FROM USER_SCHEDULER_JOB_RUN_DETAILS
     WHERE JOB_NAME='OCI_FORECAST_DAILY';
    EXIT WHEN N>0;
    DBMS_LOCK.SLEEP(5);
  END LOOP;
END;
/
