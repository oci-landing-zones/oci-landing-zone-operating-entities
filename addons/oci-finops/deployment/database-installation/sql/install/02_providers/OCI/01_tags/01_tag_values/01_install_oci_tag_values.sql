DECLARE
  L_CATALOG NUMBER;
  L_LANDING NUMBER;
  L_EXISTING NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'FOCUSPLATFORM' THEN
    RAISE_APPLICATION_ERROR(-20965,'Connect as FOCUSPLATFORM');
  END IF;
  SELECT COUNT(*) INTO L_CATALOG FROM USER_OBJECTS
   WHERE (OBJECT_NAME='OCI_TAG_SYNC_CATALOG' AND OBJECT_TYPE='PROCEDURE'
       OR OBJECT_NAME='OCI_TAG_PROFILE_API'
          AND OBJECT_TYPE IN ('PACKAGE','PACKAGE BODY'))
     AND STATUS='VALID';
  SELECT COUNT(*) INTO L_LANDING FROM USER_TABLES
   WHERE TABLE_NAME='OCI_FOCUS_REPORTS';
  SELECT COUNT(*) INTO L_EXISTING FROM USER_OBJECTS
   WHERE OBJECT_NAME LIKE 'OCI_TAG_VALUE%';
  IF L_CATALOG<>3 OR L_LANDING<>1 OR L_EXISTING<>0 THEN
    RAISE_APPLICATION_ERROR(-20966,
      'Verify OCI ingestion/catalog and a clean tag-value module first');
  END IF;
  DBMS_OUTPUT.PUT_LINE('Landing, catalog and clean optional module preflight passed');
END;
