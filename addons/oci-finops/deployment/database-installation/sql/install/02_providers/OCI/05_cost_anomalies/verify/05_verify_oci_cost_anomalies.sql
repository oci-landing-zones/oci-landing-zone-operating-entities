-- Read-only structural gate; asynchronous source run is checked separately.
SET VERIFY OFF DEFINE OFF SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 190 PAGESIZE 100
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
PROMPT === OCI Cost Anomaly objects ===
COLUMN OBJECT_TYPE FORMAT A18
COLUMN OBJECT_NAME FORMAT A44
COLUMN STATUS FORMAT A10
SELECT OBJECT_TYPE,OBJECT_NAME,STATUS FROM USER_OBJECTS
 WHERE OBJECT_NAME LIKE 'OCI_ANOMALY_%' OR OBJECT_NAME='OCI_SYNC_ANOMALIES'
 ORDER BY OBJECT_TYPE,OBJECT_NAME;
PROMPT === OCI Cost Anomaly schedule ===
COLUMN JOB_NAME FORMAT A28
COLUMN REPEAT_INTERVAL FORMAT A62
SELECT JOB_NAME,ENABLED,REPEAT_INTERVAL FROM USER_SCHEDULER_JOBS
 WHERE JOB_NAME='OCI_ANOMALY_DAILY';
DECLARE T NUMBER; V NUMBER; P NUMBER; J NUMBER; C NUMBER; I NUMBER;
BEGIN
  SELECT COUNT(*) INTO T FROM USER_OBJECTS WHERE OBJECT_TYPE='TABLE'
    AND OBJECT_NAME LIKE 'OCI_ANOMALY_%';
  SELECT COUNT(*) INTO V FROM USER_OBJECTS WHERE OBJECT_TYPE='VIEW'
    AND OBJECT_NAME LIKE 'OCI_ANOMALY_%';
  SELECT COUNT(*) INTO P FROM USER_OBJECTS WHERE OBJECT_TYPE='PROCEDURE'
    AND OBJECT_NAME='OCI_SYNC_ANOMALIES' AND STATUS='VALID';
  SELECT COUNT(*) INTO J FROM USER_SCHEDULER_JOBS
    WHERE JOB_NAME='OCI_ANOMALY_DAILY' AND ENABLED='TRUE'
      AND REPEAT_INTERVAL='FREQ=DAILY;BYHOUR=06;BYMINUTE=15;BYSECOND=00';
  SELECT COUNT(*) INTO C FROM OCI_ANOMALY_CONFIG
    WHERE IS_SYNC_ENABLED='Y' AND TENANCY_OCID LIKE 'ocid1.tenancy.%';
  SELECT COUNT(*) INTO I FROM USER_OBJECTS WHERE STATUS<>'VALID'
    AND (OBJECT_NAME LIKE 'OCI_ANOMALY_%' OR OBJECT_NAME='OCI_SYNC_ANOMALIES');
  DBMS_OUTPUT.PUT_LINE('tables='||T||' views='||V||' valid_procedure='||P||
    ' enabled_job='||J||' source_rows='||C||' invalid='||I);
  IF T<>4 OR V<>4 OR P<>1 OR J<>1 OR C<>1 OR I<>0 THEN
    RAISE_APPLICATION_ERROR(-20751,'OCI Cost Anomaly installation gate failed');
  END IF;
  DBMS_OUTPUT.PUT_LINE('OCI COST ANOMALY VERIFICATION PASS');
END;
