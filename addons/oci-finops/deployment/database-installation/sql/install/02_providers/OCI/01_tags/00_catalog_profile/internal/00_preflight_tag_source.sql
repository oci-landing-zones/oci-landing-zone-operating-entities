-- Read-only validation of the supplied tag profile before any module DDL.
SET DEFINE OFF SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
  L_REALM_DOMAIN VARCHAR2(255) := JSON_VALUE(:fp_install_config,'$.oci_realm_domain' ERROR ON ERROR);
  S JSON_OBJECT_T := JSON_OBJECT_T.PARSE(JSON_QUERY(:fp_install_config,'$.tag_profile' RETURNING CLOB ERROR ON ERROR));
  A JSON_ARRAY_T; O JSON_OBJECT_T;
  L_MODE VARCHAR2(20); L_NS VARCHAR2(100); L_TAG VARCHAR2(100);
  L_TENANCY VARCHAR2(512); L_REGION VARCHAR2(64); L_BASE VARCHAR2(1000);
  L_URI VARCHAR2(4000); L_NS_ID VARCHAR2(255);
  L_NS_PAGE VARCHAR2(4000); L_PAGE VARCHAR2(4000);
  L_NAMESPACES JSON_ARRAY_T; L_TAGS JSON_ARRAY_T; L_ITEM JSON_OBJECT_T;
  L_REQUESTED NUMBER:=0; L_MATCHED NUMBER:=0; L_NS_TAGS NUMBER;
  TYPE FLAGS IS TABLE OF BOOLEAN INDEX BY VARCHAR2(512);
  NEEDED FLAGS; SEEN_NS FLAGS; REQUESTED FLAGS; FOUND FLAGS;
  K VARCHAR2(512);
  PROCEDURE GET_PAGE(P_URI VARCHAR2,P_NEXT OUT VARCHAR2,P_ITEMS OUT JSON_ARRAY_T) IS
    R DBMS_CLOUD_TYPES.RESP; H JSON_OBJECT_T;
  BEGIN
    R:=DBMS_CLOUD.SEND_REQUEST(CREDENTIAL_NAME=>'OCI$RESOURCE_PRINCIPAL',URI=>P_URI,METHOD=>DBMS_CLOUD.METHOD_GET,TIMEOUT=>120);
    IF DBMS_CLOUD.GET_RESPONSE_STATUS_CODE(R)<>200 THEN
      RAISE_APPLICATION_ERROR(-20933,'Tag catalog HTTP '||DBMS_CLOUD.GET_RESPONSE_STATUS_CODE(R));
    END IF;
    P_ITEMS:=JSON_ARRAY_T.PARSE(DBMS_CLOUD.GET_RESPONSE_TEXT(R));
    H:=DBMS_CLOUD.GET_RESPONSE_HEADERS(R);
    P_NEXT:=NULL;
    IF H.HAS('opc-next-page') THEN P_NEXT:=H.GET_STRING('opc-next-page'); END IF;
  END;
BEGIN
  IF L_REALM_DOMAIN IS NULL OR
     NOT REGEXP_LIKE(L_REALM_DOMAIN,'^[a-z0-9]+([.-][a-z0-9]+)*$') THEN
    RAISE_APPLICATION_ERROR(-20990,'Missing or invalid tenancy realm domain; run Python configuration');
  END IF;
  S.ON_ERROR(1); L_MODE:=S.GET_STRING('mode');
  IF S.GET_NUMBER('schema_version')<>1 OR S.GET_STRING('profile_name') IS NULL OR
     NOT REGEXP_LIKE(S.GET_STRING('profile_name'),'^[A-Z][A-Z0-9_]{0,127}$','c') OR
     L_MODE NOT IN ('NAMESPACE','TAG_LIST') THEN
    RAISE_APPLICATION_ERROR(-20934,'Invalid version, profile name or tag selection mode');
  END IF;
  IF L_MODE='NAMESPACE' THEN
    IF S.HAS('tags') THEN RAISE_APPLICATION_ERROR(-20934,'Use namespace OR tags'); END IF;
    L_NS:=S.GET_STRING('namespace');
    IF L_NS IS NULL THEN RAISE_APPLICATION_ERROR(-20934,'namespace is required'); END IF;
    NEEDED(L_NS):=TRUE;
  ELSE
    IF S.HAS('namespace') THEN RAISE_APPLICATION_ERROR(-20934,'Use namespace OR tags'); END IF;
    A:=S.GET_ARRAY('tags');
    FOR I IN 0..A.GET_SIZE-1 LOOP
      O:=TREAT(A.GET(I) AS JSON_OBJECT_T); O.ON_ERROR(1);
      L_NS:=O.GET_STRING('namespace'); L_TAG:=O.GET_STRING('tag');
      IF L_NS IS NULL OR L_TAG IS NULL THEN RAISE_APPLICATION_ERROR(-20934,'Each tag needs namespace and tag'); END IF;
      K:=L_NS||CHR(1)||L_TAG;
      IF REQUESTED.EXISTS(K) THEN RAISE_APPLICATION_ERROR(-20934,'Duplicate requested tag'); END IF;
      REQUESTED(K):=TRUE; NEEDED(L_NS):=TRUE; L_REQUESTED:=L_REQUESTED+1;
    END LOOP;
    IF L_REQUESTED=0 OR L_REQUESTED>9999 THEN RAISE_APPLICATION_ERROR(-20934,'Select 1 to 9999 tags'); END IF;
  END IF;
  IF JSON_VALUE(:fp_install_config,'$.installation_mode')='LANDING_ZONE' AND
     (L_MODE<>'NAMESPACE' OR S.GET_STRING('namespace')<>'tagns-lz-cost-governance' OR
      S.GET_STRING('profile_name')<>'DEFAULT_COST_GOVERNANCE') THEN
    RAISE_APPLICATION_ERROR(-20934,'Landing Zone installation requires its governance profile');
  END IF;
  SELECT LOWER(JSON_VALUE(CLOUD_IDENTITY,'$.TENANT_OCID')),LOWER(JSON_VALUE(CLOUD_IDENTITY,'$.REGION'))
    INTO L_TENANCY,L_REGION FROM V$PDBS WHERE CON_ID=TO_NUMBER(SYS_CONTEXT('USERENV','CON_ID'));
  L_BASE:='https://identity.'||L_REGION||'.oci.'||L_REALM_DOMAIN||'/20160918';
  LOOP
    L_URI:=L_BASE||'/tagNamespaces?compartmentId='||UTL_URL.ESCAPE(L_TENANCY,TRUE,'AL32UTF8')||
      '&includeSubcompartments=true&limit=1000';
    IF L_NS_PAGE IS NOT NULL THEN L_URI:=L_URI||'&page='||UTL_URL.ESCAPE(L_NS_PAGE,TRUE,'AL32UTF8'); END IF;
    GET_PAGE(L_URI,L_NS_PAGE,L_NAMESPACES);
    FOR I IN 0..L_NAMESPACES.GET_SIZE-1 LOOP
      L_ITEM:=TREAT(L_NAMESPACES.GET(I) AS JSON_OBJECT_T); L_NS:=L_ITEM.GET_STRING('name');
      IF NEEDED.EXISTS(L_NS) AND L_ITEM.GET_STRING('lifecycleState')='ACTIVE' THEN
        IF SEEN_NS.EXISTS(L_NS) THEN RAISE_APPLICATION_ERROR(-20935,'Ambiguous namespace name: '||L_NS); END IF;
        SEEN_NS(L_NS):=TRUE; L_NS_ID:=L_ITEM.GET_STRING('id'); L_PAGE:=NULL; L_NS_TAGS:=0;
        LOOP
          L_URI:=L_BASE||'/tagNamespaces/'||UTL_URL.ESCAPE(L_NS_ID,TRUE,'AL32UTF8')||'/tags?limit=1000';
          IF L_PAGE IS NOT NULL THEN L_URI:=L_URI||'&page='||UTL_URL.ESCAPE(L_PAGE,TRUE,'AL32UTF8'); END IF;
          GET_PAGE(L_URI,L_PAGE,L_TAGS);
          FOR J IN 0..L_TAGS.GET_SIZE-1 LOOP
            L_ITEM:=TREAT(L_TAGS.GET(J) AS JSON_OBJECT_T);
            IF L_ITEM.GET_STRING('lifecycleState')='ACTIVE' THEN
              K:=L_NS||CHR(1)||L_ITEM.GET_STRING('name'); FOUND(K):=TRUE; L_NS_TAGS:=L_NS_TAGS+1;
              IF REQUESTED.EXISTS(K) THEN L_MATCHED:=L_MATCHED+1; END IF;
            END IF;
          END LOOP;
          EXIT WHEN L_PAGE IS NULL;
        END LOOP;
        IF L_MODE='NAMESPACE' AND L_NS_TAGS=0 THEN RAISE_APPLICATION_ERROR(-20936,'Selected namespace has no active tags'); END IF;
      END IF;
    END LOOP;
    EXIT WHEN L_NS_PAGE IS NULL;
  END LOOP;
  K:=NEEDED.FIRST;
  WHILE K IS NOT NULL LOOP
    IF NOT SEEN_NS.EXISTS(K) THEN RAISE_APPLICATION_ERROR(-20935,'Missing active namespace: '||K); END IF;
    K:=NEEDED.NEXT(K);
  END LOOP;
  IF L_MODE='TAG_LIST' AND L_MATCHED<>L_REQUESTED THEN RAISE_APPLICATION_ERROR(-20936,'Requested tag is missing or inactive'); END IF;
  IF S.GET_STRING('profile_name')='DEFAULT_COST_GOVERNANCE' THEN
    IF L_MODE<>'NAMESPACE' OR S.GET_STRING('namespace')<>'tagns-lz-cost-governance' THEN
      RAISE_APPLICATION_ERROR(-20936,'Reserved governance profile identity');
    END IF;
    FOR R IN (SELECT 'tag-lz-cost-center' NAME FROM DUAL UNION ALL SELECT 'tag-lz-platform' FROM DUAL
      UNION ALL SELECT 'tag-lz-environment' FROM DUAL UNION ALL SELECT 'tag-lz-owner' FROM DUAL
      UNION ALL SELECT 'tag-lz-business-unit' FROM DUAL UNION ALL SELECT 'tag-lz-project' FROM DUAL) LOOP
      IF NOT FOUND.EXISTS('tagns-lz-cost-governance'||CHR(1)||R.NAME) THEN
        RAISE_APPLICATION_ERROR(-20936,'Governance profile lacks required tag: '||R.NAME);
      END IF;
    END LOOP;
  END IF;
  DBMS_OUTPUT.PUT_LINE('OCI tag source preflight passed');
END;
