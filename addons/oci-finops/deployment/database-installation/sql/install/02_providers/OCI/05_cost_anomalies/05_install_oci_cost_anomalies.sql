-- Run as FOCUSPLATFORM from deployment/database-installation/sql/install. Reads native OCI anomaly results.
SET ECHO OFF VERIFY OFF DEFINE OFF FEEDBACK ON SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 190 PAGESIZE 100
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
PROMPT OCI COST ANOMALY INSTALLATION

DECLARE N NUMBER; C NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'FOCUSPLATFORM' THEN
    RAISE_APPLICATION_ERROR(-20750,'Connect as FOCUSPLATFORM');
  END IF;
  SELECT COUNT(*) INTO C FROM USER_OBJECTS
   WHERE OBJECT_NAME='FINOPS_CORE_RUN_DAILY' AND STATUS='VALID';
  SELECT COUNT(*) INTO N FROM USER_OBJECTS
   WHERE OBJECT_NAME LIKE 'OCI_ANOMALY_%' OR OBJECT_NAME='OCI_SYNC_ANOMALIES';
  IF C<>1 OR N<>0 THEN
    RAISE_APPLICATION_ERROR(-20750,
      'Install common core first; anomaly module must be clean');
  END IF;
  DBMS_OUTPUT.PUT_LINE('Cost Anomaly module preflight passed');
END;
/

