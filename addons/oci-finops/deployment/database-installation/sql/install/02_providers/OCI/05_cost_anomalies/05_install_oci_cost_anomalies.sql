@02_providers/OCI/05_cost_anomalies/internal/02_create_oci_anomaly_sync.sql

BEGIN
  DBMS_SCHEDULER.CREATE_JOB(
    JOB_NAME=>'OCI_ANOMALY_DAILY',JOB_TYPE=>'STORED_PROCEDURE',
    JOB_ACTION=>'OCI_SYNC_ANOMALIES',
    START_DATE=>FINOPS_CORE_SCHEDULE_API.LOCAL_START_DATE(),
    REPEAT_INTERVAL=>'FREQ=DAILY;BYHOUR=06;BYMINUTE=15;BYSECOND=00',
    ENABLED=>TRUE,COMMENTS=>'Read-only OCI Cost Anomaly observations');
END;
/

