-- Read-only installation gate. Run as FOCUSPLATFORM from deployment/database-installation/sql/install.
SET VERIFY OFF DEFINE OFF SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 190 PAGESIZE 100
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

PROMPT === OCI account and contract objects ===
COLUMN OBJECT_TYPE FORMAT A18
COLUMN OBJECT_NAME FORMAT A46
COLUMN STATUS FORMAT A10
SELECT OBJECT_TYPE,OBJECT_NAME,STATUS FROM USER_OBJECTS
 WHERE (OBJECT_NAME LIKE 'OCI_ACCOUNT_%'
     OR OBJECT_NAME IN ('OCI_SYNC_ACCOUNT_CONTEXT','OCI_SYNC_CONTRACT',
                        'OCI_SYNC_ALL_CONTRACTS'))
   AND OBJECT_TYPE IN ('TABLE','VIEW','PROCEDURE','JOB')
 ORDER BY OBJECT_TYPE,OBJECT_NAME;

PROMPT === Source, jobs and initial run state ===
COLUMN HOME_REGION FORMAT A24
SELECT CONFIG_ID,HOME_REGION,CONTEXT_ENABLED,CONTRACT_ENABLED
  FROM OCI_ACCOUNT_SOURCE;
COLUMN JOB_NAME FORMAT A32
COLUMN REPEAT_INTERVAL FORMAT A65
COLUMN NEXT_RUN FORMAT A25
SELECT JOB_NAME,ENABLED,REPEAT_INTERVAL,
       TO_CHAR(NEXT_RUN_DATE,'YYYY-MM-DD HH24:MI TZH:TZM') NEXT_RUN
  FROM USER_SCHEDULER_JOBS
 WHERE JOB_NAME IN ('OCI_ACCOUNT_CONTEXT_DAILY',
                    'OCI_ACCOUNT_CONTRACT_MONTHLY')
 ORDER BY JOB_NAME;

DECLARE
  L_TABLES NUMBER;
  L_VIEWS NUMBER;
  L_CODE NUMBER;
  L_INVALID NUMBER;
  L_SOURCE NUMBER;
  L_JOBS NUMBER;
  L_BAD_SCHEDULE NUMBER;
  L_BAD_TAGS NUMBER;
BEGIN
  SELECT COUNT(*) INTO L_TABLES FROM USER_OBJECTS
   WHERE OBJECT_TYPE='TABLE' AND OBJECT_NAME IN
     ('OCI_ACCOUNT_SOURCE','OCI_ACCOUNT_CONTEXT_RUN','OCI_ACCOUNT_ENTITY',
      'OCI_ACCOUNT_CONTRACT_CONFIG','OCI_ACCOUNT_CONTRACT_RUN',
      'OCI_ACCOUNT_CONTRACT_SUBSCRIPTION_SNAP',
      'OCI_ACCOUNT_CONTRACT_SERVICE_SNAP',
      'OCI_ACCOUNT_CONTRACT_COMMITMENT_SNAP');
  SELECT COUNT(*) INTO L_VIEWS FROM USER_OBJECTS
   WHERE OBJECT_TYPE='VIEW' AND OBJECT_NAME IN
     ('OCI_ACCOUNT_CURRENT_V','OCI_ACCOUNT_COMPARTMENT_V',
      'OCI_ACCOUNT_REGION_V','OCI_ACCOUNT_CONTEXT_HEALTH_V',
      'OCI_ACCOUNT_CONTRACT_CURRENT_RUN_V',
      'OCI_ACCOUNT_CONTRACT_SUBSCRIPTION_V',
      'OCI_ACCOUNT_CONTRACT_SERVICE_V',
      'OCI_ACCOUNT_CONTRACT_COMMITMENT_V',
      'OCI_ACCOUNT_CONTRACT_HEALTH_V');
  SELECT COUNT(*) INTO L_CODE FROM USER_OBJECTS
   WHERE OBJECT_TYPE='PROCEDURE' AND STATUS='VALID'
     AND OBJECT_NAME IN ('OCI_SYNC_ACCOUNT_CONTEXT','OCI_SYNC_CONTRACT',
                         'OCI_SYNC_ALL_CONTRACTS');
  SELECT COUNT(*) INTO L_INVALID FROM USER_OBJECTS
   WHERE (OBJECT_NAME LIKE 'OCI_ACCOUNT_%'
      OR OBJECT_NAME IN ('OCI_SYNC_ACCOUNT_CONTEXT','OCI_SYNC_CONTRACT',
                         'OCI_SYNC_ALL_CONTRACTS'))
     AND STATUS<>'VALID';
  SELECT COUNT(*) INTO L_SOURCE FROM OCI_ACCOUNT_SOURCE
   WHERE CONFIG_ID=1 AND TENANCY_OCID LIKE 'ocid1.tenancy.%'
     AND REGEXP_LIKE(HOME_REGION,'^[a-z0-9]+(-[a-z0-9]+)+$')
     AND CONTEXT_ENABLED='Y' AND CONTRACT_ENABLED='Y';
  SELECT COUNT(*) INTO L_JOBS FROM USER_SCHEDULER_JOBS
   WHERE JOB_NAME IN ('OCI_ACCOUNT_CONTEXT_DAILY',
                      'OCI_ACCOUNT_CONTRACT_MONTHLY') AND ENABLED='TRUE';
  SELECT COUNT(*) INTO L_BAD_SCHEDULE FROM USER_SCHEDULER_JOBS
   WHERE (JOB_NAME='OCI_ACCOUNT_CONTEXT_DAILY'
      AND REPEAT_INTERVAL<>'FREQ=DAILY;BYHOUR=01;BYMINUTE=00;BYSECOND=00')
      OR (JOB_NAME='OCI_ACCOUNT_CONTRACT_MONTHLY'
      AND REPEAT_INTERVAL<>
        'FREQ=MONTHLY;BYMONTHDAY=1;BYHOUR=04;BYMINUTE=45;BYSECOND=00');
  SELECT COUNT(*) INTO L_BAD_TAGS FROM USER_OBJECTS
   WHERE OBJECT_NAME LIKE 'OCI_ACCOUNT_TAG_DEFAULT%';
  DBMS_OUTPUT.PUT_LINE('tables='||L_TABLES||' views='||L_VIEWS||
    ' valid_procedures='||L_CODE||' invalid='||L_INVALID);
  DBMS_OUTPUT.PUT_LINE('source_config='||L_SOURCE||
    ' enabled_jobs='||L_JOBS||' wrong_schedules='||L_BAD_SCHEDULE||
    ' tag_default_objects='||L_BAD_TAGS);
  IF L_TABLES<>8 OR L_VIEWS<>9 OR L_CODE<>3 OR L_INVALID<>0 OR
     L_SOURCE<>1 OR L_JOBS<>2 OR L_BAD_SCHEDULE<>0 OR L_BAD_TAGS<>0 THEN
    RAISE_APPLICATION_ERROR(-20703,
      'OCI account/contract installation gate failed');
  END IF;
  DBMS_OUTPUT.PUT_LINE('OCI ACCOUNT CONTEXT AND CONTRACT VERIFICATION PASS');
END;
