-- Independent daily context sync. No tag defaults or raw tag payloads.
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE OR REPLACE PROCEDURE OCI_SYNC_ACCOUNT_CONTEXT AUTHID DEFINER AS
  C OCI_ACCOUNT_SOURCE%ROWTYPE;
  L_RUN_ID NUMBER;
  L_BASE VARCHAR2(600);
  L_TENANCY_READ NUMBER := 0;
  L_COMPARTMENTS_READ NUMBER := 0;
  L_REGIONS_READ NUMBER := 0;
  L_CHANGES NUMBER := 0;
  L_UNRESOLVED NUMBER := 0;
  L_LOCKED BOOLEAN := FALSE;
  L_ERROR VARCHAR2(4000);
  TYPE T_SEEN IS TABLE OF BOOLEAN INDEX BY VARCHAR2(600);
  L_SEEN T_SEEN;

  PROCEDURE START_RUN IS
    PRAGMA AUTONOMOUS_TRANSACTION;
  BEGIN
    INSERT INTO OCI_ACCOUNT_CONTEXT_RUN(STATUS) VALUES('RUNNING')
      RETURNING RUN_ID INTO L_RUN_ID;
    COMMIT;
  END;

  PROCEDURE GET_JSON(P_PATH VARCHAR2, P_BODY OUT CLOB,
                     P_HEADERS OUT JSON_OBJECT_T) IS
    L_RESPONSE DBMS_CLOUD_TYPES.RESP;
  BEGIN
    L_RESPONSE := DBMS_CLOUD.SEND_REQUEST(
      CREDENTIAL_NAME=>C.CREDENTIAL_NAME,
      URI=>L_BASE||P_PATH, METHOD=>DBMS_CLOUD.METHOD_GET, TIMEOUT=>120);
    IF DBMS_CLOUD.GET_RESPONSE_STATUS_CODE(L_RESPONSE)<>200 THEN
      RAISE_APPLICATION_ERROR(-20721,'OCI Identity HTTP '||
        DBMS_CLOUD.GET_RESPONSE_STATUS_CODE(L_RESPONSE));
    END IF;
    P_BODY := DBMS_CLOUD.GET_RESPONSE_TEXT(L_RESPONSE);
    P_HEADERS := DBMS_CLOUD.GET_RESPONSE_HEADERS(L_RESPONSE);
  END;

  PROCEDURE RECORD_ITEM(P_KIND VARCHAR2, P_BODY CLOB) IS
    L_OBJ JSON_OBJECT_T;
    L_ID VARCHAR2(512);
    L_PARENT VARCHAR2(512);
    L_NAME VARCHAR2(1000);
    L_STATE VARCHAR2(64);
    L_CREATED TIMESTAMP WITH TIME ZONE;
    L_HOME_KEY VARCHAR2(64);
    L_REGION_KEY VARCHAR2(64);
    L_IS_HOME CHAR(1);
    L_SEEN_KEY VARCHAR2(600);
  BEGIN
    L_OBJ := JSON_OBJECT_T.PARSE(P_BODY);
    IF P_KIND='TENANCY' THEN
      L_ID:=L_OBJ.GET_STRING('id');
      L_NAME:=L_OBJ.GET_STRING('name');
      L_HOME_KEY:=L_OBJ.GET_STRING('homeRegionKey');
      IF L_ID<>C.TENANCY_OCID THEN
        RAISE_APPLICATION_ERROR(-20722,'Tenancy identity mismatch');
      END IF;
      L_TENANCY_READ:=L_TENANCY_READ+1;
    ELSIF P_KIND='COMPARTMENT' THEN
      L_ID:=L_OBJ.GET_STRING('id');
      L_PARENT:=L_OBJ.GET_STRING('compartmentId');
      L_NAME:=L_OBJ.GET_STRING('name');
      L_STATE:=L_OBJ.GET_STRING('lifecycleState');
      L_CREATED:=JSON_VALUE(P_BODY,'$.timeCreated'
        RETURNING TIMESTAMP WITH TIME ZONE ERROR ON ERROR NULL ON EMPTY);
      IF L_PARENT IS NULL OR L_ID=C.TENANCY_OCID THEN
        RAISE_APPLICATION_ERROR(-20722,'Invalid compartment identity');
      END IF;
      L_COMPARTMENTS_READ:=L_COMPARTMENTS_READ+1;
    ELSIF P_KIND='REGION' THEN
      L_ID:=L_OBJ.GET_STRING('regionName');
      L_PARENT:=C.TENANCY_OCID;
      L_NAME:=L_ID;
      L_STATE:=L_OBJ.GET_STRING('status');
      L_REGION_KEY:=L_OBJ.GET_STRING('regionKey');
      IF L_OBJ.HAS('isHomeRegion') THEN
        IF L_OBJ.GET_BOOLEAN('isHomeRegion') THEN L_IS_HOME:='Y';
        ELSE L_IS_HOME:='N'; END IF;
      END IF;
      L_REGIONS_READ:=L_REGIONS_READ+1;
    ELSE
      RAISE_APPLICATION_ERROR(-20722,'Unsupported OCI context entity');
    END IF;
    IF L_ID IS NULL OR L_NAME IS NULL THEN
      RAISE_APPLICATION_ERROR(-20722,'OCI context entity lacks ID or name');
    END IF;
    L_SEEN_KEY:=P_KIND||':'||L_ID;
    IF L_SEEN.EXISTS(L_SEEN_KEY) THEN
      RAISE_APPLICATION_ERROR(-20722,'Duplicate OCI context entity in source');
    END IF;
    L_SEEN(L_SEEN_KEY):=TRUE;

    UPDATE OCI_ACCOUNT_ENTITY E
       SET LAST_SEEN_RUN_ID=L_RUN_ID
     WHERE E.ENTITY_TYPE=P_KIND AND E.ENTITY_ID=L_ID AND E.IS_CURRENT='Y'
       AND DECODE(E.PARENT_ID,L_PARENT,0,1)=0
       AND DECODE(E.ENTITY_NAME,L_NAME,0,1)=0
       AND DECODE(E.LIFECYCLE_STATE,L_STATE,0,1)=0
       AND DECODE(E.SOURCE_CREATED_AT,L_CREATED,0,1)=0
       AND DECODE(E.HOME_REGION_KEY,L_HOME_KEY,0,1)=0
       AND DECODE(E.REGION_KEY,L_REGION_KEY,0,1)=0
       AND DECODE(E.IS_HOME_REGION,L_IS_HOME,0,1)=0;
    IF SQL%ROWCOUNT=0 THEN
      UPDATE OCI_ACCOUNT_ENTITY E
         SET IS_CURRENT='N',CLOSED_AT=SYSTIMESTAMP
       WHERE E.ENTITY_TYPE=P_KIND AND E.ENTITY_ID=L_ID AND E.IS_CURRENT='Y';
      INSERT INTO OCI_ACCOUNT_ENTITY
        (ENTITY_TYPE,ENTITY_ID,PARENT_ID,ENTITY_NAME,LIFECYCLE_STATE,
         SOURCE_CREATED_AT,HOME_REGION_KEY,REGION_KEY,IS_HOME_REGION,
         LAST_SEEN_RUN_ID)
      VALUES(P_KIND,L_ID,L_PARENT,L_NAME,L_STATE,L_CREATED,L_HOME_KEY,
             L_REGION_KEY,L_IS_HOME,L_RUN_ID);
      L_CHANGES:=L_CHANGES+1;
    END IF;
  END;

  PROCEDURE COLLECT(P_KIND VARCHAR2, P_PATH VARCHAR2) IS
    L_PAGE VARCHAR2(4000);
    L_PATH VARCHAR2(32767);
    L_BODY CLOB;
    L_HEADERS JSON_OBJECT_T;
    L_ITEMS JSON_ARRAY_T;
    L_KEYS JSON_KEY_LIST;
    L_PAGES NUMBER:=0;
    TYPE T_TOKENS IS TABLE OF BOOLEAN INDEX BY VARCHAR2(4000);
    L_TOKENS T_TOKENS;
  BEGIN
    LOOP
      L_PATH:=P_PATH;
      IF L_PAGE IS NOT NULL THEN
        L_PATH:=L_PATH||CASE WHEN INSTR(L_PATH,'?')>0 THEN '&' ELSE '?' END||
          'page='||UTL_URL.ESCAPE(L_PAGE,TRUE,'AL32UTF8');
      END IF;
      GET_JSON(L_PATH,L_BODY,L_HEADERS);
      L_ITEMS:=JSON_ARRAY_T.PARSE(L_BODY);
      IF L_ITEMS.GET_SIZE>0 THEN
        FOR I IN 0..L_ITEMS.GET_SIZE-1 LOOP
          RECORD_ITEM(P_KIND,L_ITEMS.GET(I).TO_CLOB());
        END LOOP;
      END IF;
      L_PAGE:=NULL;
      IF L_HEADERS IS NOT NULL THEN
        L_KEYS:=L_HEADERS.GET_KEYS;
        FOR I IN 1..L_KEYS.COUNT LOOP
          IF LOWER(L_KEYS(I))='opc-next-page' THEN
            L_PAGE:=L_HEADERS.GET_STRING(L_KEYS(I)); EXIT;
          END IF;
        END LOOP;
      END IF;
      L_PAGES:=L_PAGES+1;
      IF L_PAGES>10000 THEN
        RAISE_APPLICATION_ERROR(-20723,'OCI Identity pagination limit exceeded');
      END IF;
      IF L_PAGE IS NOT NULL THEN
        IF L_TOKENS.EXISTS(L_PAGE) THEN
          RAISE_APPLICATION_ERROR(-20723,'Repeated OCI Identity page token');
        END IF;
        L_TOKENS(L_PAGE):=TRUE;
      END IF;
      EXIT WHEN L_PAGE IS NULL;
    END LOOP;
  END;
BEGIN
  SELECT * INTO C FROM OCI_ACCOUNT_SOURCE WHERE CONFIG_ID=1 FOR UPDATE NOWAIT;
  L_LOCKED:=TRUE;
  UPDATE OCI_ACCOUNT_CONTEXT_RUN SET STATUS='ERROR',FINISHED_AT=SYSTIMESTAMP,
    ERROR_MESSAGE='Previous session ended during context sync'
   WHERE STATUS='RUNNING';
  IF C.CONTEXT_ENABLED='N' THEN
    INSERT INTO OCI_ACCOUNT_CONTEXT_RUN(STATUS,FINISHED_AT)
    VALUES('SKIPPED',SYSTIMESTAMP);
    COMMIT;
    RETURN;
  END IF;
  IF NOT REGEXP_LIKE(C.HOME_REGION,'^[a-z0-9]+(-[a-z0-9]+)+$') OR
     NOT REGEXP_LIKE(C.IDENTITY_DOMAIN,'^[a-z0-9]+([.][a-z0-9-]+)+$') THEN
    RAISE_APPLICATION_ERROR(-20720,'Invalid OCI Identity endpoint configuration');
  END IF;
  L_BASE:='https://identity.'||C.HOME_REGION||'.oci.'||
    C.IDENTITY_DOMAIN||'/20160918';
  START_RUN;
  DECLARE
    L_BODY CLOB;
    L_HEADERS JSON_OBJECT_T;
  BEGIN
    GET_JSON('/tenancies/'||UTL_URL.ESCAPE(C.TENANCY_OCID,TRUE,'AL32UTF8'),
      L_BODY,L_HEADERS);
    RECORD_ITEM('TENANCY',L_BODY);
  END;
  COLLECT('COMPARTMENT','/compartments?compartmentId='||
    UTL_URL.ESCAPE(C.TENANCY_OCID,TRUE,'AL32UTF8')||
    '&compartmentIdInSubtree=true&accessLevel=ANY&limit=1000');
  COLLECT('REGION','/tenancies/'||
    UTL_URL.ESCAPE(C.TENANCY_OCID,TRUE,'AL32UTF8')||
    '/regionSubscriptions');
  IF L_TENANCY_READ<>1 OR L_REGIONS_READ=0 THEN
    RAISE_APPLICATION_ERROR(-20724,'Incomplete OCI tenancy or region source');
  END IF;
  UPDATE OCI_ACCOUNT_ENTITY SET IS_CURRENT='N',CLOSED_AT=SYSTIMESTAMP
   WHERE IS_CURRENT='Y' AND LAST_SEEN_RUN_ID<>L_RUN_ID;
  L_CHANGES:=L_CHANGES+SQL%ROWCOUNT;
  SELECT COUNT(*) INTO L_UNRESOLVED
    FROM OCI_ACCOUNT_ENTITY E
   WHERE E.ENTITY_TYPE='COMPARTMENT' AND E.IS_CURRENT='Y'
     AND NOT EXISTS
       (SELECT 1 FROM OCI_ACCOUNT_ENTITY P
         WHERE P.ENTITY_ID=E.PARENT_ID AND P.IS_CURRENT='Y'
           AND P.ENTITY_TYPE IN ('TENANCY','COMPARTMENT'));
  UPDATE OCI_ACCOUNT_CONTEXT_RUN
     SET STATUS='COMPLETE',FINISHED_AT=SYSTIMESTAMP,
         TENANCY_READ=L_TENANCY_READ,
         COMPARTMENTS_READ=L_COMPARTMENTS_READ,
         REGIONS_READ=L_REGIONS_READ,
         CHANGES_RECORDED=L_CHANGES,
         UNRESOLVED_COMPARTMENTS=L_UNRESOLVED
   WHERE RUN_ID=L_RUN_ID;
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('context_run='||L_RUN_ID||
    ' compartments='||L_COMPARTMENTS_READ||
    ' regions='||L_REGIONS_READ||' changes='||L_CHANGES);
EXCEPTION WHEN OTHERS THEN
  L_ERROR:=SUBSTR(SQLERRM,1,4000);
  ROLLBACK;
  IF L_RUN_ID IS NOT NULL THEN
    UPDATE OCI_ACCOUNT_CONTEXT_RUN
       SET STATUS='ERROR',FINISHED_AT=SYSTIMESTAMP,ERROR_MESSAGE=L_ERROR
     WHERE RUN_ID=L_RUN_ID;
    COMMIT;
  END IF;
  RAISE;
END;
