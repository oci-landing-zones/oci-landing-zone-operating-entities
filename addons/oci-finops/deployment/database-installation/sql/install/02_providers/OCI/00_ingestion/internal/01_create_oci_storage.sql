DECLARE
  l_source_column_count NUMBER;
  l_period_ts_count     NUMBER;
  l_pk_column_count     NUMBER;
BEGIN
  SELECT COUNT(*)
  INTO l_source_column_count
  FROM user_tab_columns
  WHERE table_name = 'OCI_FOCUS_REPORTS';

  IF l_source_column_count != 49 THEN
    RAISE_APPLICATION_ERROR(
      -20010,
      'OCI_FOCUS_REPORTS must have exactly 49 CSV columns. Found ' ||
      l_source_column_count
    );
  END IF;

  SELECT COUNT(*)
  INTO l_period_ts_count
  FROM user_tab_columns
  WHERE table_name = 'OCI_FOCUS_REPORTS'
    AND column_name IN (
      'BILLINGPERIODEND',
      'BILLINGPERIODSTART',
      'CHARGEPERIODEND',
      'CHARGEPERIODSTART'
    )
    AND data_type LIKE 'TIMESTAMP%';

  IF l_period_ts_count != 4 THEN
    RAISE_APPLICATION_ERROR(
      -20012,
      'OCI_FOCUS_REPORTS expects the four period columns as TIMESTAMP values.'
    );
  END IF;

  SELECT COUNT(*)
  INTO l_pk_column_count
  FROM user_constraints c
  JOIN user_cons_columns cc
    ON cc.constraint_name = c.constraint_name
   AND cc.table_name = c.table_name
  WHERE c.table_name = 'OCI_FOCUS_REPORTS'
    AND c.constraint_name = 'OCI_FOCUS_REPORTS_PK'
    AND c.constraint_type = 'P'
    AND (
      (cc.position = 1 AND cc.column_name = 'CHARGEPERIODSTART')
      OR
      (cc.position = 2 AND cc.column_name = 'OCI_REFERENCENUMBER')
    );

  IF l_pk_column_count != 2 THEN
    RAISE_APPLICATION_ERROR(
      -20013,
      'OCI_FOCUS_REPORTS expects primary key OCI_FOCUS_REPORTS_PK on (CHARGEPERIODSTART, OCI_REFERENCENUMBER).'
    );
  END IF;
END;
