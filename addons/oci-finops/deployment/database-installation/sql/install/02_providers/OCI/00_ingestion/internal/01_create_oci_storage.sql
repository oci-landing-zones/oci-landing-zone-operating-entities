-- Install the single OCI landing table for every source year.
-- Run as FOCUSPLATFORM after the common core has passed verification.
--
-- Future DBMS_CLOUD_PIPELINE pipelines will load OCI FOCUS CSV files into
-- this one table, regardless of year.
--
-- Primary key:
--   The table enforces a partition-friendly local primary key on
--   (CHARGEPERIODSTART, OCI_REFERENCENUMBER). The partition key is included so
--   Oracle can back the constraint with a local unique index on this monthly
--   interval-partitioned table.
--   The 49 FOCUS/OCI CSV columns remain in source-file order.
--
-- Timestamp design:
--   FOCUS date/time values are UTC values with a Z indicator. This table stores
--   those UTC boundaries as TIMESTAMP(6), not TIMESTAMP WITH LOCAL TIME ZONE, so
--   BI/reporting sessions do not shift the stored billing/charge boundaries.
--   CHARGEPERIODSTART is used for monthly interval partitioning.
--   P_INIT ends before 2024; OCI FOCUS reports start in 2024, and every
--   inserted 2024-or-later month gets an interval partition.

SET DEFINE OFF SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
  L_CORE NUMBER;
  L_LANDING NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'FOCUSPLATFORM' THEN
    RAISE_APPLICATION_ERROR(-20900,
      'Connect as FOCUSPLATFORM before installing the OCI landing table');
  END IF;
  SELECT COUNT(*) INTO L_CORE FROM USER_OBJECTS
   WHERE OBJECT_NAME IN ('FINOPS_CORE_PROVIDER', 'FINOPS_CORE_RUN_DAILY')
     AND STATUS = 'VALID';
  IF L_CORE <> 2 THEN
    RAISE_APPLICATION_ERROR(-20900,
      'Install and verify the common core before the OCI landing table');
  END IF;
  SELECT COUNT(*) INTO L_LANDING FROM USER_OBJECTS
   WHERE OBJECT_NAME = 'OCI_FOCUS_REPORTS';
  IF L_LANDING <> 0 THEN
    RAISE_APPLICATION_ERROR(-20900,
      'OCI_FOCUS_REPORTS already exists; inspect before rerunning installation');
  END IF;
END;
