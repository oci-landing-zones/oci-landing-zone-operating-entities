-- OCI account context. Successful syncs version only changed source fields.
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE TABLE OCI_ACCOUNT_SOURCE (
  CONFIG_ID NUMBER(1) DEFAULT 1 PRIMARY KEY CHECK (CONFIG_ID=1),
  TENANCY_OCID VARCHAR2(512) NOT NULL,
  HOME_REGION VARCHAR2(64) NOT NULL,
  IDENTITY_DOMAIN VARCHAR2(128) NOT NULL,
  CREDENTIAL_NAME VARCHAR2(128) DEFAULT 'OCI$RESOURCE_PRINCIPAL' NOT NULL,
  CONTEXT_ENABLED CHAR(1) DEFAULT 'Y' NOT NULL CHECK (CONTEXT_ENABLED IN ('Y','N')),
  CONTRACT_ENABLED CHAR(1) DEFAULT 'Y' NOT NULL CHECK (CONTRACT_ENABLED IN ('Y','N'))
);

CREATE TABLE OCI_ACCOUNT_CONTEXT_RUN (
  RUN_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  STARTED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  FINISHED_AT TIMESTAMP WITH TIME ZONE,
  STATUS VARCHAR2(12) NOT NULL
    CHECK (STATUS IN ('RUNNING','COMPLETE','ERROR','SKIPPED')),
  TENANCY_READ NUMBER DEFAULT 0 NOT NULL,
  COMPARTMENTS_READ NUMBER DEFAULT 0 NOT NULL,
  REGIONS_READ NUMBER DEFAULT 0 NOT NULL,
  CHANGES_RECORDED NUMBER DEFAULT 0 NOT NULL,
  UNRESOLVED_COMPARTMENTS NUMBER DEFAULT 0 NOT NULL,
  ERROR_MESSAGE VARCHAR2(4000)
);

CREATE TABLE OCI_ACCOUNT_ENTITY (
  VERSION_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ENTITY_TYPE VARCHAR2(12) NOT NULL
    CHECK (ENTITY_TYPE IN ('TENANCY','COMPARTMENT','REGION')),
  ENTITY_ID VARCHAR2(512) NOT NULL,
  PARENT_ID VARCHAR2(512),
  ENTITY_NAME VARCHAR2(1000),
  LIFECYCLE_STATE VARCHAR2(64),
  SOURCE_CREATED_AT TIMESTAMP WITH TIME ZONE,
  HOME_REGION_KEY VARCHAR2(64),
  REGION_KEY VARCHAR2(64),
  IS_HOME_REGION CHAR(1) CHECK (IS_HOME_REGION IN ('Y','N')),
  FIRST_SEEN_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  LAST_SEEN_RUN_ID NUMBER NOT NULL REFERENCES OCI_ACCOUNT_CONTEXT_RUN(RUN_ID),
  IS_CURRENT CHAR(1) DEFAULT 'Y' NOT NULL CHECK (IS_CURRENT IN ('Y','N')),
  CLOSED_AT TIMESTAMP WITH TIME ZONE
);

CREATE UNIQUE INDEX OCI_ACCOUNT_ENTITY_CURRENT_UX ON OCI_ACCOUNT_ENTITY
  (CASE WHEN IS_CURRENT='Y' THEN ENTITY_TYPE END,
   CASE WHEN IS_CURRENT='Y' THEN ENTITY_ID END);
CREATE INDEX OCI_ACCOUNT_ENTITY_PARENT_IX ON OCI_ACCOUNT_ENTITY
  (ENTITY_TYPE, IS_CURRENT, PARENT_ID);

CREATE OR REPLACE VIEW OCI_ACCOUNT_CURRENT_V AS
SELECT ENTITY_TYPE, ENTITY_ID, PARENT_ID, ENTITY_NAME, LIFECYCLE_STATE,
       SOURCE_CREATED_AT, HOME_REGION_KEY, REGION_KEY, IS_HOME_REGION,
       FIRST_SEEN_AT, LAST_SEEN_RUN_ID
FROM OCI_ACCOUNT_ENTITY WHERE IS_CURRENT='Y';

CREATE OR REPLACE VIEW OCI_ACCOUNT_COMPARTMENT_V AS
SELECT ENTITY_ID COMPARTMENT_ID, PARENT_ID PARENT_COMPARTMENT_ID,
       ENTITY_NAME COMPARTMENT_NAME, LIFECYCLE_STATE, SOURCE_CREATED_AT,
       FIRST_SEEN_AT, LAST_SEEN_RUN_ID
FROM OCI_ACCOUNT_CURRENT_V WHERE ENTITY_TYPE='COMPARTMENT';

CREATE OR REPLACE VIEW OCI_ACCOUNT_REGION_V AS
SELECT ENTITY_ID REGION_NAME, REGION_KEY, LIFECYCLE_STATE SUBSCRIPTION_STATUS,
       IS_HOME_REGION, FIRST_SEEN_AT, LAST_SEEN_RUN_ID
FROM OCI_ACCOUNT_CURRENT_V WHERE ENTITY_TYPE='REGION';

CREATE OR REPLACE VIEW OCI_ACCOUNT_CONTEXT_HEALTH_V AS
SELECT S.TENANCY_OCID, S.HOME_REGION, S.CONTEXT_ENABLED,
       R.RUN_ID, R.STATUS, R.STARTED_AT, R.FINISHED_AT,
       R.TENANCY_READ, R.COMPARTMENTS_READ, R.REGIONS_READ,
       R.CHANGES_RECORDED, R.UNRESOLVED_COMPARTMENTS, R.ERROR_MESSAGE,
       (SELECT MAX(FINISHED_AT) FROM OCI_ACCOUNT_CONTEXT_RUN
         WHERE STATUS='COMPLETE') LAST_SUCCESS_AT
FROM OCI_ACCOUNT_SOURCE S LEFT JOIN
  (SELECT X.*, ROW_NUMBER() OVER (ORDER BY RUN_ID DESC) AS RN
     FROM OCI_ACCOUNT_CONTEXT_RUN X) R ON R.RN=1
WHERE S.CONFIG_ID=1;
