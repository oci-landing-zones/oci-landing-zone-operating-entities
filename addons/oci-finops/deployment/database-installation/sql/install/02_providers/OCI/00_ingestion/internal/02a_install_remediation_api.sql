-- Shared admission, conversion and row provenance for OCI remediation.
-- Run for one FOCUS load pipeline at a time; the staging table is shared.
SET DEFINE OFF
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

CREATE OR REPLACE FUNCTION OCI_FOCUS_REMED_NUMBER(P_VALUE VARCHAR2)
  RETURN NUMBER DETERMINISTIC AUTHID DEFINER IS
BEGIN
  IF TRIM(P_VALUE) IS NULL THEN RETURN NULL; END IF;
  RETURN TO_NUMBER(TRIM(P_VALUE), NULL, 'NLS_NUMERIC_CHARACTERS=''.,''');
END;
/

CREATE OR REPLACE FUNCTION OCI_FOCUS_REMED_TIMESTAMP(P_VALUE VARCHAR2)
  RETURN TIMESTAMP DETERMINISTIC AUTHID DEFINER IS
  L_VALUE VARCHAR2(32767) := TRIM(P_VALUE);
  L_NORMAL VARCHAR2(32767);
  L_RESULT TIMESTAMP;
BEGIN
  IF L_VALUE IS NULL THEN RETURN NULL; END IF;
  L_NORMAL := REPLACE(REPLACE(L_VALUE, 'T', ' '), 'Z', ' UTC');
  IF REGEXP_LIKE(L_VALUE, '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}Z$') THEN
    SELECT SYS_EXTRACT_UTC(TO_TIMESTAMP_TZ(
      L_NORMAL, 'YYYY-MM-DD HH24:MI TZR'))
      INTO L_RESULT FROM DUAL;
  ELSIF REGEXP_LIKE(L_VALUE,
    '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z$') THEN
    SELECT SYS_EXTRACT_UTC(TO_TIMESTAMP_TZ(
      L_NORMAL, 'YYYY-MM-DD HH24:MI:SS TZR'))
      INTO L_RESULT FROM DUAL;
  ELSIF REGEXP_LIKE(L_VALUE,
    '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}\.[0-9]+Z$') THEN
    SELECT SYS_EXTRACT_UTC(TO_TIMESTAMP_TZ(
      L_NORMAL, 'YYYY-MM-DD HH24:MI:SS.FF9 TZR'))
      INTO L_RESULT FROM DUAL;
  ELSE
    RAISE_APPLICATION_ERROR(-20810,
      'Unsupported FOCUS timestamp: ' || SUBSTR(L_VALUE, 1, 150));
  END IF;
  RETURN L_RESULT;
END;
/

-- Internal API: callers hold OCI_FOCUS_REMED_MUTEX and own the transaction.
CREATE OR REPLACE PACKAGE OCI_FOCUS_REMED_ROW_API AUTHID DEFINER AS
  FUNCTION CLASSIFY(P_CODE NUMBER, P_MESSAGE VARCHAR2) RETURN VARCHAR2;
  PROCEDURE CHECK_FILE(P_PIPELINE VARCHAR2, P_GENERATION NUMBER,
    P_HASH RAW, P_STATE OUT VARCHAR2);
  PROCEDURE REFRESH_FILES(P_PIPELINE VARCHAR2);
  PROCEDURE INSERT_ROW(P_TARGET VARCHAR2, P_PIPELINE VARCHAR2,
    P_GENERATION NUMBER, P_HASH RAW, P_STAGE_ROWID VARCHAR2);
END OCI_FOCUS_REMED_ROW_API;
/

CREATE OR REPLACE PACKAGE BODY OCI_FOCUS_REMED_ROW_API AS
  FUNCTION CLASSIFY(P_CODE NUMBER, P_MESSAGE VARCHAR2) RETURN VARCHAR2 IS
    L_CODES VARCHAR2(4100) := CASE WHEN P_CODE IS NOT NULL THEN
      'ORA-' || TO_CHAR(ABS(P_CODE), 'FM00000') || ': ' END || P_MESSAGE;
    L_DATA_PATTERN CONSTANT VARCHAR2(512) :=
      'ORA-(00001|01400|01438|01722|01830|01840|01841|01843|01847|01849|01850|01851|01858|01859|01861|01862|02290|02291|02292|12899|40441|40597):|KUP-(04021|04023|04025|04026):';
    L_TOKEN VARCHAR2(20);
  BEGIN
    IF L_CODES IS NULL THEN RETURN 'DIAGNOSE'; END IF;
    -- Explicit allowlist. Generic wrappers alone never establish a data cause.
    IF REGEXP_LIKE(L_CODES,
      'ORA-(01017|01031|12154|125[0-9]{2}|20004|20010|20011|20025|20401|20403|20404|204[5-9][0-9]):') THEN
      RETURN 'EXCLUDED';
    END IF;
    -- An unknown accompanying error cannot be hidden by a recognized data
    -- error. Only documented reject/external/parallel/stack wrappers pass.
    FOR I IN 1 .. REGEXP_COUNT(L_CODES, '(ORA|KUP)-[0-9]{5}:') LOOP
      L_TOKEN := REGEXP_SUBSTR(L_CODES, '(ORA|KUP)-[0-9]{5}:',1,I);
      IF NOT REGEXP_LIKE(L_TOKEN, '^(' || L_DATA_PATTERN || ')$') AND
         NOT REGEXP_LIKE(L_TOKEN, '^ORA-(06512|12801|20000|20003|29913|30653):$') THEN
        RETURN 'DIAGNOSE';
      END IF;
    END LOOP;
    IF REGEXP_LIKE(L_CODES, L_DATA_PATTERN) THEN RETURN 'NEW'; END IF;
    RETURN 'DIAGNOSE';
  END CLASSIFY;

  -- Only structured log evidence with an exact source field is admissible.
  -- Unstructured shared log lines / bad CSV payloads cannot prove attribution.
  PROCEDURE LOG_EVIDENCE(P_PIPELINE VARCHAR2, P_SOURCE VARCHAR2,
    P_MESSAGE IN OUT VARCHAR2) IS
    L_LOG VARCHAR2(128);
    L_BAD VARCHAR2(128);
    L_COLUMN VARCHAR2(128);
    L_ROW CLOB;
    L_ERROR_COLUMN VARCHAR2(128);
    L_CURSOR SYS_REFCURSOR;
  BEGIN
    SELECT O.LOGFILE_TABLE, O.BADFILE_TABLE INTO L_LOG, L_BAD
      FROM USER_LOAD_OPERATIONS O JOIN USER_CLOUD_PIPELINES P
        ON P.OPERATION_ID = O.ID WHERE P.PIPELINE_NAME = P_PIPELINE;
    IF L_LOG IS NOT NULL THEN
      SELECT MIN(COLUMN_NAME) INTO L_COLUMN FROM USER_TAB_COLUMNS
       WHERE TABLE_NAME = L_LOG
         AND COLUMN_NAME IN ('NAME','FILE_NAME','FILENAME','SOURCE_NAME')
         AND DATA_TYPE IN ('VARCHAR2','CHAR');
      SELECT MIN(COLUMN_NAME) INTO L_ERROR_COLUMN FROM USER_TAB_COLUMNS
       WHERE TABLE_NAME=L_LOG AND COLUMN_NAME IN ('ERROR_MESSAGE','ERROR_TEXT')
         AND DATA_TYPE IN ('VARCHAR2','CHAR','CLOB');
      IF L_COLUMN IS NOT NULL AND L_ERROR_COLUMN IS NOT NULL THEN
        OPEN L_CURSOR FOR 'SELECT TO_CLOB(' ||
          DBMS_ASSERT.SIMPLE_SQL_NAME(L_ERROR_COLUMN) || ') FROM ' ||
          DBMS_ASSERT.SIMPLE_SQL_NAME(L_LOG) || ' WHERE ' ||
          DBMS_ASSERT.SIMPLE_SQL_NAME(L_COLUMN) || ' = :n' USING P_SOURCE;
        LOOP
          FETCH L_CURSOR INTO L_ROW;
          EXIT WHEN L_CURSOR%NOTFOUND;
          -- A later operational entry must not be hidden by a data entry.
          IF CLASSIFY(NULL, DBMS_LOB.SUBSTR(L_ROW, 3500, 1)) = 'EXCLUDED' THEN
            P_MESSAGE := DBMS_LOB.SUBSTR(L_ROW, 3500, 1);
            EXIT;
          ELSIF CLASSIFY(NULL, P_MESSAGE) <> 'NEW' AND
                CLASSIFY(NULL, DBMS_LOB.SUBSTR(L_ROW, 3500, 1)) = 'NEW' THEN
            P_MESSAGE := DBMS_LOB.SUBSTR(L_ROW, 3500, 1);
          END IF;
        END LOOP;
        CLOSE L_CURSOR;
      END IF;
    END IF;
    IF L_BAD IS NOT NULL AND CLASSIFY(NULL, P_MESSAGE) <> 'EXCLUDED' THEN
      SELECT MIN(COLUMN_NAME) INTO L_COLUMN FROM USER_TAB_COLUMNS
       WHERE TABLE_NAME=L_BAD
         AND COLUMN_NAME IN ('NAME','FILE_NAME','FILENAME','SOURCE_NAME')
         AND DATA_TYPE IN ('VARCHAR2','CHAR');
      SELECT MIN(COLUMN_NAME) INTO L_ERROR_COLUMN FROM USER_TAB_COLUMNS
       WHERE TABLE_NAME=L_BAD AND COLUMN_NAME IN ('ERROR_MESSAGE','ERROR_TEXT')
         AND DATA_TYPE IN ('VARCHAR2','CHAR','CLOB');
      IF L_COLUMN IS NOT NULL AND L_ERROR_COLUMN IS NOT NULL THEN
        OPEN L_CURSOR FOR 'SELECT TO_CLOB(' ||
          DBMS_ASSERT.SIMPLE_SQL_NAME(L_ERROR_COLUMN) || ') FROM ' ||
          DBMS_ASSERT.SIMPLE_SQL_NAME(L_BAD) || ' WHERE ' ||
          DBMS_ASSERT.SIMPLE_SQL_NAME(L_COLUMN) || ' = :n' USING P_SOURCE;
        LOOP
          FETCH L_CURSOR INTO L_ROW;
          EXIT WHEN L_CURSOR%NOTFOUND;
          IF CLASSIFY(NULL, DBMS_LOB.SUBSTR(L_ROW,3500,1)) = 'EXCLUDED' THEN
            P_MESSAGE := DBMS_LOB.SUBSTR(L_ROW,3500,1);
            EXIT;
          ELSIF CLASSIFY(NULL, P_MESSAGE) <> 'NEW' AND
                CLASSIFY(NULL, DBMS_LOB.SUBSTR(L_ROW,3500,1)) = 'NEW' THEN
            P_MESSAGE := DBMS_LOB.SUBSTR(L_ROW,3500,1);
          END IF;
        END LOOP;
        CLOSE L_CURSOR;
      END IF;
    END IF;
    IF CLASSIFY(NULL, P_MESSAGE) = 'DIAGNOSE' THEN
      P_MESSAGE := SUBSTR('No attributable deterministic data evidence; log=' ||
        NVL(L_LOG,'none') || ', bad=' || NVL(L_BAD,'none') || '; ' || P_MESSAGE,1,4000);
    END IF;
  EXCEPTION WHEN OTHERS THEN
    IF L_CURSOR%ISOPEN THEN CLOSE L_CURSOR; END IF;
    P_MESSAGE := 'Diagnostic evidence unavailable (SQLCODE=' || SQLCODE || '); inspect log/bad metadata';
  END LOG_EVIDENCE;

  PROCEDURE CHECK_FILE(P_PIPELINE VARCHAR2, P_GENERATION NUMBER,
    P_HASH RAW, P_STATE OUT VARCHAR2) IS
    L_TABLE VARCHAR2(128);
    L_SOURCE VARCHAR2(4000);
    L_COUNT NUMBER;
    L_STATUS VARCHAR2(30);
    L_CODE NUMBER;
    L_MESSAGE VARCHAR2(4000);
    L_GENERATION NUMBER;
    L_PRIOR_FULL NUMBER;
  BEGIN
    SELECT SOURCE_NAME INTO L_SOURCE FROM OCI_FOCUS_FAIL_FILE
     WHERE PIPELINE_NAME=P_PIPELINE AND GENERATION_NO=P_GENERATION
       AND SOURCE_NAME_HASH=P_HASH;
    SELECT P.STATUS_TABLE, C.GENERATION_NO INTO L_TABLE, L_GENERATION
      FROM USER_CLOUD_PIPELINES P JOIN OCI_FOCUS_FAIL_SCAN_CURSOR C
        ON C.PIPELINE_NAME=P.PIPELINE_NAME
      JOIN USER_OBJECTS O ON O.OBJECT_NAME=P.STATUS_TABLE AND O.OBJECT_TYPE='TABLE'
     WHERE P.PIPELINE_NAME=P_PIPELINE AND C.STATUS_TABLE=P.STATUS_TABLE
       AND C.PIPELINE_ID=P.PIPELINE_ID AND C.OPERATION_ID=P.OPERATION_ID
       AND O.CREATED=C.STATUS_TABLE_CREATED;
    IF L_GENERATION <> P_GENERATION THEN
      P_STATE := 'DEFERRED';
      UPDATE OCI_FOCUS_FAIL_FILE SET FILE_STATE=P_STATE,
        ERROR_MESSAGE='Current generation differs; diagnosis required'
       WHERE PIPELINE_NAME=P_PIPELINE AND GENERATION_NO=P_GENERATION
         AND SOURCE_NAME_HASH=P_HASH;
      RETURN;
    END IF;
    EXECUTE IMMEDIATE 'SELECT COUNT(*), MAX(STATUS), MAX(ERROR_CODE),' ||
      ' MAX(ERROR_MESSAGE) FROM ' || DBMS_ASSERT.SIMPLE_SQL_NAME(L_TABLE) ||
      ' WHERE NAME=:n' INTO L_COUNT, L_STATUS, L_CODE, L_MESSAGE USING L_SOURCE;
    IF L_COUNT <> 1 OR L_STATUS IS NULL OR
       L_STATUS NOT IN ('FAILED','COMPLETED') THEN
      P_STATE := 'DEFERRED';
      L_MESSAGE := 'Current Oracle status is ambiguous or not terminal: ' || NVL(L_STATUS,'absent');
    ELSIF L_STATUS = 'COMPLETED' THEN
      P_STATE := 'PIPELINE_LOADED';
    ELSE
      SELECT COUNT(*) INTO L_PRIOR_FULL FROM OCI_FOCUS_REMED_FILE R
        JOIN OCI_FOCUS_FAIL_FILE Q ON Q.PIPELINE_NAME=R.PIPELINE_NAME
          AND Q.GENERATION_NO=R.GENERATION_NO AND Q.SOURCE_NAME_HASH=R.SOURCE_NAME_HASH
       WHERE R.PIPELINE_NAME=P_PIPELINE AND R.SOURCE_NAME_HASH=P_HASH
         AND Q.SOURCE_NAME=L_SOURCE AND R.STATE='FULL';
      IF L_PRIOR_FULL > 0 THEN
        P_STATE := 'DEFERRED';
        L_MESSAGE := 'Immutable source already FULL in remediation ledger; replay suppressed';
      ELSE
        P_STATE := CLASSIFY(L_CODE, L_MESSAGE);
        IF P_STATE = 'DIAGNOSE' THEN
          LOG_EVIDENCE(P_PIPELINE, L_SOURCE, L_MESSAGE);
          P_STATE := CLASSIFY(L_CODE, L_MESSAGE);
        END IF;
      END IF;
    END IF;
    UPDATE OCI_FOCUS_FAIL_FILE SET FILE_STATE=P_STATE,
      ERROR_CODE=L_CODE, ERROR_MESSAGE=SUBSTR('Checked UTC=' ||
        TO_CHAR(SYSTIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS') ||
        '; Oracle status=' || NVL(L_STATUS,'absent') || '; ' || L_MESSAGE,1,4000)
     WHERE PIPELINE_NAME=P_PIPELINE AND GENERATION_NO=P_GENERATION
       AND SOURCE_NAME_HASH=P_HASH;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    P_STATE := 'DEFERRED';
    UPDATE OCI_FOCUS_FAIL_FILE SET FILE_STATE=P_STATE,
      ERROR_MESSAGE='Current pipeline generation/status identity cannot be established'
     WHERE PIPELINE_NAME=P_PIPELINE AND GENERATION_NO=P_GENERATION
       AND SOURCE_NAME_HASH=P_HASH;
  END CHECK_FILE;

  PROCEDURE REFRESH_FILES(P_PIPELINE VARCHAR2) IS
    L_STATE VARCHAR2(20);
    L_COUNT NUMBER;
  BEGIN
    FOR F IN (SELECT GENERATION_NO, SOURCE_NAME_HASH FROM OCI_FOCUS_FAIL_FILE
      WHERE PIPELINE_NAME=P_PIPELINE
        AND FILE_STATE IN ('NEW','EXCLUDED','DIAGNOSE','DEFERRED','ERROR')
      ORDER BY FIRST_SEEN_AT) LOOP
      CHECK_FILE(P_PIPELINE, F.GENERATION_NO, F.SOURCE_NAME_HASH, L_STATE);
      IF L_STATE = 'NEW' THEN
        FOR E IN (SELECT R.*, Q.SOURCE_URI FROM OCI_FOCUS_REMED_FILE R
          JOIN OCI_FOCUS_FAIL_FILE Q ON Q.PIPELINE_NAME=R.PIPELINE_NAME
            AND Q.GENERATION_NO=R.GENERATION_NO AND Q.SOURCE_NAME_HASH=R.SOURCE_NAME_HASH
          WHERE R.PIPELINE_NAME=P_PIPELINE AND R.GENERATION_NO=F.GENERATION_NO
            AND R.SOURCE_NAME_HASH=F.SOURCE_NAME_HASH AND R.STATE='ERROR'
            AND R.STAGED_ROWS=0 AND R.INSERTED_ROWS=0 AND R.MANUAL_ROWS=0) LOOP
          SELECT COUNT(*) INTO L_COUNT FROM OCI_FOCUS_REMED_STAGE;
          IF L_COUNT <> 0 THEN CONTINUE; END IF;
          SELECT COUNT(*) INTO L_COUNT FROM OCI_FOCUS_REMED_FILE
           WHERE STATE IN ('COPYING','STAGED','PROCESSING');
          IF L_COUNT <> 0 THEN CONTINUE; END IF;
          IF E.COPY_SESSION_SID IS NULL OR E.COPY_SESSION_SERIAL IS NULL OR
             E.SOURCE_URI IS NULL THEN CONTINUE; END IF;
          SELECT COUNT(*) INTO L_COUNT FROM V$SESSION
           WHERE SID=E.COPY_SESSION_SID AND SERIAL#=E.COPY_SESSION_SERIAL;
          IF L_COUNT <> 0 THEN CONTINUE; END IF;
          SELECT COUNT(*) INTO L_COUNT FROM USER_LOAD_OPERATIONS O
           WHERE O.TABLE_NAME='OCI_FOCUS_REMED_STAGE' AND O.FILE_URI_LIST=E.SOURCE_URI
             AND O.START_TIME>=E.STARTED_AT
             AND (NVL(O.STATUS,'?') NOT IN ('COMPLETED','FAILED') OR
               O.SID IS NULL OR O.SERIAL# IS NULL OR EXISTS
                 (SELECT 1 FROM V$SESSION V WHERE V.SID=O.SID AND V.SERIAL#=O.SERIAL#));
          IF L_COUNT <> 0 THEN CONTINUE; END IF;
          SELECT COUNT(*) INTO L_COUNT FROM OCI_FOCUS_REMED_ROW
           WHERE PIPELINE_NAME=P_PIPELINE AND GENERATION_NO=F.GENERATION_NO
             AND SOURCE_NAME_HASH=F.SOURCE_NAME_HASH;
          IF L_COUNT <> 0 THEN CONTINUE; END IF;
          SELECT COUNT(*) INTO L_COUNT FROM OCI_FOCUS_REMED_MANUAL
           WHERE PIPELINE_NAME=P_PIPELINE AND GENERATION_NO=F.GENERATION_NO
             AND SOURCE_NAME_HASH=F.SOURCE_NAME_HASH;
          IF L_COUNT <> 0 THEN CONTINUE; END IF;
          INSERT INTO OCI_FOCUS_COPY_RECOVERY
            (PIPELINE_NAME,GENERATION_NO,SOURCE_NAME_HASH,COPY_OPERATION_ID,DECISION,STAGE_ROWS,REASON)
          VALUES (P_PIPELINE,F.GENERATION_NO,F.SOURCE_NAME_HASH,E.COPY_OPERATION_ID,'REQUEUED',0,
            SUBSTR('Interrupted/failed COPY requeued after terminal operation and dead sessions; ' ||
              E.ERROR_MESSAGE,1,4000));
          DELETE FROM OCI_FOCUS_REMED_FILE WHERE PIPELINE_NAME=P_PIPELINE
            AND GENERATION_NO=F.GENERATION_NO AND SOURCE_NAME_HASH=F.SOURCE_NAME_HASH
            AND STATE='ERROR';
        END LOOP;
        -- An ERROR attempt that cannot yet be proven inactive remains visible.
        SELECT COUNT(*) INTO L_COUNT FROM OCI_FOCUS_REMED_FILE
         WHERE PIPELINE_NAME=P_PIPELINE AND GENERATION_NO=F.GENERATION_NO
           AND SOURCE_NAME_HASH=F.SOURCE_NAME_HASH AND STATE='ERROR';
        IF L_COUNT <> 0 THEN
          UPDATE OCI_FOCUS_FAIL_FILE SET FILE_STATE='DEFERRED',
            ERROR_MESSAGE='COPY ERROR attempt awaits empty stage, zero outcomes and absent sessions; checked UTC=' ||
              TO_CHAR(SYSTIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')
           WHERE PIPELINE_NAME=P_PIPELINE AND GENERATION_NO=F.GENERATION_NO
             AND SOURCE_NAME_HASH=F.SOURCE_NAME_HASH;
        END IF;
      END IF;
    END LOOP;
  END REFRESH_FILES;

  PROCEDURE LAND_ROW(P_TARGET VARCHAR2, P_STAGE_ROWID VARCHAR2,
    P_REFERENCE VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE 'INSERT INTO ' || P_TARGET || q'~ (
      AVAILABILITYZONE,BILLEDCOST,BILLINGACCOUNTID,BILLINGACCOUNTNAME,
      BILLINGCURRENCY,BILLINGPERIODEND,BILLINGPERIODSTART,CHARGECATEGORY,
      CHARGEDESCRIPTION,CHARGEFREQUENCY,CHARGEPERIODEND,CHARGEPERIODSTART,
      CHARGESUBCATEGORY,COMMITMENTDISCOUNTCATEGORY,COMMITMENTDISCOUNTID,
      COMMITMENTDISCOUNTNAME,COMMITMENTDISCOUNTTYPE,EFFECTIVECOST,
      INVOICEISSUER,LISTCOST,LISTUNITPRICE,PRICINGCATEGORY,
      PRICINGQUANTITY,PRICINGUNIT,PROVIDER,PUBLISHER,REGION,RESOURCEID,
      RESOURCENAME,RESOURCETYPE,SERVICECATEGORY,SERVICENAME,SKUID,
      SKUPRICEID,SUBACCOUNTID,SUBACCOUNTNAME,TAGS,USAGEQUANTITY,
      USAGEUNIT,OCI_REFERENCENUMBER,OCI_COMPARTMENTID,OCI_COMPARTMENTNAME,
      OCI_OVERAGEFLAG,OCI_UNITPRICEOVERAGE,OCI_BILLEDQUANTITYOVERAGE,
      OCI_COSTOVERAGE,OCI_ATTRIBUTEDUSAGE,OCI_ATTRIBUTEDCOST,
      OCI_BACKREFERENCENUMBER
    )
    SELECT
      TRIM(AVAILABILITYZONE),OCI_FOCUS_REMED_NUMBER(BILLEDCOST),
      TRIM(BILLINGACCOUNTID),TRIM(BILLINGACCOUNTNAME),TRIM(BILLINGCURRENCY),
      OCI_FOCUS_REMED_TIMESTAMP(BILLINGPERIODEND),
      OCI_FOCUS_REMED_TIMESTAMP(BILLINGPERIODSTART),
      TRIM(CHARGECATEGORY),TRIM(CHARGEDESCRIPTION),TRIM(CHARGEFREQUENCY),
      OCI_FOCUS_REMED_TIMESTAMP(CHARGEPERIODEND),
      OCI_FOCUS_REMED_TIMESTAMP(CHARGEPERIODSTART),
      TRIM(CHARGESUBCATEGORY),TRIM(COMMITMENTDISCOUNTCATEGORY),
      TRIM(COMMITMENTDISCOUNTID),TRIM(COMMITMENTDISCOUNTNAME),
      TRIM(COMMITMENTDISCOUNTTYPE),OCI_FOCUS_REMED_NUMBER(EFFECTIVECOST),
      TRIM(INVOICEISSUER),OCI_FOCUS_REMED_NUMBER(LISTCOST),
      OCI_FOCUS_REMED_NUMBER(LISTUNITPRICE),TRIM(PRICINGCATEGORY),
      OCI_FOCUS_REMED_NUMBER(PRICINGQUANTITY),TRIM(PRICINGUNIT),
      TRIM(PROVIDER),TRIM(PUBLISHER),TRIM(REGION),TRIM(RESOURCEID),
      TRIM(RESOURCENAME),TRIM(RESOURCETYPE),TRIM(SERVICECATEGORY),
      TRIM(SERVICENAME),TRIM(SKUID),TRIM(SKUPRICEID),TRIM(SUBACCOUNTID),
      TRIM(SUBACCOUNTNAME),JSON(TAGS),
      OCI_FOCUS_REMED_NUMBER(USAGEQUANTITY),TRIM(USAGEUNIT),
      :final_reference,TRIM(OCI_COMPARTMENTID),
      TRIM(OCI_COMPARTMENTNAME),TRIM(OCI_OVERAGEFLAG),
      OCI_FOCUS_REMED_NUMBER(OCI_UNITPRICEOVERAGE),
      OCI_FOCUS_REMED_NUMBER(OCI_BILLEDQUANTITYOVERAGE),
      OCI_FOCUS_REMED_NUMBER(OCI_COSTOVERAGE),
      OCI_FOCUS_REMED_NUMBER(OCI_ATTRIBUTEDUSAGE),
      OCI_FOCUS_REMED_NUMBER(OCI_ATTRIBUTEDCOST),
      TRIM(OCI_BACKREFERENCENUMBER)
    FROM OCI_FOCUS_REMED_STAGE WHERE ROWID = CHARTOROWID(:stage_rowid)~'
    USING P_REFERENCE, P_STAGE_ROWID;
    IF SQL%ROWCOUNT <> 1 THEN
      RAISE_APPLICATION_ERROR(-20827, 'Expected one landing insert');
    END IF;
  END LAND_ROW;

  PROCEDURE INSERT_ROW(P_TARGET VARCHAR2, P_PIPELINE VARCHAR2,
    P_GENERATION NUMBER, P_HASH RAW, P_STAGE_ROWID VARCHAR2) IS
    L_PERIOD TIMESTAMP(6);
    L_ORIGINAL VARCHAR2(32767);
    L_FINAL VARCHAR2(32767);
    L_RAW CLOB;
    L_PRIOR_RAW CLOB;
    L_OUTCOME VARCHAR2(20) := 'INSERTED';
    L_COUNT NUMBER;
    L_MESSAGE VARCHAR2(4000);
  BEGIN
    IF P_TARGET <> 'OCI_FOCUS_REPORTS' OR P_TARGET IS NULL THEN
      RAISE_APPLICATION_ERROR(-20874, 'Unexpected remediation target');
    END IF;
    SELECT OCI_FOCUS_REMED_TIMESTAMP(CHARGEPERIODSTART),
           TRIM(OCI_REFERENCENUMBER), JSON_OBJECT(* RETURNING CLOB)
      INTO L_PERIOD, L_ORIGINAL, L_RAW FROM OCI_FOCUS_REMED_STAGE
     WHERE ROWID=CHARTOROWID(P_STAGE_ROWID);
    L_FINAL := L_ORIGINAL;
    BEGIN
      SELECT FINAL_REFERENCE, RAW_ROW_JSON INTO L_FINAL, L_PRIOR_RAW
        FROM OCI_FOCUS_REMED_ROW
       WHERE PIPELINE_NAME=P_PIPELINE AND GENERATION_NO=P_GENERATION
         AND SOURCE_NAME_HASH=P_HASH AND ORIGINAL_CHARGEPERIODSTART=L_PERIOD
         AND ORIGINAL_REFERENCE=L_ORIGINAL;
      SELECT COUNT(*) INTO L_COUNT FROM OCI_FOCUS_REPORTS
       WHERE CHARGEPERIODSTART=L_PERIOD AND OCI_REFERENCENUMBER=L_FINAL;
      IF L_COUNT <> 1 OR DBMS_LOB.COMPARE(L_RAW,L_PRIOR_RAW) <> 0 THEN
        RAISE_APPLICATION_ERROR(-20874, 'Row provenance differs from stage/landing; diagnosis required');
      END IF;
      RETURN;
    EXCEPTION WHEN NO_DATA_FOUND THEN L_FINAL := L_ORIGINAL;
    END;
    BEGIN
      LAND_ROW(P_TARGET, P_STAGE_ROWID, L_ORIGINAL);
    EXCEPTION WHEN DUP_VAL_ON_INDEX THEN
      L_MESSAGE := SQLERRM;
      -- Match the exact owner-qualified landing PK, never another unique key.
      IF REPLACE(REGEXP_SUBSTR(L_MESSAGE, '\(([^)]+)\)',1,1,NULL,1),'"','') <>
         SYS_CONTEXT('USERENV','CURRENT_USER') || '.OCI_FOCUS_REPORTS_PK' OR
         REGEXP_SUBSTR(L_MESSAGE, '\(([^)]+)\)',1,1,NULL,1) IS NULL THEN
        RAISE;
      END IF;
      L_FINAL := L_ORIGINAL || '~' || RAWTOHEX(P_HASH);
      IF LENGTH(L_FINAL) > 512 OR LENGTHB(L_FINAL) > 512 THEN
        RAISE_APPLICATION_ERROR(-20872, 'File-qualified reference exceeds 512; no truncation permitted');
      END IF;
      BEGIN
        LAND_ROW(P_TARGET, P_STAGE_ROWID, L_FINAL);
      EXCEPTION WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20873, 'File-qualified key exists without this row ledger; diagnosis required');
      END;
      L_OUTCOME := 'REKEYED';
    END;
    -- Any accounting error escapes the caller row-error handler. The caller
    -- rolls back landing + provenance + stage deletion + counter together.
    BEGIN
      INSERT INTO OCI_FOCUS_REMED_ROW
        (PIPELINE_NAME, GENERATION_NO, SOURCE_NAME_HASH,
         ORIGINAL_CHARGEPERIODSTART, ORIGINAL_REFERENCE, FINAL_REFERENCE,
         OUTCOME, RAW_ROW_JSON)
      VALUES (P_PIPELINE,P_GENERATION,P_HASH,L_PERIOD,L_ORIGINAL,L_FINAL,L_OUTCOME,L_RAW);
    EXCEPTION WHEN OTHERS THEN
      RAISE_APPLICATION_ERROR(-20874, 'Cannot record row provenance: ' || SQLERRM);
    END;
  END INSERT_ROW;
END OCI_FOCUS_REMED_ROW_API;
