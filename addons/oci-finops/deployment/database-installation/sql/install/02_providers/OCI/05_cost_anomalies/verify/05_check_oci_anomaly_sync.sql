-- Read-only result of the initial or most recent OCI Cost Anomaly attempt.
SET VERIFY OFF DEFINE OFF SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 190 PAGESIZE 100
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
PROMPT === Latest Cost Anomaly source attempt ===
COLUMN STATUS FORMAT A12
COLUMN ERROR_MESSAGE FORMAT A90
SELECT SYNC_RUN_ID,STATUS,STARTED_AT,COMPLETED_AT,
       MONITORS_READ,EVENTS_READ,ERROR_CODE,ERROR_MESSAGE
  FROM OCI_ANOMALY_SYNC_RUN
 ORDER BY SYNC_RUN_ID DESC FETCH FIRST 1 ROW ONLY;
PROMPT === Published anomaly observations ===
SELECT (SELECT COUNT(*) FROM OCI_ANOMALY_MONITORS_V) MONITORS,
       (SELECT COUNT(*) FROM OCI_ANOMALY_EVENTS_V) LATEST_KNOWN_EVENTS
  FROM DUAL;
PROMPT === Recent Cost Anomaly Scheduler attempt ===
COLUMN JOB_NAME FORMAT A28
SELECT JOB_NAME,STATUS,ACTUAL_START_DATE,RUN_DURATION,ERROR#
  FROM USER_SCHEDULER_JOB_RUN_DETAILS
 WHERE JOB_NAME='OCI_ANOMALY_DAILY'
 ORDER BY LOG_DATE DESC FETCH FIRST 1 ROW ONLY;
DECLARE
  L_RUN_STATUS VARCHAR2(30);
  L_JOB_STATUS VARCHAR2(30);
BEGIN
  SELECT MAX(STATUS) KEEP (DENSE_RANK LAST ORDER BY SYNC_RUN_ID)
    INTO L_RUN_STATUS FROM OCI_ANOMALY_SYNC_RUN;
  SELECT MAX(STATUS) KEEP (DENSE_RANK LAST ORDER BY LOG_ID)
    INTO L_JOB_STATUS FROM USER_SCHEDULER_JOB_RUN_DETAILS
   WHERE JOB_NAME='OCI_ANOMALY_DAILY';
  DBMS_OUTPUT.PUT_LINE('source='||NVL(L_RUN_STATUS,'NOT_STARTED')||
    ' scheduler='||NVL(L_JOB_STATUS,'NOT_FINISHED'));
  IF L_RUN_STATUS='COMPLETED' AND L_JOB_STATUS='SUCCEEDED' THEN
    DBMS_OUTPUT.PUT_LINE('OCI COST ANOMALY INITIAL SYNC PASS');
  ELSIF L_RUN_STATUS='FAILED' OR L_JOB_STATUS IN ('FAILED','STOPPED','BROKEN') THEN
    DBMS_OUTPUT.PUT_LINE('OCI COST ANOMALY INITIAL SYNC NEEDS ATTENTION');
  ELSE
    DBMS_OUTPUT.PUT_LINE('OCI COST ANOMALY INITIAL SYNC PENDING');
  END IF;
END;
