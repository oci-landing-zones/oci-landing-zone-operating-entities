@02_providers/OCI/03_budgets/internal/02_create_oci_budget_sync.sql

BEGIN
  DBMS_SCHEDULER.CREATE_JOB(
    JOB_NAME=>'OCI_BUDGET_DAILY',JOB_TYPE=>'STORED_PROCEDURE',
    JOB_ACTION=>'OCI_SYNC_BUDGETS',
    START_DATE=>FINOPS_CORE_SCHEDULE_API.LOCAL_START_DATE(),
    REPEAT_INTERVAL=>'FREQ=DAILY;BYHOUR=08;BYMINUTE=15;BYSECOND=00',
    ENABLED=>TRUE,COMMENTS=>'Read-only OCI Budgets and alert-rule snapshots');
END;
/

