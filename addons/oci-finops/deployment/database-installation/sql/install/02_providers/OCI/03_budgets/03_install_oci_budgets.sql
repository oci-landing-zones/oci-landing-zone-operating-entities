DECLARE N NUMBER; C NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'FOCUSPLATFORM' THEN
    RAISE_APPLICATION_ERROR(-20760,'Connect as FOCUSPLATFORM');
  END IF;
  SELECT COUNT(*) INTO C FROM USER_OBJECTS
   WHERE OBJECT_NAME='FINOPS_CORE_RUN_DAILY' AND STATUS='VALID';
  SELECT COUNT(*) INTO N FROM USER_OBJECTS
   WHERE OBJECT_NAME LIKE 'OCI_BUDGET_%' OR OBJECT_NAME='OCI_SYNC_BUDGETS';
  IF C<>1 OR N<>0 THEN
    RAISE_APPLICATION_ERROR(-20760,
      'Install common core first; budgets module must be clean');
  END IF;
  DBMS_OUTPUT.PUT_LINE('Budgets module preflight passed');
END;
/

