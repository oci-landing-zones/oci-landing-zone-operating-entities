DECLARE
  L_SCHEMA_GRANT NUMBER;
BEGIN
  SELECT COUNT(*) INTO L_SCHEMA_GRANT FROM DBA_TAB_PRIVS
   WHERE OWNER = 'ADMIN' AND TABLE_NAME = 'OCI$RESOURCE_PRINCIPAL'
     AND GRANTEE = 'FOCUSPLATFORM';
  IF L_SCHEMA_GRANT = 0 THEN
    DBMS_CLOUD_ADMIN.ENABLE_RESOURCE_PRINCIPAL(
      USERNAME => 'FOCUSPLATFORM', GRANT_OPTION => FALSE);
    DBMS_OUTPUT.PUT_LINE('FOCUSPLATFORM resource principal enabled');
  END IF;
END;
