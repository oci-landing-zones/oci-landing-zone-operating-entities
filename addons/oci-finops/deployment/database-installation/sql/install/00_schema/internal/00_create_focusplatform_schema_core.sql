WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
PROMPT FOCUSPLATFORM SCHEMA INSTALLATION

DECLARE
  L_EXISTING NUMBER;
  L_EXISTING_READER NUMBER;
  L_ADMIN_CREDENTIAL NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'ADMIN' THEN
    RAISE_APPLICATION_ERROR(-20900, 'Connect as ADMIN before running this script');
  END IF;
  SELECT COUNT(*) INTO L_EXISTING FROM DBA_USERS
   WHERE USERNAME = 'FOCUSPLATFORM';
  SELECT COUNT(*) INTO L_EXISTING_READER FROM DBA_USERS
   WHERE USERNAME = 'OAC_FOCUS_READER';
  IF L_EXISTING <> 0 OR L_EXISTING_READER <> 0 THEN
    RAISE_APPLICATION_ERROR(-20901,
      'FOCUSPLATFORM or OAC_FOCUS_READER already exists; inspect before bootstrap');
  END IF;

  SELECT COUNT(*) INTO L_ADMIN_CREDENTIAL FROM DBA_CREDENTIALS
   WHERE OWNER = 'ADMIN' AND CREDENTIAL_NAME = 'OCI$RESOURCE_PRINCIPAL';
  IF L_ADMIN_CREDENTIAL = 0 THEN
    DBMS_CLOUD_ADMIN.ENABLE_RESOURCE_PRINCIPAL();
    DBMS_OUTPUT.PUT_LINE('ADMIN resource principal enabled');
  ELSE
    DBMS_OUTPUT.PUT_LINE('ADMIN resource principal already enabled');
  END IF;
  SELECT COUNT(*) INTO L_ADMIN_CREDENTIAL FROM DBA_CREDENTIALS
   WHERE OWNER = 'ADMIN' AND CREDENTIAL_NAME = 'OCI$RESOURCE_PRINCIPAL';
  IF L_ADMIN_CREDENTIAL <> 1 THEN
    RAISE_APPLICATION_ERROR(-20903,
      'ADMIN resource principal credential is unavailable');
  END IF;
END;
