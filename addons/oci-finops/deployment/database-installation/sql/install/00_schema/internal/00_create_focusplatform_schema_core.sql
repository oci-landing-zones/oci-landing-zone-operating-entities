DECLARE
  F VARCHAR2(4000) := :fp_focus_password;
  R VARCHAR2(4000) := :fp_reader_password;
BEGIN
  IF F IS NULL OR R IS NULL OR INSTR(F,'"')>0 OR INSTR(R,'"')>0 OR
     INSTR(F,CHR(10))>0 OR INSTR(R,CHR(10))>0 OR
     INSTR(F,CHR(13))>0 OR INSTR(R,CHR(13))>0 THEN
    RAISE_APPLICATION_ERROR(-20903,'Supply both nonempty password binds without double quotes or line breaks');
  END IF;
  EXECUTE IMMEDIATE 'CREATE USER FOCUSPLATFORM IDENTIFIED BY "'||F||'"';
  EXECUTE IMMEDIATE 'CREATE USER OAC_FOCUS_READER IDENTIFIED BY "'||R||'"';
  :fp_focus_password:=NULL;
  :fp_reader_password:=NULL;
END;
