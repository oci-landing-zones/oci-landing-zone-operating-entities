SET LINESIZE 190 PAGESIZE 100
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
PROMPT OAC OCI FOCUS COST DETAIL INSTALLATION

DECLARE
  L_REQUIRED_TABLES NUMBER;
  L_EXISTING NUMBER;
  L_PROFILE_COUNT NUMBER;
  L_MVIEW_ACCESS NUMBER;
  L_DIRECT_DDL NUMBER;
  L_MVIEW_LOG NUMBER;
  L_KNOWN_PARTIAL_OBJECTS NUMBER;
  L_RUNS NUMBER;
  L_FAILED_BUILD NUMBER;
  L_RUNNING_JOB NUMBER;
  L_RECOVERED BOOLEAN := FALSE;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER') <> 'FOCUSPLATFORM' OR
     SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> 'FOCUSPLATFORM' THEN
    RAISE_APPLICATION_ERROR(-20600,'Connect as FOCUSPLATFORM without changing CURRENT_SCHEMA');
  END IF;
  SELECT COUNT(*) INTO L_REQUIRED_TABLES FROM USER_OBJECTS
   WHERE OBJECT_NAME IN ('OCI_FOCUS_REPORTS','OCI_TAG_PROFILE_SELECTION',
                         'OCI_TAG_PROFILE_ITEM') AND OBJECT_TYPE='TABLE'
     AND STATUS='VALID';
  SELECT COUNT(*) INTO L_EXISTING FROM USER_OBJECTS
   WHERE OBJECT_NAME LIKE 'OAC_OCI_FOCUS_COST_DETAIL_%' OR OBJECT_NAME='OAC_OCI_FOCUS_COST_DETAIL'
      OR OBJECT_NAME='OAC_OCI_FOCUS_TAG_SLOT_V'
      OR OBJECT_NAME='MV_CAPABILITIES_TABLE' OR
      OBJECT_NAME LIKE 'OAC_OCI_FOCUS_COST_DETAIL_MV_V%';
  SELECT COUNT(*) INTO L_PROFILE_COUNT
    FROM OCI_TAG_PROFILE_SELECTION S JOIN OCI_TAG_PROFILE_ITEM I
      ON I.PROFILE_NAME=S.PROFILE_NAME
     AND I.PROFILE_VERSION=S.PROFILE_VERSION
   WHERE S.SELECTION_ID=1;
  SELECT COUNT(*) INTO L_MVIEW_ACCESS
    FROM ALL_SYNONYMS S JOIN ALL_TAB_PRIVS P
      ON P.TABLE_SCHEMA=S.TABLE_OWNER AND P.TABLE_NAME=S.TABLE_NAME
   WHERE S.OWNER='PUBLIC' AND S.SYNONYM_NAME='DBMS_MVIEW'
     AND S.TABLE_OWNER='SYS' AND S.TABLE_NAME='DBMS_SNAPSHOT'
     AND P.PRIVILEGE='EXECUTE'
     AND P.GRANTEE IN ('PUBLIC','FOCUSPLATFORM');
  SELECT COUNT(*) INTO L_MVIEW_LOG FROM USER_MVIEW_LOGS
   WHERE MASTER='OCI_FOCUS_REPORTS';
  SELECT COUNT(*) INTO L_DIRECT_DDL FROM USER_SYS_PRIVS
   WHERE PRIVILEGE IN ('CREATE TABLE','CREATE MATERIALIZED VIEW','CREATE SYNONYM','CREATE JOB');
  IF L_REQUIRED_TABLES<>3 OR L_PROFILE_COUNT=0 OR L_MVIEW_ACCESS=0 OR
     L_DIRECT_DDL<>4 THEN
    RAISE_APPLICATION_ERROR(-20600,
      'OCI landing, active tag profile or direct OAC creation privileges are missing');
  END IF;
  IF L_EXISTING IN (8,9) AND L_MVIEW_LOG=1 THEN
    SELECT COUNT(*) INTO L_KNOWN_PARTIAL_OBJECTS FROM USER_OBJECTS
     WHERE OBJECT_NAME IN ('MV_CAPABILITIES_TABLE',
       'OAC_OCI_FOCUS_COST_DETAIL_RUN',
       'OAC_OCI_FOCUS_COST_DETAIL_TAG_COLUMN',
       'OAC_OCI_FOCUS_COST_DETAIL_TAG_COLUMN_PK',
       'OAC_OCI_FOCUS_COST_DETAIL_TAG_COLUMN_NAME_UQ',
       'OAC_OCI_FOCUS_TAG_SLOT_V',
       'OAC_OCI_FOCUS_COST_DETAIL_API',
       'OAC_OCI_FOCUS_COST_DETAIL_REFRESH_DAILY');
    EXECUTE IMMEDIATE
      'SELECT COUNT(*),COUNT(CASE WHEN RUN_KIND=''BUILD'' AND '||
      'STATUS=''ERROR'' AND ERROR_CODE IN (-20604,-1031) THEN 1 END) '||
      'FROM OAC_OCI_FOCUS_COST_DETAIL_RUN'
      INTO L_RUNS,L_FAILED_BUILD;
    SELECT COUNT(*) INTO L_RUNNING_JOB FROM USER_SCHEDULER_RUNNING_JOBS
     WHERE JOB_NAME LIKE 'OAC_OCI_FOCUS_COST_DETAIL%';
    IF L_KNOWN_PARTIAL_OBJECTS=L_EXISTING AND L_RUNS=1 AND
       L_FAILED_BUILD=1 AND L_RUNNING_JOB=0 THEN
      DBMS_OUTPUT.PUT_LINE(
        'Removing only the known incomplete OAC build from the earlier capability or privilege check');
      DBMS_SCHEDULER.DROP_JOB('OAC_OCI_FOCUS_COST_DETAIL_REFRESH_DAILY');
      EXECUTE IMMEDIATE 'DROP PACKAGE OAC_OCI_FOCUS_COST_DETAIL_API';
      IF L_EXISTING=9 THEN
        EXECUTE IMMEDIATE 'DROP VIEW OAC_OCI_FOCUS_TAG_SLOT_V';
      END IF;
      EXECUTE IMMEDIATE 'DROP TABLE OAC_OCI_FOCUS_COST_DETAIL_TAG_COLUMN PURGE';
      EXECUTE IMMEDIATE 'DROP TABLE OAC_OCI_FOCUS_COST_DETAIL_RUN PURGE';
      EXECUTE IMMEDIATE 'DROP TABLE MV_CAPABILITIES_TABLE PURGE';
      L_EXISTING:=0;
      L_RECOVERED:=TRUE;
    END IF;
  END IF;
  DBMS_OUTPUT.PUT_LINE('required_oci_tables='||L_REQUIRED_TABLES||
    ' active_profile_tags='||L_PROFILE_COUNT||
    ' existing_oac_objects='||L_EXISTING||
    ' mview_access='||L_MVIEW_ACCESS||' landing_mv_logs='||L_MVIEW_LOG);
  IF L_REQUIRED_TABLES<>3 OR L_EXISTING<>0 OR L_PROFILE_COUNT=0 THEN
    RAISE_APPLICATION_ERROR(-20600,
      'OCI tables, active tag profile or clean OAC module preflight failed; inspect counts above');
  END IF;
  IF L_MVIEW_ACCESS=0 OR (L_MVIEW_LOG<>0 AND NOT L_RECOVERED) THEN
    RAISE_APPLICATION_ERROR(-20611,
      'DBMS_MVIEW access is required and the OCI landing MV log must be absent unless resuming the known failed build');
  END IF;
  DBMS_OUTPUT.PUT_LINE('Landing, selected profile and clean OAC cost detail preflight passed');
END;
/

DECLARE
  L_LOG NUMBER;
BEGIN
  SELECT COUNT(*) INTO L_LOG FROM USER_MVIEW_LOGS
   WHERE MASTER='OCI_FOCUS_REPORTS';
  IF L_LOG=0 THEN
    EXECUTE IMMEDIATE 'CREATE MATERIALIZED VIEW LOG ON OCI_FOCUS_REPORTS '||
      'WITH PRIMARY KEY, ROWID, SEQUENCE INCLUDING NEW VALUES';
  ELSE
    DBMS_OUTPUT.PUT_LINE('Reusing OCI landing MV log from the incomplete first attempt');
  END IF;
END;
/

CREATE TABLE MV_CAPABILITIES_TABLE (
  STATEMENT_ID VARCHAR2(30), MVOWNER VARCHAR2(128), MVNAME VARCHAR2(128),
  CAPABILITY_NAME VARCHAR2(30), POSSIBLE CHAR(1),
  RELATED_TEXT VARCHAR2(2000), RELATED_NUM NUMBER,
  MSGNO INTEGER, MSGTXT VARCHAR2(2000), SEQ NUMBER
);

CREATE TABLE OAC_OCI_FOCUS_COST_DETAIL_RUN (
  RUN_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  RUN_KIND VARCHAR2(10) NOT NULL CHECK (RUN_KIND IN ('BUILD','REFRESH')),
  STATUS VARCHAR2(12) NOT NULL CHECK
    (STATUS IN ('RUNNING','PREPARED','READY','COMPLETE','ERROR','SKIPPED')),
  MV_NAME VARCHAR2(128),
  PROFILE_NAME VARCHAR2(128),
  PROFILE_VERSION NUMBER(8),
  TAG_COLUMNS NUMBER,
  MV_ROWS NUMBER,
  STARTED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  FINISHED_AT TIMESTAMP(6) WITH TIME ZONE,
  ERROR_CODE NUMBER,
  ERROR_MESSAGE VARCHAR2(4000)
);

CREATE TABLE OAC_OCI_FOCUS_COST_DETAIL_TAG_COLUMN (
  RUN_ID NUMBER NOT NULL REFERENCES OAC_OCI_FOCUS_COST_DETAIL_RUN(RUN_ID),
  DISPLAY_ORDER NUMBER(4) NOT NULL,
  LOGICAL_TAG_NAME VARCHAR2(256) NOT NULL,
  MV_COLUMN_NAME VARCHAR2(128) NOT NULL,
  TAG_NAMESPACE_ID VARCHAR2(255) NOT NULL,
  TAG_NAME VARCHAR2(100) NOT NULL,
  CONSTRAINT OAC_OCI_FOCUS_COST_DETAIL_TAG_COLUMN_PK PRIMARY KEY (RUN_ID,DISPLAY_ORDER),
  CONSTRAINT OAC_OCI_FOCUS_COST_DETAIL_TAG_COLUMN_NAME_UQ UNIQUE (RUN_ID,MV_COLUMN_NAME)
);

CREATE TABLE OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE (
  GATE_ID NUMBER PRIMARY KEY CHECK (GATE_ID = 1),
  STATUS VARCHAR2(14) DEFAULT 'NOT_STARTED' NOT NULL CHECK
    (STATUS IN ('NOT_STARTED','WAITING','REFRESHING','COMPLETE','ERROR')),
  PIPELINES_STARTED_AT TIMESTAMP WITH TIME ZONE,
  LAST_CHECK_AT TIMESTAMP WITH TIME ZONE,
  FAILED_PIPELINES NUMBER DEFAULT 0 NOT NULL,
  ERROR_MESSAGE VARCHAR2(4000),
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
INSERT INTO OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE (GATE_ID, STATUS)
VALUES (1, 'NOT_STARTED');
COMMIT;

