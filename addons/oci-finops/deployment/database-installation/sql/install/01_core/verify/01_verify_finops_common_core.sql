-- Read-only installation gate for the provider-neutral core in FOCUSPLATFORM.
SET LINESIZE 180 PAGESIZE 100 SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE
COLUMN OBJECT_NAME FORMAT A34
COLUMN OBJECT_TYPE FORMAT A19
COLUMN STATUS FORMAT A10
COLUMN JOB_NAME FORMAT A25
COLUMN ENABLED FORMAT A8
COLUMN REPEAT_INTERVAL FORMAT A60

PROMPT === Common core objects ===
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS
 WHERE OBJECT_NAME LIKE 'FINOPS_CORE_%'
 ORDER BY OBJECT_TYPE, OBJECT_NAME;

PROMPT === Scheduler ===
SELECT JOB_NAME, ENABLED, REPEAT_INTERVAL FROM USER_SCHEDULER_JOBS
 WHERE JOB_NAME = 'FINOPS_CORE_DAILY';

DECLARE
  L_TABLES NUMBER;
  L_ROUTINES NUMBER;
  L_INVALID NUMBER;
  L_PROVIDERS NUMBER;
  L_MOCKS NUMBER;
  L_NOTIFY CHAR(1);
  L_TOPIC VARCHAR2(255);
  L_JOB VARCHAR2(5);
  L_GRANT NUMBER;
  L_NOTIFY_GRANT NUMBER;
  L_DRY_RUN NUMBER;
  L_LOCK_POLICY NUMBER;
  L_NOTIFY_CONFIG_VALID NUMBER := 0;
  L_TIME_ZONE VARCHAR2(64);
  L_SCHEDULE_API NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'FOCUSPLATFORM' THEN
    RAISE_APPLICATION_ERROR(-20900,
      'Connect as FOCUSPLATFORM to verify the common core');
  END IF;
  SELECT COUNT(*) INTO L_TABLES FROM USER_OBJECTS
   WHERE OBJECT_NAME LIKE 'FINOPS_CORE_%' AND OBJECT_TYPE = 'TABLE';
  SELECT COUNT(*) INTO L_ROUTINES FROM USER_OBJECTS
   WHERE OBJECT_NAME IN ('FINOPS_CORE_REPORT','FINOPS_CORE_RUN_DAILY','FINOPS_CORE_ENDPOINT_DOMAIN')
     AND OBJECT_TYPE IN ('FUNCTION','PROCEDURE') AND STATUS = 'VALID';
  SELECT COUNT(*) INTO L_SCHEDULE_API FROM USER_OBJECTS
   WHERE OBJECT_NAME IN ('FINOPS_CORE_SCHEDULE_API')
     AND OBJECT_TYPE IN ('PACKAGE','PACKAGE BODY') AND STATUS = 'VALID';
  SELECT COUNT(*) INTO L_INVALID FROM USER_OBJECTS
   WHERE OBJECT_NAME LIKE 'FINOPS_CORE_%' AND STATUS <> 'VALID';
  SELECT COUNT(*) INTO L_PROVIDERS FROM FINOPS_CORE_PROVIDER;
  SELECT COUNT(*) INTO L_MOCKS FROM USER_OBJECTS
   WHERE OBJECT_NAME IN ('ERR_CORE_TEST_API','TST_CORE_TEST_API');
  SELECT ENABLED, TOPIC_OCID INTO L_NOTIFY, L_TOPIC
    FROM FINOPS_CORE_NOTIFY_CONFIG
   WHERE CONFIG_ID = 1;
  IF (L_NOTIFY = 'N' AND L_TOPIC IS NULL) OR
     (L_NOTIFY = 'Y' AND L_TOPIC IS NOT NULL AND
      REGEXP_LIKE(L_TOPIC, '^ocid1\.onstopic\.oc[0-9]+\.[A-Za-z0-9._-]+$')) THEN
    L_NOTIFY_CONFIG_VALID := 1;
  END IF;
  SELECT ENABLED INTO L_JOB FROM USER_SCHEDULER_JOBS
   WHERE JOB_NAME = 'FINOPS_CORE_DAILY';
  SELECT TIME_ZONE INTO L_TIME_ZONE FROM FINOPS_CORE_SCHEDULE_CONFIG
   WHERE CONFIG_ID = 1;
  SELECT COUNT(*) INTO L_GRANT FROM USER_TAB_PRIVS_RECD
   WHERE TABLE_NAME = 'DBMS_LOCK' AND PRIVILEGE = 'EXECUTE';
  SELECT COUNT(*) INTO L_NOTIFY_GRANT FROM USER_TAB_PRIVS_RECD
   WHERE TABLE_NAME = 'DBMS_CLOUD_NOTIFICATION' AND PRIVILEGE = 'EXECUTE';
  SELECT COUNT(*) INTO L_DRY_RUN FROM FINOPS_CORE_RUN
   WHERE STATUS = 'COMPLETE' AND EMAIL_STATUS = 'SKIPPED'
     AND PROVIDERS_FOUND = 0 AND PROVIDERS_ERROR = 0;
  SELECT COUNT(*) INTO L_LOCK_POLICY FROM USER_SOURCE
   WHERE NAME = 'FINOPS_CORE_RUN_DAILY' AND TYPE = 'PROCEDURE'
     AND UPPER(TEXT) LIKE '%TIMEOUT => 0%';
  DBMS_OUTPUT.PUT_LINE('tables=' || L_TABLES ||
    ' valid_routines=' || L_ROUTINES || ' invalid=' || L_INVALID);
  DBMS_OUTPUT.PUT_LINE('scheduler_time_zone=' || L_TIME_ZONE ||
    ' valid_schedule_api_objects=' || L_SCHEDULE_API);
  DBMS_OUTPUT.PUT_LINE('registered_providers=' || L_PROVIDERS ||
    ' test_packages=' || L_MOCKS || ' dbms_lock_grant=' || L_GRANT ||
    ' notification_grant=' || L_NOTIFY_GRANT);
  DBMS_OUTPUT.PUT_LINE('daily_job_enabled=' || L_JOB ||
    ' notification_enabled=' || L_NOTIFY ||
    ' topic_configured=' || CASE WHEN L_TOPIC IS NOT NULL THEN 'Y' ELSE 'N' END ||
    ' notification_config_valid=' || L_NOTIFY_CONFIG_VALID);
  DBMS_OUTPUT.PUT_LINE('successful_no_email_runs=' || L_DRY_RUN ||
    ' nonwaiting_lock_policy=' || L_LOCK_POLICY);
  IF L_TABLES <> 6 OR L_ROUTINES <> 3 OR L_SCHEDULE_API <> 2 OR L_INVALID <> 0 OR
     L_PROVIDERS <> 0 OR L_MOCKS <> 0 OR
     L_GRANT <> 1 OR L_NOTIFY_GRANT <> 1 OR
     L_JOB <> 'TRUE' OR L_NOTIFY_CONFIG_VALID <> 1 OR L_DRY_RUN = 0 OR
     L_LOCK_POLICY <> 1 THEN
    RAISE_APPLICATION_ERROR(-20910, 'FINOPS CORE verification failed');
  END IF;
  DBMS_OUTPUT.PUT_LINE('FINOPS CORE VERIFICATION PASS');
END;
/
