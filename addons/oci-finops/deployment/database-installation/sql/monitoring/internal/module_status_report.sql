  TYPE MODULE_REC IS RECORD (
    LABEL VARCHAR2(80), MANDATORY CHAR(1), EXPECTED VARCHAR2(32767),
    DEPS VARCHAR2(100), STATE VARCHAR2(30), FOUND NUMBER,
    MISSING NUMBER, INVALID NUMBER, CONFIG_BAD NUMBER);
  TYPE MODULE_MAP IS TABLE OF MODULE_REC INDEX BY VARCHAR2(20);
  TYPE ID_LIST IS TABLE OF VARCHAR2(20) INDEX BY PLS_INTEGER;
  M MODULE_MAP; IDS ID_LIST; N PLS_INTEGER:=0;
  OWNER_NAME VARCHAR2(128):=SYS_CONTEXT('USERENV','CURRENT_SCHEMA');
  BASELINE_OK BOOLEAN:=TRUE;
  L_DETAIL VARCHAR2(5):=NVL(:fp_status_detail,'LONG');
  ID VARCHAR2(20); DEP VARCHAR2(20); I PLS_INTEGER;
  FILTER_JSON JSON_ARRAY_T := JSON_ARRAY_T.PARSE(NVL(:fp_status_module_ids, TO_CLOB('["ALL"]')));
  FUNCTION SELECTED(P_ID VARCHAR2) RETURN BOOLEAN IS
  BEGIN
    IF P_ID IN ('CORE','OCI00','OCI01A','OCI02') THEN RETURN TRUE; END IF;
    FOR K IN 0..FILTER_JSON.GET_SIZE-1 LOOP
      IF FILTER_JSON.GET_STRING(K) IN ('ALL',P_ID) THEN RETURN TRUE; END IF;
    END LOOP;
    RETURN FALSE;
  END;
  PROCEDURE ADD_MODULE(P_ID VARCHAR2,P_LABEL VARCHAR2,P_MANDATORY CHAR,
                       P_EXPECTED VARCHAR2,P_DEPS VARCHAR2) IS
  BEGIN
    N:=N+1; IDS(N):=P_ID; M(P_ID).LABEL:=P_LABEL;
    M(P_ID).MANDATORY:=P_MANDATORY; M(P_ID).EXPECTED:=P_EXPECTED;
    M(P_ID).DEPS:=P_DEPS;
  END;
  PROCEDURE CONFIG_CHECK(P_ID VARCHAR2,P_SQL VARCHAR2,P_MIN NUMBER DEFAULT 1) IS
    C NUMBER;
  BEGIN
    IF SELECTED(P_ID) AND M(P_ID).STATE='INSTALLED' THEN
      BEGIN
        EXECUTE IMMEDIATE P_SQL INTO C;
        IF C<P_MIN THEN
          M(P_ID).CONFIG_BAD:=1; M(P_ID).STATE:='NEEDS_CONFIGURATION';
          DBMS_OUTPUT.PUT_LINE('CONFIG '||P_ID||': required configuration is missing');
        END IF;
      EXCEPTION WHEN OTHERS THEN
        M(P_ID).CONFIG_BAD:=1; M(P_ID).STATE:='CHECK_ERROR';
        DBMS_OUTPUT.PUT_LINE('CONFIG '||P_ID||': '||SQLERRM);
      END;
    END IF;
  END;
  PROCEDURE CHECK_MODULE(P_ID VARCHAR2) IS
    TOKEN VARCHAR2(260); KIND VARCHAR2(30); NAME VARCHAR2(128);
    CNT NUMBER; BAD NUMBER; I PLS_INTEGER:=1;
  BEGIN
    M(P_ID).FOUND:=0; M(P_ID).MISSING:=0; M(P_ID).INVALID:=0;
    M(P_ID).CONFIG_BAD:=0;
    LOOP
      TOKEN:=REGEXP_SUBSTR(M(P_ID).EXPECTED,'[^,]+',1,I);
      EXIT WHEN TOKEN IS NULL;
      KIND:=SUBSTR(TOKEN,1,INSTR(TOKEN,':')-1);
      NAME:=SUBSTR(TOKEN,INSTR(TOKEN,':')+1);
      IF KIND='JOB' THEN
        SELECT COUNT(*),0 INTO CNT,BAD FROM ALL_SCHEDULER_JOBS
        WHERE OWNER=OWNER_NAME AND JOB_NAME=NAME;
      ELSE
        SELECT COUNT(*),COUNT(CASE WHEN STATUS<>'VALID' THEN 1 END)
        INTO CNT,BAD FROM ALL_OBJECTS
        WHERE OWNER=OWNER_NAME AND OBJECT_TYPE=KIND AND OBJECT_NAME=NAME;
      END IF;
      IF CNT=0 THEN M(P_ID).MISSING:=M(P_ID).MISSING+1;
      ELSE M(P_ID).FOUND:=M(P_ID).FOUND+1; END IF;
      M(P_ID).INVALID:=M(P_ID).INVALID+BAD;
      I:=I+1;
    END LOOP;
    M(P_ID).STATE:=CASE WHEN M(P_ID).FOUND=0 THEN 'NOT_INSTALLED'
      WHEN M(P_ID).MISSING>0 THEN 'PARTIAL'
      WHEN M(P_ID).INVALID>0 THEN 'INVALID' ELSE 'INSTALLED' END;
  END;
  PROCEDURE SOURCE_AUDIT(P_TABLE VARCHAR2) IS
    C NUMBER; L_STATUS VARCHAR2(100); L_ERROR VARCHAR2(1000);
  BEGIN
    SELECT COUNT(*) INTO C FROM ALL_TAB_COLUMNS WHERE OWNER=OWNER_NAME
      AND TABLE_NAME=P_TABLE AND COLUMN_NAME IN ('STATUS','STARTED_AT','ERROR_MESSAGE');
    IF C<>3 THEN DBMS_OUTPUT.PUT_LINE('  SOURCE '||P_TABLE||': NOT AVAILABLE'); RETURN; END IF;
    BEGIN
      EXECUTE IMMEDIATE 'SELECT STATUS,SUBSTR(ERROR_MESSAGE,1,500) FROM '||DBMS_ASSERT.SIMPLE_SQL_NAME(P_TABLE)||
        ' ORDER BY STARTED_AT DESC FETCH FIRST 1 ROW ONLY' INTO L_STATUS,L_ERROR;
      DBMS_OUTPUT.PUT_LINE('  SOURCE '||P_TABLE||': '||L_STATUS||' '||L_ERROR);
    EXCEPTION WHEN NO_DATA_FOUND THEN DBMS_OUTPUT.PUT_LINE('  SOURCE '||P_TABLE||': NO RUNS YET'); END;
  EXCEPTION WHEN OTHERS THEN DBMS_OUTPUT.PUT_LINE('  SOURCE CHECK_ERROR '||P_TABLE||': '||SQLERRM);
  END;
  FUNCTION CELL(P_VALUE VARCHAR2,P_WIDTH NUMBER) RETURN VARCHAR2 IS
  BEGIN RETURN RPAD(SUBSTR(NVL(REPLACE(REPLACE(P_VALUE,CHR(10),' '),CHR(13),' '),'-'),1,P_WIDTH),P_WIDTH)||' | '; END;
  FUNCTION SCHEDULE_LABEL(P_INTERVAL VARCHAR2) RETURN VARCHAR2 IS
    H VARCHAR2(8):=REGEXP_SUBSTR(P_INTERVAL,'BYHOUR=([0-9]+)',1,1,NULL,1);
    MI VARCHAR2(8):=REGEXP_SUBSTR(P_INTERVAL,'BYMINUTE=([0-9]+)',1,1,NULL,1);
    EVERY_N VARCHAR2(8):=NVL(REGEXP_SUBSTR(P_INTERVAL,';INTERVAL=([0-9]+)',1,1,NULL,1),'1');
    D VARCHAR2(8):=REGEXP_SUBSTR(P_INTERVAL,'BYMONTHDAY=([0-9]+)',1,1,NULL,1);
  BEGIN
    IF P_INTERVAL IS NULL THEN RETURN 'One-time / on demand'; END IF;
    IF INSTR(P_INTERVAL,'FREQ=DAILY')>0 THEN RETURN 'Daily '||LPAD(NVL(H,'0'),2,'0')||':'||LPAD(NVL(MI,'0'),2,'0'); END IF;
    IF INSTR(P_INTERVAL,'FREQ=HOURLY')>0 THEN RETURN 'Every '||EVERY_N||' hour(s), minute '||NVL(MI,'0'); END IF;
    IF INSTR(P_INTERVAL,'FREQ=MINUTELY')>0 THEN RETURN 'Every '||EVERY_N||' minute(s)'; END IF;
    IF INSTR(P_INTERVAL,'FREQ=MONTHLY')>0 THEN RETURN 'Monthly day '||NVL(D,'?')||' '||LPAD(NVL(H,'0'),2,'0')||':'||LPAD(NVL(MI,'0'),2,'0'); END IF;
    RETURN P_INTERVAL;
  END;
  PROCEDURE TABLE_DETAILS(P_ID VARCHAR2) IS
    TYPE COUNTS_REC IS RECORD (FOUND NUMBER, MISSING NUMBER, INVALID NUMBER);
    TYPE COUNTS_MAP IS TABLE OF COUNTS_REC INDEX BY VARCHAR2(30);
    COUNTS COUNTS_MAP;
    TOKEN VARCHAR2(260); NAME VARCHAR2(128); KIND VARCHAR2(30); GROUP_NAME VARCHAR2(30);
    K PLS_INTEGER:=1; C NUMBER; BAD NUMBER; L_STATE VARCHAR2(30);
    PROCEDURE OBJECT_STATE IS
    BEGIN
      IF KIND='JOB' THEN
        SELECT COUNT(*),0 INTO C,BAD FROM ALL_SCHEDULER_JOBS WHERE OWNER=OWNER_NAME AND JOB_NAME=NAME;
        L_STATE:=CASE WHEN C>0 THEN 'CREATED' ELSE 'MISSING' END;
      ELSE
        SELECT COUNT(*),COUNT(CASE WHEN STATUS<>'VALID' THEN 1 END),MAX(STATUS)
          INTO C,BAD,L_STATE FROM ALL_OBJECTS
          WHERE OWNER=OWNER_NAME AND OBJECT_NAME=NAME AND OBJECT_TYPE=KIND;
        L_STATE:=NVL(L_STATE,'MISSING');
      END IF;
    END;
  BEGIN
    LOOP
      TOKEN:=REGEXP_SUBSTR(M(P_ID).EXPECTED,'[^,]+',1,K); EXIT WHEN TOKEN IS NULL;
      KIND:=SUBSTR(TOKEN,1,INSTR(TOKEN,':')-1); NAME:=SUBSTR(TOKEN,INSTR(TOKEN,':')+1);
      OBJECT_STATE;
      IF NOT COUNTS.EXISTS(KIND) THEN COUNTS(KIND).FOUND:=0; COUNTS(KIND).MISSING:=0; COUNTS(KIND).INVALID:=0; END IF;
      IF C>0 THEN COUNTS(KIND).FOUND:=COUNTS(KIND).FOUND+1;
      ELSE COUNTS(KIND).MISSING:=COUNTS(KIND).MISSING+1; END IF;
      COUNTS(KIND).INVALID:=COUNTS(KIND).INVALID+BAD;
      K:=K+1;
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('OBJECTS BY TYPE');
    DBMS_OUTPUT.PUT_LINE(CELL('OBJECT TYPE',24)||CELL('FOUND',12)||CELL('MISSING',12)||'INVALID');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',68,'-'));
    GROUP_NAME:=COUNTS.FIRST;
    WHILE GROUP_NAME IS NOT NULL LOOP
      DBMS_OUTPUT.PUT_LINE(CELL(GROUP_NAME,24)||CELL(TO_CHAR(COUNTS(GROUP_NAME).FOUND),12)||
        CELL(TO_CHAR(COUNTS(GROUP_NAME).MISSING),12)||TO_CHAR(COUNTS(GROUP_NAME).INVALID));
      GROUP_NAME:=COUNTS.NEXT(GROUP_NAME);
    END LOOP;
    DBMS_OUTPUT.PUT_LINE(' ');
    IF L_DETAIL='SHORT' THEN RETURN; END IF;
    DBMS_OUTPUT.PUT_LINE('TABLES AND OTHER OBJECTS');
    DBMS_OUTPUT.PUT_LINE(CELL('OBJECT TYPE',20)||CELL('OBJECT NAME',48)||CELL('CREATED',10)||'STATUS');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',100,'-'));
    K:=1;
    LOOP
      TOKEN:=REGEXP_SUBSTR(M(P_ID).EXPECTED,'[^,]+',1,K); EXIT WHEN TOKEN IS NULL;
      KIND:=SUBSTR(TOKEN,1,INSTR(TOKEN,':')-1); NAME:=SUBSTR(TOKEN,INSTR(TOKEN,':')+1);
      OBJECT_STATE;
      DBMS_OUTPUT.PUT_LINE(CELL(KIND,20)||CELL(NAME,48)||CELL(CASE WHEN C>0 THEN 'YES' ELSE 'NO' END,10)||L_STATE);
      K:=K+1;
    END LOOP;
    DBMS_OUTPUT.PUT_LINE(' ');
  END;
  PROCEDURE PIPELINE_DETAILS IS
    L_COUNT NUMBER; L_TRACKED NUMBER;
    L_DONE NUMBER; L_BAD NUMBER; L_PENDING NUMBER; L_RUNNING NUMBER; L_SKIPPED NUMBER;
    L_LAST_RESULT VARCHAR2(30); L_ERROR VARCHAR2(1000);
  BEGIN
    IF SYS_CONTEXT('USERENV','CURRENT_USER')=OWNER_NAME THEN
      DBMS_OUTPUT.PUT_LINE('PIPELINES - ORACLE RECORDED STATE');
      SELECT COUNT(*) INTO L_COUNT FROM USER_CLOUD_PIPELINES WHERE REGEXP_LIKE(PIPELINE_NAME,'^OCI_FOCUS_REPORTS_LOAD_[0-9]{4}$');
      IF L_COUNT=0 THEN DBMS_OUTPUT.PUT_LINE('No FOCUS year pipelines found.'); RETURN; END IF;
      DBMS_OUTPUT.PUT_LINE(CELL('PIPELINE NAME',40)||CELL('ORACLE STATE',14)||CELL('LAST JOB RESULT',16)||CELL('SCHEDULE',20)||'TRACKED FILES');
      DBMS_OUTPUT.PUT_LINE(RPAD('-',115,'-'));
      FOR P IN (SELECT P.PIPELINE_NAME,P.STATUS,P.STATUS_TABLE,
          DBMS_LOB.SUBSTR(A.ATTRIBUTE_VALUE,10,1) INTERVAL_MINUTES
        FROM USER_CLOUD_PIPELINES P LEFT JOIN USER_CLOUD_PIPELINE_ATTRIBUTES A
          ON A.PIPELINE_NAME=P.PIPELINE_NAME AND A.ATTRIBUTE_NAME='interval'
        WHERE REGEXP_LIKE(P.PIPELINE_NAME,'^OCI_FOCUS_REPORTS_LOAD_[0-9]{4}$')) LOOP
        L_LAST_RESULT:='NO RUN YET'; L_ERROR:=NULL;
        FOR H IN (SELECT STATUS,SUBSTR(ERROR_MESSAGE,1,500) ERROR_MESSAGE FROM USER_CLOUD_PIPELINE_HISTORY
          WHERE PIPELINE_NAME=P.PIPELINE_NAME ORDER BY START_DATE DESC FETCH FIRST 1 ROW ONLY) LOOP
          L_LAST_RESULT:=H.STATUS; L_ERROR:=H.ERROR_MESSAGE;
        END LOOP;
        L_TRACKED:=0; L_DONE:=0; L_BAD:=0; L_PENDING:=0; L_RUNNING:=0; L_SKIPPED:=0;
        IF P.STATUS_TABLE IS NOT NULL THEN
          EXECUTE IMMEDIATE 'SELECT COUNT(*),COUNT(CASE WHEN STATUS=''COMPLETED'' THEN 1 END),COUNT(CASE WHEN STATUS=''FAILED'' THEN 1 END),COUNT(CASE WHEN STATUS=''PENDING'' THEN 1 END),COUNT(CASE WHEN STATUS=''RUNNING'' THEN 1 END),COUNT(CASE WHEN STATUS=''SKIPPED'' THEN 1 END) FROM '||
            DBMS_ASSERT.SIMPLE_SQL_NAME(P.STATUS_TABLE)
            INTO L_TRACKED,L_DONE,L_BAD,L_PENDING,L_RUNNING,L_SKIPPED;
        END IF;
        DBMS_OUTPUT.PUT_LINE(CELL(P.PIPELINE_NAME,40)||CELL(P.STATUS,14)||CELL(L_LAST_RESULT,16)||
          CELL('Every '||P.INTERVAL_MINUTES||' min',20)||
          CASE WHEN P.STATUS_TABLE IS NULL THEN 'NO TRACKING TABLE' WHEN L_TRACKED=0 THEN '0 - NO RECORDS' ELSE TO_CHAR(L_TRACKED) END);
        IF L_DETAIL='SHORT' THEN CONTINUE; END IF;
        DBMS_OUTPUT.PUT_LINE('  ORACLE FILE STATUS: '||CELL('COMPLETED',12)||CELL('FAILED',12)||CELL('PENDING',12)||CELL('RUNNING',12)||'SKIPPED');
        DBMS_OUTPUT.PUT_LINE('                      '||CELL(TO_CHAR(L_DONE),12)||CELL(TO_CHAR(L_BAD),12)||CELL(TO_CHAR(L_PENDING),12)||CELL(TO_CHAR(L_RUNNING),12)||TO_CHAR(L_SKIPPED));
        IF P.STATUS_TABLE IS NOT NULL AND L_TRACKED=0 THEN
          DBMS_OUTPUT.PUT_LINE('  Oracle tracking table has no file records; no per-file result is established.');
        END IF;
        IF L_ERROR IS NOT NULL THEN DBMS_OUTPUT.PUT_LINE('  ORACLE HISTORY ERROR: '||CELL(L_ERROR,180)); END IF;
      END LOOP;
    END IF;
  EXCEPTION WHEN OTHERS THEN DBMS_OUTPUT.PUT_LINE('  PIPELINE CHECK_ERROR: '||SQLERRM);
  END;
  PROCEDURE RUNTIME_DETAILS(P_ID VARCHAR2) IS
    TOKEN VARCHAR2(260); NAME VARCHAR2(128); K PLS_INTEGER:=1;
    L_STATUS VARCHAR2(100); L_ERROR VARCHAR2(1000); C NUMBER;
    L_DONE NUMBER; L_BAD NUMBER; L_PENDING NUMBER; L_RUNNING NUMBER;
    L_LAST_RESULT VARCHAR2(30); L_JOB_ERROR VARCHAR2(1000);
  BEGIN
    DBMS_OUTPUT.PUT_LINE('JOBS AND SCHEDULES');
    DBMS_OUTPUT.PUT_LINE(CELL('JOB NAME',48)||CELL('ENABLED',9)||CELL('RUNNING',9)||CELL('LAST RESULT',15)||CELL('NEXT RUN (WITH OFFSET)',27)||'SCHEDULE');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',150,'-'));
    LOOP
      TOKEN:=REGEXP_SUBSTR(M(P_ID).EXPECTED,'[^,]+',1,K); EXIT WHEN TOKEN IS NULL;
      IF SUBSTR(TOKEN,1,4)='JOB:' THEN
        NAME:=SUBSTR(TOKEN,5);
        SELECT COUNT(*) INTO C FROM ALL_SCHEDULER_JOBS WHERE OWNER=OWNER_NAME AND JOB_NAME=NAME;
        IF C=0 THEN DBMS_OUTPUT.PUT_LINE(CELL(NAME,48)||'NOT CREATED'); END IF;
        FOR J IN (SELECT JOB_NAME,ENABLED,STATE,NEXT_RUN_DATE,REPEAT_INTERVAL,LAST_START_DATE FROM ALL_SCHEDULER_JOBS
                   WHERE OWNER=OWNER_NAME AND JOB_NAME=NAME) LOOP
          L_LAST_RESULT:='NO RUN YET'; L_JOB_ERROR:=NULL;
          FOR R IN (SELECT STATUS,ERROR#,SUBSTR(ADDITIONAL_INFO,1,600) INFO FROM ALL_SCHEDULER_JOB_RUN_DETAILS
            WHERE OWNER=OWNER_NAME AND JOB_NAME=NAME AND J.LAST_START_DATE IS NOT NULL
              AND ACTUAL_START_DATE >=
              (SELECT FROM_TZ(CAST(MIN(O.CREATED) AS TIMESTAMP),TO_CHAR(SYSTIMESTAMP,'TZR'))
                 FROM ALL_OBJECTS O WHERE O.OWNER=OWNER_NAME AND O.OBJECT_NAME=NAME AND O.OBJECT_TYPE='JOB')
            ORDER BY LOG_DATE DESC,LOG_ID DESC FETCH FIRST 1 ROW ONLY) LOOP
            L_LAST_RESULT:=R.STATUS;
            IF NVL(R.ERROR#,0)<>0 OR R.STATUS IN ('FAILED','STOPPED','BROKEN') THEN L_JOB_ERROR:='error='||R.ERROR#||' '||R.INFO; END IF;
          END LOOP;
          DBMS_OUTPUT.PUT_LINE(CELL(J.JOB_NAME,48)||CELL(CASE J.ENABLED WHEN 'TRUE' THEN 'YES' ELSE 'NO' END,9)||
            CELL(CASE WHEN J.STATE='RUNNING' THEN 'YES' ELSE 'NO' END,9)||CELL(L_LAST_RESULT,15)||
            CELL(TO_CHAR(J.NEXT_RUN_DATE,'YYYY-MM-DD HH24:MI TZH:TZM'),27)||SCHEDULE_LABEL(J.REPEAT_INTERVAL));
          IF L_JOB_ERROR IS NOT NULL THEN DBMS_OUTPUT.PUT_LINE('  ATTENTION: '||NAME||' '||CELL(L_JOB_ERROR,180)); END IF;
        END LOOP;
      END IF;
      K:=K+1;
    END LOOP;
    DBMS_OUTPUT.PUT_LINE(' ');
    CASE P_ID
      WHEN 'CORE' THEN SOURCE_AUDIT('FINOPS_CORE_RUN');
      WHEN 'OCI01B' THEN SOURCE_AUDIT('OCI_TAG_VALUE_RUN');
      WHEN 'OCI02' THEN SOURCE_AUDIT('OCI_ACCOUNT_CONTEXT_RUN'); SOURCE_AUDIT('OCI_ACCOUNT_CONTRACT_RUN');
      WHEN 'OCI03' THEN SOURCE_AUDIT('OCI_BUDGET_SYNC_RUN');
      WHEN 'OCI04' THEN SOURCE_AUDIT('OCI_ADVISOR_SYNC_RUN');
      WHEN 'OCI05' THEN SOURCE_AUDIT('OCI_ANOMALY_SYNC_RUN');
      WHEN 'OCI06' THEN SOURCE_AUDIT('OCI_FORECAST_RUN');
      WHEN 'OAC_COST' THEN
        SOURCE_AUDIT('OAC_OCI_FOCUS_COST_DETAIL_RUN');
        SELECT COUNT(*) INTO C FROM ALL_TABLES WHERE OWNER=OWNER_NAME AND TABLE_NAME='OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE';
        IF C=1 THEN
          EXECUTE IMMEDIATE 'SELECT STATUS,SUBSTR(ERROR_MESSAGE,1,500) FROM OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE WHERE GATE_ID=1' INTO L_STATUS,L_ERROR;
          DBMS_OUTPUT.PUT_LINE('INITIAL MV LOAD: '||L_STATUS||' '||L_ERROR);
        END IF;
        DBMS_OUTPUT.PUT_LINE(CELL('MATERIALIZED VIEW',48)||CELL('COMPILE',12)||CELL('FRESHNESS',16)||'LAST REFRESH');
        FOR V IN (SELECT MVIEW_NAME,COMPILE_STATE,STALENESS,LAST_REFRESH_TYPE FROM ALL_MVIEWS
          WHERE OWNER=OWNER_NAME AND MVIEW_NAME LIKE 'OAC_OCI_FOCUS_COST_DETAIL_MV_V%') LOOP
          DBMS_OUTPUT.PUT_LINE(CELL(V.MVIEW_NAME,48)||CELL(V.COMPILE_STATE,12)||CELL(V.STALENESS,16)||V.LAST_REFRESH_TYPE);
        END LOOP;
      ELSE NULL;
    END CASE;

  EXCEPTION WHEN OTHERS THEN DBMS_OUTPUT.PUT_LINE('  RUNTIME CHECK_ERROR '||P_ID||': '||SQLERRM);
  END;
  PROCEDURE DETAILS(P_ID VARCHAR2) IS
    TOKEN VARCHAR2(260); KIND VARCHAR2(30); NAME VARCHAR2(128);
    CNT NUMBER; BAD NUMBER; I PLS_INTEGER:=1;
  BEGIN
    IF M(P_ID).STATE IN ('NOT_INSTALLED','INSTALLED') THEN RETURN; END IF;
    LOOP
      TOKEN:=REGEXP_SUBSTR(M(P_ID).EXPECTED,'[^,]+',1,I);
      EXIT WHEN TOKEN IS NULL;
      KIND:=SUBSTR(TOKEN,1,INSTR(TOKEN,':')-1);
      NAME:=SUBSTR(TOKEN,INSTR(TOKEN,':')+1);
      IF KIND='JOB' THEN
        SELECT COUNT(*),0 INTO CNT,BAD FROM ALL_SCHEDULER_JOBS
        WHERE OWNER=OWNER_NAME AND JOB_NAME=NAME;
      ELSE
        SELECT COUNT(*),COUNT(CASE WHEN STATUS<>'VALID' THEN 1 END)
        INTO CNT,BAD FROM ALL_OBJECTS
        WHERE OWNER=OWNER_NAME AND OBJECT_TYPE=KIND AND OBJECT_NAME=NAME;
      END IF;
      IF CNT=0 THEN DBMS_OUTPUT.PUT_LINE('  MISSING '||KIND||' '||NAME);
      ELSIF BAD>0 THEN DBMS_OUTPUT.PUT_LINE('  INVALID '||KIND||' '||NAME); END IF;
      I:=I+1;
    END LOOP;
  END;
