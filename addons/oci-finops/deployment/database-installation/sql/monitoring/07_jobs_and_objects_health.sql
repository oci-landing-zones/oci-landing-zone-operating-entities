-- Optional read-only operating-state snapshot; no jobs are started or changed.
-- Run as FOCUSPLATFORM, or ADMIN with CURRENT_SCHEMA=FOCUSPLATFORM.
SET ECHO OFF VERIFY OFF DEFINE OFF FEEDBACK ON
SET LINESIZE 240 PAGESIZE 100 TRIMSPOOL ON
COLUMN OBJECT_NAME FORMAT A52
COLUMN OBJECT_TYPE FORMAT A22
COLUMN JOB_NAME FORMAT A48
COLUMN STATE FORMAT A18
COLUMN LAST_STATUS FORMAT A18
COLUMN LAST_START FORMAT A30
COLUMN NEXT_RUN FORMAT A30
PROMPT === Invalid schema objects (not the same as stale data) ===
SELECT OBJECT_NAME,OBJECT_TYPE,STATUS,LAST_DDL_TIME FROM ALL_OBJECTS
WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND STATUS<>'VALID'
ORDER BY OBJECT_TYPE,OBJECT_NAME;
PROMPT === Jobs, enablement and latest result ===
SELECT J.JOB_NAME,J.ENABLED,J.STATE,
 TO_CHAR(J.NEXT_RUN_DATE,'YYYY-MM-DD HH24:MI:SS TZH:TZM') NEXT_RUN,
 R.STATUS LAST_STATUS,TO_CHAR(R.ACTUAL_START_DATE,'YYYY-MM-DD HH24:MI:SS TZH:TZM') LAST_START,
 R.ERROR# LAST_ERROR,R.RUN_DURATION
FROM ALL_SCHEDULER_JOBS J
LEFT JOIN (SELECT OWNER,JOB_NAME,STATUS,ACTUAL_START_DATE,ERROR#,RUN_DURATION,
 ROW_NUMBER() OVER(PARTITION BY OWNER,JOB_NAME ORDER BY LOG_DATE DESC,LOG_ID DESC) RN
 FROM ALL_SCHEDULER_JOB_RUN_DETAILS H
 WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
 AND ACTUAL_START_DATE >=
   (SELECT FROM_TZ(CAST(MIN(O.CREATED) AS TIMESTAMP),TO_CHAR(SYSTIMESTAMP,'TZR'))
      FROM ALL_OBJECTS O WHERE O.OWNER=H.OWNER AND O.OBJECT_NAME=H.JOB_NAME AND O.OBJECT_TYPE='JOB')) R
 ON R.OWNER=J.OWNER AND R.JOB_NAME=J.JOB_NAME AND R.RN=1
WHERE J.OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') ORDER BY J.JOB_NAME;
PROMPT === Running jobs ===
SELECT JOB_NAME,SESSION_ID,ELAPSED_TIME FROM ALL_SCHEDULER_RUNNING_JOBS
WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') ORDER BY JOB_NAME;
PROMPT === Compilation errors ===
SELECT NAME,TYPE,LINE,POSITION,TEXT FROM ALL_ERRORS
WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND ATTRIBUTE='ERROR'
ORDER BY NAME,TYPE,SEQUENCE;
PROMPT === Unusable indexes and index partitions ===
SELECT INDEX_NAME,STATUS FROM ALL_INDEXES
WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND STATUS NOT IN ('VALID','N/A');
SELECT INDEX_NAME,PARTITION_NAME,STATUS FROM ALL_IND_PARTITIONS
WHERE INDEX_OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND STATUS<>'USABLE';
PROMPT === Disabled or unvalidated constraints ===
SELECT TABLE_NAME,CONSTRAINT_NAME,STATUS,VALIDATED FROM ALL_CONSTRAINTS
WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
 AND (STATUS<>'ENABLED' OR VALIDATED<>'VALIDATED') ORDER BY TABLE_NAME,CONSTRAINT_NAME;
PROMPT Disabled jobs can be intentional. SUCCEEDED alone does not prove complete source coverage.
