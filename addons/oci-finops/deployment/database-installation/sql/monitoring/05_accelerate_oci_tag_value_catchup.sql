-- Run as FOCUSPLATFORM after the optional OCI tag-value module is installed.
-- Change only the existing tag-value worker's batch limit and cadence.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 200 PAGESIZE 100
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
  L_CONFIG NUMBER;
  L_JOB NUMBER;
  L_RUNNING NUMBER;
BEGIN
  SELECT COUNT(*) INTO L_CONFIG FROM OCI_TAG_VALUE_CONFIG
   WHERE CONFIG_ID=1 AND MAX_ROWS_PER_RUN IN (10000,40000);
  SELECT COUNT(*) INTO L_JOB FROM USER_SCHEDULER_JOBS
   WHERE JOB_NAME='OCI_TAG_VALUE_HOURLY'
     AND JOB_ACTION='OCI_TAG_VALUE_API.RUN_SCHEDULED'
     AND ENABLED='TRUE';
  SELECT COUNT(*) INTO L_RUNNING FROM USER_SCHEDULER_RUNNING_JOBS
   WHERE JOB_NAME='OCI_TAG_VALUE_HOURLY';
  IF L_CONFIG<>1 OR L_JOB<>1 OR L_RUNNING<>0 THEN
    RAISE_APPLICATION_ERROR(-20983,
      'Expected one enabled, idle OCI tag-value worker and a 10000/40000-row config');
  END IF;
  DBMS_SCHEDULER.SET_ATTRIBUTE(
    NAME=>'OCI_TAG_VALUE_HOURLY',ATTRIBUTE=>'repeat_interval',
    VALUE=>'FREQ=HOURLY;BYMINUTE=00,05,10,15,20,25,30,35,40,45,50,55;BYSECOND=00');
  UPDATE OCI_TAG_VALUE_CONFIG
     SET MAX_ROWS_PER_RUN=40000,UPDATED_AT=SYSTIMESTAMP
   WHERE CONFIG_ID=1;
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('OCI TAG VALUE CATCH-UP SET TO 40000 ROWS EVERY 5 MINUTES');
END;
/

COLUMN JOB_NAME FORMAT A28
COLUMN ENABLED FORMAT A7
COLUMN STATE FORMAT A12
COLUMN REPEAT_INTERVAL FORMAT A88
COLUMN NEXT_RUN FORMAT A26
SELECT C.MAX_ROWS_PER_RUN,J.JOB_NAME,J.ENABLED,J.STATE,
       J.REPEAT_INTERVAL,
       TO_CHAR(J.NEXT_RUN_DATE,'YYYY-MM-DD HH24:MI:SS TZH:TZM') NEXT_RUN
  FROM OCI_TAG_VALUE_CONFIG C CROSS JOIN USER_SCHEDULER_JOBS J
 WHERE C.CONFIG_ID=1 AND J.JOB_NAME='OCI_TAG_VALUE_HOURLY';

DECLARE
  L_VALID NUMBER;
BEGIN
  SELECT COUNT(*) INTO L_VALID
    FROM OCI_TAG_VALUE_CONFIG C CROSS JOIN USER_SCHEDULER_JOBS J
   WHERE C.CONFIG_ID=1 AND C.MAX_ROWS_PER_RUN=40000
     AND J.JOB_NAME='OCI_TAG_VALUE_HOURLY' AND J.ENABLED='TRUE'
     AND J.REPEAT_INTERVAL=
       'FREQ=HOURLY;BYMINUTE=00,05,10,15,20,25,30,35,40,45,50,55;BYSECOND=00';
  IF L_VALID<>1 THEN
    RAISE_APPLICATION_ERROR(-20984,'OCI tag-value catch-up configuration verification failed');
  END IF;
  DBMS_OUTPUT.PUT_LINE('OCI TAG VALUE CATCH-UP CONFIGURATION PASS');
END;
/
