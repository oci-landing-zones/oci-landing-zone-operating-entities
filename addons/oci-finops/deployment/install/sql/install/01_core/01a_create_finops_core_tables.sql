CREATE TABLE FINOPS_CORE_PROVIDER (
  PROVIDER_CODE VARCHAR2(3) PRIMARY KEY,
  LANDING_TABLE VARCHAR2(128) NOT NULL UNIQUE,
  API_PACKAGE VARCHAR2(128) NOT NULL UNIQUE,
  ENABLED CHAR(1) DEFAULT 'N' NOT NULL CHECK (ENABLED IN ('Y','N')),
  MAX_FILES_PER_PIPELINE NUMBER(4) DEFAULT 2000 NOT NULL
    CHECK (MAX_FILES_PER_PIPELINE BETWEEN 1 AND 2000),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE FINOPS_CORE_RUN (
  RUN_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  STARTED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  FINISHED_AT TIMESTAMP WITH TIME ZONE,
  STATUS VARCHAR2(20) DEFAULT 'RUNNING' NOT NULL
    CHECK (STATUS IN ('RUNNING','COMPLETE','ERROR','INTERRUPTED')),
  PROVIDERS_FOUND NUMBER DEFAULT 0 NOT NULL,
  PROVIDERS_ERROR NUMBER DEFAULT 0 NOT NULL,
  PIPELINES_FOUND NUMBER DEFAULT 0 NOT NULL,
  PIPELINES_ERROR NUMBER DEFAULT 0 NOT NULL,
  FILES_FULL NUMBER DEFAULT 0 NOT NULL,
  FILES_PARTIAL NUMBER DEFAULT 0 NOT NULL,
  FILES_ERROR NUMBER DEFAULT 0 NOT NULL,
  PIPELINES_AT_LIMIT NUMBER DEFAULT 0 NOT NULL,
  EMAIL_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL
    CHECK (EMAIL_STATUS IN ('PENDING','SENT','SKIPPED','ERROR')),
  EMAIL_ERROR VARCHAR2(4000),
  ERROR_MESSAGE VARCHAR2(4000)
);

CREATE TABLE FINOPS_CORE_PROVIDER_RUN (
  RUN_ID NUMBER NOT NULL REFERENCES FINOPS_CORE_RUN(RUN_ID),
  PROVIDER_CODE VARCHAR2(3) NOT NULL
    REFERENCES FINOPS_CORE_PROVIDER(PROVIDER_CODE),
  LANDING_TABLE VARCHAR2(128) NOT NULL,
  STARTED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  FINISHED_AT TIMESTAMP WITH TIME ZONE,
  STATUS VARCHAR2(20) DEFAULT 'RUNNING' NOT NULL
    CHECK (STATUS IN ('RUNNING','COMPLETE','ERROR','INTERRUPTED')),
  PIPELINES_FOUND NUMBER DEFAULT 0 NOT NULL,
  PIPELINES_ERROR NUMBER DEFAULT 0 NOT NULL,
  FILES_FULL NUMBER DEFAULT 0 NOT NULL,
  FILES_PARTIAL NUMBER DEFAULT 0 NOT NULL,
  FILES_ERROR NUMBER DEFAULT 0 NOT NULL,
  PIPELINES_AT_LIMIT NUMBER DEFAULT 0 NOT NULL,
  ERROR_MESSAGE VARCHAR2(4000),
  CONSTRAINT FINOPS_CORE_PROVIDER_RUN_PK PRIMARY KEY (RUN_ID, PROVIDER_CODE)
);

CREATE TABLE FINOPS_CORE_PIPELINE_RUN (
  RUN_ID NUMBER NOT NULL,
  PROVIDER_CODE VARCHAR2(3) NOT NULL,
  PIPELINE_NAME VARCHAR2(128) NOT NULL,
  LANDING_TABLE VARCHAR2(128) NOT NULL,
  PIPELINE_STATUS VARCHAR2(30),
  PROCESS_STATUS VARCHAR2(20) NOT NULL
    CHECK (PROCESS_STATUS IN ('COMPLETE','ERROR','SKIPPED')),
  FILES_FULL NUMBER DEFAULT 0 NOT NULL CHECK (FILES_FULL >= 0),
  FILES_PARTIAL NUMBER DEFAULT 0 NOT NULL CHECK (FILES_PARTIAL >= 0),
  FILES_ERROR NUMBER DEFAULT 0 NOT NULL CHECK (FILES_ERROR >= 0),
  QUEUED_AFTER NUMBER DEFAULT 0 NOT NULL CHECK (QUEUED_AFTER >= 0),
  OPEN_FILE_ERRORS NUMBER DEFAULT 0 NOT NULL CHECK (OPEN_FILE_ERRORS >= 0),
  MANUAL_PENDING_ROWS NUMBER DEFAULT 0 NOT NULL
    CHECK (MANUAL_PENDING_ROWS >= 0),
  LIMIT_REACHED CHAR(1) DEFAULT 'N' NOT NULL
    CHECK (LIMIT_REACHED IN ('Y','N')),
  ERROR_MESSAGE VARCHAR2(4000),
  CONSTRAINT FINOPS_CORE_PIPELINE_RUN_PK PRIMARY KEY
    (RUN_ID, PROVIDER_CODE, PIPELINE_NAME),
  CONSTRAINT FINOPS_CORE_PIPELINE_RUN_FK FOREIGN KEY
    (RUN_ID, PROVIDER_CODE) REFERENCES FINOPS_CORE_PROVIDER_RUN
    (RUN_ID, PROVIDER_CODE)
);

CREATE TABLE FINOPS_CORE_NOTIFY_CONFIG (
  CONFIG_ID NUMBER PRIMARY KEY CHECK (CONFIG_ID = 1),
  TOPIC_OCID VARCHAR2(255),
  ENABLED CHAR(1) DEFAULT 'N' NOT NULL CHECK (ENABLED IN ('Y','N')),
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
