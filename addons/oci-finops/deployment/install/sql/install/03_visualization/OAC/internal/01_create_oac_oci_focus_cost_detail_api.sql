-- Versioned profile-driven MV builder and FAST refresh worker.
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE OR REPLACE PACKAGE OAC_OCI_FOCUS_COST_DETAIL_API AUTHID DEFINER AS
  PROCEDURE BUILD_ACTIVE(P_PREPARE_ONLY IN NUMBER DEFAULT 0,
                         P_AUTO_PUBLISH IN NUMBER DEFAULT 1);
  PROCEDURE PUBLISH_READY(P_RUN_ID IN NUMBER);
  PROCEDURE POPULATE_INITIAL;
  PROCEDURE REFRESH_CURRENT;
  PROCEDURE CHECK_INITIAL_LOAD;
  PROCEDURE STOP_INITIAL_LOAD_GATE;
END OAC_OCI_FOCUS_COST_DETAIL_API;
/

CREATE OR REPLACE PACKAGE BODY OAC_OCI_FOCUS_COST_DETAIL_API AS
  FUNCTION LOCK_ID RETURN INTEGER IS
  BEGIN
    RETURN DBMS_UTILITY.GET_HASH_VALUE(
      'OAC_OCI_FOCUS_COST_DETAIL:'||SYS_CONTEXT('USERENV','CURRENT_USER'),
      1,1073741823);
  END;

  PROCEDURE CLOSE_INTERRUPTED_RUNS IS
  BEGIN
    -- Holding the cost-detail lock proves that an earlier RUNNING session ended.
    -- READY is committed immediately before synonym cutover. A lost session
    -- after that DDL must not leave a published MV without a build record.
    UPDATE OAC_OCI_FOCUS_COST_DETAIL_RUN R
       SET STATUS='COMPLETE',FINISHED_AT=SYSTIMESTAMP
     WHERE R.RUN_KIND='BUILD' AND R.STATUS='READY'
       AND EXISTS (SELECT 1 FROM USER_SYNONYMS S
                    WHERE S.SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL'
                      AND S.TABLE_NAME=R.MV_NAME);
    UPDATE OAC_OCI_FOCUS_COST_DETAIL_RUN R
       SET STATUS='ERROR',FINISHED_AT=SYSTIMESTAMP,
           ERROR_CODE=-20614,
           ERROR_MESSAGE='Prepared candidate was not published before session ended'
     WHERE R.RUN_KIND='BUILD' AND R.STATUS='READY'
       AND R.MV_ROWS IS NULL;
    UPDATE OAC_OCI_FOCUS_COST_DETAIL_RUN SET STATUS='ERROR',FINISHED_AT=SYSTIMESTAMP,
      ERROR_CODE=-20614,
      ERROR_MESSAGE='Previous build or refresh session ended before completion'
     WHERE STATUS='RUNNING';
    COMMIT;
  END;

  PROCEDURE FINISH_RUN(P_RUN_ID NUMBER, P_STATUS VARCHAR2,
                       P_ROWS NUMBER DEFAULT NULL,
                       P_ERROR_CODE NUMBER DEFAULT NULL,
                       P_ERROR_MESSAGE VARCHAR2 DEFAULT NULL) IS
  BEGIN
    UPDATE OAC_OCI_FOCUS_COST_DETAIL_RUN
       SET STATUS=P_STATUS, MV_ROWS=P_ROWS, FINISHED_AT=SYSTIMESTAMP,
           ERROR_CODE=P_ERROR_CODE,
           ERROR_MESSAGE=SUBSTR(P_ERROR_MESSAGE,1,4000)
     WHERE RUN_ID=P_RUN_ID;
    COMMIT;
  END;

  PROCEDURE BUILD_ACTIVE(P_PREPARE_ONLY IN NUMBER DEFAULT 0,
                         P_AUTO_PUBLISH IN NUMBER DEFAULT 1) IS
    L_LOCKED BOOLEAN := FALSE;
    L_RESULT INTEGER;
    L_RUN_ID NUMBER;
    L_PROFILE VARCHAR2(128);
    L_VERSION NUMBER;
    L_MV VARCHAR2(128);
    L_STMT_ID VARCHAR2(30);
    L_SELECT VARCHAR2(32767) := 'select';
    L_DDL VARCHAR2(32767);
    L_PATH VARCHAR2(4000);
    L_ALIAS VARCHAR2(128);
    L_CURSOR INTEGER;
    L_TAGS NUMBER := 0;
    L_MAX_SLOT NUMBER;
    L_FAST NUMBER;
    L_INSERT NUMBER;
    L_ROWS NUMBER;
    L_VALID NUMBER;
    L_COMPILE_STATE VARCHAR2(30);
    L_ACTIVE_PROFILE VARCHAR2(128);
    L_ACTIVE_VERSION NUMBER;
    L_EXISTING_SYNONYM NUMBER;
    L_ERR_CODE NUMBER;
    L_ERR_MSG VARCHAR2(4000);
    L_PUBLISHED NUMBER;
    L_BASE SYS.ODCIVARCHAR2LIST := SYS.ODCIVARCHAR2LIST(
      'AVAILABILITYZONE','BILLEDCOST','BILLINGACCOUNTID','BILLINGACCOUNTNAME',
      'BILLINGCURRENCY','BILLINGPERIODEND','BILLINGPERIODSTART',
      'CHARGECATEGORY','CHARGEDESCRIPTION','CHARGEFREQUENCY',
      'CHARGEPERIODEND','CHARGEPERIODSTART','CHARGESUBCATEGORY',
      'COMMITMENTDISCOUNTCATEGORY','COMMITMENTDISCOUNTID',
      'COMMITMENTDISCOUNTNAME','COMMITMENTDISCOUNTTYPE','EFFECTIVECOST',
      'INVOICEISSUER','LISTCOST','LISTUNITPRICE','PRICINGCATEGORY',
      'PRICINGQUANTITY','PRICINGUNIT','PROVIDER','PUBLISHER','REGION',
      'RESOURCEID','RESOURCENAME','RESOURCETYPE','SERVICECATEGORY',
      'SERVICENAME','SKUID','SKUPRICEID','SUBACCOUNTID','SUBACCOUNTNAME',
      'USAGEQUANTITY','USAGEUNIT','OCI_REFERENCENUMBER','OCI_COMPARTMENTID',
      'OCI_COMPARTMENTNAME','OCI_OVERAGEFLAG','OCI_UNITPRICEOVERAGE',
      'OCI_BILLEDQUANTITYOVERAGE','OCI_COSTOVERAGE','OCI_ATTRIBUTEDUSAGE',
      'OCI_ATTRIBUTEDCOST','OCI_BACKREFERENCENUMBER');
  BEGIN
    IF P_PREPARE_ONLY NOT IN (0,1) OR P_PREPARE_ONLY IS NULL THEN
      RAISE_APPLICATION_ERROR(-20615,'P_PREPARE_ONLY must be 0 or 1');
    END IF;
    IF P_AUTO_PUBLISH NOT IN (0,1) OR P_AUTO_PUBLISH IS NULL OR
       (P_PREPARE_ONLY=1 AND P_AUTO_PUBLISH=0) THEN
      RAISE_APPLICATION_ERROR(-20621,'P_AUTO_PUBLISH must be 0 or 1 and cannot be disabled for prepare-only');
    END IF;
    L_RESULT := DBMS_LOCK.REQUEST(ID=>LOCK_ID,
      LOCKMODE=>DBMS_LOCK.X_MODE,TIMEOUT=>0,RELEASE_ON_COMMIT=>FALSE);
    IF L_RESULT<>0 THEN
      DBMS_OUTPUT.PUT_LINE('OAC cost detail build skipped: another build or refresh is active');
      RETURN;
    END IF;
    L_LOCKED := TRUE;
    CLOSE_INTERRUPTED_RUNS;
    IF P_PREPARE_ONLY=1 THEN
      SELECT COUNT(*) INTO L_EXISTING_SYNONYM FROM USER_SYNONYMS
       WHERE SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL';
      IF L_EXISTING_SYNONYM<>0 THEN
        RAISE_APPLICATION_ERROR(-20619,
          'Prepare-only build requires no existing OAC cost detail synonym');
      END IF;
    END IF;

    SELECT PROFILE_NAME,PROFILE_VERSION INTO L_PROFILE,L_VERSION
      FROM OCI_TAG_PROFILE_SELECTION WHERE SELECTION_ID=1;
    INSERT INTO OAC_OCI_FOCUS_COST_DETAIL_RUN(RUN_KIND,STATUS,PROFILE_NAME,PROFILE_VERSION)
      VALUES('BUILD','RUNNING',L_PROFILE,L_VERSION)
      RETURNING RUN_ID INTO L_RUN_ID;
    L_MV := 'OAC_OCI_FOCUS_COST_DETAIL_MV_V'||TO_CHAR(L_RUN_ID,'FM9999999990');
    L_STMT_ID := 'OAC_COST_DETAIL_'||TO_CHAR(L_RUN_ID,'FM9999999990');
    UPDATE OAC_OCI_FOCUS_COST_DETAIL_RUN SET MV_NAME=L_MV WHERE RUN_ID=L_RUN_ID;
    COMMIT;

    FOR I IN 1..L_BASE.COUNT LOOP
      IF I>1 THEN L_SELECT := L_SELECT||','; END IF;
      L_SELECT := L_SELECT||CHR(10)||'  L.'||L_BASE(I);
    END LOOP;
    -- The new MV schema follows exactly the selected profile. DISPLAY_ORDER
    -- defines persistent slot numbers. Retired positions remain typed NULL columns.
    -- Old published MV columns remain on the old versioned MV until cutover.
    SELECT COUNT(*) INTO L_MAX_SLOT FROM OCI_TAG_PROFILE_ITEM
     WHERE PROFILE_NAME=L_PROFILE AND PROFILE_VERSION=L_VERSION;
    IF L_MAX_SLOT=0 THEN
      RAISE_APPLICATION_ERROR(-20603,'Selected profile contains no tag slots');
    END IF;
    FOR T IN (
      SELECT I.DISPLAY_ORDER,
             I.LOGICAL_TAG_NAME,
             I.TAG_NAMESPACE_ID,I.TAG_NAME,I.IS_ACTIVE,N.NAMESPACE_NAME
        FROM OCI_TAG_PROFILE_ITEM I
        JOIN OCI_TAG_NAMESPACE N
          ON N.TAG_NAMESPACE_ID=I.TAG_NAMESPACE_ID
       WHERE I.PROFILE_NAME=L_PROFILE AND I.PROFILE_VERSION=L_VERSION
       ORDER BY I.DISPLAY_ORDER
    ) LOOP
      L_ALIAS := 'TAG_'||TO_CHAR(T.DISPLAY_ORDER,'FM9999');
      L_PATH := '$."'||REPLACE(REPLACE(
        T.NAMESPACE_NAME||'.'||T.TAG_NAME,
        CHR(92),CHR(92)||CHR(92)),
        '"',CHR(92)||'"')||'"';
      IF T.IS_ACTIVE='N' THEN
        L_SELECT:=L_SELECT||','||CHR(10)||'  CAST(NULL AS VARCHAR2(4000)) AS '||L_ALIAS;
      ELSE
      L_SELECT := L_SELECT||','||CHR(10)||
        '  JSON_VALUE(L.TAGS, '''||REPLACE(L_PATH,'''','''''')||
        ''' RETURNING VARCHAR2(4000) NULL ON EMPTY NULL ON ERROR) AS '||L_ALIAS;
      END IF;
      INSERT INTO OAC_OCI_FOCUS_COST_DETAIL_TAG_COLUMN
        (RUN_ID,DISPLAY_ORDER,LOGICAL_TAG_NAME,MV_COLUMN_NAME,
         TAG_NAMESPACE_ID,TAG_NAME)
      VALUES(L_RUN_ID,T.DISPLAY_ORDER,T.LOGICAL_TAG_NAME,L_ALIAS,
             T.TAG_NAMESPACE_ID,T.TAG_NAME);
      L_TAGS := L_TAGS+1;
      IF LENGTHB(L_SELECT)>29000 THEN
        RAISE_APPLICATION_ERROR(-20602,'Selected profile exceeds MV SQL length limit');
      END IF;
    END LOOP;
    IF L_TAGS=0 THEN
      RAISE_APPLICATION_ERROR(-20603,'Selected profile contains no tag columns');
    END IF;
    UPDATE OAC_OCI_FOCUS_COST_DETAIL_RUN SET TAG_COLUMNS=L_TAGS WHERE RUN_ID=L_RUN_ID;
    COMMIT;

    L_SELECT := L_SELECT||CHR(10)||'from OCI_FOCUS_REPORTS L';
    L_CURSOR := DBMS_SQL.OPEN_CURSOR;
    DBMS_SQL.PARSE(L_CURSOR,L_SELECT,DBMS_SQL.NATIVE);
    DBMS_SQL.CLOSE_CURSOR(L_CURSOR);
    L_CURSOR := NULL;

    L_DDL := 'create materialized view '||DBMS_ASSERT.ENQUOTE_NAME(L_MV,FALSE)||' parallel 8'||CHR(10)||
      'partition by range (CHARGEPERIODSTART)'||CHR(10)||
      'interval (numtoyminterval(1, ''MONTH''))'||CHR(10)||
      '(partition P_INIT values less than (timestamp ''2024-01-01 00:00:00''))'||CHR(10)||
      'build deferred refresh fast on demand with primary key as'||CHR(10)||
      L_SELECT;
    -- EXPLAIN_MVIEW reports every FAST capability as unavailable for a
    -- BUILD DEFERRED statement (MSGNO 2164), even when its SELECT is eligible.
    -- Explain the defining SELECT; the CREATE below validates the full DDL.
    DBMS_MVIEW.EXPLAIN_MVIEW(L_SELECT,L_STMT_ID);
    SELECT COUNT(*) INTO L_FAST FROM MV_CAPABILITIES_TABLE
     WHERE STATEMENT_ID=L_STMT_ID AND CAPABILITY_NAME='REFRESH_FAST'
       AND POSSIBLE='Y';
    SELECT COUNT(*) INTO L_INSERT FROM MV_CAPABILITIES_TABLE
     WHERE STATEMENT_ID=L_STMT_ID
       AND CAPABILITY_NAME='REFRESH_FAST_AFTER_INSERT' AND POSSIBLE='Y';
    COMMIT;
    IF L_FAST=0 OR L_INSERT=0 THEN
      RAISE_APPLICATION_ERROR(-20604,
        'FAST refresh not supported; inspect MV_CAPABILITIES_TABLE for '||L_STMT_ID);
    END IF;

    EXECUTE IMMEDIATE L_DDL;
    EXECUTE IMMEDIATE 'alter materialized view '||
      DBMS_ASSERT.ENQUOTE_NAME(L_MV,FALSE)||' parallel 8';
    IF P_PREPARE_ONLY=0 THEN
      -- Oracle requires a COMPLETE first refresh for BUILD DEFERRED.
      -- Keep the old synonym in place until this candidate is populated.
      EXECUTE IMMEDIATE 'alter session enable parallel dml';
      DBMS_MVIEW.REFRESH(L_MV,'C',parallelism=>8);
    END IF;
    SELECT COMPILE_STATE INTO L_COMPILE_STATE FROM USER_MVIEWS
     WHERE MVIEW_NAME=L_MV;
    IF L_COMPILE_STATE='NEEDS_COMPILE' AND P_PREPARE_ONLY=0 THEN
      EXECUTE IMMEDIATE 'alter materialized view '||
        DBMS_ASSERT.ENQUOTE_NAME(L_MV,FALSE)||' compile';
    END IF;
    SELECT COUNT(*) INTO L_VALID FROM USER_MVIEWS M JOIN USER_OBJECTS O
      ON O.OBJECT_NAME=M.MVIEW_NAME AND O.OBJECT_TYPE='MATERIALIZED VIEW'
     WHERE M.MVIEW_NAME=L_MV AND M.REFRESH_METHOD='FAST'
       AND (P_PREPARE_ONLY=1 OR O.STATUS='VALID');
    IF L_VALID<>1 THEN
      RAISE_APPLICATION_ERROR(-20605,'Created MV is not FAST ON DEMAND');
    END IF;
    IF P_PREPARE_ONLY=0 THEN
      EXECUTE IMMEDIATE 'select count(*) from '||DBMS_ASSERT.ENQUOTE_NAME(L_MV,FALSE)
        INTO L_ROWS;
    END IF;
    SELECT PROFILE_NAME,PROFILE_VERSION INTO L_ACTIVE_PROFILE,L_ACTIVE_VERSION
      FROM OCI_TAG_PROFILE_SELECTION WHERE SELECTION_ID=1;
    IF L_ACTIVE_PROFILE<>L_PROFILE OR L_ACTIVE_VERSION<>L_VERSION THEN
      RAISE_APPLICATION_ERROR(-20606,
        'Profile changed during MV build; candidate retained without synonym cutover');
    END IF;

    IF P_PREPARE_ONLY=1 THEN
      EXECUTE IMMEDIATE 'create or replace synonym OAC_OCI_FOCUS_COST_DETAIL for '||
        DBMS_ASSERT.ENQUOTE_NAME(L_MV,FALSE);
      UPDATE OAC_OCI_FOCUS_COST_DETAIL_RUN SET STATUS='PREPARED' WHERE RUN_ID=L_RUN_ID;
      COMMIT;
      DBMS_OUTPUT.PUT_LINE('OAC cost detail synonym prepared: '||L_MV||
        ' profile='||L_PROFILE||' version='||L_VERSION||
        ' tags='||L_TAGS||'; initial population pending');
      L_RESULT := DBMS_LOCK.RELEASE(ID=>LOCK_ID);
      L_LOCKED := FALSE;
      RETURN;
    END IF;
    IF P_AUTO_PUBLISH=0 THEN
      FINISH_RUN(L_RUN_ID,'READY',L_ROWS);
      DBMS_OUTPUT.PUT_LINE('OAC cost detail candidate ready: '||L_MV||
        ' profile='||L_PROFILE||' version='||L_VERSION||
        ' tags='||L_TAGS||' rows='||L_ROWS||'; synonym unchanged');
      L_RESULT := DBMS_LOCK.RELEASE(ID=>LOCK_ID);
      L_LOCKED := FALSE;
      RETURN;
    END IF;
    UPDATE OAC_OCI_FOCUS_COST_DETAIL_RUN SET STATUS='READY'
     WHERE RUN_ID=L_RUN_ID;
    COMMIT;
    EXECUTE IMMEDIATE 'create or replace synonym OAC_OCI_FOCUS_COST_DETAIL for '||
      DBMS_ASSERT.ENQUOTE_NAME(L_MV,FALSE);
    FINISH_RUN(L_RUN_ID,'COMPLETE',L_ROWS);
    DBMS_OUTPUT.PUT_LINE('OAC cost detail published: '||L_MV||
      ' profile='||L_PROFILE||' version='||L_VERSION||
      ' tags='||L_TAGS||' rows='||L_ROWS);
    L_RESULT := DBMS_LOCK.RELEASE(ID=>LOCK_ID);
    L_LOCKED := FALSE;
  EXCEPTION WHEN OTHERS THEN
    L_ERR_CODE := SQLCODE;
    L_ERR_MSG := SQLERRM;
    IF L_CURSOR IS NOT NULL THEN
      IF DBMS_SQL.IS_OPEN(L_CURSOR) THEN DBMS_SQL.CLOSE_CURSOR(L_CURSOR); END IF;
    END IF;
    ROLLBACK;
    IF L_RUN_ID IS NOT NULL THEN
      SELECT COUNT(*) INTO L_PUBLISHED FROM USER_SYNONYMS
       WHERE SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL'
         AND TABLE_NAME=L_MV;
      IF L_PUBLISHED=1 AND P_PREPARE_ONLY=0 THEN
        FINISH_RUN(L_RUN_ID,'COMPLETE',L_ROWS);
      ELSE
        FINISH_RUN(L_RUN_ID,'ERROR',NULL,L_ERR_CODE,L_ERR_MSG);
      END IF;
    END IF;
    IF L_LOCKED THEN L_RESULT := DBMS_LOCK.RELEASE(ID=>LOCK_ID); END IF;
    RAISE;
  END BUILD_ACTIVE;

  PROCEDURE PUBLISH_READY(P_RUN_ID IN NUMBER) IS
    L_LOCKED BOOLEAN := FALSE;
    L_RESULT INTEGER;
    L_MV VARCHAR2(128);
    L_PROFILE VARCHAR2(128);
    L_VERSION NUMBER;
    L_ACTIVE_PROFILE VARCHAR2(128);
    L_ACTIVE_VERSION NUMBER;
    L_TAG_COLUMNS NUMBER;
    L_RUN_TAG_COLUMNS NUMBER;
    L_MAPPED_TAG_COLUMNS NUMBER;
    L_MV_TAG_COLUMNS NUMBER;
    L_ROWS NUMBER;
    L_VALID NUMBER;
  BEGIN
    L_RESULT := DBMS_LOCK.REQUEST(ID=>LOCK_ID,
      LOCKMODE=>DBMS_LOCK.X_MODE,TIMEOUT=>0,RELEASE_ON_COMMIT=>FALSE);
    IF L_RESULT<>0 THEN
      RAISE_APPLICATION_ERROR(-20622,
        'Cannot publish while another cost-detail build or refresh is active');
    END IF;
    L_LOCKED := TRUE;
    CLOSE_INTERRUPTED_RUNS;
    SELECT MV_NAME,PROFILE_NAME,PROFILE_VERSION,TAG_COLUMNS,MV_ROWS
      INTO L_MV,L_PROFILE,L_VERSION,L_RUN_TAG_COLUMNS,L_ROWS
      FROM OAC_OCI_FOCUS_COST_DETAIL_RUN
     WHERE RUN_ID=P_RUN_ID AND RUN_KIND='BUILD' AND STATUS='READY'
       AND MV_ROWS IS NOT NULL
     FOR UPDATE;
    SELECT PROFILE_NAME,PROFILE_VERSION INTO L_ACTIVE_PROFILE,L_ACTIVE_VERSION
      FROM OCI_TAG_PROFILE_SELECTION WHERE SELECTION_ID=1;
    IF L_PROFILE<>L_ACTIVE_PROFILE OR L_VERSION<>L_ACTIVE_VERSION THEN
      RAISE_APPLICATION_ERROR(-20623,
        'Active tag profile differs from the candidate; build a new candidate');
    END IF;
    SELECT COUNT(*) INTO L_TAG_COLUMNS FROM OCI_TAG_PROFILE_ITEM
     WHERE PROFILE_NAME=L_PROFILE AND PROFILE_VERSION=L_VERSION;
    SELECT COUNT(*) INTO L_MV_TAG_COLUMNS FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME=L_MV AND REGEXP_LIKE(COLUMN_NAME,'^TAG_[0-9]+$','c');
    SELECT COUNT(*) INTO L_MAPPED_TAG_COLUMNS
      FROM OAC_OCI_FOCUS_COST_DETAIL_TAG_COLUMN C
      JOIN (SELECT I.DISPLAY_ORDER SLOT,
                   I.LOGICAL_TAG_NAME,I.TAG_NAMESPACE_ID,I.TAG_NAME
              FROM OCI_TAG_PROFILE_ITEM I
             WHERE I.PROFILE_NAME=L_PROFILE AND I.PROFILE_VERSION=L_VERSION) P
        ON C.DISPLAY_ORDER=P.SLOT
       AND C.MV_COLUMN_NAME='TAG_'||TO_CHAR(P.SLOT,'FM9999')
       AND C.LOGICAL_TAG_NAME=P.LOGICAL_TAG_NAME
       AND C.TAG_NAMESPACE_ID=P.TAG_NAMESPACE_ID
       AND C.TAG_NAME=P.TAG_NAME
     WHERE C.RUN_ID=P_RUN_ID;
    IF L_TAG_COLUMNS=0 OR L_TAG_COLUMNS<>L_RUN_TAG_COLUMNS OR
       L_TAG_COLUMNS<>L_MV_TAG_COLUMNS OR L_TAG_COLUMNS<>L_MAPPED_TAG_COLUMNS THEN
      RAISE_APPLICATION_ERROR(-20624,
        'Candidate TAG_n columns do not match the current profile mapping');
    END IF;
    SELECT COUNT(*) INTO L_VALID FROM USER_MVIEWS M JOIN USER_OBJECTS O
      ON O.OBJECT_NAME=M.MVIEW_NAME AND O.OBJECT_TYPE='MATERIALIZED VIEW'
     WHERE M.MVIEW_NAME=L_MV AND M.COMPILE_STATE='VALID'
       AND M.STALENESS<>'UNUSABLE' AND M.REFRESH_METHOD='FAST'
       AND O.STATUS='VALID';
    IF L_VALID<>1 THEN
      RAISE_APPLICATION_ERROR(-20625,
        'Candidate MV is not valid and available for publication');
    END IF;
    EXECUTE IMMEDIATE 'create or replace synonym OAC_OCI_FOCUS_COST_DETAIL for '||
      DBMS_ASSERT.ENQUOTE_NAME(L_MV,FALSE);
    FINISH_RUN(P_RUN_ID,'COMPLETE',L_ROWS);
    DBMS_OUTPUT.PUT_LINE('OAC cost detail candidate published: '||L_MV||
      ' profile='||L_PROFILE||' version='||L_VERSION||
      ' tags='||L_TAG_COLUMNS||' rows='||L_ROWS);
    L_RESULT := DBMS_LOCK.RELEASE(ID=>LOCK_ID);
    L_LOCKED := FALSE;
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    IF L_LOCKED THEN L_RESULT := DBMS_LOCK.RELEASE(ID=>LOCK_ID); END IF;
    RAISE;
  END PUBLISH_READY;

  PROCEDURE POPULATE_INITIAL IS
    L_LOCKED BOOLEAN := FALSE;
    L_RESULT INTEGER;
    L_RUN_ID NUMBER;
    L_MV VARCHAR2(128);
    L_PROFILE VARCHAR2(128);
    L_VERSION NUMBER;
    L_ACTIVE_PROFILE VARCHAR2(128);
    L_ACTIVE_VERSION NUMBER;
    L_COMPILE_STATE VARCHAR2(30);
    L_VALID NUMBER;
    L_ROWS NUMBER;
    L_ERR_CODE NUMBER;
    L_ERR_MSG VARCHAR2(4000);
  BEGIN
    L_RESULT := DBMS_LOCK.REQUEST(ID=>LOCK_ID,
      LOCKMODE=>DBMS_LOCK.X_MODE,TIMEOUT=>0,RELEASE_ON_COMMIT=>FALSE);
    IF L_RESULT<>0 THEN
      DBMS_OUTPUT.PUT_LINE('OAC initial population skipped: another build or refresh is active');
      RETURN;
    END IF;
    L_LOCKED := TRUE;
    CLOSE_INTERRUPTED_RUNS;
    SELECT R.RUN_ID,R.MV_NAME,R.PROFILE_NAME,R.PROFILE_VERSION
      INTO L_RUN_ID,L_MV,L_PROFILE,L_VERSION
      FROM USER_SYNONYMS S JOIN OAC_OCI_FOCUS_COST_DETAIL_RUN R ON R.MV_NAME=S.TABLE_NAME
     WHERE S.SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL'
       AND S.TABLE_OWNER=SYS_CONTEXT('USERENV','CURRENT_USER')
       AND S.DB_LINK IS NULL AND R.RUN_KIND='BUILD'
       AND R.STATUS IN ('PREPARED','ERROR');
    SELECT PROFILE_NAME,PROFILE_VERSION INTO L_ACTIVE_PROFILE,L_ACTIVE_VERSION
      FROM OCI_TAG_PROFILE_SELECTION WHERE SELECTION_ID=1;
    IF L_ACTIVE_PROFILE<>L_PROFILE OR L_ACTIVE_VERSION<>L_VERSION THEN
      RAISE_APPLICATION_ERROR(-20616,
        'Selected profile changed before initial population; rebuild explicitly');
    END IF;
    UPDATE OAC_OCI_FOCUS_COST_DETAIL_RUN SET STATUS='RUNNING',FINISHED_AT=NULL,
      ERROR_CODE=NULL,ERROR_MESSAGE=NULL WHERE RUN_ID=L_RUN_ID;
    COMMIT;
    EXECUTE IMMEDIATE 'alter session enable parallel dml';
    DBMS_MVIEW.REFRESH(L_MV,'C',parallelism=>8);
    SELECT COMPILE_STATE INTO L_COMPILE_STATE FROM USER_MVIEWS
     WHERE MVIEW_NAME=L_MV;
    IF L_COMPILE_STATE='NEEDS_COMPILE' THEN
      EXECUTE IMMEDIATE 'alter materialized view '||
        DBMS_ASSERT.ENQUOTE_NAME(L_MV,FALSE)||' compile';
    END IF;
    SELECT COUNT(*) INTO L_VALID FROM USER_MVIEWS M JOIN USER_OBJECTS O
      ON O.OBJECT_NAME=M.MVIEW_NAME AND O.OBJECT_TYPE='MATERIALIZED VIEW'
     WHERE M.MVIEW_NAME=L_MV AND M.REFRESH_METHOD='FAST'
       AND M.STALENESS<>'UNUSABLE' AND O.STATUS='VALID';
    IF L_VALID<>1 THEN
      RAISE_APPLICATION_ERROR(-20617,'Populated MV is not VALID FAST ON DEMAND');
    END IF;
    SELECT PROFILE_NAME,PROFILE_VERSION INTO L_ACTIVE_PROFILE,L_ACTIVE_VERSION
      FROM OCI_TAG_PROFILE_SELECTION WHERE SELECTION_ID=1;
    IF L_ACTIVE_PROFILE<>L_PROFILE OR L_ACTIVE_VERSION<>L_VERSION THEN
      RAISE_APPLICATION_ERROR(-20618,
        'Selected profile changed during initial population');
    END IF;
    EXECUTE IMMEDIATE 'select count(*) from '||DBMS_ASSERT.ENQUOTE_NAME(L_MV,FALSE)
      INTO L_ROWS;
    FINISH_RUN(L_RUN_ID,'COMPLETE',L_ROWS);
    DBMS_OUTPUT.PUT_LINE('OAC initial cost-detail population complete: '||L_MV||
      ' rows='||L_ROWS);
    L_RESULT := DBMS_LOCK.RELEASE(ID=>LOCK_ID);
    L_LOCKED := FALSE;
  EXCEPTION WHEN OTHERS THEN
    L_ERR_CODE := SQLCODE;
    L_ERR_MSG := SQLERRM;
    ROLLBACK;
    IF L_RUN_ID IS NOT NULL THEN
      FINISH_RUN(L_RUN_ID,'ERROR',NULL,L_ERR_CODE,L_ERR_MSG);
    END IF;
    IF L_LOCKED THEN L_RESULT := DBMS_LOCK.RELEASE(ID=>LOCK_ID); END IF;
    RAISE;
  END POPULATE_INITIAL;

  PROCEDURE REFRESH_CURRENT IS
    L_LOCKED BOOLEAN := FALSE;
    L_RESULT INTEGER;
    L_RUN_ID NUMBER;
    L_MV VARCHAR2(128);
    L_COMPILE_STATE VARCHAR2(30);
    L_OBJECT_STATUS VARCHAR2(30);
    L_ERR_CODE NUMBER;
    L_ERR_MSG VARCHAR2(4000);
  BEGIN
    L_RESULT := DBMS_LOCK.REQUEST(ID=>LOCK_ID,
      LOCKMODE=>DBMS_LOCK.X_MODE,TIMEOUT=>0,RELEASE_ON_COMMIT=>FALSE);
    IF L_RESULT<>0 THEN
      DBMS_OUTPUT.PUT_LINE('OAC cost detail refresh skipped: another build or refresh is active');
      RETURN;
    END IF;
    L_LOCKED := TRUE;
    CLOSE_INTERRUPTED_RUNS;
    BEGIN
      SELECT S.TABLE_NAME,M.COMPILE_STATE INTO L_MV,L_COMPILE_STATE
        FROM USER_SYNONYMS S JOIN USER_MVIEWS M
          ON M.MVIEW_NAME=S.TABLE_NAME
       WHERE S.SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL'
         AND S.TABLE_OWNER=SYS_CONTEXT('USERENV','CURRENT_USER')
         AND S.DB_LINK IS NULL;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      L_RESULT := DBMS_LOCK.RELEASE(ID=>LOCK_ID);
      RETURN;
    END;
    SELECT COUNT(*) INTO L_RESULT FROM OAC_OCI_FOCUS_COST_DETAIL_RUN
     WHERE MV_NAME=L_MV AND RUN_KIND='BUILD' AND STATUS='COMPLETE';
    IF L_RESULT=0 THEN
      DBMS_OUTPUT.PUT_LINE('OAC cost detail refresh skipped: initial population is not complete');
      L_RESULT := DBMS_LOCK.RELEASE(ID=>LOCK_ID);
      L_LOCKED := FALSE;
      RETURN;
    END IF;
    INSERT INTO OAC_OCI_FOCUS_COST_DETAIL_RUN(RUN_KIND,STATUS,MV_NAME)
      VALUES('REFRESH','RUNNING',L_MV) RETURNING RUN_ID INTO L_RUN_ID;
    COMMIT;
    IF L_COMPILE_STATE='NEEDS_COMPILE' THEN
      EXECUTE IMMEDIATE 'alter materialized view '||
        DBMS_ASSERT.ENQUOTE_NAME(L_MV,FALSE)||' compile';
    END IF;
    EXECUTE IMMEDIATE 'alter session enable parallel dml';
    DBMS_MVIEW.REFRESH(L_MV,'F',parallelism=>8);
    SELECT M.COMPILE_STATE,O.STATUS
      INTO L_COMPILE_STATE,L_OBJECT_STATUS
      FROM USER_MVIEWS M JOIN USER_OBJECTS O
        ON O.OBJECT_NAME=M.MVIEW_NAME AND O.OBJECT_TYPE='MATERIALIZED VIEW'
     WHERE M.MVIEW_NAME=L_MV;
    IF L_COMPILE_STATE<>'VALID' OR L_OBJECT_STATUS<>'VALID' THEN
      EXECUTE IMMEDIATE 'alter materialized view '||
        DBMS_ASSERT.ENQUOTE_NAME(L_MV,FALSE)||' compile';
      SELECT M.COMPILE_STATE,O.STATUS
        INTO L_COMPILE_STATE,L_OBJECT_STATUS
        FROM USER_MVIEWS M JOIN USER_OBJECTS O
          ON O.OBJECT_NAME=M.MVIEW_NAME AND O.OBJECT_TYPE='MATERIALIZED VIEW'
       WHERE M.MVIEW_NAME=L_MV;
      IF L_COMPILE_STATE<>'VALID' OR L_OBJECT_STATUS<>'VALID' THEN
        RAISE_APPLICATION_ERROR(-20626,
          'OAC cost detail MV is not valid after FAST refresh and compile: '||
          L_MV||' ('||L_COMPILE_STATE||','||L_OBJECT_STATUS||')');
      END IF;
    END IF;
    FINISH_RUN(L_RUN_ID,'COMPLETE');
    DBMS_OUTPUT.PUT_LINE('OAC cost detail FAST refresh completed: '||L_MV);
    L_RESULT := DBMS_LOCK.RELEASE(ID=>LOCK_ID);
    L_LOCKED := FALSE;
  EXCEPTION WHEN OTHERS THEN
    L_ERR_CODE := SQLCODE;
    L_ERR_MSG := SQLERRM;
    ROLLBACK;
    IF L_RUN_ID IS NOT NULL THEN
      FINISH_RUN(L_RUN_ID,'ERROR',NULL,L_ERR_CODE,L_ERR_MSG);
    END IF;
    IF L_LOCKED THEN L_RESULT := DBMS_LOCK.RELEASE(ID=>LOCK_ID); END IF;
    RAISE;
  END REFRESH_CURRENT;

  PROCEDURE CHECK_INITIAL_LOAD IS
    L_GATE_STATUS VARCHAR2(14);
    L_STARTED_AT TIMESTAMP WITH TIME ZONE;
    L_PIPELINES NUMBER;
    L_READY_PIPELINES NUMBER := 0;
    L_FAILED_PIPELINES NUMBER := 0;
    L_HISTORY_STATUS VARCHAR2(30);
    L_HISTORY_END TIMESTAMP WITH TIME ZONE;
    L_PENDING NUMBER;
    L_RUNNING NUMBER;
    L_STATUS_TABLE VARCHAR2(128);
    L_RUN_STATUS VARCHAR2(12);
    L_PRIOR_RUN_ID NUMBER;
    L_NEW_RUN_ID NUMBER;
    L_NEW_RUN_STATUS VARCHAR2(12);
    L_ERROR_MESSAGE VARCHAR2(4000);
  BEGIN
    SELECT STATUS, PIPELINES_STARTED_AT INTO L_GATE_STATUS, L_STARTED_AT
      FROM OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE WHERE GATE_ID = 1 FOR UPDATE;
    IF L_GATE_STATUS IN ('COMPLETE','ERROR','NOT_STARTED') THEN
      RETURN;
    END IF;
    UPDATE OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE
       SET LAST_CHECK_AT = SYSTIMESTAMP, UPDATED_AT = SYSTIMESTAMP
     WHERE GATE_ID = 1;
    SELECT COUNT(*) INTO L_PIPELINES FROM USER_CLOUD_PIPELINES
     WHERE REGEXP_LIKE(PIPELINE_NAME,'^OCI_FOCUS_REPORTS_LOAD_[0-9]{4}$');
    IF L_PIPELINES = 0 OR L_STARTED_AT IS NULL THEN
      RETURN;
    END IF;

    FOR P IN (
      SELECT PIPELINE_NAME, STATUS_TABLE
        FROM USER_CLOUD_PIPELINES
       WHERE REGEXP_LIKE(PIPELINE_NAME,'^OCI_FOCUS_REPORTS_LOAD_[0-9]{4}$')
       ORDER BY PIPELINE_NAME
    ) LOOP
      L_HISTORY_STATUS := NULL;
      L_HISTORY_END := NULL;
      BEGIN
        SELECT STATUS, END_DATE INTO L_HISTORY_STATUS, L_HISTORY_END
          FROM (
            SELECT STATUS, END_DATE FROM USER_CLOUD_PIPELINE_HISTORY
             WHERE PIPELINE_NAME = P.PIPELINE_NAME
               AND START_DATE >= L_STARTED_AT
             ORDER BY START_DATE DESC
          ) WHERE ROWNUM = 1;
      EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
      END;
      L_PENDING := 0;
      L_RUNNING := 0;
      IF P.STATUS_TABLE IS NOT NULL THEN
        EXECUTE IMMEDIATE
          'SELECT COUNT(CASE WHEN STATUS = ''PENDING'' THEN 1 END),'||
          ' COUNT(CASE WHEN STATUS = ''RUNNING'' THEN 1 END) FROM '||
          DBMS_ASSERT.SIMPLE_SQL_NAME(P.STATUS_TABLE)
          INTO L_PENDING, L_RUNNING;
      ELSE
        L_PENDING := 1;
      END IF;
      IF L_HISTORY_STATUS = 'SUCCEEDED' AND L_HISTORY_END IS NOT NULL AND
         L_PENDING = 0 AND L_RUNNING = 0 THEN
        L_READY_PIPELINES := L_READY_PIPELINES + 1;
      ELSIF L_HISTORY_STATUS = 'FAILED' THEN
        L_FAILED_PIPELINES := L_FAILED_PIPELINES + 1;
      END IF;
    END LOOP;

    UPDATE OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE
       SET FAILED_PIPELINES = L_FAILED_PIPELINES,
           LAST_CHECK_AT = SYSTIMESTAMP,
           UPDATED_AT = SYSTIMESTAMP
     WHERE GATE_ID = 1;
    COMMIT;
    IF L_READY_PIPELINES <> L_PIPELINES THEN
      RETURN;
    END IF;

    UPDATE OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE
       SET STATUS = 'REFRESHING', UPDATED_AT = SYSTIMESTAMP
     WHERE GATE_ID = 1;
    COMMIT;
    SELECT NVL(MAX(RUN_ID),0) INTO L_PRIOR_RUN_ID
      FROM OAC_OCI_FOCUS_COST_DETAIL_RUN WHERE RUN_KIND='REFRESH';
    REFRESH_CURRENT;
    SELECT MAX(RUN_ID), MAX(STATUS) KEEP (DENSE_RANK LAST ORDER BY RUN_ID)
      INTO L_NEW_RUN_ID,L_NEW_RUN_STATUS
      FROM OAC_OCI_FOCUS_COST_DETAIL_RUN
     WHERE RUN_KIND='REFRESH' AND RUN_ID>L_PRIOR_RUN_ID;
    IF L_NEW_RUN_ID IS NULL OR L_NEW_RUN_STATUS <> 'COMPLETE' THEN
      UPDATE OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE
         SET STATUS = 'WAITING', UPDATED_AT = SYSTIMESTAMP,
             ERROR_MESSAGE = 'Initial FAST refresh has not completed; the monitor will retry'
       WHERE GATE_ID = 1;
      COMMIT;
      RETURN;
    END IF;

    DBMS_SCHEDULER.ENABLE('OAC_OCI_FOCUS_COST_DETAIL_REFRESH_2H');
    UPDATE OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE
       SET STATUS = 'COMPLETE', ERROR_MESSAGE = NULL, UPDATED_AT = SYSTIMESTAMP
     WHERE GATE_ID = 1;
    COMMIT;
    DBMS_SCHEDULER.CREATE_JOB(
      JOB_NAME=>'OAC_OCI_FOCUS_COST_DETAIL_GATE_STOP',
      JOB_TYPE=>'STORED_PROCEDURE',
      JOB_ACTION=>'OAC_OCI_FOCUS_COST_DETAIL_API.STOP_INITIAL_LOAD_GATE',
      START_DATE=>SYSTIMESTAMP+INTERVAL '1' MINUTE,
      ENABLED=>TRUE,AUTO_DROP=>TRUE,
      COMMENTS=>'Disable completed OAC initial-load monitor after it returns');
    DBMS_OUTPUT.PUT_LINE('Initial OCI pipeline catch-up refreshed; two-hour OAC refresh enabled');
  EXCEPTION WHEN OTHERS THEN
    L_ERROR_MESSAGE := SUBSTR(SQLERRM,1,4000);
    UPDATE OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE
       SET STATUS = 'WAITING', ERROR_MESSAGE = L_ERROR_MESSAGE,
           UPDATED_AT = SYSTIMESTAMP
     WHERE GATE_ID = 1;
    COMMIT;
    RAISE;
  END CHECK_INITIAL_LOAD;

  PROCEDURE STOP_INITIAL_LOAD_GATE IS
  BEGIN
    DBMS_SCHEDULER.DISABLE('OAC_OCI_FOCUS_COST_DETAIL_INITIAL_LOAD_GATE');
    DBMS_OUTPUT.PUT_LINE('Initial-load monitor disabled after successful catch-up');
  END STOP_INITIAL_LOAD_GATE;
END OAC_OCI_FOCUS_COST_DETAIL_API;
