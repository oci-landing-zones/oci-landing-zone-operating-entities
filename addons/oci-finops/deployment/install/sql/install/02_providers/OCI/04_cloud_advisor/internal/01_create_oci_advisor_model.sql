-- OCI-owned Cloud Advisor persistence; install after source access preflight.

create table oci_advisor_config (
  config_id             number generated by default as identity primary key,
  tenancy_ocid          varchar2(512) not null,
  endpoint_region       varchar2(64) not null,
  credential_name       varchar2(128) default 'OCI$RESOURCE_PRINCIPAL' not null,
  is_sync_enabled       char(1) not null check (is_sync_enabled in ('Y', 'N')),
  created_at            timestamp(6) with time zone default systimestamp not null,
  updated_at            timestamp(6) with time zone default systimestamp not null,
  constraint oci_advisor_config_uq unique (tenancy_ocid, endpoint_region)
);

create table oci_advisor_sync_run (
  sync_run_id           number generated by default as identity primary key,
  started_at             timestamp(6) with time zone default systimestamp not null,
  completed_at           timestamp(6) with time zone,
  status                 varchar2(30) not null,
  endpoint_region        varchar2(64) not null,
  recommendations_read   number default 0 not null,
  resource_actions_read  number default 0 not null,
  error_code             number,
  error_message          varchar2(4000),
  constraint oci_advisor_sync_run_ck
    check (status in ('RUNNING', 'COMPLETED', 'FAILED', 'SKIPPED'))
);

create table oci_advisor_recommendation (
  recommendation_id      varchar2(512) primary key,
  compartment_id         varchar2(512),
  category_id            varchar2(512),
  recommendation_name    varchar2(512),
  description_code       varchar2(1000),
  importance             varchar2(30),
  lifecycle_state        varchar2(30),
  recommendation_status  varchar2(30),
  estimated_cost_saving  number,
  currency_code          varchar2(30),
  time_status_begin      timestamp(6) with time zone,
  time_status_end        timestamp(6) with time zone,
  source_created_at      timestamp(6) with time zone,
  source_updated_at      timestamp(6) with time zone,
  first_seen_at          timestamp(6) with time zone not null,
  last_seen_at           timestamp(6) with time zone not null,
  last_seen_run_id       number not null references oci_advisor_sync_run(sync_run_id),
  source_payload         json
);

create table oci_advisor_recommendation_snap (
  sync_run_id            number not null references oci_advisor_sync_run(sync_run_id),
  recommendation_id      varchar2(512) not null,
  compartment_id         varchar2(512),
  category_id            varchar2(512),
  recommendation_name    varchar2(512),
  importance             varchar2(30),
  lifecycle_state        varchar2(30),
  recommendation_status  varchar2(30),
  estimated_cost_saving  number,
  currency_code          varchar2(30),
  source_updated_at      timestamp(6) with time zone,
  source_payload         json,
  constraint oci_advisor_recommendation_snap_pk
    primary key (sync_run_id, recommendation_id)
);

create table oci_advisor_resource_action (
  resource_action_id      varchar2(512) primary key,
  recommendation_id       varchar2(512),
  category_id             varchar2(512),
  resource_ocid           varchar2(512),
  resource_name           varchar2(1000),
  resource_type           varchar2(256),
  compartment_id          varchar2(512),
  compartment_name        varchar2(1000),
  resource_region         varchar2(64),
  action_type             varchar2(100),
  action_description      varchar2(4000),
  action_url              varchar2(4000),
  lifecycle_state         varchar2(30),
  action_status           varchar2(30),
  estimated_cost_saving   number,
  currency_code           varchar2(30),
  time_status_begin       timestamp(6) with time zone,
  time_status_end         timestamp(6) with time zone,
  source_created_at       timestamp(6) with time zone,
  source_updated_at       timestamp(6) with time zone,
  first_seen_at           timestamp(6) with time zone not null,
  last_seen_at            timestamp(6) with time zone not null,
  last_seen_run_id        number not null references oci_advisor_sync_run(sync_run_id),
  source_payload          json
);

create table oci_advisor_resource_action_snap (
  sync_run_id            number not null references oci_advisor_sync_run(sync_run_id),
  resource_action_id     varchar2(512) not null,
  recommendation_id      varchar2(512),
  resource_ocid          varchar2(512),
  resource_type          varchar2(256),
  resource_region        varchar2(64),
  lifecycle_state        varchar2(30),
  action_status          varchar2(30),
  estimated_cost_saving  number,
  currency_code          varchar2(30),
  source_updated_at      timestamp(6) with time zone,
  source_payload         json,
  constraint oci_advisor_resource_action_snap_pk
    primary key (sync_run_id, resource_action_id)
);

create index oci_advisor_ra_resource_ix
  on oci_advisor_resource_action (resource_ocid, action_status);

create index oci_advisor_ra_recommendation_ix
  on oci_advisor_resource_action (recommendation_id);

create or replace view oci_advisor_recommendation_current as
select r.*
  from oci_advisor_recommendation r;

create or replace view oci_advisor_open_actions_v as
select a.resource_action_id,
       a.recommendation_id,
       r.recommendation_name,
       r.importance,
       r.recommendation_status,
       a.resource_ocid,
       a.resource_name,
       a.resource_type,
       a.resource_region,
       a.compartment_id,
       a.compartment_name,
       a.action_type,
       a.action_description,
       a.action_url,
       a.estimated_cost_saving,
       a.currency_code,
       a.time_status_begin,
       a.source_updated_at
  from oci_advisor_resource_action a
  left join oci_advisor_recommendation r
    on r.recommendation_id = a.recommendation_id
 where a.action_status = 'PENDING'
   and a.lifecycle_state = 'ACTIVE';
