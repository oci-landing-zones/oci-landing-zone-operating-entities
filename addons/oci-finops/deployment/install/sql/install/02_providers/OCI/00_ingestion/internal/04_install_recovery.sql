-- Recover an interrupted COPY_DATA attempt using its recorded operation and
-- session evidence. Requires the direct V_$SESSION SELECT grant.
-- All Oracle pipeline/load metadata is read-only. Only owner ledgers change.
SET DEFINE OFF
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

CREATE OR REPLACE PROCEDURE OCI_FOCUS_RECOVER_COPYING (
  P_ACTION OUT VARCHAR2
) AUTHID CURRENT_USER IS
  L_PIPELINE VARCHAR2(128);
  L_GENERATION NUMBER;
  L_HASH RAW(32);
  L_SOURCE_URI VARCHAR2(4000);
  L_QUEUE_STATE VARCHAR2(20);
  L_STARTED_AT TIMESTAMP WITH TIME ZONE;
  L_SID NUMBER;
  L_SERIAL NUMBER;
  L_LEDGER_OPERATION NUMBER;
  L_STAGED NUMBER;
  L_INSERTED NUMBER;
  L_MANUAL NUMBER;
  L_ACTIVE_COUNT NUMBER;
  L_STAGE_COUNT NUMBER;
  L_OPERATION_COUNT NUMBER;
  L_OPERATION_ID NUMBER;
  L_OPERATION_STATUS VARCHAR2(30);
  L_OPERATION_ROWS NUMBER;
  L_OPERATION_UPDATED TIMESTAMP WITH TIME ZONE;
  L_OPERATION_SID NUMBER;
  L_OPERATION_SERIAL NUMBER;
  L_OPERATION_ALIVE NUMBER := 0;
  L_CALLER_ALIVE NUMBER := 0;
  L_KNOWN_SESSION NUMBER := 0;
  L_OPEN_RUNS NUMBER;
  L_PRIOR_REQUEUES NUMBER;
  L_MANUAL_OUTCOMES NUMBER;
  L_REASON VARCHAR2(4000);
BEGIN
  OCI_FOCUS_REMED_MUTEX.ENTER;
  P_ACTION := 'NONE';
  SELECT COUNT(*) INTO L_ACTIVE_COUNT FROM OCI_FOCUS_REMED_FILE
   WHERE STATE IN ('COPYING','STAGED','PROCESSING');
  IF L_ACTIVE_COUNT <> 1 THEN
    RAISE_APPLICATION_ERROR(-20899,
      'COPYING recovery requires exactly one active file');
  END IF;
  SELECT R.PIPELINE_NAME, R.GENERATION_NO, R.SOURCE_NAME_HASH,
         R.STARTED_AT, R.COPY_SESSION_SID, R.COPY_SESSION_SERIAL,
         R.COPY_OPERATION_ID, R.STAGED_ROWS, R.INSERTED_ROWS, R.MANUAL_ROWS
    INTO L_PIPELINE, L_GENERATION, L_HASH, L_STARTED_AT, L_SID, L_SERIAL,
         L_LEDGER_OPERATION, L_STAGED, L_INSERTED, L_MANUAL
    FROM OCI_FOCUS_REMED_FILE R
   WHERE R.STATE = 'COPYING'
   FOR UPDATE NOWAIT;
  SELECT Q.SOURCE_URI, Q.FILE_STATE
    INTO L_SOURCE_URI, L_QUEUE_STATE
    FROM OCI_FOCUS_FAIL_FILE Q
   WHERE Q.PIPELINE_NAME = L_PIPELINE
     AND Q.GENERATION_NO = L_GENERATION
     AND Q.SOURCE_NAME_HASH = L_HASH
   FOR UPDATE NOWAIT;
  IF L_QUEUE_STATE <> 'IN_PROGRESS' OR L_SOURCE_URI IS NULL OR
     L_LEDGER_OPERATION IS NOT NULL THEN
    RAISE_APPLICATION_ERROR(-20891,
      'COPYING queue, source, or ledger operation is inconsistent');
  END IF;
  SELECT COUNT(ROWID) INTO L_STAGE_COUNT FROM OCI_FOCUS_REMED_STAGE;
  SELECT COUNT(*) INTO L_MANUAL_OUTCOMES FROM OCI_FOCUS_REMED_MANUAL
   WHERE PIPELINE_NAME = L_PIPELINE AND GENERATION_NO = L_GENERATION
     AND SOURCE_NAME_HASH = L_HASH;
  IF L_MANUAL_OUTCOMES <> 0 THEN
    RAISE_APPLICATION_ERROR(-20890,
      'COPYING ledger has manual outcomes; operator review required');
  END IF;
  SELECT COUNT(*) INTO L_OPERATION_COUNT FROM USER_LOAD_OPERATIONS O
   WHERE O.TABLE_NAME = 'OCI_FOCUS_REMED_STAGE'
     AND O.FILE_URI_LIST = L_SOURCE_URI
     AND O.START_TIME >= L_STARTED_AT;
  IF L_OPERATION_COUNT = 1 THEN
    SELECT O.ID, O.STATUS, O.ROWS_LOADED, O.SID, O.SERIAL#,
           O.UPDATE_TIME
      INTO L_OPERATION_ID, L_OPERATION_STATUS, L_OPERATION_ROWS,
           L_OPERATION_SID, L_OPERATION_SERIAL, L_OPERATION_UPDATED
      FROM USER_LOAD_OPERATIONS O
     WHERE O.TABLE_NAME = 'OCI_FOCUS_REMED_STAGE'
       AND O.FILE_URI_LIST = L_SOURCE_URI
       AND O.START_TIME >= L_STARTED_AT;
  END IF;
  IF L_SID IS NOT NULL AND L_SERIAL IS NOT NULL THEN
    L_KNOWN_SESSION := 1;
    SELECT COUNT(*) INTO L_CALLER_ALIVE FROM V$SESSION
     WHERE SID = L_SID AND SERIAL# = L_SERIAL;
  END IF;
  IF L_OPERATION_COUNT = 1 AND L_OPERATION_SID IS NOT NULL AND
     L_OPERATION_SERIAL IS NOT NULL THEN
    L_KNOWN_SESSION := 1;
    SELECT COUNT(*) INTO L_OPERATION_ALIVE FROM V$SESSION
     WHERE SID = L_OPERATION_SID AND SERIAL# = L_OPERATION_SERIAL;
  ELSIF L_OPERATION_COUNT = 1 THEN
    -- A live operation without session identity cannot be ruled out.
    L_OPERATION_ALIVE := 1;
  END IF;
  P_ACTION := OCI_FOCUS_COPY_RECOVERY_DECIDE(
    L_STAGE_COUNT, L_STAGED, L_INSERTED, L_MANUAL,
    L_OPERATION_COUNT, L_OPERATION_STATUS, L_OPERATION_ROWS,
    L_KNOWN_SESSION, L_CALLER_ALIVE, L_OPERATION_ALIVE);
  IF P_ACTION = 'BLOCK' THEN
    RAISE_APPLICATION_ERROR(-20891,
      'COPYING evidence is ambiguous: stage=' || L_STAGE_COUNT ||
      ', operations=' || L_OPERATION_COUNT ||
      ', status=' || NVL(L_OPERATION_STATUS,'?') ||
      ', caller_alive=' || L_CALLER_ALIVE ||
      ', operation_alive=' || L_OPERATION_ALIVE);
  END IF;
  IF P_ACTION = 'REQUEUE' AND
     (L_STARTED_AT > SYSTIMESTAMP - INTERVAL '5' MINUTE OR
      (L_OPERATION_COUNT = 1 AND
       (L_OPERATION_UPDATED IS NULL OR
        L_OPERATION_UPDATED > SYSTIMESTAMP - INTERVAL '5' MINUTE))) THEN
    RAISE_APPLICATION_ERROR(-20896,
      'COPYING attempt is too recent to classify as stale');
  END IF;
  L_REASON := 'Interrupted COPY_DATA; operation=' ||
              NVL(TO_CHAR(L_OPERATION_ID), 'none') ||
              ', operation_status=' || NVL(L_OPERATION_STATUS, 'none') ||
              ', caller and operation sessions absent';
  IF P_ACTION = 'STAGED' THEN
    UPDATE OCI_FOCUS_REMED_FILE
       SET STATE = 'STAGED', STAGED_ROWS = L_STAGE_COUNT,
           COPY_OPERATION_ID = L_OPERATION_ID
     WHERE PIPELINE_NAME = L_PIPELINE AND GENERATION_NO = L_GENERATION
       AND SOURCE_NAME_HASH = L_HASH AND STATE = 'COPYING';
    IF SQL%ROWCOUNT <> 1 THEN
      RAISE_APPLICATION_ERROR(-20892, 'COPYING to STAGED update failed');
    END IF;
  ELSE
    SELECT COUNT(*) INTO L_PRIOR_REQUEUES FROM OCI_FOCUS_COPY_RECOVERY
     WHERE PIPELINE_NAME = L_PIPELINE AND GENERATION_NO = L_GENERATION
       AND SOURCE_NAME_HASH = L_HASH AND DECISION = 'REQUEUED';
    IF L_PRIOR_REQUEUES >= 2 THEN
      RAISE_APPLICATION_ERROR(-20897,
        'COPYING retry limit reached; review repeated interrupted copies');
    END IF;
    SELECT COUNT(*) INTO L_OPEN_RUNS FROM OCI_FOCUS_REMED_RUN
     WHERE PIPELINE_NAME = L_PIPELINE AND FINISHED_AT IS NULL;
    IF L_OPEN_RUNS <> 1 THEN
      RAISE_APPLICATION_ERROR(-20893,
        'Expected one interrupted worker run before requeue');
    END IF;
    UPDATE OCI_FOCUS_REMED_RUN
       SET FINISHED_AT = SYSTIMESTAMP,
           ERROR_MESSAGE = SUBSTR(L_REASON || '; file requeued', 1, 4000)
     WHERE PIPELINE_NAME = L_PIPELINE AND FINISHED_AT IS NULL;
    DELETE FROM OCI_FOCUS_REMED_FILE
     WHERE PIPELINE_NAME = L_PIPELINE AND GENERATION_NO = L_GENERATION
       AND SOURCE_NAME_HASH = L_HASH AND STATE = 'COPYING';
    IF SQL%ROWCOUNT <> 1 THEN
      RAISE_APPLICATION_ERROR(-20894, 'COPYING ledger removal failed');
    END IF;
    UPDATE OCI_FOCUS_FAIL_FILE SET FILE_STATE = 'NEW'
     WHERE PIPELINE_NAME = L_PIPELINE AND GENERATION_NO = L_GENERATION
       AND SOURCE_NAME_HASH = L_HASH AND FILE_STATE = 'IN_PROGRESS';
    IF SQL%ROWCOUNT <> 1 THEN
      RAISE_APPLICATION_ERROR(-20895, 'COPYING queue requeue failed');
    END IF;
  END IF;
  INSERT INTO OCI_FOCUS_COPY_RECOVERY
    (PIPELINE_NAME, GENERATION_NO, SOURCE_NAME_HASH,
     COPY_OPERATION_ID, DECISION, STAGE_ROWS, REASON)
  VALUES (L_PIPELINE, L_GENERATION, L_HASH, L_OPERATION_ID,
          CASE P_ACTION WHEN 'STAGED' THEN 'STAGED' ELSE 'REQUEUED' END,
          L_STAGE_COUNT, L_REASON);
  COMMIT;
  OCI_FOCUS_REMED_MUTEX.LEAVE;
EXCEPTION WHEN OTHERS THEN
  ROLLBACK;
  OCI_FOCUS_REMED_MUTEX.LEAVE;
  RAISE;
END;
