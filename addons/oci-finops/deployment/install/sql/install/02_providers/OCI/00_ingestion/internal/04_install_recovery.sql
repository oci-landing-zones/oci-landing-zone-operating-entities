-- Pure recovery decision: may be installed and tested while a worker runs.
SET DEFINE OFF
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
CREATE OR REPLACE FUNCTION OCI_FOCUS_COPY_RECOVERY_DECIDE (
  P_STAGE_ROWS IN NUMBER,
  P_LEDGER_STAGED IN NUMBER,
  P_INSERTED IN NUMBER,
  P_MANUAL IN NUMBER,
  P_OPERATION_COUNT IN NUMBER,
  P_OPERATION_STATUS IN VARCHAR2,
  P_OPERATION_ROWS IN NUMBER,
  P_KNOWN_SESSION IN NUMBER,
  P_CALLER_ALIVE IN NUMBER,
  P_OPERATION_ALIVE IN NUMBER
) RETURN VARCHAR2 DETERMINISTIC AUTHID CURRENT_USER IS
BEGIN
  IF P_STAGE_ROWS IS NULL OR P_LEDGER_STAGED IS NULL OR
     P_INSERTED IS NULL OR P_MANUAL IS NULL OR
     P_OPERATION_COUNT IS NULL OR P_KNOWN_SESSION IS NULL OR
     P_CALLER_ALIVE IS NULL OR P_OPERATION_ALIVE IS NULL OR
     P_STAGE_ROWS < 0 OR P_OPERATION_COUNT NOT IN (0,1) OR
     P_LEDGER_STAGED <> 0 OR P_INSERTED <> 0 OR P_MANUAL <> 0 OR
     P_KNOWN_SESSION <> 1 OR P_CALLER_ALIVE <> 0 OR
     P_OPERATION_ALIVE <> 0 THEN
    RETURN 'BLOCK';
  END IF;
  IF P_STAGE_ROWS > 0 AND P_OPERATION_COUNT = 1 AND
     P_OPERATION_STATUS = 'COMPLETED' AND
     P_OPERATION_ROWS = P_STAGE_ROWS THEN
    RETURN 'STAGED';
  END IF;
  IF P_STAGE_ROWS = 0 AND
     (P_OPERATION_COUNT = 0 OR
      (P_OPERATION_COUNT = 1 AND
       P_OPERATION_STATUS IN ('RUNNING','FAILED') AND
       P_OPERATION_ROWS IS NULL)) THEN
    RETURN 'REQUEUE';
  END IF;
  RETURN 'BLOCK';
END;
