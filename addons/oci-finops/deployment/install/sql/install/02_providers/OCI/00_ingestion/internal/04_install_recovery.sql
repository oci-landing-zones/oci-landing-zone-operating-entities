WHENEVER SQLERROR EXIT FAILURE ROLLBACK

CREATE OR REPLACE PROCEDURE OCI_FOCUS_RESOLVE_MANUAL_ROW (
  P_MANUAL_ID IN NUMBER,
  P_ACTION IN VARCHAR2,
  P_RESOLUTION_NOTE IN VARCHAR2,
  P_CHARGEPERIODSTART IN TIMESTAMP DEFAULT NULL,
  P_OCI_REFERENCENUMBER IN VARCHAR2 DEFAULT NULL
) AUTHID CURRENT_USER IS
  L_ACTION VARCHAR2(20) := UPPER(TRIM(P_ACTION));
  L_PIPELINE VARCHAR2(128);
  L_GENERATION NUMBER;
  L_HASH RAW(32);
  L_STATUS VARCHAR2(20);
  L_TARGET VARCHAR2(128);
  L_PRESENT NUMBER;
  L_STAGED NUMBER;
  L_INSERTED NUMBER;
  L_MANUAL NUMBER;
  L_RESOLVED NUMBER;
  L_WAIVED NUMBER;
  L_FILE_STATE VARCHAR2(20);
BEGIN
  IF L_ACTION NOT IN ('INSERTED','ACCEPTED_EXISTING','WAIVED')
     OR L_ACTION IS NULL THEN
    RAISE_APPLICATION_ERROR(-20850, 'Unsupported manual resolution action');
  END IF;
  IF TRIM(P_RESOLUTION_NOTE) IS NULL THEN
    RAISE_APPLICATION_ERROR(-20851, 'Resolution note is required');
  END IF;

  SELECT PIPELINE_NAME, GENERATION_NO, SOURCE_NAME_HASH, RESOLUTION_STATUS
    INTO L_PIPELINE, L_GENERATION, L_HASH, L_STATUS
    FROM OCI_FOCUS_REMED_MANUAL
   WHERE MANUAL_ID = P_MANUAL_ID
   FOR UPDATE NOWAIT;
  IF L_STATUS <> 'PENDING' THEN
    RAISE_APPLICATION_ERROR(-20852, 'Manual row is already resolved');
  END IF;

  SELECT STATE, STAGED_ROWS, INSERTED_ROWS, MANUAL_ROWS,
         RESOLVED_ROWS, WAIVED_ROWS
    INTO L_FILE_STATE, L_STAGED, L_INSERTED, L_MANUAL,
         L_RESOLVED, L_WAIVED
    FROM OCI_FOCUS_REMED_FILE
   WHERE PIPELINE_NAME = L_PIPELINE
     AND GENERATION_NO = L_GENERATION
     AND SOURCE_NAME_HASH = L_HASH
   FOR UPDATE NOWAIT;
  IF L_FILE_STATE <> 'PARTIAL' OR
     L_STAGED <> L_INSERTED + L_MANUAL OR
     L_RESOLVED + L_WAIVED >= L_MANUAL THEN
    RAISE_APPLICATION_ERROR(-20853, 'File is not ready for manual resolution');
  END IF;

  IF L_ACTION IN ('INSERTED','ACCEPTED_EXISTING') THEN
    IF P_CHARGEPERIODSTART IS NULL OR
       TRIM(P_OCI_REFERENCENUMBER) IS NULL THEN
      RAISE_APPLICATION_ERROR(-20854, 'Landing primary key is required');
    END IF;
    SELECT DBMS_ASSERT.SIMPLE_SQL_NAME(
             DBMS_LOB.SUBSTR(ATTRIBUTE_VALUE, 128, 1))
      INTO L_TARGET
      FROM USER_CLOUD_PIPELINE_ATTRIBUTES
     WHERE PIPELINE_NAME = L_PIPELINE
       AND ATTRIBUTE_NAME = 'table_name';
    IF L_TARGET NOT LIKE 'OCI_FOCUS_REPORTS%' THEN
      RAISE_APPLICATION_ERROR(-20855, 'Unexpected landing target');
    END IF;
    EXECUTE IMMEDIATE
      'SELECT COUNT(*) FROM ' || L_TARGET ||
      ' WHERE CHARGEPERIODSTART = :1 AND OCI_REFERENCENUMBER = :2'
      INTO L_PRESENT
      USING P_CHARGEPERIODSTART, TRIM(P_OCI_REFERENCENUMBER);
    IF L_PRESENT <> 1 THEN
      RAISE_APPLICATION_ERROR(-20856, 'Landing key is not present exactly once');
    END IF;
  ELSIF P_CHARGEPERIODSTART IS NOT NULL OR
        P_OCI_REFERENCENUMBER IS NOT NULL THEN
    RAISE_APPLICATION_ERROR(-20857, 'WAIVED must not claim a landing key');
  END IF;

  UPDATE OCI_FOCUS_REMED_MANUAL
     SET RESOLUTION_STATUS = L_ACTION,
         RESOLVED_AT = SYSTIMESTAMP,
         RESOLVED_BY = SYS_CONTEXT('USERENV', 'SESSION_USER'),
         RESOLUTION_NOTE = TRIM(P_RESOLUTION_NOTE),
         RESOLVED_CHARGEPERIODSTART = P_CHARGEPERIODSTART,
         RESOLVED_OCI_REFERENCENUMBER = TRIM(P_OCI_REFERENCENUMBER)
   WHERE MANUAL_ID = P_MANUAL_ID AND RESOLUTION_STATUS = 'PENDING';
  IF SQL%ROWCOUNT <> 1 THEN
    RAISE_APPLICATION_ERROR(-20858, 'Manual row update was not unique');
  END IF;

  IF L_ACTION = 'WAIVED' THEN
    L_WAIVED := L_WAIVED + 1;
  ELSE
    L_RESOLVED := L_RESOLVED + 1;
  END IF;
  UPDATE OCI_FOCUS_REMED_FILE
     SET RESOLVED_ROWS = L_RESOLVED,
         WAIVED_ROWS = L_WAIVED,
         RESOLUTION_COMPLETED_AT = CASE
           WHEN L_RESOLVED + L_WAIVED = L_MANUAL THEN SYSTIMESTAMP
           ELSE RESOLUTION_COMPLETED_AT END,
         STATE = CASE
           WHEN L_RESOLVED = L_MANUAL AND L_WAIVED = 0 THEN 'FULL'
           ELSE STATE END
   WHERE PIPELINE_NAME = L_PIPELINE
     AND GENERATION_NO = L_GENERATION
     AND SOURCE_NAME_HASH = L_HASH;
  IF SQL%ROWCOUNT <> 1 THEN
    RAISE_APPLICATION_ERROR(-20859, 'File ledger update was not unique');
  END IF;

  IF L_RESOLVED = L_MANUAL AND L_WAIVED = 0 THEN
    UPDATE OCI_FOCUS_FAIL_FILE
       SET FILE_STATE = 'FULL'
     WHERE PIPELINE_NAME = L_PIPELINE
       AND GENERATION_NO = L_GENERATION
       AND SOURCE_NAME_HASH = L_HASH
       AND FILE_STATE = 'PARTIAL';
    IF SQL%ROWCOUNT <> 1 THEN
      RAISE_APPLICATION_ERROR(-20860, 'Queue update was not unique');
    END IF;
  END IF;
  COMMIT;
EXCEPTION WHEN OTHERS THEN
  ROLLBACK;
  RAISE;
END;
