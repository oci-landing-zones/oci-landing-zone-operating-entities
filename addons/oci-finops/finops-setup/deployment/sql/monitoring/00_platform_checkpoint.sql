       TO_CHAR(J.NEXT_RUN_DATE,'YYYY-MM-DD HH24:MI TZR') NEXT_RUN,
       R.STATUS LAST_STATUS,
       TO_CHAR(R.ACTUAL_START_DATE,'YYYY-MM-DD HH24:MI TZR') LAST_START,
       R.ERROR# LAST_ERROR
 FROM DBA_SCHEDULER_JOBS J
