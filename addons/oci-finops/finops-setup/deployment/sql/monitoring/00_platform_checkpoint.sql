PROMPT === Installed module object counts ===
SELECT MODULE_NAME,COUNT(*) OBJECTS,
       SUM(CASE WHEN OBJECT_TYPE='TABLE' THEN 1 ELSE 0 END) TABLES,
       SUM(CASE WHEN OBJECT_TYPE='JOB' THEN 1 ELSE 0 END) JOBS,
       SUM(CASE WHEN OBJECT_TYPE IN ('FUNCTION','PROCEDURE','PACKAGE','PACKAGE BODY')
                THEN 1 ELSE 0 END) CODE_OBJECTS,
       SUM(CASE WHEN STATUS<>'VALID' THEN 1 ELSE 0 END) NONVALID
 FROM (SELECT OBJECT_TYPE,STATUS,
         CASE WHEN OBJECT_NAME LIKE 'FINOPS_CORE_%' THEN 'COMMON_CORE'
              WHEN OBJECT_NAME LIKE 'OCI_FOCUS_%' OR OBJECT_NAME LIKE 'PIPELINE$%'
                THEN 'OCI_INGESTION'
              WHEN OBJECT_NAME LIKE 'OCI_TAG_%' THEN 'OCI_TAGS'
              WHEN OBJECT_NAME LIKE 'OCI_ACCOUNT_%' OR OBJECT_NAME IN
                ('OCI_SYNC_ACCOUNT_CONTEXT','OCI_SYNC_ALL_CONTRACTS','OCI_SYNC_CONTRACT')
                THEN 'OCI_ACCOUNT_CONTRACT'
              WHEN OBJECT_NAME LIKE 'OCI_ADVISOR_%' OR OBJECT_NAME='OCI_SYNC_ADVISOR'
                THEN 'OCI_ADVISOR'
              WHEN OBJECT_NAME LIKE 'OCI_ANOMALY_%' OR OBJECT_NAME='OCI_SYNC_ANOMALIES'
                THEN 'OCI_ANOMALY'
              WHEN OBJECT_NAME LIKE 'OCI_FORECAST_%' OR OBJECT_NAME='OCI_SYNC_FORECAST'
                THEN 'OCI_FORECAST'
              WHEN OBJECT_NAME LIKE 'OAC_%' OR OBJECT_NAME IN
                ('MV_CAPABILITIES_TABLE','MLOG$_OCI_FOCUS_REPORTS') THEN 'OAC'
              ELSE 'OTHER' END MODULE_NAME
         FROM DBA_OBJECTS
        WHERE OWNER='FOCUSPLATFORM'
          AND OBJECT_TYPE NOT IN ('TABLE PARTITION','INDEX PARTITION','LOB PARTITION','LOB','SEQUENCE','INDEX'))
 GROUP BY MODULE_NAME ORDER BY MODULE_NAME;
