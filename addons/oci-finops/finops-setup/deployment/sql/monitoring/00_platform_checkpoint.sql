PROMPT === Pipeline files and remediation, by pipeline ===
DECLARE
  L_SQL VARCHAR2(32767);
  L_COMPLETED NUMBER; L_PENDING NUMBER; L_FAILED NUMBER; L_RUNNING NUMBER;
  L_NEW NUMBER; L_ACTIVE NUMBER; L_FULL NUMBER; L_PARTIAL NUMBER; L_ERROR NUMBER;
  L_UNREGISTERED NUMBER;
BEGIN
  FOR P IN (SELECT PIPELINE_NAME,STATUS,STATUS_TABLE
              FROM DBA_CLOUD_PIPELINES
             WHERE OWNER='FOCUSPLATFORM' AND PIPELINE_TYPE='LOAD'
             ORDER BY PIPELINE_NAME) LOOP
    DBMS_OUTPUT.PUT_LINE('pipeline='||P.PIPELINE_NAME||' status='||P.STATUS||
                         ' status_table='||NVL(P.STATUS_TABLE,'NONE'));
    IF P.STATUS_TABLE IS NOT NULL THEN
      L_SQL := 'SELECT SUM(CASE WHEN STATUS=''COMPLETED'' THEN 1 ELSE 0 END),'
        ||'SUM(CASE WHEN STATUS=''PENDING'' THEN 1 ELSE 0 END),'
        ||'SUM(CASE WHEN STATUS=''FAILED'' THEN 1 ELSE 0 END),'
        ||'SUM(CASE WHEN STATUS=''RUNNING'' THEN 1 ELSE 0 END) FROM FOCUSPLATFORM.'
        ||DBMS_ASSERT.SIMPLE_SQL_NAME(P.STATUS_TABLE);
      EXECUTE IMMEDIATE L_SQL INTO L_COMPLETED,L_PENDING,L_FAILED,L_RUNNING;
      L_SQL := 'SELECT COUNT(*) FROM FOCUSPLATFORM.'
        ||DBMS_ASSERT.SIMPLE_SQL_NAME(P.STATUS_TABLE)
        ||' S WHERE S.STATUS=''FAILED'' AND NOT EXISTS '
        ||'(SELECT 1 FROM FOCUSPLATFORM.OCI_FOCUS_FAIL_FILE Q '
        ||'WHERE Q.PIPELINE_NAME=:p AND Q.SOURCE_NAME=S.NAME)';
      EXECUTE IMMEDIATE L_SQL INTO L_UNREGISTERED USING P.PIPELINE_NAME;
      DBMS_OUTPUT.PUT_LINE('  oracle completed='||NVL(L_COMPLETED,0)||
        ' pending='||NVL(L_PENDING,0)||' failed='||NVL(L_FAILED,0)||
        ' running='||NVL(L_RUNNING,0)||' failed_not_in_ledger='||L_UNREGISTERED);
    END IF;
    SELECT NVL(SUM(CASE WHEN FILE_STATE='NEW' THEN 1 ELSE 0 END),0),
           NVL(SUM(CASE WHEN FILE_STATE='IN_PROGRESS' THEN 1 ELSE 0 END),0),
           NVL(SUM(CASE WHEN FILE_STATE='FULL' THEN 1 ELSE 0 END),0),
           NVL(SUM(CASE WHEN FILE_STATE='PARTIAL' THEN 1 ELSE 0 END),0),
           NVL(SUM(CASE WHEN FILE_STATE='ERROR' THEN 1 ELSE 0 END),0)
      INTO L_NEW,L_ACTIVE,L_FULL,L_PARTIAL,L_ERROR
      FROM FOCUSPLATFORM.OCI_FOCUS_FAIL_FILE
     WHERE PIPELINE_NAME=P.PIPELINE_NAME;
    DBMS_OUTPUT.PUT_LINE('  remediation new='||L_NEW||' active='||L_ACTIVE||
      ' full='||L_FULL||' partial='||L_PARTIAL||' error='||L_ERROR);
  END LOOP;
END;
