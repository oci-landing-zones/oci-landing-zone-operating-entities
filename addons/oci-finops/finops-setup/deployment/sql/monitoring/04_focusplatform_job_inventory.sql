-- Read-only inventory. Run as FOCUSPLATFORM from any SQL*Plus directory.
SET LINESIZE 260 PAGESIZE 100 TRIMSPOOL ON
COLUMN JOB_NAME FORMAT A48
COLUMN ENABLED FORMAT A7
COLUMN STATE FORMAT A13
COLUMN REPEAT_INTERVAL FORMAT A67
COLUMN START_ZONE FORMAT A20
COLUMN NEXT_RUN FORMAT A30
COLUMN CREATED_DB_TIME FORMAT A19

SELECT J.JOB_NAME, J.ENABLED, J.STATE,
       NVL(J.REPEAT_INTERVAL, '(one-time)') REPEAT_INTERVAL,
       TO_CHAR(J.START_DATE, 'TZR') START_ZONE,
       TO_CHAR(J.NEXT_RUN_DATE,
               'YYYY-MM-DD HH24:MI TZH:TZM') NEXT_RUN,
       TO_CHAR(O.CREATED, 'YYYY-MM-DD HH24:MI:SS') CREATED_DB_TIME
  FROM USER_SCHEDULER_JOBS J
  LEFT JOIN USER_OBJECTS O
    ON O.OBJECT_NAME = J.JOB_NAME AND O.OBJECT_TYPE = 'JOB'
 ORDER BY J.JOB_NAME;

SELECT CONFIG_ID, TIME_ZONE AS SELECTED_TIME_ZONE, UPDATED_AT
  FROM FINOPS_CORE_SCHEDULE_CONFIG
 ORDER BY CONFIG_ID;

SELECT J.JOB_NAME, J.ELAPSED_TIME
  FROM USER_SCHEDULER_RUNNING_JOBS J
 ORDER BY J.JOB_NAME;
