-- Optional read-only MV snapshot. Safe when OAC is absent. No compile/refresh.
-- Run as FOCUSPLATFORM, or ADMIN with CURRENT_SCHEMA=FOCUSPLATFORM.
-- Spool repeated executions outside Git to establish when states change.
SET ECHO OFF VERIFY OFF DEFINE OFF FEEDBACK ON
SET LINESIZE 260 PAGESIZE 100 TRIMSPOOL ON
COLUMN MVIEW_NAME FORMAT A52
COLUMN TABLE_NAME FORMAT A52
COLUMN OBJECT_NAME FORMAT A52
COLUMN REFERENCED_NAME FORMAT A52
COLUMN SUBOBJECT_NAME FORMAT A26
COLUMN COMPILE_STATE FORMAT A18
COLUMN STALENESS FORMAT A18
COLUMN SNAPSHOT_UTC FORMAT A20
PROMPT === Snapshot time (UTC) ===
SELECT TO_CHAR(SYS_EXTRACT_UTC(SYSTIMESTAMP),'YYYY-MM-DD HH24:MI:SS') SNAPSHOT_UTC FROM DUAL;
PROMPT === Published interface (empty means unpublished or absent) ===
SELECT SYNONYM_NAME,TABLE_OWNER,TABLE_NAME,DB_LINK FROM ALL_SYNONYMS
WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
 AND SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL';
PROMPT === All cost-detail MV versions; identify the published one above ===
SELECT M.MVIEW_NAME,O.STATUS OBJECT_STATUS,M.COMPILE_STATE,M.STALENESS,
 M.REFRESH_METHOD,M.LAST_REFRESH_TYPE,
 TO_CHAR(M.LAST_REFRESH_DATE,'YYYY-MM-DD HH24:MI:SS') LAST_REFRESH,
 TO_CHAR(M.LAST_REFRESH_END_TIME,'YYYY-MM-DD HH24:MI:SS') REFRESH_END,
 TO_CHAR(M.STALE_SINCE,'YYYY-MM-DD HH24:MI:SS') STALE_SINCE,
 TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') MV_LAST_DDL,
 M.FAST_REFRESHABLE,M.REWRITE_ENABLED
FROM ALL_MVIEWS M LEFT JOIN ALL_OBJECTS O ON O.OWNER=M.OWNER
 AND O.OBJECT_NAME=M.MVIEW_NAME AND O.OBJECT_TYPE='MATERIALIZED VIEW'
WHERE M.OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
 AND M.MVIEW_NAME LIKE 'OAC_OCI_FOCUS_COST_DETAIL_MV_V%'
ORDER BY M.MVIEW_NAME;
PROMPT === Direct dependency objects and their DDL timestamps ===
SELECT D.NAME MV_NAME,D.REFERENCED_OWNER,D.REFERENCED_NAME,D.REFERENCED_TYPE,
 O.STATUS,TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL
FROM ALL_DEPENDENCIES D LEFT JOIN ALL_OBJECTS O ON O.OWNER=D.REFERENCED_OWNER
 AND O.OBJECT_NAME=D.REFERENCED_NAME AND O.OBJECT_TYPE=D.REFERENCED_TYPE
WHERE D.OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND D.TYPE='MATERIALIZED VIEW'
 AND D.NAME LIKE 'OAC_OCI_FOCUS_COST_DETAIL_MV_V%'
ORDER BY D.NAME,D.REFERENCED_OWNER,D.REFERENCED_NAME;
PROMPT === Source DML counters (approximate/asynchronous; not a transaction audit) ===
SELECT TABLE_NAME,PARTITION_NAME,INSERTS,UPDATES,DELETES,
 TO_CHAR(TIMESTAMP,'YYYY-MM-DD HH24:MI:SS') LAST_RECORDED,TRUNCATED
FROM ALL_TAB_MODIFICATIONS
WHERE TABLE_OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND TABLE_NAME='OCI_FOCUS_REPORTS'
ORDER BY TIMESTAMP DESC;
PROMPT === Most recently created source partitions ===
SELECT SUBOBJECT_NAME,TO_CHAR(CREATED,'YYYY-MM-DD HH24:MI:SS') CREATED,
 TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL
FROM ALL_OBJECTS WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
 AND OBJECT_NAME='OCI_FOCUS_REPORTS' AND OBJECT_TYPE='TABLE PARTITION'
ORDER BY CREATED DESC FETCH FIRST 10 ROWS ONLY;
PROMPT NEEDS_COMPILE does not by itself prove corrupt data or identify DDL as the cause.
PROMPT Do not trust STALENESS classification until compilation validity is established.
PROMPT STALE means older source data; refresh completion and later source changes are separate events.
PROMPT This script never repairs, recompiles, refreshes or changes schedules.
