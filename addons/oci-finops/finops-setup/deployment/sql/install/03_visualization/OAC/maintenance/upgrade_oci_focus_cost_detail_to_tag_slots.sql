DECLARE
  L_FOUND NUMBER;
  L_LOCK_RESULT INTEGER;
  L_LOCK_ID INTEGER := DBMS_UTILITY.GET_HASH_VALUE(
    'OAC_OCI_FOCUS_COST_DETAIL:'||SYS_CONTEXT('USERENV','CURRENT_USER'),
    1,1073741823);
  L_CONSTRAINT VARCHAR2(128);
  L_NEW_CONSTRAINT NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'FOCUSPLATFORM' OR
     SYS_CONTEXT('USERENV','CURRENT_SCHEMA')<>'FOCUSPLATFORM' THEN
    RAISE_APPLICATION_ERROR(-20650,'Connect as FOCUSPLATFORM');
  END IF;
  SELECT COUNT(*) INTO L_FOUND FROM USER_OBJECTS
   WHERE OBJECT_NAME IN ('OAC_OCI_FOCUS_COST_DETAIL_API',
                         'OAC_OCI_FOCUS_COST_DETAIL_RUN',
                         'OAC_OCI_FOCUS_COST_DETAIL_TAG_COLUMN')
     AND OBJECT_TYPE IN ('PACKAGE','TABLE');
  IF L_FOUND<>3 THEN
    RAISE_APPLICATION_ERROR(-20651,'Install the OAC cost-detail module first');
  END IF;
  L_LOCK_RESULT:=DBMS_LOCK.REQUEST(ID=>L_LOCK_ID,
    LOCKMODE=>DBMS_LOCK.X_MODE,TIMEOUT=>0,RELEASE_ON_COMMIT=>FALSE);
  IF L_LOCK_RESULT<>0 THEN
    RAISE_APPLICATION_ERROR(-20653,'An OAC cost-detail build or refresh is active');
  END IF;
  SELECT COUNT(*) INTO L_NEW_CONSTRAINT FROM USER_CONSTRAINTS
   WHERE TABLE_NAME='OAC_OCI_FOCUS_COST_DETAIL_RUN'
     AND CONSTRAINT_TYPE='C'
     AND SEARCH_CONDITION_VC LIKE '%READY%'
     AND SEARCH_CONDITION_VC LIKE '%PREPARED%';
  IF L_NEW_CONSTRAINT=0 THEN
    SELECT MIN(CONSTRAINT_NAME) INTO L_CONSTRAINT FROM USER_CONSTRAINTS
     WHERE TABLE_NAME='OAC_OCI_FOCUS_COST_DETAIL_RUN'
       AND CONSTRAINT_TYPE='C'
       AND SEARCH_CONDITION_VC LIKE '%RUNNING%'
       AND SEARCH_CONDITION_VC LIKE '%PREPARED%';
    IF L_CONSTRAINT IS NOT NULL THEN
      EXECUTE IMMEDIATE 'ALTER TABLE OAC_OCI_FOCUS_COST_DETAIL_RUN DROP CONSTRAINT '||
        DBMS_ASSERT.ENQUOTE_NAME(L_CONSTRAINT,FALSE);
    END IF;
    EXECUTE IMMEDIATE 'ALTER TABLE OAC_OCI_FOCUS_COST_DETAIL_RUN ADD CONSTRAINT '||
      'OAC_OCI_FOCUS_COST_DETAIL_STATUS_CK CHECK '||
      '(STATUS IN (''RUNNING'',''PREPARED'',''READY'',''COMPLETE'',''ERROR'',''SKIPPED''))';
  END IF;
  DBMS_OUTPUT.PUT_LINE('Run audit now supports READY cutover state');
END;
