-- Labels always resolve through the published synonym, not the active profile.
-- READY covers the brief interval between synonym DDL and audit completion.
CREATE OR REPLACE VIEW OAC_OCI_FOCUS_TAG_SLOT_V AS
WITH PUBLISHED AS (
  SELECT R.RUN_ID,R.PROFILE_NAME,R.PROFILE_VERSION,R.MV_NAME
    FROM OAC_OCI_FOCUS_COST_DETAIL_RUN R JOIN USER_SYNONYMS S
      ON S.TABLE_NAME=R.MV_NAME
   WHERE S.SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL'
     AND S.TABLE_OWNER=SYS_CONTEXT('USERENV','CURRENT_USER')
     AND S.DB_LINK IS NULL
     AND R.RUN_KIND='BUILD' AND R.STATUS IN ('READY','COMPLETE')
), SLOTS AS (
  SELECT P.RUN_ID,
         TO_NUMBER(REGEXP_SUBSTR(C.COLUMN_NAME,'^TAG_([0-9]+)$',1,1,'c',1))
           SLOT_NUMBER,
         C.COLUMN_NAME MV_COLUMN_NAME
    FROM PUBLISHED P JOIN USER_TAB_COLUMNS C ON C.TABLE_NAME=P.MV_NAME
   WHERE REGEXP_LIKE(C.COLUMN_NAME,'^TAG_[0-9]+$','c')
)
SELECT P.MV_NAME,P.PROFILE_NAME,P.PROFILE_VERSION,
       S.SLOT_NUMBER,S.MV_COLUMN_NAME,
       COALESCE(C.LOGICAL_TAG_NAME,'Unassigned') DISPLAY_LABEL,
       N.NAMESPACE_NAME,C.TAG_NAME,
       NVL(I.IS_ACTIVE,'N') ASSIGNED
  FROM PUBLISHED P JOIN SLOTS S ON S.RUN_ID=P.RUN_ID
  LEFT JOIN OAC_OCI_FOCUS_COST_DETAIL_TAG_COLUMN C
    ON C.RUN_ID=P.RUN_ID AND C.DISPLAY_ORDER=S.SLOT_NUMBER
  LEFT JOIN OCI_TAG_NAMESPACE N ON N.TAG_NAMESPACE_ID=C.TAG_NAMESPACE_ID
  LEFT JOIN OCI_TAG_PROFILE_ITEM I ON I.PROFILE_NAME=P.PROFILE_NAME
    AND I.PROFILE_VERSION=P.PROFILE_VERSION AND I.DISPLAY_ORDER=S.SLOT_NUMBER;
