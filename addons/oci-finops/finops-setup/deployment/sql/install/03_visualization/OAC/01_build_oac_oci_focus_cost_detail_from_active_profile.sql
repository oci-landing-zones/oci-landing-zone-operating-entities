-- After an explicit profile change, request another candidate MV in the background.
-- Run as FOCUSPLATFORM from deployment/sql/install. The published synonym remains available.
SET ECHO OFF VERIFY OFF DEFINE OFF SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
  L_JOB VARCHAR2(128) := 'OAC_OCI_FOCUS_COST_DETAIL_BUILD_'||SUBSTR(RAWTOHEX(SYS_GUID()),1,16);
  L_PROFILE VARCHAR2(128);
  L_VERSION NUMBER;
  L_CURRENT NUMBER;
  L_SLOT_VIEW NUMBER;
  L_PROFILE_TAGS NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'FOCUSPLATFORM' THEN
    RAISE_APPLICATION_ERROR(-20609,'Connect as FOCUSPLATFORM');
  END IF;
  SELECT COUNT(*) INTO L_SLOT_VIEW FROM USER_OBJECTS
   WHERE OBJECT_NAME='OAC_OCI_FOCUS_TAG_SLOT_V'
     AND OBJECT_TYPE='VIEW' AND STATUS='VALID';
  IF L_SLOT_VIEW<>1 THEN
    RAISE_APPLICATION_ERROR(-20628,
      'Install or upgrade the stable tag-slot OAC module before building');
  END IF;
  SELECT PROFILE_NAME,PROFILE_VERSION INTO L_PROFILE,L_VERSION
    FROM OCI_TAG_PROFILE_SELECTION WHERE SELECTION_ID=1;
  SELECT COUNT(*) INTO L_PROFILE_TAGS FROM OCI_TAG_PROFILE_ITEM
   WHERE PROFILE_NAME=L_PROFILE AND PROFILE_VERSION=L_VERSION;
  SELECT COUNT(*) INTO L_CURRENT
    FROM USER_SYNONYMS S JOIN OAC_OCI_FOCUS_COST_DETAIL_RUN R ON R.MV_NAME=S.TABLE_NAME
    JOIN USER_MVIEWS M ON M.MVIEW_NAME=S.TABLE_NAME
   WHERE S.SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL' AND R.RUN_KIND='BUILD'
     AND R.STATUS IN ('READY','COMPLETE') AND R.PROFILE_NAME=L_PROFILE
     AND R.PROFILE_VERSION=L_VERSION AND M.COMPILE_STATE='VALID'
     AND M.STALENESS<>'UNUSABLE'
     AND R.TAG_COLUMNS=L_PROFILE_TAGS
     AND (SELECT COUNT(*) FROM USER_TAB_COLUMNS C
           WHERE C.TABLE_NAME=M.MVIEW_NAME
             AND REGEXP_LIKE(C.COLUMN_NAME,'^TAG_[0-9]+$','c'))=L_PROFILE_TAGS
     AND (SELECT COUNT(*)
            FROM OAC_OCI_FOCUS_COST_DETAIL_TAG_COLUMN C
            JOIN (SELECT I.DISPLAY_ORDER SLOT,
                         I.LOGICAL_TAG_NAME,I.TAG_NAMESPACE_ID,I.TAG_NAME
                    FROM OCI_TAG_PROFILE_ITEM I
                   WHERE I.PROFILE_NAME=L_PROFILE
                     AND I.PROFILE_VERSION=L_VERSION) P
              ON C.DISPLAY_ORDER=P.SLOT
             AND C.MV_COLUMN_NAME='TAG_'||TO_CHAR(P.SLOT,'FM9999')
             AND C.LOGICAL_TAG_NAME=P.LOGICAL_TAG_NAME
             AND C.TAG_NAMESPACE_ID=P.TAG_NAMESPACE_ID
             AND C.TAG_NAME=P.TAG_NAME
           WHERE C.RUN_ID=R.RUN_ID)=L_PROFILE_TAGS;
  IF L_CURRENT>0 THEN
    DBMS_OUTPUT.PUT_LINE(
      'Selected profile mapping already published; no rebuild requested');
    RETURN;
  END IF;
  DBMS_SCHEDULER.CREATE_JOB(
    JOB_NAME=>L_JOB,JOB_TYPE=>'PLSQL_BLOCK',
    JOB_ACTION=>'BEGIN OAC_OCI_FOCUS_COST_DETAIL_API.BUILD_ACTIVE(0,0); END;',
    START_DATE=>SYSTIMESTAMP + INTERVAL '10' SECOND,
    ENABLED=>TRUE,AUTO_DROP=>TRUE,
    COMMENTS=>'Build an OAC OCI FOCUS cost-detail candidate without changing the stable synonym');
  DBMS_OUTPUT.PUT_LINE('Requested background candidate build='||L_JOB||
    ' profile='||L_PROFILE||' version='||L_VERSION||' synonym_unchanged=TRUE');
END;
