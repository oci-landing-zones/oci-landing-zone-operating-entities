-- Read-only structure and background-build status for OCI FOCUS cost detail.
SET VERIFY OFF DEFINE OFF SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 260 PAGESIZE 100
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
PROMPT === OAC cost detail objects ===
COLUMN OBJECT_NAME FORMAT A50
COLUMN OBJECT_TYPE FORMAT A22
SELECT OBJECT_NAME,OBJECT_TYPE,STATUS FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('OAC_OCI_FOCUS_COST_DETAIL_API','OAC_OCI_FOCUS_COST_DETAIL_RUN','OAC_OCI_FOCUS_COST_DETAIL_TAG_COLUMN',
                       'OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE','MV_CAPABILITIES_TABLE',
                       'OAC_OCI_FOCUS_COST_DETAIL_REFRESH_2H',
                       'OAC_OCI_FOCUS_COST_DETAIL_INITIAL_LOAD_GATE',
                       'OAC_OCI_FOCUS_COST_DETAIL_INITIAL_BUILD','OAC_OCI_FOCUS_COST_DETAIL')
 ORDER BY OBJECT_TYPE,OBJECT_NAME;
PROMPT === Selected profile and current cost detail ===
COLUMN PROFILE_NAME FORMAT A36
COLUMN MV_NAME FORMAT A50
SELECT PROFILE_NAME,PROFILE_VERSION FROM OCI_TAG_PROFILE_SELECTION
 WHERE SELECTION_ID=1;
SELECT S.TABLE_NAME MV_NAME,M.STALENESS,M.COMPILE_STATE,M.REFRESH_METHOD
  FROM USER_SYNONYMS S LEFT JOIN USER_MVIEWS M
    ON M.MVIEW_NAME=S.TABLE_NAME
 WHERE S.SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL';
PROMPT === Published tag slots and labels ===
COLUMN MV_COLUMN_NAME FORMAT A16
COLUMN DISPLAY_LABEL FORMAT A40
SELECT SLOT_NUMBER,MV_COLUMN_NAME,DISPLAY_LABEL,NAMESPACE_NAME,TAG_NAME,ASSIGNED
  FROM OAC_OCI_FOCUS_TAG_SLOT_V ORDER BY SLOT_NUMBER;
PROMPT === Latest builds and refreshes ===
COLUMN RUN_KIND FORMAT A9
COLUMN STATUS FORMAT A12
COLUMN ERROR_MESSAGE FORMAT A80
SELECT RUN_ID,RUN_KIND,STATUS,MV_NAME,PROFILE_NAME,PROFILE_VERSION,
       TAG_COLUMNS,MV_ROWS,STARTED_AT,FINISHED_AT,ERROR_CODE,ERROR_MESSAGE
  FROM OAC_OCI_FOCUS_COST_DETAIL_RUN ORDER BY RUN_ID DESC FETCH FIRST 5 ROWS ONLY;
PROMPT === Scheduler ===
COLUMN JOB_NAME FORMAT A50
SELECT JOB_NAME,ENABLED,STATE,REPEAT_INTERVAL FROM USER_SCHEDULER_JOBS
 WHERE JOB_NAME IN ('OAC_OCI_FOCUS_COST_DETAIL_INITIAL_BUILD',
                    'OAC_OCI_FOCUS_COST_DETAIL_REFRESH_2H',
                    'OAC_OCI_FOCUS_COST_DETAIL_INITIAL_LOAD_GATE')
 ORDER BY JOB_NAME;
SELECT R.JOB_NAME,R.STATUS,R.ACTUAL_START_DATE,R.RUN_DURATION,R.ERROR#
  FROM USER_SCHEDULER_JOB_RUN_DETAILS R
  JOIN USER_OBJECTS O ON O.OBJECT_NAME=R.JOB_NAME AND O.OBJECT_TYPE='JOB'
 WHERE R.JOB_NAME IN ('OAC_OCI_FOCUS_COST_DETAIL_INITIAL_BUILD',
                    'OAC_OCI_FOCUS_COST_DETAIL_REFRESH_2H',
                    'OAC_OCI_FOCUS_COST_DETAIL_INITIAL_LOAD_GATE')
   AND R.ACTUAL_START_DATE >= FROM_TZ(CAST(O.CREATED AS TIMESTAMP),TO_CHAR(SYSTIMESTAMP,'TZR'))
 ORDER BY R.LOG_DATE DESC FETCH FIRST 3 ROWS ONLY;
DECLARE
  L_TABLES NUMBER;
  L_CODE NUMBER;
  L_LOG NUMBER;
  L_JOB NUMBER;
  L_INVALID NUMBER;
  L_BUILD VARCHAR2(12);
  L_SYNONYM NUMBER;
  L_SLOT_VIEW NUMBER;
  L_SLOT_COLUMNS NUMBER;
  L_SLOT_LABELS NUMBER;
  L_PUBLISHED_BUILD NUMBER;
  L_MV_COMPILE_STATE VARCHAR2(30);
  L_ACTIVE_PROFILE VARCHAR2(128);
  L_ACTIVE_VERSION NUMBER;
  L_ACTIVE_BUILD_MV VARCHAR2(128);
  L_ACTIVE_SYNONYM NUMBER;
  L_GATE_TABLE NUMBER;
  L_MONITOR_JOB NUMBER;
  L_GATE_STATUS VARCHAR2(14);
  L_REFRESH_ENABLED VARCHAR2(5);
BEGIN
  SELECT COUNT(*) INTO L_TABLES FROM USER_TABLES
   WHERE TABLE_NAME IN ('MV_CAPABILITIES_TABLE','OAC_OCI_FOCUS_COST_DETAIL_RUN',
                        'OAC_OCI_FOCUS_COST_DETAIL_TAG_COLUMN');
  SELECT COUNT(*) INTO L_GATE_TABLE FROM USER_TABLES
   WHERE TABLE_NAME='OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE';
  SELECT COUNT(*) INTO L_CODE FROM USER_OBJECTS
   WHERE OBJECT_NAME='OAC_OCI_FOCUS_COST_DETAIL_API' AND STATUS='VALID'
     AND OBJECT_TYPE IN ('PACKAGE','PACKAGE BODY');
  SELECT COUNT(*) INTO L_LOG FROM USER_MVIEW_LOGS
   WHERE MASTER='OCI_FOCUS_REPORTS';
  SELECT COUNT(*) INTO L_JOB FROM USER_SCHEDULER_JOBS
   WHERE JOB_NAME='OAC_OCI_FOCUS_COST_DETAIL_REFRESH_2H'
     AND REPEAT_INTERVAL='FREQ=HOURLY;INTERVAL=2;BYMINUTE=30;BYSECOND=00';
  SELECT COUNT(*) INTO L_MONITOR_JOB FROM USER_SCHEDULER_JOBS
   WHERE JOB_NAME='OAC_OCI_FOCUS_COST_DETAIL_INITIAL_LOAD_GATE'
     AND REPEAT_INTERVAL='FREQ=MINUTELY;INTERVAL=5';
  SELECT STATUS INTO L_GATE_STATUS FROM OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE
   WHERE GATE_ID=1;
  SELECT ENABLED INTO L_REFRESH_ENABLED FROM USER_SCHEDULER_JOBS
   WHERE JOB_NAME='OAC_OCI_FOCUS_COST_DETAIL_REFRESH_2H';
  SELECT COUNT(*) INTO L_INVALID FROM USER_OBJECTS
   WHERE OBJECT_NAME LIKE 'OAC_OCI_FOCUS_COST_DETAIL_%'
     AND OBJECT_NAME NOT LIKE 'OAC_OCI_FOCUS_COST_DETAIL_MV_V%'
     AND STATUS<>'VALID';
  SELECT COUNT(*) INTO L_SYNONYM FROM USER_SYNONYMS S JOIN USER_MVIEWS M
    ON M.MVIEW_NAME=S.TABLE_NAME
   WHERE S.SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL'
     AND S.TABLE_OWNER=SYS_CONTEXT('USERENV','CURRENT_USER')
     AND S.DB_LINK IS NULL;
  SELECT COUNT(*) INTO L_SLOT_VIEW FROM USER_OBJECTS
   WHERE OBJECT_NAME='OAC_OCI_FOCUS_TAG_SLOT_V'
     AND OBJECT_TYPE='VIEW' AND STATUS='VALID';
  IF L_TABLES<>3 OR L_GATE_TABLE<>1 OR L_CODE<>2 OR L_LOG<>1 OR
     L_JOB<>1 OR L_MONITOR_JOB<>1 OR
     L_INVALID<>0 OR L_SYNONYM<>1 OR L_SLOT_VIEW<>1 THEN
    RAISE_APPLICATION_ERROR(-20608,'OAC cost detail structure verification failed');
  END IF;
  IF (L_GATE_STATUS='COMPLETE' AND L_REFRESH_ENABLED<>'TRUE') OR
     (L_GATE_STATUS IN ('NOT_STARTED','WAITING') AND L_REFRESH_ENABLED<>'FALSE') THEN
    RAISE_APPLICATION_ERROR(-20628,
      'Two-hour refresh enabled state does not match initial-load gate status');
  END IF;
  SELECT COUNT(*) INTO L_SLOT_COLUMNS
    FROM USER_SYNONYMS S JOIN USER_TAB_COLUMNS C
      ON C.TABLE_NAME=S.TABLE_NAME
   WHERE S.SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL'
     AND REGEXP_LIKE(C.COLUMN_NAME,'^TAG_[0-9]+$','c');
  SELECT COUNT(*) INTO L_SLOT_LABELS FROM OAC_OCI_FOCUS_TAG_SLOT_V;
  SELECT COUNT(*) INTO L_PUBLISHED_BUILD
    FROM USER_SYNONYMS S JOIN OAC_OCI_FOCUS_COST_DETAIL_RUN R
      ON R.MV_NAME=S.TABLE_NAME
   WHERE S.SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL'
     AND R.RUN_KIND='BUILD' AND R.STATUS IN ('READY','COMPLETE');
  IF L_PUBLISHED_BUILD>0 AND L_SLOT_LABELS<>L_SLOT_COLUMNS THEN
    RAISE_APPLICATION_ERROR(-20627,
      'Published TAG_n columns and label rows differ');
  END IF;
  DBMS_OUTPUT.PUT_LINE('OAC COST DETAIL STRUCTURE PASS');
  DBMS_OUTPUT.PUT_LINE('published_tag_slots='||L_SLOT_COLUMNS||
    ' published_label_rows='||L_SLOT_LABELS);
  DBMS_OUTPUT.PUT_LINE('initial_load_gate='||L_GATE_STATUS||
    ' two_hour_refresh_enabled='||L_REFRESH_ENABLED);
  SELECT PROFILE_NAME,PROFILE_VERSION INTO L_ACTIVE_PROFILE,L_ACTIVE_VERSION
    FROM OCI_TAG_PROFILE_SELECTION WHERE SELECTION_ID=1;
  SELECT MAX(STATUS) KEEP (DENSE_RANK LAST ORDER BY RUN_ID),
         MAX(MV_NAME) KEEP (DENSE_RANK LAST ORDER BY RUN_ID)
    INTO L_BUILD,L_ACTIVE_BUILD_MV
    FROM OAC_OCI_FOCUS_COST_DETAIL_RUN
   WHERE RUN_KIND='BUILD' AND PROFILE_NAME=L_ACTIVE_PROFILE
     AND PROFILE_VERSION=L_ACTIVE_VERSION;
  IF L_BUILD='COMPLETE' AND L_ACTIVE_BUILD_MV IS NOT NULL THEN
    SELECT COUNT(*) INTO L_ACTIVE_SYNONYM FROM USER_SYNONYMS
     WHERE SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL'
       AND TABLE_NAME=L_ACTIVE_BUILD_MV;
    IF L_ACTIVE_SYNONYM=1 THEN
      SELECT COMPILE_STATE INTO L_MV_COMPILE_STATE
        FROM USER_MVIEWS WHERE MVIEW_NAME=L_ACTIVE_BUILD_MV;
      IF L_MV_COMPILE_STATE='VALID' THEN
        DBMS_OUTPUT.PUT_LINE('OAC COST DETAIL BUILD PASS; active profile is published');
      ELSE
        DBMS_OUTPUT.PUT_LINE('OAC COST DETAIL PUBLISHED; current MV compile state='||
          L_MV_COMPILE_STATE||'; inspect refresh history');
      END IF;
    ELSE
      DBMS_OUTPUT.PUT_LINE('OAC COST DETAIL CANDIDATE COMPLETE; synonym still points to '||
        'the previously published profile; publish explicitly after review');
    END IF;
  ELSIF L_BUILD='READY' THEN
    DBMS_OUTPUT.PUT_LINE('OAC COST DETAIL CANDIDATE READY; stable synonym unchanged; '||
      'publish explicitly after review');
  ELSIF L_BUILD='RUNNING' THEN
    DBMS_OUTPUT.PUT_LINE('OAC COST DETAIL CANDIDATE BUILD RUNNING; stable synonym unchanged');
  ELSIF L_BUILD='ERROR' THEN
    DBMS_OUTPUT.PUT_LINE('OAC COST DETAIL BUILD NEEDS ATTENTION; inspect OAC_OCI_FOCUS_COST_DETAIL_RUN');
  ELSIF L_BUILD='PREPARED' AND L_SYNONYM=1 THEN
    DBMS_OUTPUT.PUT_LINE('OAC COST DETAIL SYNONYM READY; INITIAL POPULATION PENDING');
  ELSE
    DBMS_OUTPUT.PUT_LINE('OAC COST DETAIL BUILD PENDING FOR ACTIVE PROFILE; current synonym remains unchanged');
  END IF;
END;
