-- Start OCI FOCUS year pipelines only after an empty, fully populated OAC MV.
-- Run once as FOCUSPLATFORM from deployment/sql/install after the OAC installer.
SET DEFINE OFF VERIFY OFF SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
PROMPT Start OCI FOCUS pipelines after validating the empty OAC MV

DECLARE
  L_PIPELINES NUMBER;
  L_STOPPED NUMBER;
  L_ROWS NUMBER;
  L_BUILD NUMBER;
  L_MV VARCHAR2(128);
  L_COMPILE_STATE VARCHAR2(30);
  L_STATUS VARCHAR2(30);
  L_PROVIDER NUMBER;
  L_GATE VARCHAR2(14);
  L_RUNNING NUMBER;
  L_BUILD_STATUS VARCHAR2(12);
  L_ATTEMPTS PLS_INTEGER := 0;
  L_ERROR_MESSAGE VARCHAR2(4000);
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER') <> 'FOCUSPLATFORM' OR
     SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> 'FOCUSPLATFORM' THEN
    RAISE_APPLICATION_ERROR(-20920,'Connect as FOCUSPLATFORM');
  END IF;
  SELECT COUNT(*),COUNT(CASE WHEN STATUS='STOPPED' THEN 1 END)
    INTO L_PIPELINES,L_STOPPED
    FROM USER_CLOUD_PIPELINES
   WHERE REGEXP_LIKE(PIPELINE_NAME,'^OCI_FOCUS_REPORTS_LOAD_[0-9]{4}$');
  IF L_PIPELINES=0 OR L_PIPELINES<>L_STOPPED THEN
    RAISE_APPLICATION_ERROR(-20921,'All OCI FOCUS year pipelines must exist and be STOPPED');
  END IF;
  SELECT COUNT(*) INTO L_PROVIDER FROM FINOPS_CORE_PROVIDER
   WHERE PROVIDER_CODE='OCI' AND ENABLED='N';
  IF L_PROVIDER<>1 THEN
    RAISE_APPLICATION_ERROR(-20922,'OCI provider must be registered and disabled');
  END IF;
  SELECT COUNT(*) INTO L_ROWS FROM OCI_FOCUS_REPORTS;
  IF L_ROWS<>0 THEN
    RAISE_APPLICATION_ERROR(-20923,'Landing table is not empty; do not start the master first-load sequence');
  END IF;
  SELECT TABLE_NAME INTO L_MV FROM USER_SYNONYMS
   WHERE SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL'
     AND TABLE_OWNER=SYS_CONTEXT('USERENV','CURRENT_USER') AND DB_LINK IS NULL;
  SELECT COMPILE_STATE INTO L_COMPILE_STATE FROM USER_MVIEWS WHERE MVIEW_NAME=L_MV;
  LOOP
    SELECT MAX(STATUS) KEEP (DENSE_RANK LAST ORDER BY RUN_ID), COUNT(*)
      INTO L_BUILD_STATUS,L_BUILD FROM OAC_OCI_FOCUS_COST_DETAIL_RUN
     WHERE RUN_KIND='BUILD' AND MV_NAME=L_MV;
    EXIT WHEN L_BUILD_STATUS='COMPLETE';
    IF L_BUILD_STATUS='ERROR' THEN
      RAISE_APPLICATION_ERROR(-20924,'Initial MV COMPLETE build failed; inspect OAC_OCI_FOCUS_COST_DETAIL_RUN');
    END IF;
    L_ATTEMPTS:=L_ATTEMPTS+1;
    IF L_ATTEMPTS>180 THEN
      RAISE_APPLICATION_ERROR(-20928,'Timed out waiting 30 minutes for the empty MV initial COMPLETE build');
    END IF;
    DBMS_LOCK.SLEEP(10);
  END LOOP;
  IF L_BUILD=0 THEN
    RAISE_APPLICATION_ERROR(-20924,'Published MV must have a successful COMPLETE build');
  END IF;
  SELECT COMPILE_STATE INTO L_COMPILE_STATE FROM USER_MVIEWS WHERE MVIEW_NAME=L_MV;
  SELECT COUNT(*) INTO L_RUNNING FROM USER_OBJECTS
   WHERE OBJECT_NAME=L_MV AND OBJECT_TYPE='MATERIALIZED VIEW' AND STATUS='VALID';
  IF L_COMPILE_STATE<>'VALID' OR L_RUNNING<>1 THEN
    RAISE_APPLICATION_ERROR(-20924,'Published MV must be VALID after its COMPLETE build');
  END IF;
  EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM '||DBMS_ASSERT.ENQUOTE_NAME(L_MV,FALSE) INTO L_ROWS;
  IF L_ROWS<>0 THEN
    RAISE_APPLICATION_ERROR(-20925,'The initial MV must be empty before starting pipelines');
  END IF;
  SELECT STATUS INTO L_GATE FROM OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE WHERE GATE_ID=1;
  IF L_GATE NOT IN ('NOT_STARTED','WAITING') THEN
    RAISE_APPLICATION_ERROR(-20926,'Initial-load gate is not in a startable state: '||L_GATE);
  END IF;
  SELECT COUNT(*) INTO L_RUNNING FROM USER_SCHEDULER_RUNNING_JOBS
   WHERE JOB_NAME IN ('OAC_OCI_FOCUS_COST_DETAIL_INITIAL_BUILD',
                      'OAC_OCI_FOCUS_COST_DETAIL_REFRESH_2H');
  IF L_RUNNING<>0 THEN
    RAISE_APPLICATION_ERROR(-20927,'An OAC build or refresh is still running');
  END IF;

  UPDATE OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE
     SET STATUS='WAITING',PIPELINES_STARTED_AT=SYSTIMESTAMP,
         LAST_CHECK_AT=NULL,FAILED_PIPELINES=0,ERROR_MESSAGE=NULL,
         UPDATED_AT=SYSTIMESTAMP
   WHERE GATE_ID=1;
  COMMIT;
  FOR P IN (SELECT PIPELINE_NAME FROM USER_CLOUD_PIPELINES
             WHERE REGEXP_LIKE(PIPELINE_NAME,'^OCI_FOCUS_REPORTS_LOAD_[0-9]{4}$')
             ORDER BY PIPELINE_NAME) LOOP
    DBMS_CLOUD_PIPELINE.START_PIPELINE(PIPELINE_NAME=>P.PIPELINE_NAME);
    DBMS_OUTPUT.PUT_LINE('started='||P.PIPELINE_NAME);
  END LOOP;
  UPDATE FINOPS_CORE_PROVIDER SET ENABLED='Y',UPDATED_AT=SYSTIMESTAMP
   WHERE PROVIDER_CODE='OCI';
  COMMIT;
  DBMS_SCHEDULER.ENABLE('OAC_OCI_FOCUS_COST_DETAIL_INITIAL_LOAD_GATE');
  SELECT COUNT(*) INTO L_RUNNING FROM USER_SCHEDULER_RUNNING_JOBS
   WHERE JOB_NAME='FINOPS_CORE_DAILY';
  IF L_RUNNING=0 THEN
    DBMS_SCHEDULER.RUN_JOB(
      JOB_NAME=>'FINOPS_CORE_DAILY',USE_CURRENT_SESSION=>FALSE);
    DBMS_OUTPUT.PUT_LINE('Initial coordinator run requested in background');
  ELSE
    DBMS_OUTPUT.PUT_LINE('Initial coordinator run already active; no duplicate requested');
  END IF;
  DBMS_OUTPUT.PUT_LINE('Pipelines started. The gate will wait for each pipeline to complete an initial run with no pending or running files.');
EXCEPTION WHEN OTHERS THEN
  L_ERROR_MESSAGE := SUBSTR(SQLERRM,1,4000);
  -- Roll back the start sequence if a pipeline fails; OAC refresh remains disabled.
  FOR P IN (SELECT PIPELINE_NAME FROM USER_CLOUD_PIPELINES
             WHERE REGEXP_LIKE(PIPELINE_NAME,'^OCI_FOCUS_REPORTS_LOAD_[0-9]{4}$')
               AND STATUS='STARTED') LOOP
    BEGIN
      DBMS_CLOUD_PIPELINE.STOP_PIPELINE(PIPELINE_NAME=>P.PIPELINE_NAME);
    EXCEPTION WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('Could not stop partially started pipeline='||P.PIPELINE_NAME||' error='||SQLERRM);
    END;
  END LOOP;
  UPDATE FINOPS_CORE_PROVIDER SET ENABLED='N',UPDATED_AT=SYSTIMESTAMP
   WHERE PROVIDER_CODE='OCI';
  UPDATE OAC_OCI_FOCUS_COST_DETAIL_LOAD_GATE
     SET STATUS='NOT_STARTED',PIPELINES_STARTED_AT=NULL,
         ERROR_MESSAGE=L_ERROR_MESSAGE,UPDATED_AT=SYSTIMESTAMP
   WHERE GATE_ID=1;
  COMMIT;
  RAISE;
END;
