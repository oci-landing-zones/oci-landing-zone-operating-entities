-- Read-only post-install check. Run as FOCUSPLATFORM from deployment/sql/install.
SET VERIFY OFF DEFINE OFF SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 190 PAGESIZE 100
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

PROMPT === Latest OCI account-context attempt ===
COLUMN STATUS FORMAT A12
COLUMN ERROR_MESSAGE FORMAT A85
SELECT RUN_ID,STATUS,STARTED_AT,FINISHED_AT,TENANCY_READ,
       COMPARTMENTS_READ,REGIONS_READ,CHANGES_RECORDED,
       UNRESOLVED_COMPARTMENTS,ERROR_MESSAGE
  FROM OCI_ACCOUNT_CONTEXT_RUN
 ORDER BY RUN_ID DESC FETCH FIRST 1 ROW ONLY;

PROMPT === Discovered commercial subscriptions and latest attempts ===
COLUMN SUBSCRIPTION_ID FORMAT A25
SELECT C.SUBSCRIPTION_ID,C.IS_DISCOVERED,R.SYNC_RUN_ID,R.STATUS,
       R.SERVICES_READ,R.COMMITMENTS_READ,R.ERROR_CODE,R.ERROR_MESSAGE
  FROM OCI_ACCOUNT_CONTRACT_CONFIG C LEFT JOIN
       (SELECT X.*,ROW_NUMBER() OVER
          (PARTITION BY SUBSCRIPTION_ID ORDER BY SYNC_RUN_ID DESC) RN
          FROM OCI_ACCOUNT_CONTRACT_RUN X) R
    ON R.SUBSCRIPTION_ID=C.SUBSCRIPTION_ID AND R.RN=1
 ORDER BY C.SUBSCRIPTION_ID;

PROMPT === Published current entity counts ===
SELECT (SELECT COUNT(*) FROM OCI_ACCOUNT_COMPARTMENT_V) CURRENT_COMPARTMENTS,
       (SELECT COUNT(*) FROM OCI_ACCOUNT_REGION_V) CURRENT_REGIONS,
       (SELECT COUNT(*) FROM OCI_ACCOUNT_CONTRACT_SUBSCRIPTION_V) CURRENT_SUBSCRIPTIONS,
       (SELECT COUNT(*) FROM OCI_ACCOUNT_CONTRACT_SERVICE_V) CURRENT_SERVICES,
       (SELECT COUNT(*) FROM OCI_ACCOUNT_CONTRACT_COMMITMENT_V) CURRENT_COMMITMENTS
  FROM DUAL;

PROMPT === Recent Scheduler attempts ===
COLUMN JOB_NAME FORMAT A31
SELECT JOB_NAME,STATUS,ACTUAL_START_DATE,RUN_DURATION,ERROR#
  FROM USER_SCHEDULER_JOB_RUN_DETAILS
 WHERE JOB_NAME IN ('OCI_ACCOUNT_CONTEXT_DAILY',
                    'OCI_ACCOUNT_CONTRACT_MONTHLY')
 ORDER BY LOG_DATE DESC FETCH FIRST 6 ROWS ONLY;

DECLARE
  L_CONTEXT VARCHAR2(12);
  L_DISCOVERED NUMBER;
  L_COMPLETED NUMBER;
  L_FAILED NUMBER;
  L_JOB_FAILED NUMBER;
BEGIN
  SELECT MAX(STATUS) KEEP (DENSE_RANK LAST ORDER BY RUN_ID)
    INTO L_CONTEXT FROM OCI_ACCOUNT_CONTEXT_RUN;
  SELECT COUNT(*) INTO L_DISCOVERED FROM OCI_ACCOUNT_CONTRACT_CONFIG
   WHERE IS_DISCOVERED='Y';
  SELECT COUNT(*) INTO L_COMPLETED
    FROM OCI_ACCOUNT_CONTRACT_CONFIG C
    JOIN (SELECT X.*,ROW_NUMBER() OVER
            (PARTITION BY SUBSCRIPTION_ID ORDER BY SYNC_RUN_ID DESC) RN
            FROM OCI_ACCOUNT_CONTRACT_RUN X) R
      ON R.SUBSCRIPTION_ID=C.SUBSCRIPTION_ID AND R.RN=1
   WHERE C.IS_DISCOVERED='Y' AND R.STATUS='COMPLETED';
  -- A failed latest attempt must not look pending.
  SELECT COUNT(*) INTO L_FAILED
    FROM OCI_ACCOUNT_CONTRACT_CONFIG C
    JOIN (SELECT X.*,ROW_NUMBER() OVER
            (PARTITION BY SUBSCRIPTION_ID ORDER BY SYNC_RUN_ID DESC) RN
            FROM OCI_ACCOUNT_CONTRACT_RUN X) R
      ON R.SUBSCRIPTION_ID=C.SUBSCRIPTION_ID AND R.RN=1
   WHERE C.IS_DISCOVERED='Y' AND R.STATUS='FAILED';
  SELECT COUNT(*) INTO L_JOB_FAILED FROM
    (SELECT JOB_NAME,STATUS,ROW_NUMBER() OVER
       (PARTITION BY JOB_NAME ORDER BY LOG_DATE DESC) RN
       FROM USER_SCHEDULER_JOB_RUN_DETAILS
      WHERE JOB_NAME IN ('OCI_ACCOUNT_CONTEXT_DAILY',
                         'OCI_ACCOUNT_CONTRACT_MONTHLY'))
   WHERE RN=1 AND STATUS IN ('FAILED','STOPPED','BROKEN');
  DBMS_OUTPUT.PUT_LINE('context='||NVL(L_CONTEXT,'NOT_STARTED')||
    ' discovered_subscriptions='||L_DISCOVERED||
    ' completed_contracts='||L_COMPLETED||' failed_contracts='||L_FAILED||
    ' failed_jobs='||L_JOB_FAILED);
  IF L_CONTEXT='COMPLETE' AND L_DISCOVERED>0 AND
     L_COMPLETED=L_DISCOVERED THEN
    DBMS_OUTPUT.PUT_LINE('OCI ACCOUNT AND CONTRACT INITIAL SYNC PASS');
  ELSIF L_CONTEXT='ERROR' OR L_FAILED>0 OR L_JOB_FAILED>0 THEN
    DBMS_OUTPUT.PUT_LINE('OCI ACCOUNT AND CONTRACT INITIAL SYNC NEEDS ATTENTION');
  ELSE
    DBMS_OUTPUT.PUT_LINE('OCI ACCOUNT AND CONTRACT INITIAL SYNC PENDING');
  END IF;
END;
