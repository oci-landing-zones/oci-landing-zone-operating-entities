-- Read-only metadata and startup gate for the complete OCI ingestion module.
SET DEFINE OFF SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 190 PAGESIZE 100
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

COLUMN PIPELINE_NAME FORMAT A38
COLUMN PIPELINE_TYPE FORMAT A13
COLUMN STATUS FORMAT A12
COLUMN STATUS_TABLE FORMAT A35
COLUMN INTERVAL_MINUTES FORMAT A16
COLUMN LATEST_RUN_STATUS FORMAT A18
COLUMN LATEST_ERROR FORMAT A80

PROMPT === OCI pipeline startup ===
SELECT P.PIPELINE_NAME, P.PIPELINE_TYPE, P.STATUS, P.STATUS_TABLE,
       DBMS_LOB.SUBSTR(A.ATTRIBUTE_VALUE, 16, 1) INTERVAL_MINUTES
  FROM USER_CLOUD_PIPELINES P
  LEFT JOIN USER_CLOUD_PIPELINE_ATTRIBUTES A
    ON A.PIPELINE_NAME = P.PIPELINE_NAME
   AND A.ATTRIBUTE_NAME = 'interval'
 WHERE REGEXP_LIKE(P.PIPELINE_NAME,
                   '^OCI_FOCUS_REPORTS_LOAD_[0-9]{4}$')
 ORDER BY P.PIPELINE_NAME;

PROMPT === Latest OCI pipeline execution, if available ===
SELECT PIPELINE_NAME, STATUS LATEST_RUN_STATUS, START_DATE, END_DATE,
       SUBSTR(ERROR_MESSAGE, 1, 80) LATEST_ERROR
  FROM (
    SELECT H.PIPELINE_NAME, H.STATUS, H.START_DATE, H.END_DATE,
           H.ERROR_MESSAGE,
           ROW_NUMBER() OVER (PARTITION BY H.PIPELINE_NAME
                              ORDER BY H.START_DATE DESC) RN
      FROM USER_CLOUD_PIPELINE_HISTORY H
     WHERE REGEXP_LIKE(H.PIPELINE_NAME,
                       '^OCI_FOCUS_REPORTS_LOAD_[0-9]{4}$')
  )
 WHERE RN = 1
 ORDER BY PIPELINE_NAME;

DECLARE
  L_TABLES NUMBER;
  L_LANDING_COLUMNS NUMBER;
  L_STAGE_COLUMNS NUMBER;
  L_STAGE_COMPRESSION VARCHAR2(20);
  L_NAMED_INDEXES NUMBER;
  L_CODE NUMBER;
  L_INVALID NUMBER;
  L_PIPELINES NUMBER;
  L_FIRST_YEAR NUMBER;
  L_LAST_YEAR NUMBER;
  L_CURRENT_YEAR NUMBER;
  L_WRONG_TYPES NUMBER;
  L_NOT_STARTED NUMBER;
  L_WRONG_TARGETS NUMBER;
  L_WRONG_SOURCES NUMBER;
  L_WRONG_INTERVALS NUMBER;
  L_PROVIDER NUMBER;
  L_CONFIG NUMBER;
  L_CORE_LOCK_POLICY NUMBER;
  L_JOB VARCHAR2(5);
  L_NOTIFY CHAR(1);
  L_STAGE_ROWS NUMBER;
  L_QUEUE_ROWS NUMBER;
  L_MANUAL_ROWS NUMBER;
  L_COMPLETED NUMBER;
  L_FAILED NUMBER;
  L_PENDING NUMBER;
  L_RUNNING NUMBER;
  L_STATUS_TABLE VARCHAR2(128);
  L_RETENTION_JOB NUMBER;
  L_RETENTION_CONFIG NUMBER;
  L_EXPECTED_STATE VARCHAR2(10) := NVL(JSON_VALUE(:fp_install_config, '$.ingestion_expected_state'), 'STOPPED');
BEGIN
  IF L_EXPECTED_STATE NOT IN ('STOPPED','STARTED') THEN
    RAISE_APPLICATION_ERROR(-20965, 'Ingestion verification state must be STOPPED or STARTED');
  END IF;
  IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'FOCUSPLATFORM' THEN
    RAISE_APPLICATION_ERROR(-20963,
      'Connect as FOCUSPLATFORM to verify OCI ingestion');
  END IF;
  SELECT COUNT(*) INTO L_TABLES FROM USER_OBJECTS
   WHERE OBJECT_NAME LIKE 'OCI_FOCUS_%' AND OBJECT_TYPE = 'TABLE'
     AND STATUS = 'VALID';
  SELECT COUNT(*) INTO L_LANDING_COLUMNS FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'OCI_FOCUS_REPORTS';
  SELECT COUNT(*) INTO L_STAGE_COLUMNS FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'OCI_FOCUS_REMED_STAGE';
  SELECT COMPRESSION INTO L_STAGE_COMPRESSION FROM USER_TABLES
   WHERE TABLE_NAME = 'OCI_FOCUS_REMED_STAGE';
  SELECT COUNT(*) INTO L_NAMED_INDEXES FROM USER_OBJECTS
   WHERE OBJECT_TYPE = 'INDEX' AND STATUS = 'VALID'
     AND OBJECT_NAME IN ('OCI_FOCUS_REPORTS_PK',
       'OCI_FOCUS_FAIL_FILE_STATE_I', 'OCI_FOCUS_REMED_ONE_ACTIVE',
       'OCI_FOCUS_REMED_MANUAL_PENDING_I',
       'OCI_FOCUS_COPY_RECOVERY_FILE_I');
  SELECT COUNT(*) INTO L_CODE FROM USER_OBJECTS
   WHERE OBJECT_NAME IN ('OCI_FOCUS_SOURCE_PREFIX',
       'OCI_FOCUS_FILL_SOURCE_URIS', 'OCI_FOCUS_DISCOVER_FAILURES',
       'OCI_FOCUS_REMED_MUTEX', 'OCI_FOCUS_REMED_NUMBER',
       'OCI_FOCUS_REMED_TIMESTAMP', 'OCI_FOCUS_REMEDIATE_FILES',
       'OCI_FOCUS_RESOLVE_MANUAL_ROW',
       'OCI_FOCUS_COPY_RECOVERY_DECIDE', 'OCI_FOCUS_RECOVER_COPYING',
       'OCI_FOCUS_RECOVER_ACTIVE_FILE',
       'OCI_FOCUS_GET_INGESTION_REPORT', 'OCI_FOCUS_CORE_API', 'OCI_FOCUS_RETENTION_API')
     AND OBJECT_TYPE IN ('FUNCTION','PROCEDURE','PACKAGE','PACKAGE BODY')
     AND STATUS = 'VALID';
  SELECT COUNT(*) INTO L_INVALID FROM USER_OBJECTS
   WHERE OBJECT_NAME LIKE 'OCI_FOCUS_%' AND STATUS <> 'VALID';
  SELECT COUNT(*), MIN(TO_NUMBER(SUBSTR(PIPELINE_NAME, -4))),
         MAX(TO_NUMBER(SUBSTR(PIPELINE_NAME, -4))),
         COUNT(CASE WHEN PIPELINE_TYPE <> 'LOAD' THEN 1 END),
         COUNT(CASE WHEN NVL(STATUS,'UNKNOWN') <> L_EXPECTED_STATE THEN 1 END)
    INTO L_PIPELINES, L_FIRST_YEAR, L_LAST_YEAR,
         L_WRONG_TYPES, L_NOT_STARTED
    FROM USER_CLOUD_PIPELINES
   WHERE REGEXP_LIKE(PIPELINE_NAME, '^OCI_FOCUS_REPORTS_LOAD_[0-9]{4}$');
  SELECT EXTRACT(YEAR FROM SYSTIMESTAMP AT TIME ZONE 'UTC')
    INTO L_CURRENT_YEAR FROM DUAL;
  SELECT COUNT(*) INTO L_WRONG_TARGETS
    FROM USER_CLOUD_PIPELINES P
    LEFT JOIN USER_CLOUD_PIPELINE_ATTRIBUTES A
      ON A.PIPELINE_NAME = P.PIPELINE_NAME
     AND A.ATTRIBUTE_NAME = 'table_name'
   WHERE REGEXP_LIKE(P.PIPELINE_NAME,
                     '^OCI_FOCUS_REPORTS_LOAD_[0-9]{4}$')
     AND (A.PIPELINE_NAME IS NULL OR
          NVL(UPPER(TRIM(DBMS_LOB.SUBSTR(A.ATTRIBUTE_VALUE,128,1))), '?') <>
          'OCI_FOCUS_REPORTS');
  SELECT COUNT(*) INTO L_WRONG_SOURCES
    FROM USER_CLOUD_PIPELINES P
    LEFT JOIN USER_CLOUD_PIPELINE_ATTRIBUTES A
      ON A.PIPELINE_NAME = P.PIPELINE_NAME
     AND A.ATTRIBUTE_NAME = 'location'
    LEFT JOIN USER_CLOUD_PIPELINE_ATTRIBUTES F
      ON F.PIPELINE_NAME = P.PIPELINE_NAME
     AND F.ATTRIBUTE_NAME = 'format'
   WHERE REGEXP_LIKE(P.PIPELINE_NAME,
                     '^OCI_FOCUS_REPORTS_LOAD_[0-9]{4}$')
     AND (A.PIPELINE_NAME IS NULL OR F.PIPELINE_NAME IS NULL OR
          INSTR(DBMS_LOB.SUBSTR(A.ATTRIBUTE_VALUE,4000,1), '/b/') = 0 OR
          CASE
            WHEN REGEXP_LIKE(DBMS_LOB.SUBSTR(F.ATTRIBUTE_VALUE,4000,1),
                             '"regexuri"\s*:\s*true', 'i') THEN
              CASE WHEN SUBSTR(DBMS_LOB.SUBSTR(A.ATTRIBUTE_VALUE,4000,1),
                               -LENGTH(SUBSTR(P.PIPELINE_NAME,-4) ||
                                 '/.*[.]csv[.]gz')) <>
                             SUBSTR(P.PIPELINE_NAME,-4) || '/.*[.]csv[.]gz'
                     THEN 1 ELSE 0 END
            ELSE
              CASE WHEN SUBSTR(DBMS_LOB.SUBSTR(A.ATTRIBUTE_VALUE,4000,1),
                               -LENGTH('/0000/*/*/*.csv.gz')) <>
                             '/' || SUBSTR(P.PIPELINE_NAME,-4) || '/*/*/*.csv.gz'
                     THEN 1 ELSE 0 END
          END = 1);
  SELECT COUNT(*) INTO L_WRONG_INTERVALS
    FROM USER_CLOUD_PIPELINES P
    LEFT JOIN USER_CLOUD_PIPELINE_ATTRIBUTES A
      ON A.PIPELINE_NAME = P.PIPELINE_NAME
     AND A.ATTRIBUTE_NAME = 'interval'
   WHERE REGEXP_LIKE(P.PIPELINE_NAME,
                     '^OCI_FOCUS_REPORTS_LOAD_[0-9]{4}$')
     AND (A.PIPELINE_NAME IS NULL OR
          NVL(TRIM(DBMS_LOB.SUBSTR(A.ATTRIBUTE_VALUE,128,1)), '?') <> '60');
  SELECT COUNT(*) INTO L_PROVIDER FROM FINOPS_CORE_PROVIDER
   WHERE PROVIDER_CODE = 'OCI' AND LANDING_TABLE = 'OCI_FOCUS_REPORTS'
     AND API_PACKAGE = 'OCI_FOCUS_CORE_API' AND ENABLED = CASE WHEN L_EXPECTED_STATE='STARTED' THEN 'Y' ELSE 'N' END
     AND MAX_FILES_PER_PIPELINE = 2000;
  SELECT COUNT(*) INTO L_CONFIG FROM OCI_FOCUS_REMED_TARGET_CONFIG
   WHERE TARGET_TABLE = 'OCI_FOCUS_REPORTS' AND ENABLED = 'Y';
  SELECT COUNT(*) INTO L_CORE_LOCK_POLICY FROM USER_SOURCE
   WHERE NAME = 'FINOPS_CORE_RUN_DAILY' AND TYPE = 'PROCEDURE'
     AND UPPER(TEXT) LIKE '%TIMEOUT => 0%';
  SELECT ENABLED INTO L_JOB FROM USER_SCHEDULER_JOBS
   WHERE JOB_NAME = 'FINOPS_CORE_DAILY';
  SELECT ENABLED INTO L_NOTIFY FROM FINOPS_CORE_NOTIFY_CONFIG
   WHERE CONFIG_ID = 1;
  SELECT COUNT(ROWID) INTO L_STAGE_ROWS FROM OCI_FOCUS_REMED_STAGE;
  SELECT COUNT(*) INTO L_QUEUE_ROWS FROM OCI_FOCUS_FAIL_FILE;
  SELECT COUNT(*) INTO L_MANUAL_ROWS FROM OCI_FOCUS_REMED_MANUAL;

  DBMS_OUTPUT.PUT_LINE('tables=' || L_TABLES ||
    ' named_indexes=' || L_NAMED_INDEXES || ' valid_code=' || L_CODE ||
    ' invalid_objects=' || L_INVALID);
  DBMS_OUTPUT.PUT_LINE('landing_columns=' || L_LANDING_COLUMNS ||
    ' stage_columns=' || L_STAGE_COLUMNS ||
    ' stage_compression=' || L_STAGE_COMPRESSION);
  DBMS_OUTPUT.PUT_LINE('pipelines=' || L_PIPELINES ||
    ' years=' || L_FIRST_YEAR || '-' || L_LAST_YEAR ||
    ' current_utc_year=' || L_CURRENT_YEAR ||
    ' unexpected_pipeline_state=' || L_NOT_STARTED || ' expected_state=' || L_EXPECTED_STATE);
  DBMS_OUTPUT.PUT_LINE('wrong_types=' || L_WRONG_TYPES ||
    ' wrong_targets=' || L_WRONG_TARGETS ||
    ' wrong_sources=' || L_WRONG_SOURCES ||
    ' wrong_intervals=' || L_WRONG_INTERVALS);
  DBMS_OUTPUT.PUT_LINE('registered_oci=' || L_PROVIDER ||
    ' approved_target=' || L_CONFIG ||
    ' core_nonwaiting_lock=' || L_CORE_LOCK_POLICY ||
    ' common_job_enabled=' || L_JOB ||
    ' notification_enabled=' || L_NOTIFY);
  DBMS_OUTPUT.PUT_LINE('stage_rows=' || L_STAGE_ROWS ||
    ' queued_files=' || L_QUEUE_ROWS || ' manual_rows=' || L_MANUAL_ROWS);
  SELECT COUNT(*) INTO L_RETENTION_JOB FROM USER_SCHEDULER_JOBS
   WHERE JOB_NAME='OCI_FOCUS_RETENTION_MONTHLY' AND ENABLED='FALSE'
     AND REPEAT_INTERVAL='FREQ=MONTHLY;BYMONTHDAY=1;BYHOUR=03;BYMINUTE=30;BYSECOND=00';
  SELECT COUNT(*) INTO L_RETENTION_CONFIG FROM OCI_FOCUS_RETENTION_CONFIG
   WHERE CONFIG_ID=1 AND KEEP_MONTHS>=12 AND KEEP_MONTHS=TRUNC(KEEP_MONTHS);
  DBMS_OUTPUT.PUT_LINE('retention_job_disabled='||L_RETENTION_JOB||' valid_retention_config='||L_RETENTION_CONFIG);
  IF L_RETENTION_JOB<>1 OR L_RETENTION_CONFIG<>1 OR
     L_TABLES <> 13 OR L_NAMED_INDEXES <> 5 OR L_CODE <> 17 OR
     L_INVALID <> 0 OR L_LANDING_COLUMNS <> 49 OR L_STAGE_COLUMNS <> 49 OR
     L_STAGE_COMPRESSION <> 'DISABLED' OR
     L_PIPELINES < 1 OR L_LAST_YEAR <> L_CURRENT_YEAR OR
     L_PIPELINES <> L_LAST_YEAR - L_FIRST_YEAR + 1 OR
     L_WRONG_TYPES <> 0 OR L_NOT_STARTED <> 0 OR
     L_WRONG_TARGETS <> 0 OR L_WRONG_SOURCES <> 0 OR
     L_WRONG_INTERVALS <> 0 OR L_PROVIDER <> 1 OR L_CONFIG <> 1 OR
     L_CORE_LOCK_POLICY <> 1 OR L_JOB <> 'TRUE' OR L_NOTIFY NOT IN ('Y','N') THEN
    RAISE_APPLICATION_ERROR(-20964, 'OCI ingestion verification failed');
  END IF;
  DBMS_OUTPUT.PUT_LINE('OCI INGESTION VERIFICATION PASS');

  DBMS_OUTPUT.PUT_LINE('=== Initial Oracle file status after one minute ===');
  FOR P IN (
    SELECT PIPELINE_NAME, STATUS_TABLE FROM USER_CLOUD_PIPELINES
     WHERE REGEXP_LIKE(PIPELINE_NAME,
                       '^OCI_FOCUS_REPORTS_LOAD_[0-9]{4}$')
     ORDER BY PIPELINE_NAME
  ) LOOP
    L_STATUS_TABLE := P.STATUS_TABLE;
    IF L_STATUS_TABLE IS NULL THEN
      DBMS_OUTPUT.PUT_LINE(P.PIPELINE_NAME ||
        ': no status table yet; the pipeline remains scheduled');
    ELSE
      L_STATUS_TABLE := DBMS_ASSERT.SIMPLE_SQL_NAME(L_STATUS_TABLE);
      EXECUTE IMMEDIATE
        'SELECT COUNT(CASE WHEN STATUS = ''COMPLETED'' THEN 1 END),' ||
        ' COUNT(CASE WHEN STATUS = ''FAILED'' THEN 1 END),' ||
        ' COUNT(CASE WHEN STATUS = ''PENDING'' THEN 1 END),' ||
        ' COUNT(CASE WHEN STATUS = ''RUNNING'' THEN 1 END)' ||
        ' FROM ' || L_STATUS_TABLE
        INTO L_COMPLETED, L_FAILED, L_PENDING, L_RUNNING;
      DBMS_OUTPUT.PUT_LINE(P.PIPELINE_NAME ||
        ': completed=' || L_COMPLETED ||
        ' failed=' || L_FAILED ||
        ' pending=' || L_PENDING ||
        ' running=' || L_RUNNING);
    END IF;
  END LOOP;
END;
