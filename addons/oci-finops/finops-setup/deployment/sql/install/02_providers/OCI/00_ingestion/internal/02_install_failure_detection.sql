-- Discover failed files incrementally from Oracle pipeline status tables.
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

CREATE OR REPLACE PROCEDURE OCI_FOCUS_DISCOVER_FAILURES (
  P_PIPELINE_NAME   IN VARCHAR2,
  P_OVERLAP_MINUTES IN NUMBER DEFAULT 1440,
  P_SETTLE_MINUTES  IN NUMBER DEFAULT 60
) AUTHID DEFINER AS
  L_PIPELINE_NAME        VARCHAR2(128) := UPPER(TRIM(P_PIPELINE_NAME));
  L_PIPELINE_ID          NUMBER;
  L_OPERATION_ID         NUMBER;
  L_STATUS_TABLE         VARCHAR2(128);
  L_STATUS_TABLE_CREATED DATE;
  L_SAVED_PIPELINE_ID    NUMBER;
  L_SAVED_OPERATION_ID   NUMBER;
  L_SAVED_STATUS_TABLE   VARCHAR2(128);
  L_SAVED_CREATED        DATE;
  L_GENERATION_NO        NUMBER;
  L_LAST_CUTOFF          TIMESTAMP WITH TIME ZONE;
  L_WINDOW_START         TIMESTAMP WITH TIME ZONE;
  L_WINDOW_END           TIMESTAMP WITH TIME ZONE;
  L_NEW_FILE_COUNT       NUMBER;
  L_SQL                  VARCHAR2(32767);
BEGIN
  IF L_PIPELINE_NAME IS NULL OR LENGTH(L_PIPELINE_NAME) > 128 OR
     P_OVERLAP_MINUTES IS NULL OR P_OVERLAP_MINUTES < 0 OR
     P_OVERLAP_MINUTES > 10080 OR
     P_SETTLE_MINUTES IS NULL OR P_SETTLE_MINUTES < 0 OR
     P_SETTLE_MINUTES > 1440 THEN
    RAISE_APPLICATION_ERROR(-20760, 'Invalid discovery parameters');
  END IF;

  SELECT PIPELINE_ID, OPERATION_ID, STATUS_TABLE
  INTO L_PIPELINE_ID, L_OPERATION_ID, L_STATUS_TABLE
  FROM USER_CLOUD_PIPELINES
  WHERE PIPELINE_NAME = L_PIPELINE_NAME
    AND PIPELINE_TYPE = 'LOAD';

  IF L_OPERATION_ID IS NULL OR L_STATUS_TABLE IS NULL THEN
    RAISE_APPLICATION_ERROR(-20761, 'Pipeline has no load status table');
  END IF;
  L_STATUS_TABLE := DBMS_ASSERT.SIMPLE_SQL_NAME(L_STATUS_TABLE);

  SELECT CREATED INTO L_STATUS_TABLE_CREATED
  FROM USER_OBJECTS
  WHERE OBJECT_NAME = L_STATUS_TABLE AND OBJECT_TYPE = 'TABLE';

  BEGIN
    INSERT INTO OCI_FOCUS_FAIL_SCAN_CURSOR
      (PIPELINE_NAME, PIPELINE_ID, OPERATION_ID, STATUS_TABLE,
       STATUS_TABLE_CREATED, GENERATION_NO)
    VALUES
      (L_PIPELINE_NAME, L_PIPELINE_ID, L_OPERATION_ID, L_STATUS_TABLE,
       L_STATUS_TABLE_CREATED, 1);
  EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN NULL;
  END;

  SELECT PIPELINE_ID, OPERATION_ID, STATUS_TABLE, STATUS_TABLE_CREATED,
         GENERATION_NO, LAST_CUTOFF
  INTO L_SAVED_PIPELINE_ID, L_SAVED_OPERATION_ID, L_SAVED_STATUS_TABLE,
       L_SAVED_CREATED, L_GENERATION_NO, L_LAST_CUTOFF
  FROM OCI_FOCUS_FAIL_SCAN_CURSOR
  WHERE PIPELINE_NAME = L_PIPELINE_NAME
  FOR UPDATE NOWAIT;

  IF L_SAVED_PIPELINE_ID <> L_PIPELINE_ID OR
     L_SAVED_OPERATION_ID <> L_OPERATION_ID OR
     L_SAVED_STATUS_TABLE <> L_STATUS_TABLE OR
     L_SAVED_CREATED <> L_STATUS_TABLE_CREATED THEN
    L_GENERATION_NO := L_GENERATION_NO + 1;
    L_LAST_CUTOFF := NULL;
    UPDATE OCI_FOCUS_FAIL_SCAN_CURSOR
    SET PIPELINE_ID = L_PIPELINE_ID,
        OPERATION_ID = L_OPERATION_ID,
        STATUS_TABLE = L_STATUS_TABLE,
        STATUS_TABLE_CREATED = L_STATUS_TABLE_CREATED,
        GENERATION_NO = L_GENERATION_NO,
        LAST_CUTOFF = NULL
    WHERE PIPELINE_NAME = L_PIPELINE_NAME;
  END IF;

  L_WINDOW_START := NVL(L_LAST_CUTOFF,
    TO_TIMESTAMP_TZ('1970-01-01 00:00:00 +00:00',
                    'YYYY-MM-DD HH24:MI:SS TZH:TZM')) -
    NUMTODSINTERVAL(P_OVERLAP_MINUTES, 'MINUTE');
  L_WINDOW_END := SYSTIMESTAMP -
    NUMTODSINTERVAL(P_SETTLE_MINUTES, 'MINUTE');

  IF L_WINDOW_END <= L_WINDOW_START THEN
    RAISE_APPLICATION_ERROR(-20763, 'Discovery window is empty');
  END IF;

  L_SQL :=
    'MERGE INTO OCI_FOCUS_FAIL_FILE Q USING (' ||
    ' SELECT :pipeline_name AS pipeline_name,' ||
    ' :generation_no AS generation_no,' ||
    ' STANDARD_HASH(S.NAME, ''SHA256'') AS source_name_hash,' ||
    ' S.NAME AS source_name, S.ID AS source_id,' ||
    ' S.BYTES AS source_bytes, S.CHECKSUM AS source_checksum,' ||
    ' S.LAST_MODIFIED AS source_last_modified,' ||
    ' S.END_TIME AS source_end_time,' ||
    ' S.ERROR_CODE AS error_code, S.ERROR_MESSAGE AS error_message,' ||
    ' S.ROWS_LOADED AS rows_loaded' ||
    ' FROM ' || L_STATUS_TABLE || ' S' ||
    ' WHERE S.STATUS = ''FAILED''' ||
    ' AND SYS_EXTRACT_UTC(S.END_TIME) >=' ||
    ' SYS_EXTRACT_UTC(:window_start)' ||
    ' AND SYS_EXTRACT_UTC(S.END_TIME) <' ||
    ' SYS_EXTRACT_UTC(:window_end)' ||
    ') D ON (Q.PIPELINE_NAME = D.PIPELINE_NAME' ||
    ' AND Q.GENERATION_NO = D.GENERATION_NO' ||
    ' AND Q.SOURCE_NAME_HASH = D.SOURCE_NAME_HASH' ||
    ' AND Q.SOURCE_NAME = D.SOURCE_NAME)' ||
    ' WHEN NOT MATCHED THEN INSERT' ||
    ' (PIPELINE_NAME, GENERATION_NO, SOURCE_NAME_HASH, SOURCE_NAME,' ||
    ' SOURCE_ID, SOURCE_BYTES, SOURCE_CHECKSUM, SOURCE_LAST_MODIFIED,' ||
    ' SOURCE_END_TIME, ERROR_CODE, ERROR_MESSAGE, ROWS_LOADED)' ||
    ' VALUES (D.PIPELINE_NAME, D.GENERATION_NO, D.SOURCE_NAME_HASH,' ||
    ' D.SOURCE_NAME, D.SOURCE_ID, D.SOURCE_BYTES, D.SOURCE_CHECKSUM,' ||
    ' D.SOURCE_LAST_MODIFIED, D.SOURCE_END_TIME, D.ERROR_CODE,' ||
    ' D.ERROR_MESSAGE, D.ROWS_LOADED)';
  EXECUTE IMMEDIATE L_SQL USING L_PIPELINE_NAME, L_GENERATION_NO,
    L_WINDOW_START, L_WINDOW_END;
  L_NEW_FILE_COUNT := SQL%ROWCOUNT;

  UPDATE OCI_FOCUS_FAIL_SCAN_CURSOR
  SET LAST_CUTOFF = L_WINDOW_END,
      LAST_SCAN_AT = SYSTIMESTAMP
  WHERE PIPELINE_NAME = L_PIPELINE_NAME;

  INSERT INTO OCI_FOCUS_FAIL_SCAN_RUN
    (PIPELINE_NAME, GENERATION_NO, STATUS_TABLE, WINDOW_START,
     WINDOW_END, NEW_FILE_COUNT)
  VALUES
    (L_PIPELINE_NAME, L_GENERATION_NO, L_STATUS_TABLE, L_WINDOW_START,
     L_WINDOW_END, L_NEW_FILE_COUNT);

  COMMIT;
  DBMS_OUTPUT.PUT_LINE('pipeline=' || L_PIPELINE_NAME ||
    ' generation=' || L_GENERATION_NO ||
    ' new_failed_files=' || L_NEW_FILE_COUNT);
EXCEPTION
  WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
END OCI_FOCUS_DISCOVER_FAILURES;
/

-- One ADB user lock serializes all FOCUS remediation entry points across
-- pipelines and sessions. Install after the direct DBMS_LOCK grant.
-- The lock is held across per-row COMMIT/ROLLBACK and is released when the
-- outermost call exits or its database session ends.
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

CREATE OR REPLACE PACKAGE OCI_FOCUS_REMED_MUTEX AUTHID DEFINER AS
  PROCEDURE ENTER;
  PROCEDURE LEAVE;
END OCI_FOCUS_REMED_MUTEX;
/

CREATE OR REPLACE PACKAGE BODY OCI_FOCUS_REMED_MUTEX AS
  G_DEPTH PLS_INTEGER := 0;

  FUNCTION LOCK_ID RETURN INTEGER IS
  BEGIN
    -- DBMS_LOCK numeric IDs are database-wide. Derive a stable owner-specific
    -- ID to avoid coupling separate schemas that install this solution.
    RETURN DBMS_UTILITY.GET_HASH_VALUE(
      SYS_CONTEXT('USERENV', 'CURRENT_USER') || '.OCI_FOCUS_REMED_MUTEX',
      0, 1073741823);
  END LOCK_ID;

  PROCEDURE ENTER IS
    L_RESULT INTEGER;
  BEGIN
    IF G_DEPTH > 0 THEN
      G_DEPTH := G_DEPTH + 1;
      RETURN;
    END IF;
    LOOP
      L_RESULT := DBMS_LOCK.REQUEST(
        ID => LOCK_ID,
        LOCKMODE => DBMS_LOCK.X_MODE,
        TIMEOUT => DBMS_LOCK.MAXWAIT,
        RELEASE_ON_COMMIT => FALSE);
      EXIT WHEN L_RESULT = 0;
      IF L_RESULT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20940,
          'FOCUS remediation mutex request failed, code=' || L_RESULT);
      END IF;
      -- A timeout only bounds one wait call; keep waiting for the active
      -- execution instead of starting a second shared-stage worker.
    END LOOP;
    G_DEPTH := 1;
  END ENTER;

  PROCEDURE LEAVE IS
    L_RESULT INTEGER;
  BEGIN
    IF G_DEPTH = 0 THEN
      RETURN;
    END IF;
    IF G_DEPTH > 1 THEN
      G_DEPTH := G_DEPTH - 1;
      RETURN;
    END IF;
    L_RESULT := DBMS_LOCK.RELEASE(ID => LOCK_ID);
    IF L_RESULT <> 0 THEN
      RAISE_APPLICATION_ERROR(-20941,
        'FOCUS remediation mutex release failed, code=' || L_RESULT);
    END IF;
    G_DEPTH := 0;
  END LEAVE;
END OCI_FOCUS_REMED_MUTEX;
/

SELECT NAME, TYPE, LINE, POSITION, TEXT FROM USER_ERRORS
 WHERE NAME = 'OCI_FOCUS_REMED_MUTEX' ORDER BY TYPE, SEQUENCE;

DECLARE
  L_BAD NUMBER;
BEGIN
  SELECT COUNT(*) INTO L_BAD FROM USER_OBJECTS
   WHERE OBJECT_NAME = 'OCI_FOCUS_REMED_MUTEX'
     AND OBJECT_TYPE IN ('PACKAGE', 'PACKAGE BODY')
     AND STATUS = 'VALID';
  IF L_BAD <> 2 THEN
    RAISE_APPLICATION_ERROR(-20942, 'FOCUS remediation mutex is invalid');
  END IF;
END;
