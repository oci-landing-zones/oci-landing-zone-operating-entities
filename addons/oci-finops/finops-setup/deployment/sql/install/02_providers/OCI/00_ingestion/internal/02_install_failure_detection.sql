-- Resolve concrete source URIs for wildcard and regexuri pipeline locations.
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

CREATE OR REPLACE FUNCTION OCI_FOCUS_SOURCE_PREFIX(P_LOCATION IN CLOB)
  RETURN VARCHAR2 AUTHID DEFINER IS
  L_LOCATION VARCHAR2(4000) := DBMS_LOB.SUBSTR(P_LOCATION, 4000, 1);
  L_OBJECT_START PLS_INTEGER;
  L_PATTERN_START PLS_INTEGER := 0;
  L_SLASH PLS_INTEGER := 0;
BEGIN
  L_OBJECT_START := INSTR(L_LOCATION, '/o/');
  IF L_OBJECT_START = 0 OR DBMS_LOB.GETLENGTH(P_LOCATION) > 4000 THEN
    RAISE_APPLICATION_ERROR(-20863, 'Expected Object Storage location URI');
  END IF;
  FOR I IN L_OBJECT_START + 3 .. LENGTH(L_LOCATION) LOOP
    IF INSTR('*?([{+|^$', SUBSTR(L_LOCATION, I, 1)) > 0 THEN
      L_PATTERN_START := I;
      EXIT;
    END IF;
  END LOOP;
  IF L_PATTERN_START = 0 THEN
    RAISE_APPLICATION_ERROR(-20864, 'Location has no wildcard or regex path');
  END IF;
  FOR I IN REVERSE L_OBJECT_START + 3 .. L_PATTERN_START - 1 LOOP
    IF SUBSTR(L_LOCATION, I, 1) = '/' THEN
      L_SLASH := I;
      EXIT;
    END IF;
  END LOOP;
  IF L_SLASH <= L_OBJECT_START + 2 THEN
    RAISE_APPLICATION_ERROR(-20865, 'Location has no fixed object prefix');
  END IF;
  RETURN SUBSTR(L_LOCATION, 1, L_SLASH);
END;
/

CREATE OR REPLACE PROCEDURE OCI_FOCUS_FILL_SOURCE_URIS(
  P_PIPELINE_NAME IN VARCHAR2 DEFAULT NULL
) AUTHID CURRENT_USER IS
  L_LOCATION CLOB;
  L_PREFIX VARCHAR2(4000);
  L_BAD_COUNT NUMBER;
  L_UPDATED NUMBER;
BEGIN
  FOR P IN (
    SELECT DISTINCT PIPELINE_NAME
      FROM OCI_FOCUS_FAIL_FILE
     WHERE SOURCE_URI IS NULL
       AND (P_PIPELINE_NAME IS NULL OR
            PIPELINE_NAME = UPPER(TRIM(P_PIPELINE_NAME)))
     ORDER BY PIPELINE_NAME
  ) LOOP
    SELECT ATTRIBUTE_VALUE INTO L_LOCATION
      FROM USER_CLOUD_PIPELINE_ATTRIBUTES
     WHERE PIPELINE_NAME = P.PIPELINE_NAME
       AND ATTRIBUTE_NAME = 'location';
    L_PREFIX := OCI_FOCUS_SOURCE_PREFIX(L_LOCATION);
    SELECT COUNT(*) INTO L_BAD_COUNT
      FROM OCI_FOCUS_FAIL_FILE
     WHERE PIPELINE_NAME = P.PIPELINE_NAME
       AND SOURCE_URI IS NULL
       AND (INSTR(SOURCE_NAME, '..') > 0 OR
            INSTR(SOURCE_NAME, '*') > 0 OR
            INSTR(SOURCE_NAME, '?') > 0 OR
            INSTR(SOURCE_NAME, ',') > 0 OR
            SUBSTR(SOURCE_NAME, 1, 1) = '/');
    IF L_BAD_COUNT <> 0 THEN
      RAISE_APPLICATION_ERROR(-20862, 'Unsafe source name in failed-file queue');
    END IF;
    UPDATE OCI_FOCUS_FAIL_FILE
       SET SOURCE_URI = CASE
             WHEN SOURCE_NAME LIKE 'https://%' THEN SOURCE_NAME
             ELSE L_PREFIX || SOURCE_NAME END
     WHERE PIPELINE_NAME = P.PIPELINE_NAME
       AND SOURCE_URI IS NULL;
    L_UPDATED := SQL%ROWCOUNT;
    DBMS_OUTPUT.PUT_LINE('pipeline=' || P.PIPELINE_NAME ||
      ' source_uris_filled=' || L_UPDATED);
  END LOOP;
  COMMIT;
EXCEPTION WHEN OTHERS THEN
  ROLLBACK;
  RAISE;
END;
/

SELECT NAME, TYPE, LINE, POSITION, TEXT
  FROM USER_ERRORS
 WHERE NAME IN ('OCI_FOCUS_SOURCE_PREFIX', 'OCI_FOCUS_FILL_SOURCE_URIS')
 ORDER BY NAME, SEQUENCE;

DECLARE
  L_ERRORS NUMBER;
BEGIN
  SELECT COUNT(*) INTO L_ERRORS
    FROM USER_ERRORS
   WHERE NAME IN ('OCI_FOCUS_SOURCE_PREFIX', 'OCI_FOCUS_FILL_SOURCE_URIS');
  IF L_ERRORS <> 0 THEN
    RAISE_APPLICATION_ERROR(-20866, 'Regex URI objects have compile errors');
  END IF;
END;
