-- Bounded, resumable extraction of all cataloged OCI defined-tag values.
SET DEFINE OFF SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE OR REPLACE PACKAGE OCI_TAG_VALUE_API AUTHID DEFINER AS
  PROCEDURE PROCESS_WINDOW(
    P_START IN TIMESTAMP, P_END IN TIMESTAMP,
    P_MAX_ROWS IN NUMBER DEFAULT 10000);
  PROCEDURE RECHECK_WINDOW(P_START IN TIMESTAMP, P_END IN TIMESTAMP);
  PROCEDURE RUN_SCHEDULED;
END OCI_TAG_VALUE_API;
/

CREATE OR REPLACE PACKAGE BODY OCI_TAG_VALUE_API AS
  C_LOCK_ID CONSTANT PLS_INTEGER := 768090432;

  PROCEDURE CHECK_WINDOW(P_START TIMESTAMP, P_END TIMESTAMP) IS
  BEGIN
    IF P_START IS NULL OR P_END IS NULL OR P_END <= P_START OR
       P_END > P_START + INTERVAL '1' DAY THEN
      RAISE_APPLICATION_ERROR(-20960,
        'Supply a valid end-exclusive window no longer than one day');
    END IF;
  END;

  FUNCTION GET_LOCK RETURN BOOLEAN IS
    L_RESULT PLS_INTEGER;
  BEGIN
    L_RESULT := DBMS_LOCK.REQUEST(
      ID=>C_LOCK_ID,LOCKMODE=>DBMS_LOCK.X_MODE,
      TIMEOUT=>0,RELEASE_ON_COMMIT=>FALSE);
    IF L_RESULT=0 THEN RETURN TRUE; END IF;
    IF L_RESULT=1 THEN RETURN FALSE; END IF;
    RAISE_APPLICATION_ERROR(-20961,
      'OCI tag-value lock request returned '||L_RESULT);
  END;

  PROCEDURE RELEASE_LOCK IS
    L_RESULT PLS_INTEGER;
  BEGIN
    L_RESULT := DBMS_LOCK.RELEASE(ID=>C_LOCK_ID);
    IF L_RESULT<>0 THEN
      DBMS_OUTPUT.PUT_LINE('Tag-value lock release returned '||L_RESULT);
    END IF;
  END;

  PROCEDURE PROCESS_WINDOW_IMPL(
    P_START IN TIMESTAMP,P_END IN TIMESTAMP,P_MAX_ROWS IN NUMBER,
    P_RUN_ID IN NUMBER,P_ROWS OUT NUMBER,P_VALUES OUT NUMBER) IS
    L_LIMIT PLS_INTEGER;
    L_KEYS PLS_INTEGER;
    L_VALUES PLS_INTEGER;
    L_LAST_START TIMESTAMP(6);
    L_LAST_REF VARCHAR2(512);
    L_PATH VARCHAR2(1000);
    L_SQL VARCHAR2(10000);
  BEGIN
    CHECK_WINDOW(P_START,P_END);
    IF P_MAX_ROWS IS NULL OR P_MAX_ROWS<>TRUNC(P_MAX_ROWS) OR
       P_MAX_ROWS<1 OR P_MAX_ROWS>100000 THEN
      RAISE_APPLICATION_ERROR(-20962,'P_MAX_ROWS must be 1 to 100000');
    END IF;
    P_ROWS := 0;
    P_VALUES := 0;
    LOOP
      L_LIMIT := LEAST(500,P_MAX_ROWS-P_ROWS);
      EXIT WHEN L_LIMIT<=0;
      INSERT INTO OCI_TAG_VALUE_WORK_KEYS
        (CHARGEPERIODSTART,OCI_REFERENCENUMBER)
      SELECT L.CHARGEPERIODSTART,L.OCI_REFERENCENUMBER
        FROM OCI_FOCUS_REPORTS L
       WHERE L.CHARGEPERIODSTART>=P_START
         AND L.CHARGEPERIODSTART<P_END
         AND (L_LAST_START IS NULL OR
              L.CHARGEPERIODSTART>L_LAST_START OR
              (L.CHARGEPERIODSTART=L_LAST_START AND
               L.OCI_REFERENCENUMBER>L_LAST_REF))
         AND NOT EXISTS (
           SELECT 1 FROM OCI_TAG_VALUE_PROCESSING P
            WHERE P.CHARGEPERIODSTART=L.CHARGEPERIODSTART
              AND P.OCI_REFERENCENUMBER=L.OCI_REFERENCENUMBER)
       ORDER BY L.CHARGEPERIODSTART,L.OCI_REFERENCENUMBER
       FETCH FIRST L_LIMIT ROWS ONLY;
      L_KEYS := SQL%ROWCOUNT;
      EXIT WHEN L_KEYS=0;
      SELECT CHARGEPERIODSTART,OCI_REFERENCENUMBER
        INTO L_LAST_START,L_LAST_REF
        FROM (SELECT CHARGEPERIODSTART,OCI_REFERENCENUMBER
                FROM OCI_TAG_VALUE_WORK_KEYS
               ORDER BY CHARGEPERIODSTART DESC,OCI_REFERENCENUMBER DESC)
       WHERE ROWNUM=1;
      L_VALUES := 0;
      FOR D IN (
        SELECT DISTINCT N.NAMESPACE_NAME,T.TAG_NAME
          FROM OCI_TAG_NAMESPACE N JOIN OCI_TAG_DEFINITION T
            ON T.TAG_NAMESPACE_ID=N.TAG_NAMESPACE_ID
         ORDER BY N.NAMESPACE_NAME,T.TAG_NAME
      ) LOOP
        -- OCI FOCUS has flat JSON keys such as
        -- "tagns-lz-cost-governance.tag-lz-cost-center".
        L_PATH := '$."'||
          REPLACE(REPLACE(D.NAMESPACE_NAME||'.'||D.TAG_NAME,
            CHR(92),CHR(92)||CHR(92)), '"',CHR(92)||'"')||'"';
        L_SQL := q'[
          INSERT INTO OCI_TAG_VALUE
            (CHARGEPERIODSTART,OCI_REFERENCENUMBER,
             TAG_NAMESPACE_NAME,TAG_NAME,TAG_VALUE)
          SELECT X.CHARGEPERIODSTART,X.OCI_REFERENCENUMBER,
                 :NAMESPACE_NAME,:TAG_NAME,X.TAG_VALUE
            FROM (
              SELECT L.CHARGEPERIODSTART,L.OCI_REFERENCENUMBER,
                     JSON_VALUE(L.TAGS, ]'||
                       DBMS_ASSERT.ENQUOTE_LITERAL(L_PATH)||
                       q'[ RETURNING VARCHAR2(4000)
                        NULL ON EMPTY ERROR ON ERROR) TAG_VALUE
                FROM OCI_FOCUS_REPORTS L
                JOIN OCI_TAG_VALUE_WORK_KEYS W
                  ON W.CHARGEPERIODSTART=L.CHARGEPERIODSTART
                 AND W.OCI_REFERENCENUMBER=L.OCI_REFERENCENUMBER
            ) X
           WHERE TRIM(X.TAG_VALUE) IS NOT NULL
             AND NOT EXISTS (
               SELECT 1 FROM OCI_TAG_VALUE V
                WHERE V.CHARGEPERIODSTART=X.CHARGEPERIODSTART
                  AND V.OCI_REFERENCENUMBER=X.OCI_REFERENCENUMBER
                  AND V.TAG_NAMESPACE_NAME=:EXIST_NAMESPACE
                  AND V.TAG_NAME=:EXIST_TAG)]';
        EXECUTE IMMEDIATE L_SQL USING D.NAMESPACE_NAME,D.TAG_NAME,
          D.NAMESPACE_NAME,D.TAG_NAME;
        L_VALUES := L_VALUES+SQL%ROWCOUNT;
      END LOOP;
      INSERT INTO OCI_TAG_VALUE_PROCESSING
        (CHARGEPERIODSTART,OCI_REFERENCENUMBER)
      SELECT CHARGEPERIODSTART,OCI_REFERENCENUMBER
        FROM OCI_TAG_VALUE_WORK_KEYS;
      IF SQL%ROWCOUNT<>L_KEYS THEN
        RAISE_APPLICATION_ERROR(-20963,'Tag-value row accounting mismatch');
      END IF;
      IF P_RUN_ID IS NOT NULL THEN
        UPDATE OCI_TAG_VALUE_RUN
           SET ROWS_PROCESSED=ROWS_PROCESSED+L_KEYS,
               VALUES_INSERTED=VALUES_INSERTED+L_VALUES
         WHERE RUN_ID=P_RUN_ID;
      END IF;
      COMMIT; -- Values and completion markers are one transaction.
      P_ROWS := P_ROWS+L_KEYS;
      P_VALUES := P_VALUES+L_VALUES;
      EXIT WHEN L_KEYS<L_LIMIT;
    END LOOP;
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK; -- Earlier committed batches remain safely accounted for.
    RAISE;
  END;

  PROCEDURE PROCESS_WINDOW(
    P_START IN TIMESTAMP,P_END IN TIMESTAMP,
    P_MAX_ROWS IN NUMBER DEFAULT 10000) IS
    L_ROWS NUMBER;
    L_VALUES NUMBER;
  BEGIN
    IF NOT GET_LOCK THEN
      RAISE_APPLICATION_ERROR(-20964,'OCI tag-value worker is already running');
    END IF;
    BEGIN
      PROCESS_WINDOW_IMPL(P_START,P_END,P_MAX_ROWS,NULL,L_ROWS,L_VALUES);
      RELEASE_LOCK;
      DBMS_OUTPUT.PUT_LINE('tag_rows_processed='||L_ROWS||
        ' values_inserted='||L_VALUES);
    EXCEPTION WHEN OTHERS THEN
      RELEASE_LOCK;
      RAISE;
    END;
  END;

  PROCEDURE RECHECK_WINDOW(P_START IN TIMESTAMP,P_END IN TIMESTAMP) IS
    L_ROWS NUMBER;
    L_VALUES NUMBER;
    L_KEYS PLS_INTEGER;
    L_LAST_START TIMESTAMP(6);
    L_LAST_REF VARCHAR2(512);
  BEGIN
    CHECK_WINDOW(P_START,P_END);
    IF NOT GET_LOCK THEN
      RAISE_APPLICATION_ERROR(-20964,'OCI tag-value worker is already running');
    END IF;
    BEGIN
      -- Keep existing value rows; the PK and NOT EXISTS admit only new keys.
      -- Remove completion markers in small commits to avoid monthly UNDO.
      LOOP
        INSERT INTO OCI_TAG_VALUE_WORK_KEYS
          (CHARGEPERIODSTART,OCI_REFERENCENUMBER)
        SELECT P.CHARGEPERIODSTART,P.OCI_REFERENCENUMBER
          FROM OCI_TAG_VALUE_PROCESSING P
         WHERE P.CHARGEPERIODSTART>=P_START
           AND P.CHARGEPERIODSTART<P_END
           AND (L_LAST_START IS NULL OR
                P.CHARGEPERIODSTART>L_LAST_START OR
                (P.CHARGEPERIODSTART=L_LAST_START AND
                 P.OCI_REFERENCENUMBER>L_LAST_REF))
         ORDER BY P.CHARGEPERIODSTART,P.OCI_REFERENCENUMBER
         FETCH FIRST 500 ROWS ONLY;
        L_KEYS:=SQL%ROWCOUNT;
        EXIT WHEN L_KEYS=0;
        SELECT CHARGEPERIODSTART,OCI_REFERENCENUMBER
          INTO L_LAST_START,L_LAST_REF
          FROM (SELECT CHARGEPERIODSTART,OCI_REFERENCENUMBER
                  FROM OCI_TAG_VALUE_WORK_KEYS
                 ORDER BY CHARGEPERIODSTART DESC,OCI_REFERENCENUMBER DESC)
         WHERE ROWNUM=1;
        DELETE FROM OCI_TAG_VALUE_PROCESSING P
         WHERE EXISTS (
           SELECT 1 FROM OCI_TAG_VALUE_WORK_KEYS W
            WHERE W.CHARGEPERIODSTART=P.CHARGEPERIODSTART
              AND W.OCI_REFERENCENUMBER=P.OCI_REFERENCENUMBER);
        IF SQL%ROWCOUNT<>L_KEYS THEN
          RAISE_APPLICATION_ERROR(-20969,'Recheck marker accounting mismatch');
        END IF;
        COMMIT;
        EXIT WHEN L_KEYS<500;
      END LOOP;
      LOOP
        PROCESS_WINDOW_IMPL(P_START,P_END,10000,NULL,L_ROWS,L_VALUES);
        EXIT WHEN L_ROWS<10000;
      END LOOP;
      RELEASE_LOCK;
      DBMS_OUTPUT.PUT_LINE('tag_value_recheck_complete');
    EXCEPTION WHEN OTHERS THEN
      RELEASE_LOCK;
      RAISE;
    END;
  END;

  PROCEDURE PROCESS_DAY(P_DAY TIMESTAMP,P_LIMIT NUMBER,
                        P_REMAIN OUT NUMBER) IS
    L_RUN_ID NUMBER;
    L_ROWS NUMBER;
    L_VALUES NUMBER;
    L_ERROR VARCHAR2(4000);
  BEGIN
    INSERT INTO OCI_TAG_VALUE_RUN (WINDOW_START,WINDOW_END,STATUS)
    VALUES (P_DAY,P_DAY+INTERVAL '1' DAY,'RUNNING')
    RETURNING RUN_ID INTO L_RUN_ID;
    COMMIT;
    PROCESS_WINDOW_IMPL(P_DAY,P_DAY+INTERVAL '1' DAY,P_LIMIT,
      L_RUN_ID,L_ROWS,L_VALUES);
    SELECT COUNT(*) INTO P_REMAIN FROM (
      SELECT 1 FROM OCI_FOCUS_REPORTS L
       WHERE L.CHARGEPERIODSTART>=P_DAY
         AND L.CHARGEPERIODSTART<P_DAY+INTERVAL '1' DAY
         AND NOT EXISTS (
           SELECT 1 FROM OCI_TAG_VALUE_PROCESSING P
            WHERE P.CHARGEPERIODSTART=L.CHARGEPERIODSTART
              AND P.OCI_REFERENCENUMBER=L.OCI_REFERENCENUMBER)
       FETCH FIRST 1 ROW ONLY);
    UPDATE OCI_TAG_VALUE_RUN
       SET STATUS='COMPLETE',FINISHED_AT=SYSTIMESTAMP
     WHERE RUN_ID=L_RUN_ID;
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('tag_value_day='||TO_CHAR(P_DAY,'YYYY-MM-DD')||
      ' rows='||L_ROWS||' values='||L_VALUES||
      ' remaining='||P_REMAIN);
  EXCEPTION WHEN OTHERS THEN
    L_ERROR:=SUBSTR(SQLERRM,1,4000);
    ROLLBACK;
    IF L_RUN_ID IS NOT NULL THEN
      UPDATE OCI_TAG_VALUE_RUN SET STATUS='ERROR',
        FINISHED_AT=SYSTIMESTAMP,ERROR_MESSAGE=L_ERROR
       WHERE RUN_ID=L_RUN_ID;
      COMMIT;
    END IF;
    RAISE;
  END;

  PROCEDURE RUN_SCHEDULED IS
    L_DAY TIMESTAMP(6);
    L_FIRST TIMESTAMP(6);
    L_TODAY TIMESTAMP(6);
    L_LIMIT NUMBER;
    L_RECENT_LIMIT NUMBER;
    L_REMAIN NUMBER;
  BEGIN
    IF NOT GET_LOCK THEN
      INSERT INTO OCI_TAG_VALUE_RUN (STATUS,FINISHED_AT,ERROR_MESSAGE)
      VALUES ('SKIPPED',SYSTIMESTAMP,'Another tag-value run holds the lock');
      COMMIT;
      RETURN;
    END IF;
    BEGIN
      -- A vanished session releases the lock; preserve its partial run audit.
      UPDATE OCI_TAG_VALUE_RUN
         SET STATUS='ERROR',FINISHED_AT=SYSTIMESTAMP,
             ERROR_MESSAGE='Interrupted before completion; committed batches remain in the ledger'
       WHERE STATUS='RUNNING';
      COMMIT;
      SELECT NEXT_DAY,MAX_ROWS_PER_RUN INTO L_DAY,L_LIMIT
        FROM OCI_TAG_VALUE_CONFIG WHERE CONFIG_ID=1;
      SELECT CAST(TRUNC(MIN(CHARGEPERIODSTART)) AS TIMESTAMP)
        INTO L_FIRST FROM OCI_FOCUS_REPORTS;
      L_TODAY := CAST(TRUNC(SYS_EXTRACT_UTC(SYSTIMESTAMP)) AS TIMESTAMP);
      IF L_DAY IS NULL OR L_DAY>L_TODAY THEN L_DAY:=L_FIRST; END IF;
      IF L_DAY IS NULL THEN
        INSERT INTO OCI_TAG_VALUE_RUN
          (STATUS,FINISHED_AT,ERROR_MESSAGE)
        VALUES ('SKIPPED',SYSTIMESTAMP,'Landing has no rows yet');
        COMMIT;
        RELEASE_LOCK;
        RETURN;
      END IF;
      IF L_DAY=L_TODAY THEN
        PROCESS_DAY(L_DAY,L_LIMIT,L_REMAIN);
      ELSE
        -- Recent ingestion is processed every hour during historical catch-up.
        L_RECENT_LIMIT:=GREATEST(1,TRUNC(L_LIMIT/5));
        PROCESS_DAY(L_TODAY,L_RECENT_LIMIT,L_REMAIN);
        PROCESS_DAY(L_DAY,L_LIMIT-L_RECENT_LIMIT,L_REMAIN);
      END IF;
      IF L_REMAIN=0 THEN
        UPDATE OCI_TAG_VALUE_CONFIG
           SET NEXT_DAY=L_DAY+INTERVAL '1' DAY,
               UPDATED_AT=SYSTIMESTAMP
         WHERE CONFIG_ID=1;
      ELSE
        UPDATE OCI_TAG_VALUE_CONFIG
           SET NEXT_DAY=L_DAY,UPDATED_AT=SYSTIMESTAMP
         WHERE CONFIG_ID=1;
      END IF;
      COMMIT;
      RELEASE_LOCK;
    EXCEPTION WHEN OTHERS THEN
      ROLLBACK;
      RELEASE_LOCK;
      RAISE;
    END;
  END;
END OCI_TAG_VALUE_API;
