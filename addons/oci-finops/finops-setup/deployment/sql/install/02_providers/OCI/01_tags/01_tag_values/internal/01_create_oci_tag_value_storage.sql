-- Optional provider-owned long-form defined-tag values and durable progress.
SET DEFINE OFF SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE TABLE OCI_TAG_VALUE (
  CHARGEPERIODSTART TIMESTAMP(6) NOT NULL,
  OCI_REFERENCENUMBER VARCHAR2(512) NOT NULL,
  TAG_NAMESPACE_NAME VARCHAR2(100) NOT NULL,
  TAG_NAME VARCHAR2(100) NOT NULL,
  TAG_VALUE VARCHAR2(4000) NOT NULL,
  EXTRACTED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT OCI_TAG_VALUE_PK PRIMARY KEY
    (CHARGEPERIODSTART,OCI_REFERENCENUMBER,TAG_NAMESPACE_NAME,TAG_NAME)
    USING INDEX LOCAL
)
PARTITION BY RANGE (CHARGEPERIODSTART)
INTERVAL (NUMTOYMINTERVAL(1,'MONTH'))
(
  PARTITION P_INIT VALUES LESS THAN (TIMESTAMP '2024-01-01 00:00:00')
);

CREATE INDEX OCI_TAG_VALUE_LOOKUP_IX
  ON OCI_TAG_VALUE (TAG_NAMESPACE_NAME,TAG_NAME,CHARGEPERIODSTART)
  LOCAL;

CREATE TABLE OCI_TAG_VALUE_PROCESSING (
  CHARGEPERIODSTART TIMESTAMP(6) NOT NULL,
  OCI_REFERENCENUMBER VARCHAR2(512) NOT NULL,
  PROCESSED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT OCI_TAG_VALUE_PROCESSING_PK PRIMARY KEY
    (CHARGEPERIODSTART,OCI_REFERENCENUMBER) USING INDEX LOCAL
)
PARTITION BY RANGE (CHARGEPERIODSTART)
INTERVAL (NUMTOYMINTERVAL(1,'MONTH'))
(
  PARTITION P_INIT VALUES LESS THAN (TIMESTAMP '2024-01-01 00:00:00')
);

-- Only the current batch is held here; COMMIT clears its keys.
CREATE GLOBAL TEMPORARY TABLE OCI_TAG_VALUE_WORK_KEYS (
  CHARGEPERIODSTART TIMESTAMP(6) NOT NULL,
  OCI_REFERENCENUMBER VARCHAR2(512) NOT NULL,
  CONSTRAINT OCI_TAG_VALUE_WORK_KEYS_PK PRIMARY KEY
    (CHARGEPERIODSTART,OCI_REFERENCENUMBER)
) ON COMMIT DELETE ROWS;

CREATE TABLE OCI_TAG_VALUE_CONFIG (
  CONFIG_ID NUMBER(1) DEFAULT 1 NOT NULL,
  NEXT_DAY TIMESTAMP(6),
  MAX_ROWS_PER_RUN NUMBER(6) DEFAULT 10000 NOT NULL,
  UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT OCI_TAG_VALUE_CONFIG_PK PRIMARY KEY (CONFIG_ID),
  CONSTRAINT OCI_TAG_VALUE_CONFIG_ONE_CK CHECK (CONFIG_ID=1),
  CONSTRAINT OCI_TAG_VALUE_CONFIG_LIMIT_CK
    CHECK (MAX_ROWS_PER_RUN BETWEEN 100 AND 100000)
);

INSERT INTO OCI_TAG_VALUE_CONFIG (CONFIG_ID,MAX_ROWS_PER_RUN)
VALUES (1,10000);
COMMIT;

CREATE TABLE OCI_TAG_VALUE_RUN (
  RUN_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  WINDOW_START TIMESTAMP(6),
  WINDOW_END TIMESTAMP(6),
  STARTED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  FINISHED_AT TIMESTAMP(6) WITH TIME ZONE,
  STATUS VARCHAR2(12) NOT NULL,
  ROWS_PROCESSED NUMBER DEFAULT 0 NOT NULL,
  VALUES_INSERTED NUMBER DEFAULT 0 NOT NULL,
  ERROR_MESSAGE VARCHAR2(4000),
  CONSTRAINT OCI_TAG_VALUE_RUN_STATUS_CK
    CHECK (STATUS IN ('RUNNING','COMPLETE','ERROR','SKIPPED'))
);

CREATE INDEX OCI_TAG_VALUE_RUN_STATUS_IX
  ON OCI_TAG_VALUE_RUN (STATUS,STARTED_AT);
