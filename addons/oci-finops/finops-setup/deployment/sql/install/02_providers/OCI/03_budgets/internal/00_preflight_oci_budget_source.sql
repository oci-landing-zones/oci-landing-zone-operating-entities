-- Read-only source connectivity check. Never prints the tenancy OCID.
VARIABLE source_tenancy_ocid VARCHAR2(512)
VARIABLE source_home_region VARCHAR2(64)
SET DEFINE OFF SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
  L_TENANCY VARCHAR2(512);
  L_ADB_REGION VARCHAR2(64);
  L_HOME_REGION VARCHAR2(64);
  L_RESPONSE DBMS_CLOUD_TYPES.RESP;
  L_BODY CLOB;
  L_ITEMS JSON_ARRAY_T;
  L_DOC JSON_OBJECT_T;
  L_ITEM JSON_OBJECT_T;
  L_BUDGET_ID VARCHAR2(512);
  L_BUDGET_SAMPLE NUMBER:=0;
  FUNCTION RESPONSE_ITEMS(P_BODY CLOB) RETURN JSON_ARRAY_T IS
    L_RESPONSE_ROOT JSON_ELEMENT_T;
    L_RESPONSE_OBJECT JSON_OBJECT_T;
  BEGIN
    L_RESPONSE_ROOT:=JSON_ELEMENT_T.PARSE(P_BODY);
    IF L_RESPONSE_ROOT.IS_ARRAY THEN
      RETURN TREAT(L_RESPONSE_ROOT AS JSON_ARRAY_T);
    ELSIF L_RESPONSE_ROOT.IS_OBJECT THEN
      L_RESPONSE_OBJECT:=TREAT(L_RESPONSE_ROOT AS JSON_OBJECT_T);
      IF L_RESPONSE_OBJECT.HAS('items') AND L_RESPONSE_OBJECT.GET('items').IS_ARRAY THEN
        RETURN L_RESPONSE_OBJECT.GET_ARRAY('items');
      END IF;
    END IF;
    RAISE_APPLICATION_ERROR(-20763,'OCI list response is not an array or an object with items');
  END;
  PROCEDURE GET_BODY(P_URI VARCHAR2,P_BODY OUT CLOB) IS
  BEGIN
    L_RESPONSE:=DBMS_CLOUD.SEND_REQUEST(
      CREDENTIAL_NAME=>'OCI$RESOURCE_PRINCIPAL',URI=>P_URI,
      METHOD=>DBMS_CLOUD.METHOD_GET,TIMEOUT=>120);
    IF DBMS_CLOUD.GET_RESPONSE_STATUS_CODE(L_RESPONSE)<>200 THEN
      RAISE_APPLICATION_ERROR(-20761,'OCI source preflight HTTP '||
        DBMS_CLOUD.GET_RESPONSE_STATUS_CODE(L_RESPONSE));
    END IF;
    P_BODY:=DBMS_CLOUD.GET_RESPONSE_TEXT(L_RESPONSE);
  END;
BEGIN
  SELECT LOWER(JSON_VALUE(CLOUD_IDENTITY,'$.TENANT_OCID')),
         LOWER(JSON_VALUE(CLOUD_IDENTITY,'$.REGION'))
    INTO L_TENANCY,L_ADB_REGION FROM V$PDBS
   WHERE CON_ID=TO_NUMBER(SYS_CONTEXT('USERENV','CON_ID'));
  IF NOT REGEXP_LIKE(L_TENANCY,'^ocid1\.tenancy\.') OR
     NOT REGEXP_LIKE(L_ADB_REGION,'^[a-z0-9]+(-[a-z0-9]+)+$') THEN
    RAISE_APPLICATION_ERROR(-20762,'ADB tenancy identity is unavailable');
  END IF;
  GET_BODY('https://identity.'||L_ADB_REGION||
    '.oci.oraclecloud.com/20160918/tenancies/'||L_TENANCY||
    '/regionSubscriptions',L_BODY);
  L_ITEMS:=JSON_ARRAY_T.PARSE(L_BODY);
  FOR I IN 0..L_ITEMS.GET_SIZE-1 LOOP
    L_ITEM:=TREAT(L_ITEMS.GET(I) AS JSON_OBJECT_T);
    IF L_ITEM.HAS('isHomeRegion') AND L_ITEM.GET_BOOLEAN('isHomeRegion') THEN
      IF L_HOME_REGION IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20762,'Multiple home regions returned');
      END IF;
      L_HOME_REGION:=LOWER(L_ITEM.GET_STRING('regionName'));
    END IF;
  END LOOP;
  IF NOT REGEXP_LIKE(L_HOME_REGION,'^[a-z0-9]+(-[a-z0-9]+)+$') THEN
    RAISE_APPLICATION_ERROR(-20762,'Tenancy home region is unavailable');
  END IF;
  GET_BODY('https://usage.'||L_HOME_REGION||'.oci.oraclecloud.com/20190111/budgets?compartmentId='||
    UTL_URL.ESCAPE(L_TENANCY,TRUE,'AL32UTF8')||'&targetType=ALL&limit=1',L_BODY);
  L_ITEMS:=RESPONSE_ITEMS(L_BODY);
  L_BUDGET_SAMPLE:=L_ITEMS.GET_SIZE;
  IF L_ITEMS.GET_SIZE>0 THEN
    L_ITEM:=TREAT(L_ITEMS.GET(0) AS JSON_OBJECT_T);
    L_BUDGET_ID:=L_ITEM.GET_STRING('id');
    IF L_BUDGET_ID IS NULL THEN
      RAISE_APPLICATION_ERROR(-20763,'Budget summary has no id');
    END IF;
    GET_BODY('https://usage.'||L_HOME_REGION||'.oci.oraclecloud.com/20190111/budgets/'||
      UTL_URL.ESCAPE(L_BUDGET_ID,TRUE,'AL32UTF8'),L_BODY);
    L_DOC:=JSON_OBJECT_T.PARSE(L_BODY);
    IF NOT L_DOC.HAS('id') OR L_DOC.GET_STRING('id')<>L_BUDGET_ID THEN
      RAISE_APPLICATION_ERROR(-20763,'Budget detail access or identity check failed');
    END IF;
    GET_BODY('https://usage.'||L_HOME_REGION||'.oci.oraclecloud.com/20190111/budgets/'||
      UTL_URL.ESCAPE(L_BUDGET_ID,TRUE,'AL32UTF8')||'/alertRules?limit=1',L_BODY);
    L_ITEMS:=RESPONSE_ITEMS(L_BODY);
  END IF;
  :source_tenancy_ocid:=L_TENANCY;
  :source_home_region:=L_HOME_REGION;
  DBMS_OUTPUT.PUT_LINE('OCI Budgets source preflight passed: home_region='||
    L_HOME_REGION||' visible_budgets_sample='||L_BUDGET_SAMPLE);
END;
