-- Provider-owned metadata; no OCI namespace or tag is created in the tenancy.
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE TABLE OCI_TAG_NAMESPACE (
  TAG_NAMESPACE_ID VARCHAR2(255) NOT NULL,
  NAMESPACE_NAME VARCHAR2(100) NOT NULL,
  DESCRIPTION VARCHAR2(400),
  LIFECYCLE_STATE VARCHAR2(30),
  IS_RETIRED VARCHAR2(5),
  OCI_TIME_CREATED VARCHAR2(40),
  OCI_TIME_UPDATED VARCHAR2(40),
  IS_CURRENT CHAR(1) DEFAULT 'Y' NOT NULL,
  FIRST_SEEN_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  LAST_SEEN_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  NO_LONGER_SEEN_AT TIMESTAMP(6) WITH TIME ZONE,
  CONSTRAINT OCI_TAG_NAMESPACE_PK PRIMARY KEY (TAG_NAMESPACE_ID),
  CONSTRAINT OCI_TAG_NAMESPACE_CURRENT_CK CHECK (IS_CURRENT IN ('Y','N'))
);

CREATE TABLE OCI_TAG_DEFINITION (
  TAG_NAMESPACE_ID VARCHAR2(255) NOT NULL,
  TAG_NAME VARCHAR2(100) NOT NULL,
  DESCRIPTION VARCHAR2(400),
  LIFECYCLE_STATE VARCHAR2(30),
  IS_RETIRED VARCHAR2(5),
  IS_COST_TRACKING VARCHAR2(5),
  OCI_TIME_CREATED VARCHAR2(40),
  OCI_TIME_UPDATED VARCHAR2(40),
  IS_CURRENT CHAR(1) DEFAULT 'Y' NOT NULL,
  FIRST_SEEN_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  LAST_SEEN_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  NO_LONGER_SEEN_AT TIMESTAMP(6) WITH TIME ZONE,
  CONSTRAINT OCI_TAG_DEFINITION_PK PRIMARY KEY (TAG_NAMESPACE_ID,TAG_NAME),
  CONSTRAINT OCI_TAG_DEFINITION_NS_FK FOREIGN KEY (TAG_NAMESPACE_ID)
    REFERENCES OCI_TAG_NAMESPACE (TAG_NAMESPACE_ID),
  CONSTRAINT OCI_TAG_DEFINITION_CURRENT_CK CHECK (IS_CURRENT IN ('Y','N'))
);
