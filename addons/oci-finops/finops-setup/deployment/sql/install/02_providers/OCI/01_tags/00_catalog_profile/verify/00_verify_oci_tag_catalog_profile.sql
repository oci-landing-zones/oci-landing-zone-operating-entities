-- Read-only installation gate. May also be rerun later by the operator.
SET ECHO OFF VERIFY OFF DEFINE OFF FEEDBACK ON SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 190 PAGESIZE 100
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

COLUMN OBJECT_NAME FORMAT A34
COLUMN OBJECT_TYPE FORMAT A18
COLUMN STATUS FORMAT A10
COLUMN JOB_NAME FORMAT A27
COLUMN ENABLED FORMAT A8
COLUMN REPEAT_INTERVAL FORMAT A60
COLUMN TAG_NAME FORMAT A24
COLUMN NAMESPACE_NAME FORMAT A24
COLUMN PROFILE_NAME FORMAT A36
COLUMN LOGICAL_TAG_NAME FORMAT A40
COLUMN PROFILE_VERSION FORMAT 99999999
COLUMN PROFILE_TAGS FORMAT 999999
COLUMN START_ZONE FORMAT A28
COLUMN NEXT_RUN FORMAT A30

PROMPT === OCI tag catalog objects ===
SELECT OBJECT_TYPE,OBJECT_NAME,STATUS FROM USER_OBJECTS
 WHERE OBJECT_NAME LIKE 'OCI_TAG_%'
 ORDER BY OBJECT_TYPE,OBJECT_NAME;

PROMPT === Catalog and optional governance profile ===
SELECT (SELECT COUNT(*) FROM OCI_TAG_NAMESPACE WHERE IS_CURRENT='Y')
         CURRENT_NAMESPACES,
       (SELECT COUNT(*) FROM OCI_TAG_DEFINITION WHERE IS_CURRENT='Y')
         CURRENT_DEFINED_TAGS,
       (SELECT COUNT(*) FROM OCI_TAG_PROFILE_ITEM I
         JOIN OCI_TAG_PROFILE P ON P.PROFILE_NAME=I.PROFILE_NAME
                               AND P.PROFILE_VERSION=I.PROFILE_VERSION
         WHERE I.PROFILE_NAME='DEFAULT_COST_GOVERNANCE'
           AND I.PROFILE_VERSION=(SELECT MAX(PROFILE_VERSION)
                                    FROM OCI_TAG_PROFILE
                                   WHERE PROFILE_NAME='DEFAULT_COST_GOVERNANCE')
           AND P.PROFILE_KIND='DEFAULT')
         DEFAULT_PROFILE_TAGS
FROM DUAL;

PROMPT === Active profile and its defined tags ===
SELECT S.PROFILE_NAME,S.PROFILE_VERSION,
       CASE WHEN P.TAG_NAMESPACE_ID IS NULL THEN 'MULTIPLE'
            ELSE N.NAMESPACE_NAME END NAMESPACE_NAME,
       COUNT(I.TAG_NAME) PROFILE_TAGS
  FROM OCI_TAG_PROFILE_SELECTION S JOIN OCI_TAG_PROFILE P
    ON P.PROFILE_NAME=S.PROFILE_NAME
   AND P.PROFILE_VERSION=S.PROFILE_VERSION
  LEFT JOIN OCI_TAG_NAMESPACE N ON N.TAG_NAMESPACE_ID=P.TAG_NAMESPACE_ID
  JOIN OCI_TAG_PROFILE_ITEM I
    ON I.PROFILE_NAME=S.PROFILE_NAME
   AND I.PROFILE_VERSION=S.PROFILE_VERSION
 WHERE S.SELECTION_ID=1
 GROUP BY S.PROFILE_NAME,S.PROFILE_VERSION,P.TAG_NAMESPACE_ID,N.NAMESPACE_NAME;

SELECT I.DISPLAY_ORDER,N.NAMESPACE_NAME,I.TAG_NAME,I.LOGICAL_TAG_NAME
  FROM OCI_TAG_PROFILE_SELECTION S JOIN OCI_TAG_PROFILE_ITEM I
    ON I.PROFILE_NAME=S.PROFILE_NAME
   AND I.PROFILE_VERSION=S.PROFILE_VERSION
  JOIN OCI_TAG_NAMESPACE N ON N.TAG_NAMESPACE_ID=I.TAG_NAMESPACE_ID
 WHERE S.SELECTION_ID=1
 ORDER BY I.DISPLAY_ORDER;

PROMPT === Catalog schedule ===
SELECT JOB_NAME,ENABLED,REPEAT_INTERVAL,
       TO_CHAR(START_DATE,'YYYY-MM-DD HH24:MI TZR') START_ZONE,
       TO_CHAR(NEXT_RUN_DATE,'YYYY-MM-DD HH24:MI TZR') NEXT_RUN
  FROM USER_SCHEDULER_JOBS
 WHERE JOB_NAME='OCI_TAG_CATALOG_DAILY';

DECLARE
  L_TABLES NUMBER;
  L_CODE NUMBER;
  L_INVALID NUMBER;
  L_NAMESPACES NUMBER;
  L_DEFINITIONS NUMBER;
  L_PROFILE NUMBER;
  L_PROFILE_ITEMS NUMBER;
  L_SELECTION NUMBER;
  L_ACTIVE_ITEMS NUMBER;
  L_DEFAULT_NAMESPACE NUMBER;
  L_DEFAULT_VERSION NUMBER;
  L_JOB VARCHAR2(5);
  L_INTERVAL VARCHAR2(200);
  L_BRIDGE NUMBER;
BEGIN
  SELECT COUNT(*) INTO L_TABLES FROM USER_TABLES
   WHERE TABLE_NAME IN ('OCI_TAG_NAMESPACE','OCI_TAG_DEFINITION',
                        'OCI_TAG_PROFILE','OCI_TAG_PROFILE_ITEM',
                        'OCI_TAG_PROFILE_SELECTION');
  SELECT COUNT(*) INTO L_CODE FROM USER_OBJECTS
   WHERE (OBJECT_NAME='OCI_TAG_SYNC_CATALOG' AND OBJECT_TYPE='PROCEDURE'
      OR OBJECT_NAME='OCI_TAG_PROFILE_API'
         AND OBJECT_TYPE IN ('PACKAGE','PACKAGE BODY'))
     AND STATUS='VALID';
  SELECT COUNT(*) INTO L_INVALID FROM USER_OBJECTS
   WHERE OBJECT_NAME IN ('OCI_TAG_NAMESPACE','OCI_TAG_DEFINITION',
     'OCI_TAG_PROFILE','OCI_TAG_PROFILE_ITEM',
     'OCI_TAG_PROFILE_SELECTION','OCI_TAG_SYNC_CATALOG',
     'OCI_TAG_PROFILE_API','OCI_TAG_CATALOG_DAILY')
     AND STATUS <> 'VALID';
  SELECT COUNT(*) INTO L_NAMESPACES FROM OCI_TAG_NAMESPACE
   WHERE IS_CURRENT='Y';
  SELECT COUNT(*) INTO L_DEFINITIONS FROM OCI_TAG_DEFINITION
   WHERE IS_CURRENT='Y';
  SELECT NVL(MAX(PROFILE_VERSION),0) INTO L_DEFAULT_VERSION
    FROM OCI_TAG_PROFILE
   WHERE PROFILE_NAME='DEFAULT_COST_GOVERNANCE';
  SELECT COUNT(*) INTO L_PROFILE
    FROM OCI_TAG_PROFILE P JOIN OCI_TAG_NAMESPACE N
      ON N.TAG_NAMESPACE_ID=P.TAG_NAMESPACE_ID
   WHERE P.PROFILE_NAME='DEFAULT_COST_GOVERNANCE'
     AND P.PROFILE_VERSION=L_DEFAULT_VERSION
     AND P.PROFILE_KIND='DEFAULT'
     AND N.NAMESPACE_NAME='tagns-lz-cost-governance';
  SELECT COUNT(*) INTO L_PROFILE_ITEMS FROM OCI_TAG_PROFILE_ITEM
   WHERE PROFILE_NAME='DEFAULT_COST_GOVERNANCE'
     AND PROFILE_VERSION=L_DEFAULT_VERSION;
  SELECT COUNT(*) INTO L_DEFAULT_NAMESPACE
    FROM OCI_TAG_PROFILE_ITEM I JOIN OCI_TAG_DEFINITION D
      ON D.TAG_NAMESPACE_ID=I.TAG_NAMESPACE_ID AND D.TAG_NAME=I.TAG_NAME
    JOIN OCI_TAG_NAMESPACE N ON N.TAG_NAMESPACE_ID=I.TAG_NAMESPACE_ID
   WHERE I.PROFILE_NAME='DEFAULT_COST_GOVERNANCE'
     AND I.PROFILE_VERSION=L_DEFAULT_VERSION
     AND N.NAMESPACE_NAME='tagns-lz-cost-governance'
     AND D.IS_CURRENT='Y' AND D.LIFECYCLE_STATE='ACTIVE';
  SELECT COUNT(*) INTO L_SELECTION FROM OCI_TAG_PROFILE_SELECTION
   WHERE SELECTION_ID=1;
  SELECT COUNT(*) INTO L_ACTIVE_ITEMS FROM OCI_TAG_PROFILE_SELECTION S
   JOIN OCI_TAG_PROFILE_ITEM I ON I.PROFILE_NAME=S.PROFILE_NAME
     AND I.PROFILE_VERSION=S.PROFILE_VERSION
   WHERE S.SELECTION_ID=1;
  SELECT ENABLED,REPEAT_INTERVAL INTO L_JOB,L_INTERVAL
    FROM USER_SCHEDULER_JOBS
   WHERE JOB_NAME='OCI_TAG_CATALOG_DAILY';
  SELECT COUNT(*) INTO L_BRIDGE FROM USER_TABLES
   WHERE TABLE_NAME IN ('OCI_TAG_VALUE','OCI_TAG_ROW_PROCESSING');
  DBMS_OUTPUT.PUT_LINE('tables=' || L_TABLES || ' valid_code=' ||
    L_CODE || ' invalid=' || L_INVALID);
  DBMS_OUTPUT.PUT_LINE('current_namespaces=' || L_NAMESPACES ||
    ' current_defined_tags=' || L_DEFINITIONS ||
    ' default_profile_version=' || L_DEFAULT_VERSION ||
    ' default_profile_tags=' || L_PROFILE_ITEMS ||
    ' default_lz_tags=' || L_DEFAULT_NAMESPACE ||
    ' active_profile_tags=' || L_ACTIVE_ITEMS);
  DBMS_OUTPUT.PUT_LINE('daily_job_enabled=' || L_JOB ||
    ' row_extraction_tables=' || L_BRIDGE);
  IF L_TABLES <> 5 OR L_CODE <> 3 OR L_INVALID <> 0 OR
     L_NAMESPACES < 1 OR L_DEFINITIONS < 1 OR L_SELECTION <> 1 OR
     L_ACTIVE_ITEMS < 1 OR L_JOB <> 'TRUE' OR
     L_INTERVAL <> 'FREQ=DAILY;BYHOUR=00;BYMINUTE=00;BYSECOND=00' THEN
    RAISE_APPLICATION_ERROR(-20950,
      'OCI tag catalog/profile verification failed');
  END IF;
  DBMS_OUTPUT.PUT_LINE('OCI TAG CATALOG AND PROFILE VERIFICATION PASS');
END;
