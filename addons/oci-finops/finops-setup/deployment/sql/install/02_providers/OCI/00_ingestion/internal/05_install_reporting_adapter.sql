CREATE OR REPLACE PACKAGE OCI_FOCUS_CORE_API AUTHID DEFINER AS
  PROCEDURE RUN(
    P_CORE_RUN_ID IN NUMBER,
    P_MAX_FILES_PER_PIPELINE IN NUMBER
  );
  FUNCTION REPORT RETURN CLOB;
END OCI_FOCUS_CORE_API;
/

CREATE OR REPLACE PACKAGE BODY OCI_FOCUS_CORE_API AS
  PROCEDURE RUN(
    P_CORE_RUN_ID IN NUMBER,
    P_MAX_FILES_PER_PIPELINE IN NUMBER
  ) IS
    L_STARTED_AT TIMESTAMP WITH TIME ZONE;
    L_GENERATION NUMBER;
    L_FULL NUMBER;
    L_PARTIAL NUMBER;
    L_FILE_ERROR NUMBER;
    L_QUEUED NUMBER;
    L_OPEN_ERROR NUMBER;
    L_MANUAL_PENDING NUMBER;
    L_ERROR_MESSAGE VARCHAR2(4000);
  BEGIN
    IF P_MAX_FILES_PER_PIPELINE IS NULL OR
       P_MAX_FILES_PER_PIPELINE NOT BETWEEN 1 AND 2000 THEN
      RAISE_APPLICATION_ERROR(-20950,
        'OCI per-pipeline file limit must be between 1 and 2000');
    END IF;
    SELECT STARTED_AT INTO L_STARTED_AT
      FROM FINOPS_CORE_PROVIDER_RUN
     WHERE RUN_ID = P_CORE_RUN_ID AND PROVIDER_CODE = 'OCI';
    OCI_FOCUS_REMED_MUTEX.ENTER;

    -- Register every approved pipeline before starting any remediation. The
    -- complete failure scan is then performed across all pipelines first.
    FOR P IN (
      SELECT P.PIPELINE_NAME, P.STATUS AS PIPELINE_STATUS,
             P.OPERATION_ID, P.STATUS_TABLE,
             UPPER(TRIM(DBMS_LOB.SUBSTR(A.ATTRIBUTE_VALUE, 128, 1)))
               AS TARGET_TABLE
        FROM USER_CLOUD_PIPELINES P
        JOIN USER_CLOUD_PIPELINE_ATTRIBUTES A
          ON A.PIPELINE_NAME = P.PIPELINE_NAME
         AND A.ATTRIBUTE_NAME = 'table_name'
        JOIN OCI_FOCUS_REMED_TARGET_CONFIG T
          ON T.TARGET_TABLE =
             UPPER(TRIM(DBMS_LOB.SUBSTR(A.ATTRIBUTE_VALUE, 128, 1)))
         AND T.ENABLED = 'Y'
       WHERE P.PIPELINE_TYPE = 'LOAD'
       ORDER BY P.PIPELINE_NAME
    ) LOOP
      INSERT INTO FINOPS_CORE_PIPELINE_RUN
        (RUN_ID, PROVIDER_CODE, PIPELINE_NAME, LANDING_TABLE,
         PIPELINE_STATUS, PROCESS_STATUS)
      VALUES
        (P_CORE_RUN_ID, 'OCI', P.PIPELINE_NAME, P.TARGET_TABLE,
         P.PIPELINE_STATUS, 'SKIPPED');
      COMMIT;
      IF P.OPERATION_ID IS NULL OR P.STATUS_TABLE IS NULL THEN
        UPDATE FINOPS_CORE_PIPELINE_RUN
           SET ERROR_MESSAGE = 'Awaiting initial Oracle pipeline status table'
         WHERE RUN_ID = P_CORE_RUN_ID AND PROVIDER_CODE = 'OCI'
           AND PIPELINE_NAME = P.PIPELINE_NAME;
        COMMIT;
        CONTINUE;
      END IF;
      BEGIN
        OCI_FOCUS_DISCOVER_FAILURES(
          P_PIPELINE_NAME => P.PIPELINE_NAME,
          P_OVERLAP_MINUTES => 1440,
          P_SETTLE_MINUTES => 0);
      EXCEPTION WHEN OTHERS THEN
        L_ERROR_MESSAGE := SUBSTR(SQLERRM, 1, 4000);
        ROLLBACK;
        UPDATE FINOPS_CORE_PIPELINE_RUN
           SET PROCESS_STATUS = 'ERROR', ERROR_MESSAGE = L_ERROR_MESSAGE
         WHERE RUN_ID = P_CORE_RUN_ID AND PROVIDER_CODE = 'OCI'
           AND PIPELINE_NAME = P.PIPELINE_NAME;
        COMMIT;
      END;
    END LOOP;

    -- Recovery uses the same shared stage and lock as normal processing.
    OCI_FOCUS_RECOVER_ACTIVE_FILE;

    FOR P IN (
      SELECT PIPELINE_NAME
        FROM FINOPS_CORE_PIPELINE_RUN
       WHERE RUN_ID = P_CORE_RUN_ID AND PROVIDER_CODE = 'OCI'
         AND PROCESS_STATUS = 'SKIPPED'
         AND ERROR_MESSAGE IS NULL
       ORDER BY PIPELINE_NAME
    ) LOOP
      BEGIN
        SELECT GENERATION_NO INTO L_GENERATION
          FROM OCI_FOCUS_FAIL_SCAN_CURSOR
         WHERE PIPELINE_NAME = P.PIPELINE_NAME;
        SELECT NVL(SUM(FILES_FULL), 0), NVL(SUM(FILES_PARTIAL), 0),
               NVL(SUM(FILES_ERROR), 0)
          INTO L_FULL, L_PARTIAL, L_FILE_ERROR
          FROM OCI_FOCUS_REMED_RUN
         WHERE PIPELINE_NAME = P.PIPELINE_NAME
           AND STARTED_AT >= L_STARTED_AT;
        IF L_FULL + L_PARTIAL + L_FILE_ERROR < P_MAX_FILES_PER_PIPELINE THEN
          OCI_FOCUS_REMEDIATE_FILES(
            P.PIPELINE_NAME,
            P_MAX_FILES_PER_PIPELINE - L_FULL - L_PARTIAL - L_FILE_ERROR);
        END IF;
        SELECT NVL(SUM(FILES_FULL), 0), NVL(SUM(FILES_PARTIAL), 0),
               NVL(SUM(FILES_ERROR), 0)
          INTO L_FULL, L_PARTIAL, L_FILE_ERROR
          FROM OCI_FOCUS_REMED_RUN
         WHERE PIPELINE_NAME = P.PIPELINE_NAME
           AND STARTED_AT >= L_STARTED_AT;
        SELECT COUNT(*) INTO L_QUEUED FROM OCI_FOCUS_FAIL_FILE
         WHERE PIPELINE_NAME = P.PIPELINE_NAME
           AND GENERATION_NO = L_GENERATION AND FILE_STATE = 'NEW';
        SELECT COUNT(*) INTO L_OPEN_ERROR FROM OCI_FOCUS_FAIL_FILE
         WHERE PIPELINE_NAME = P.PIPELINE_NAME
           AND GENERATION_NO = L_GENERATION AND FILE_STATE = 'ERROR';
        SELECT COUNT(*) INTO L_MANUAL_PENDING FROM OCI_FOCUS_REMED_MANUAL
         WHERE PIPELINE_NAME = P.PIPELINE_NAME
           AND RESOLUTION_STATUS = 'PENDING';
        UPDATE FINOPS_CORE_PIPELINE_RUN
           SET PROCESS_STATUS = 'COMPLETE', FILES_FULL = L_FULL,
               FILES_PARTIAL = L_PARTIAL, FILES_ERROR = L_FILE_ERROR,
               QUEUED_AFTER = L_QUEUED, OPEN_FILE_ERRORS = L_OPEN_ERROR,
               MANUAL_PENDING_ROWS = L_MANUAL_PENDING,
               LIMIT_REACHED = CASE
                 WHEN L_FULL + L_PARTIAL + L_FILE_ERROR >=
                      P_MAX_FILES_PER_PIPELINE THEN 'Y' ELSE 'N' END
         WHERE RUN_ID = P_CORE_RUN_ID AND PROVIDER_CODE = 'OCI'
           AND PIPELINE_NAME = P.PIPELINE_NAME;
        COMMIT;
      EXCEPTION WHEN OTHERS THEN
        L_ERROR_MESSAGE := SUBSTR(SQLERRM, 1, 4000);
        ROLLBACK;
        UPDATE FINOPS_CORE_PIPELINE_RUN
           SET PROCESS_STATUS = 'ERROR', ERROR_MESSAGE = L_ERROR_MESSAGE
         WHERE RUN_ID = P_CORE_RUN_ID AND PROVIDER_CODE = 'OCI'
           AND PIPELINE_NAME = P.PIPELINE_NAME;
        COMMIT;
      END;
    END LOOP;
    OCI_FOCUS_REMED_MUTEX.LEAVE;
  EXCEPTION WHEN OTHERS THEN
    OCI_FOCUS_REMED_MUTEX.LEAVE;
    RAISE;
  END RUN;

  FUNCTION REPORT RETURN CLOB IS
    L_REPORT CLOB;
    L_RETENTION_STATUS VARCHAR2(16);
    L_RETENTION_MESSAGE VARCHAR2(4000);
    L_RETENTION_ROWS NUMBER;
  BEGIN
    OCI_FOCUS_GET_INGESTION_REPORT(L_REPORT);
    BEGIN
      SELECT STATUS,MESSAGE,ROWS_DELETED INTO L_RETENTION_STATUS,L_RETENTION_MESSAGE,L_RETENTION_ROWS
        FROM OCI_FOCUS_RETENTION_RUN ORDER BY RUN_ID DESC FETCH FIRST 1 ROW ONLY;
      L_REPORT:=L_REPORT||CHR(10)||'Latest optional retention: '||L_RETENTION_STATUS||
        '; rows_deleted='||L_RETENTION_ROWS||'; '||L_RETENTION_MESSAGE;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      L_REPORT:=L_REPORT||CHR(10)||'Optional retention has not run (monthly job disabled by default).';
    END;
    RETURN L_REPORT;
  END REPORT;
END OCI_FOCUS_CORE_API;
