-- Report pipeline, failed-file, and manual-review state on demand.
SET DEFINE OFF
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

CREATE OR REPLACE PROCEDURE OCI_FOCUS_GET_INGESTION_REPORT (
  P_REPORT OUT CLOB,
  P_SINCE IN TIMESTAMP WITH TIME ZONE DEFAULT NULL
) AUTHID CURRENT_USER IS
  L_SINCE TIMESTAMP WITH TIME ZONE :=
    COALESCE(P_SINCE, SYSTIMESTAMP - INTERVAL '1' DAY);
  L_PIPELINES NUMBER := 0;
  L_GENERATION NUMBER;
  L_COMPLETED NUMBER;
  L_FAILED NUMBER;
  L_OTHER NUMBER;
  L_NEW NUMBER;
  L_ACTIVE NUMBER;
  L_FULL NUMBER;
  L_PARTIAL NUMBER;
  L_ERROR NUMBER;
  L_TODAY_FULL NUMBER;
  L_TODAY_PARTIAL NUMBER;
  L_TODAY_ERROR NUMBER;
  L_PENDING_MANUAL NUMBER;
  L_STATUS_NOTE VARCHAR2(300);
  L_LAST_RUN_STATUS VARCHAR2(30);
  L_HAS_RESOLUTION NUMBER;
  L_MANUAL_FILTER VARCHAR2(100);
  L_MANUAL_CURSOR SYS_REFCURSOR;
  L_MANUAL_ID NUMBER;
  L_MANUAL_PIPELINE VARCHAR2(128);

  PROCEDURE ADD_LINE(P_TEXT VARCHAR2) IS
  BEGIN
    DBMS_LOB.APPEND(P_REPORT, TO_CLOB(P_TEXT || CHR(10)));
  END;
BEGIN
  DBMS_LOB.CREATETEMPORARY(P_REPORT, TRUE);
  SELECT COUNT(*) INTO L_HAS_RESOLUTION
    FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'OCI_FOCUS_REMED_MANUAL'
     AND COLUMN_NAME = 'RESOLUTION_STATUS';
  L_MANUAL_FILTER := CASE WHEN L_HAS_RESOLUTION = 1
    THEN ' WHERE RESOLUTION_STATUS = ''PENDING'''
    ELSE '' END;
  ADD_LINE('FOCUS ingestion and remediation report');
  ADD_LINE('Generated UTC: ' ||
    TO_CHAR(SYSTIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS TZR'));
  ADD_LINE('Remediation activity since UTC: ' ||
    TO_CHAR(L_SINCE AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS TZR'));
  ADD_LINE('Oracle file counts are cumulative for each current status table.');
  ADD_LINE('An Oracle FAILED file may already be FULL/PARTIAL in our remediation ledger.');
  ADD_LINE('');

  FOR P IN (
    SELECT P.PIPELINE_NAME, P.STATUS, P.STATUS_TABLE,
           UPPER(TRIM(DBMS_LOB.SUBSTR(A.ATTRIBUTE_VALUE, 128, 1))) TARGET_TABLE
      FROM USER_CLOUD_PIPELINES P
      JOIN USER_CLOUD_PIPELINE_ATTRIBUTES A
        ON A.PIPELINE_NAME = P.PIPELINE_NAME
       AND A.ATTRIBUTE_NAME = 'table_name'
      JOIN OCI_FOCUS_REMED_TARGET_CONFIG T
        ON T.TARGET_TABLE =
           UPPER(TRIM(DBMS_LOB.SUBSTR(A.ATTRIBUTE_VALUE, 128, 1)))
       AND T.ENABLED = 'Y'
     WHERE P.PIPELINE_TYPE = 'LOAD'
     ORDER BY T.TARGET_TABLE, P.PIPELINE_NAME
  ) LOOP
    L_PIPELINES := L_PIPELINES + 1;
    L_COMPLETED := 0;
    L_FAILED := 0;
    L_OTHER := 0;
    L_NEW := 0;
    L_ACTIVE := 0;
    L_FULL := 0;
    L_PARTIAL := 0;
    L_ERROR := 0;
    L_TODAY_FULL := 0;
    L_TODAY_PARTIAL := 0;
    L_TODAY_ERROR := 0;
    L_PENDING_MANUAL := 0;
    L_GENERATION := NULL;
    L_STATUS_NOTE := NULL;
    L_LAST_RUN_STATUS := '-';

    BEGIN
      SELECT STATUS INTO L_LAST_RUN_STATUS
        FROM (
          SELECT STATUS FROM USER_CLOUD_PIPELINE_HISTORY
           WHERE PIPELINE_NAME = P.PIPELINE_NAME
           ORDER BY START_DATE DESC
        ) WHERE ROWNUM = 1;
    EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
    END;

    IF P.STATUS_TABLE IS NOT NULL THEN
      BEGIN
        EXECUTE IMMEDIATE
          'SELECT NVL(SUM(CASE WHEN STATUS = ''COMPLETED'' THEN 1 ELSE 0 END), 0),' ||
          ' NVL(SUM(CASE WHEN STATUS = ''FAILED'' THEN 1 ELSE 0 END), 0),' ||
          ' NVL(SUM(CASE WHEN STATUS NOT IN (''COMPLETED'', ''FAILED'')' ||
          ' THEN 1 ELSE 0 END), 0) FROM ' ||
          DBMS_ASSERT.SIMPLE_SQL_NAME(P.STATUS_TABLE)
          INTO L_COMPLETED, L_FAILED, L_OTHER;
      EXCEPTION WHEN OTHERS THEN
        L_STATUS_NOTE := SUBSTR(SQLERRM, 1, 250);
      END;
    ELSE
      L_STATUS_NOTE := 'no status table';
    END IF;

    BEGIN
      SELECT GENERATION_NO INTO L_GENERATION
        FROM OCI_FOCUS_FAIL_SCAN_CURSOR
       WHERE PIPELINE_NAME = P.PIPELINE_NAME;
    EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
    END;

    IF L_GENERATION IS NOT NULL THEN
      SELECT NVL(SUM(CASE WHEN FILE_STATE = 'NEW' THEN 1 ELSE 0 END), 0),
             NVL(SUM(CASE WHEN FILE_STATE = 'IN_PROGRESS' THEN 1 ELSE 0 END), 0),
             NVL(SUM(CASE WHEN FILE_STATE = 'FULL' THEN 1 ELSE 0 END), 0),
             NVL(SUM(CASE WHEN FILE_STATE = 'PARTIAL' THEN 1 ELSE 0 END), 0),
             NVL(SUM(CASE WHEN FILE_STATE = 'ERROR' THEN 1 ELSE 0 END), 0)
        INTO L_NEW, L_ACTIVE, L_FULL, L_PARTIAL, L_ERROR
        FROM OCI_FOCUS_FAIL_FILE
       WHERE PIPELINE_NAME = P.PIPELINE_NAME
         AND GENERATION_NO = L_GENERATION;
    END IF;

    SELECT NVL(SUM(FILES_FULL), 0), NVL(SUM(FILES_PARTIAL), 0),
           NVL(SUM(FILES_ERROR), 0)
      INTO L_TODAY_FULL, L_TODAY_PARTIAL, L_TODAY_ERROR
      FROM OCI_FOCUS_REMED_RUN
     WHERE PIPELINE_NAME = P.PIPELINE_NAME
       AND STARTED_AT >= L_SINCE;

    IF L_HAS_RESOLUTION = 1 THEN
      EXECUTE IMMEDIATE
        'SELECT COUNT(*) FROM OCI_FOCUS_REMED_MANUAL' || L_MANUAL_FILTER ||
        ' AND PIPELINE_NAME = :pipeline'
        INTO L_PENDING_MANUAL USING P.PIPELINE_NAME;
    ELSE
      SELECT COUNT(*) INTO L_PENDING_MANUAL
        FROM OCI_FOCUS_REMED_MANUAL
       WHERE PIPELINE_NAME = P.PIPELINE_NAME;
    END IF;

    ADD_LINE(P.PIPELINE_NAME || ' | target=' || P.TARGET_TABLE ||
      ' | pipeline=' || P.STATUS ||
      ' last_run=' || L_LAST_RUN_STATUS ||
      ' | Oracle completed=' || L_COMPLETED ||
      ' failed=' || L_FAILED || ' other=' || L_OTHER ||
      ' | remediation generation=' || NVL(TO_CHAR(L_GENERATION), '-') ||
      ' queued=' || L_NEW || ' active=' || L_ACTIVE ||
      ' full=' || L_FULL || ' partial=' || L_PARTIAL ||
      ' error=' || L_ERROR ||
      ' | since cutoff full=' || L_TODAY_FULL ||
      ' partial=' || L_TODAY_PARTIAL || ' error=' || L_TODAY_ERROR ||
      ' | manual pending=' || L_PENDING_MANUAL ||
      CASE WHEN L_STATUS_NOTE IS NULL THEN ''
           ELSE ' | status read error=' || L_STATUS_NOTE END);
  END LOOP;

  ADD_LINE('');
  ADD_LINE('Authorized-target pipelines: ' || L_PIPELINES);
  SELECT COUNT(ROWID) INTO L_ACTIVE FROM OCI_FOCUS_REMED_STAGE;
  ADD_LINE('Rows remaining in shared stage: ' || L_ACTIVE);
  SELECT COUNT(*) INTO L_ERROR
    FROM OCI_FOCUS_FAIL_FILE Q WHERE Q.FILE_STATE = 'ERROR';
  ADD_LINE('Files in terminal ERROR across all generations: ' || L_ERROR);
  IF L_ERROR > 0 THEN
    ADD_LINE('First files in ERROR (full list and causes remain in ADB):');
    FOR E IN (
      SELECT Q.PIPELINE_NAME, Q.GENERATION_NO,
             SUBSTR(Q.SOURCE_NAME, 1, 250) SOURCE_NAME,
             SUBSTR(COALESCE(R.ERROR_MESSAGE, Q.ERROR_MESSAGE), 1, 250)
               ERROR_MESSAGE
        FROM OCI_FOCUS_FAIL_FILE Q
        LEFT JOIN OCI_FOCUS_REMED_FILE R
          ON R.PIPELINE_NAME = Q.PIPELINE_NAME
         AND R.GENERATION_NO = Q.GENERATION_NO
         AND R.SOURCE_NAME_HASH = Q.SOURCE_NAME_HASH
       WHERE Q.FILE_STATE = 'ERROR'
       ORDER BY Q.FIRST_SEEN_AT, Q.PIPELINE_NAME
       FETCH FIRST 10 ROWS ONLY
    ) LOOP
      ADD_LINE('  ' || E.PIPELINE_NAME || ' | generation=' ||
        E.GENERATION_NO || ' | ' || E.SOURCE_NAME ||
        ' | error=' || NVL(E.ERROR_MESSAGE, '-'));
    END LOOP;
    ADD_LINE('Full ERROR list: SELECT Q.*, R.ERROR_MESSAGE REMEDIATION_ERROR'
      || ' FROM OCI_FOCUS_FAIL_FILE Q LEFT JOIN OCI_FOCUS_REMED_FILE R'
      || ' ON R.PIPELINE_NAME=Q.PIPELINE_NAME'
      || ' AND R.GENERATION_NO=Q.GENERATION_NO'
      || ' AND R.SOURCE_NAME_HASH=Q.SOURCE_NAME_HASH'
      || ' WHERE Q.FILE_STATE=''ERROR'';');
  END IF;
  EXECUTE IMMEDIATE
    'SELECT COUNT(*) FROM OCI_FOCUS_REMED_MANUAL' || L_MANUAL_FILTER
    INTO L_PENDING_MANUAL;
  ADD_LINE('Manual rows pending across all generations: ' || L_PENDING_MANUAL);
  IF L_PENDING_MANUAL > 0 THEN
    ADD_LINE('First pending MANUAL_ID values (complete list is in ADB):');
    OPEN L_MANUAL_CURSOR FOR
      'SELECT MANUAL_ID, PIPELINE_NAME FROM OCI_FOCUS_REMED_MANUAL' ||
      L_MANUAL_FILTER ||
      ' ORDER BY CREATED_AT, MANUAL_ID FETCH FIRST 30 ROWS ONLY';
    LOOP
      FETCH L_MANUAL_CURSOR INTO L_MANUAL_ID, L_MANUAL_PIPELINE;
      EXIT WHEN L_MANUAL_CURSOR%NOTFOUND;
      ADD_LINE('  ' || L_MANUAL_ID || ' | ' || L_MANUAL_PIPELINE);
    END LOOP;
    CLOSE L_MANUAL_CURSOR;
  END IF;
  ADD_LINE('');
  ADD_LINE('Full manual queue: SELECT * FROM OCI_FOCUS_REMED_MANUAL' ||
    L_MANUAL_FILTER || ' ORDER BY CREATED_AT, MANUAL_ID;');
END;
