-- OCI-owned optional execution: installed with ingestion; never enabled here.
SET DEFINE OFF SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE N NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'FOCUSPLATFORM' THEN
    RAISE_APPLICATION_ERROR(-20946,'Connect as FOCUSPLATFORM to install retention');
  END IF;
  SELECT COUNT(*) INTO N FROM USER_TABLES WHERE TABLE_NAME='OCI_FOCUS_REPORTS';
  IF N<>1 THEN RAISE_APPLICATION_ERROR(-20946,'Install the OCI landing table first'); END IF;
  SELECT COUNT(*) INTO N FROM USER_OBJECTS WHERE OBJECT_NAME='FINOPS_CORE_SCHEDULE_API'
    AND OBJECT_TYPE IN ('PACKAGE','PACKAGE BODY') AND STATUS='VALID';
  IF N<>2 THEN RAISE_APPLICATION_ERROR(-20946,'Install the valid common-core schedule API first'); END IF;
  SELECT COUNT(*) INTO N FROM USER_OBJECTS WHERE OBJECT_NAME LIKE 'OCI_FOCUS_RETENTION%';
  IF N>0 THEN RAISE_APPLICATION_ERROR(-20946,'Retention objects already exist; inspect before retrying this create-only script'); END IF;
END;
/
CREATE TABLE OCI_FOCUS_RETENTION_CONFIG (
  CONFIG_ID NUMBER(1) PRIMARY KEY CHECK (CONFIG_ID=1),
  KEEP_MONTHS NUMBER DEFAULT 24 NOT NULL
    CHECK (KEEP_MONTHS>=12 AND KEEP_MONTHS=TRUNC(KEEP_MONTHS))
);
INSERT INTO OCI_FOCUS_RETENTION_CONFIG VALUES (1,24);
CREATE TABLE OCI_FOCUS_RETENTION_RUN (
  RUN_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  STARTED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  FINISHED_AT TIMESTAMP WITH TIME ZONE,
  KEEP_MONTHS NUMBER NOT NULL,
  CUTOFF_UTC TIMESTAMP(6) NOT NULL,
  PREVIEW_ONLY NUMBER(1) NOT NULL CHECK (PREVIEW_ONLY IN (0,1)),
  STATUS VARCHAR2(16) NOT NULL CHECK
    (STATUS IN ('RUNNING','PREVIEW','COMPLETED','NO_DATA','BLOCKED','FAILED')),
  ROWS_ELIGIBLE NUMBER DEFAULT 0 NOT NULL,
  ROWS_DELETED NUMBER DEFAULT 0 NOT NULL,
  MESSAGE VARCHAR2(4000)
);
CREATE TABLE OCI_FOCUS_RETENTION_MONTH (
  RUN_ID NUMBER REFERENCES OCI_FOCUS_RETENTION_RUN(RUN_ID),
  MONTH_START_UTC DATE NOT NULL,
  ROWS_ELIGIBLE NUMBER NOT NULL,
  ROWS_DELETED NUMBER DEFAULT 0 NOT NULL,
  COMMITTED_AT TIMESTAMP WITH TIME ZONE,
  PRIMARY KEY (RUN_ID,MONTH_START_UTC)
);
COMMIT;

CREATE OR REPLACE PACKAGE OCI_FOCUS_RETENTION_API AUTHID DEFINER AS
  PROCEDURE SET_POLICY(P_KEEP_MONTHS NUMBER);
  PROCEDURE RUN(P_KEEP_MONTHS NUMBER DEFAULT NULL, P_PREVIEW_ONLY NUMBER DEFAULT 1);
  PROCEDURE RUN_SCHEDULED;
END;
/
CREATE OR REPLACE PACKAGE BODY OCI_FOCUS_RETENTION_API AS
  PROCEDURE CHECK_MONTHS(P_MONTHS NUMBER) IS
  BEGIN
    IF P_MONTHS IS NULL OR P_MONTHS<>TRUNC(P_MONTHS) OR P_MONTHS<12 THEN
      RAISE_APPLICATION_ERROR(-20945,'Retention requires at least 12 complete months plus the current month');
    END IF;
  END;

  PROCEDURE SET_POLICY(P_KEEP_MONTHS NUMBER) IS
    PRAGMA AUTONOMOUS_TRANSACTION;
  BEGIN
    CHECK_MONTHS(P_KEEP_MONTHS);
    UPDATE OCI_FOCUS_RETENTION_CONFIG SET KEEP_MONTHS=P_KEEP_MONTHS WHERE CONFIG_ID=1;
    COMMIT;
  END;

  PROCEDURE RUN(P_KEEP_MONTHS NUMBER DEFAULT NULL, P_PREVIEW_ONLY NUMBER DEFAULT 1) IS
    -- Commits belong only to retention, never to the calling application.
    PRAGMA AUTONOMOUS_TRANSACTION;
    L_KEEP NUMBER;
    L_TODAY DATE := CAST(SYS_EXTRACT_UTC(SYSTIMESTAMP) AS DATE);
    L_CUTOFF TIMESTAMP(6);
    L_YEAR_START TIMESTAMP(6);
    L_RUN NUMBER;
    L_LOCK_ID NUMBER := DBMS_UTILITY.GET_HASH_VALUE('OCI_FOCUS_RETENTION',0,1073741823);
    L_LOCK_RESULT NUMBER;
    L_LOCKED BOOLEAN := FALSE;
    L_MV VARCHAR2(128);
    L_CAP NUMBER;
    L_COUNT NUMBER;
    L_DELETED NUMBER;
    L_ERROR VARCHAR2(4000);
    L_ERROR_STATUS VARCHAR2(16) := 'FAILED';
    L_BLOCKERS VARCHAR2(4000);
    PROCEDURE CHECK_PIPELINES IS
      L_N NUMBER := 0;
    BEGIN
      L_BLOCKERS:=NULL;
      FOR P IN (
        SELECT PIPELINE_NAME,STATUS FROM USER_CLOUD_PIPELINES P
         WHERE REGEXP_LIKE(PIPELINE_NAME,'^OCI_FOCUS_REPORTS_LOAD_[0-9]{4}$')
           AND (NVL(STATUS,'UNKNOWN')<>'STOPPED' OR EXISTS (
             SELECT 1 FROM USER_CLOUD_PIPELINE_HISTORY H
              WHERE H.PIPELINE_NAME=P.PIPELINE_NAME AND H.STATUS='RUNNING' AND H.END_DATE IS NULL))
           AND EXISTS (
             SELECT 1 FROM OCI_FOCUS_REPORTS F
              WHERE F.CHARGEPERIODSTART<L_CUTOFF
                AND TO_CHAR(F.CHARGEPERIODSTART,'YYYY')=SUBSTR(P.PIPELINE_NAME,-4))
         ORDER BY PIPELINE_NAME
      ) LOOP
        L_N:=L_N+1;
        L_BLOCKERS:=SUBSTR(L_BLOCKERS||P.PIPELINE_NAME||' ('||P.STATUS||'); ',1,3000);
      END LOOP;
      IF L_N>0 THEN
        L_ERROR_STATUS:='BLOCKED';
        RAISE_APPLICATION_ERROR(-20947,'Retention blocked by affected-year pipeline(s): '||
          L_BLOCKERS||'Stop these pipelines and wait for their running loads before retrying. No pipeline was changed.');
      END IF;
    END;
  BEGIN
    SELECT NVL(P_KEEP_MONTHS,KEEP_MONTHS) INTO L_KEEP FROM OCI_FOCUS_RETENTION_CONFIG WHERE CONFIG_ID=1;
    CHECK_MONTHS(L_KEEP);
    IF P_PREVIEW_ONLY IS NULL OR P_PREVIEW_ONLY NOT IN (0,1) THEN
      RAISE_APPLICATION_ERROR(-20945,'Preview flag must be 0 or 1');
    END IF;
    L_YEAR_START:=CAST(TRUNC(L_TODAY,'YYYY') AS TIMESTAMP);
    L_CUTOFF:=LEAST(CAST(TRUNC(L_TODAY,'MM') AS TIMESTAMP)-NUMTOYMINTERVAL(L_KEEP,'MONTH'),L_YEAR_START);
    INSERT INTO OCI_FOCUS_RETENTION_RUN(KEEP_MONTHS,CUTOFF_UTC,PREVIEW_ONLY,STATUS)
      VALUES(L_KEEP,L_CUTOFF,P_PREVIEW_ONLY,'RUNNING') RETURNING RUN_ID INTO L_RUN;
    COMMIT;
    L_LOCK_RESULT:=DBMS_LOCK.REQUEST(L_LOCK_ID,DBMS_LOCK.X_MODE,0,FALSE);
    IF L_LOCK_RESULT<>0 THEN
      L_ERROR_STATUS:='BLOCKED';
      RAISE_APPLICATION_ERROR(-20947,'Another retention session holds the lock; no landing rows deleted');
    END IF;
    L_LOCKED:=TRUE;
    -- With exclusive ownership, prior abandoned runs can be marked honestly.
    UPDATE OCI_FOCUS_RETENTION_RUN SET STATUS='FAILED',FINISHED_AT=SYSTIMESTAMP,
      MESSAGE='Interrupted retention run; prior monthly commits remain; inspect month audit'
      WHERE STATUS='RUNNING' AND RUN_ID<>L_RUN;
    COMMIT;
    CHECK_PIPELINES; -- All affected years checked before any landing DELETE.
    INSERT INTO OCI_FOCUS_RETENTION_MONTH(RUN_ID,MONTH_START_UTC,ROWS_ELIGIBLE)
      SELECT L_RUN,TRUNC(CAST(CHARGEPERIODSTART AS DATE),'MM'),COUNT(*)
        FROM OCI_FOCUS_REPORTS WHERE CHARGEPERIODSTART<L_CUTOFF
       GROUP BY TRUNC(CAST(CHARGEPERIODSTART AS DATE),'MM');
    SELECT NVL(SUM(ROWS_ELIGIBLE),0) INTO L_COUNT FROM OCI_FOCUS_RETENTION_MONTH WHERE RUN_ID=L_RUN;
    UPDATE OCI_FOCUS_RETENTION_RUN SET ROWS_ELIGIBLE=L_COUNT WHERE RUN_ID=L_RUN;
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Retention run='||L_RUN||' keep_months='||L_KEEP||
      ' cutoff_utc_exclusive='||TO_CHAR(L_CUTOFF,'YYYY-MM-DD')||' eligible='||L_COUNT);
    FOR M IN (SELECT * FROM OCI_FOCUS_RETENTION_MONTH WHERE RUN_ID=L_RUN ORDER BY MONTH_START_UTC) LOOP
      DBMS_OUTPUT.PUT_LINE('month='||TO_CHAR(M.MONTH_START_UTC,'YYYY-MM')||' eligible='||M.ROWS_ELIGIBLE);
    END LOOP;
    IF P_PREVIEW_ONLY=1 OR L_COUNT=0 THEN
      UPDATE OCI_FOCUS_RETENTION_RUN SET STATUS=CASE WHEN P_PREVIEW_ONLY=1 THEN 'PREVIEW' ELSE 'NO_DATA' END,
        FINISHED_AT=SYSTIMESTAMP WHERE RUN_ID=L_RUN;
      COMMIT;
    ELSE
      -- Resolve MV checks at runtime: ingestion is installed before the MV.
      SELECT TABLE_NAME INTO L_MV FROM USER_SYNONYMS
       WHERE SYNONYM_NAME='OAC_OCI_FOCUS_COST_DETAIL' AND TABLE_OWNER=USER AND DB_LINK IS NULL;
      EXECUTE IMMEDIATE 'DELETE FROM MV_CAPABILITIES_TABLE WHERE STATEMENT_ID=''OCI_RETENTION_CHECK''';
      DBMS_MVIEW.EXPLAIN_MVIEW(L_MV,'OCI_RETENTION_CHECK');
      EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM MV_CAPABILITIES_TABLE WHERE STATEMENT_ID=''OCI_RETENTION_CHECK'' AND CAPABILITY_NAME=''REFRESH_FAST_AFTER_ONETAB_DML'' AND POSSIBLE=''Y'''
        INTO L_CAP;
      IF L_CAP=0 THEN RAISE_APPLICATION_ERROR(-20944,'MV FAST after deletes is not verified; no landing rows deleted'); END IF;
      COMMIT;
      FOR M IN (SELECT MONTH_START_UTC FROM OCI_FOCUS_RETENTION_MONTH WHERE RUN_ID=L_RUN ORDER BY MONTH_START_UTC) LOOP
        CHECK_PIPELINES; -- Also detects a historical pipeline restarted mid-run.
        DELETE FROM OCI_FOCUS_REPORTS
         WHERE CHARGEPERIODSTART>=CAST(M.MONTH_START_UTC AS TIMESTAMP)
           AND CHARGEPERIODSTART<CAST(M.MONTH_START_UTC AS TIMESTAMP)+INTERVAL '1' MONTH
           AND CHARGEPERIODSTART<L_CUTOFF AND CHARGEPERIODSTART<L_YEAR_START;
        L_DELETED:=SQL%ROWCOUNT;
        UPDATE OCI_FOCUS_RETENTION_MONTH SET ROWS_DELETED=L_DELETED,COMMITTED_AT=SYSTIMESTAMP
         WHERE RUN_ID=L_RUN AND MONTH_START_UTC=M.MONTH_START_UTC;
        UPDATE OCI_FOCUS_RETENTION_RUN SET ROWS_DELETED=ROWS_DELETED+L_DELETED WHERE RUN_ID=L_RUN;
        COMMIT;
        DBMS_OUTPUT.PUT_LINE('month='||TO_CHAR(M.MONTH_START_UTC,'YYYY-MM')||' deleted='||L_DELETED);
      END LOOP;
      UPDATE OCI_FOCUS_RETENTION_RUN SET STATUS='COMPLETED',FINISHED_AT=SYSTIMESTAMP,
        MESSAGE='Landing DELETE completed; await the next successful MV refresh' WHERE RUN_ID=L_RUN;
      COMMIT;
    END IF;
    L_LOCK_RESULT:=DBMS_LOCK.RELEASE(L_LOCK_ID);
    L_LOCKED:=FALSE;
  EXCEPTION WHEN OTHERS THEN
    L_ERROR:=SUBSTR(SQLERRM,1,4000);
    ROLLBACK;
    IF L_RUN IS NOT NULL THEN
      UPDATE OCI_FOCUS_RETENTION_RUN SET STATUS=L_ERROR_STATUS,FINISHED_AT=SYSTIMESTAMP,
        MESSAGE=L_ERROR WHERE RUN_ID=L_RUN;
      COMMIT;
    END IF;
    IF L_LOCKED THEN L_LOCK_RESULT:=DBMS_LOCK.RELEASE(L_LOCK_ID); END IF;
    DBMS_OUTPUT.PUT_LINE('Retention '||L_ERROR_STATUS||': '||L_ERROR);
    RAISE; -- Scheduler must expose BLOCKED/FAILED, never report success.
  END;

  PROCEDURE RUN_SCHEDULED IS
  BEGIN
    RUN(P_PREVIEW_ONLY=>0);
  END;
END;
