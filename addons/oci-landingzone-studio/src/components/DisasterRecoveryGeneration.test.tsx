import { describe, expect, it } from 'vitest';
import { renderToStaticMarkup } from 'react-dom/server';
import { emptyLzModel } from '../model/defaults';
import { createDrDraft } from '../services/disasterRecoveryDesign';
import DisasterRecoveryGeneration from './DisasterRecoveryGeneration';

describe('generation deployment steps', () => {
  it('omits the Home update and numbers DR as step 2 when RPC is disabled', () => {
    const model = emptyLzModel();
    const html = renderToStaticMarkup(<DisasterRecoveryGeneration name="test" model={model} draft={{ ...createDrDraft(model), rpcEnabled: false }} onChangeDraft={() => {}} />);
    expect(html).not.toContain('Home region including RPC');
    expect(html).not.toContain('Download updated network file');
    expect(html).toContain('aria-label="Step 2"');
    expect(html).not.toContain('aria-label="Step 3"');
    expect(html).toContain('Stack 2 · DR region · without RPC');
    expect(html).toContain('Use the outputs generated by Stack 1 (Home) as dependencies for this stack.');
    expect(html).toContain('aria-labelledby="dr-required-outputs-title"');
    expect(html).toContain('aria-labelledby="home-required-outputs-title"');
    expect(html).toContain('Required dependencies');
    expect(html).toContain('Enable output generation in Stack 1 (Home). Stack 2 needs these outputs as dependencies to deploy the DR resources.');
  });

  it('shows the Home update as step 2 and DR as step 3 when RPC is enabled', () => {
    const model = emptyLzModel();
    const html = renderToStaticMarkup(<DisasterRecoveryGeneration name="test" model={model} draft={{ ...createDrDraft(model), rpcEnabled: true }} onChangeDraft={() => {}} />);
    expect(html).toContain('Home region including RPC');
    expect(html).toContain('Download updated network file');
    expect(html).toContain('aria-label="Step 2"');
    expect(html).toContain('aria-label="Step 3"');
    expect(html).not.toContain('DR region · without RPC');
  });
});
