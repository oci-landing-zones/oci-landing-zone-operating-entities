import { describe, expect, it } from 'vitest';
import { renderToStaticMarkup } from 'react-dom/server';
import { emptyLzModel } from '../model/defaults';
import { newPlatform, newSharedPlatform } from '../services/platforms';
import { createDrDraft, createDrHubNetwork } from '../services/disasterRecoveryDesign';
import DisasterRecoveryConfiguration from './DisasterRecoveryConfiguration';

describe('Home and DR configuration columns', () => {
  it('offers an editable OCVS DR VCN with its generator-managed provisioning subnet', () => {
    const model = emptyLzModel();
    const platform = newPlatform('ocvs', [], model.environments);
    platform.environments = [model.environments[0].id];
    model.platforms = [platform];
    const html = renderToStaticMarkup(<DisasterRecoveryConfiguration name="Source" model={model} sourceLabel="Saved Landing Zone" draft={createDrDraft(model)} onChange={() => {}} />);
    expect(html).toContain('aria-label="OCVS prod DR VCN CIDR"');
    expect(html).toContain('value="10.0.224.0/22"');
    expect(html).toContain('10.0.224.0/26');
    expect(html).toContain('Provisioning subnet');
    expect(html).toContain('>OCVS cluster configuration</summary>');
    expect(html).toContain('DR OCVS management cluster settings');
    const cluster = html.slice(html.indexOf('aria-label="DR OCVS management cluster settings"'));
    expect(cluster).toContain('SSH public key');
    expect(cluster).toContain('SDDC name');
    expect(cluster).toContain('Availability domain');
    const network = html.slice(html.indexOf('aria-label="OCVS prod DR VCN CIDR"'));
    expect(network.indexOf('Subnets in this VCN')).toBeLessThan(network.indexOf('OCVS cluster configuration'));
    expect(html).toMatch(/<details[^>]*aria-label="DR OCVS management cluster settings"[^>]*><summary/);
  });
  it('shows the editable preprod default and keeps a saved custom CIDR', () => {
    const model = emptyLzModel();
    const platform = newPlatform('ocvs', [], model.environments);
    platform.environments = [model.environments[1].id];
    model.platforms = [platform];
    const draft = createDrDraft(model);
    const render = () => renderToStaticMarkup(<DisasterRecoveryConfiguration name="Source" model={model} sourceLabel="Saved Landing Zone" draft={draft} onChange={() => {}} />);
    expect(render()).toContain('value="10.0.248.0/21"');
    const id = `platform:${platform.id}:${model.environments[1].id}`;
    draft.platformVcnCidrs = { [id]: '10.12.0.0/22' };
    expect(render()).toContain('value="10.12.0.0/22"');
    expect(render()).toContain('10.12.0.0/26');
  });
  it('offers editable OKE DR networking and cluster settings with Home parity', () => {
    const model = emptyLzModel();
    const platform = newPlatform('oke_simple', [], model.environments);
    platform.environments = [model.environments[0].id];
    model.platforms = [platform];
    const html = renderToStaticMarkup(<DisasterRecoveryConfiguration name="Source" model={model} sourceLabel="Saved Landing Zone" draft={createDrDraft(model)} onChange={() => {}} />);
    expect(html).toContain('aria-label="OKE prod DR VCN CIDR"');
    expect(html).toContain('value="10.0.216.0/21"');
    expect(html).toContain('>OKE cluster configuration</summary>');
    for (const label of ['Kubernetes version', 'Services CIDR', 'Pod networking', 'Network profile', 'Worker image selector', 'Worker boot volume (GB)', 'Allow public load balancers', 'Enable File Storage support']) expect(html).toContain(label);
    expect(html).toContain('OKE prod DR workers subnet CIDR');
  });
  it('shows shared EXACS infrastructure as inherited read-only compartments in DR', () => {
    const model = emptyLzModel();
    model.exadata.exacs.enabled = true;
    model.exadata.exacs.database = 'per_environment';
    model.exadata.exacs.service = 'vmc';
    model.exadata.exacs.environments = model.environments.map((env) => env.id);
    const html = renderToStaticMarkup(<DisasterRecoveryConfiguration name="Source" model={model} sourceLabel="Saved Landing Zone" draft={createDrDraft(model)} onChange={() => {}} />);
    expect(html).toContain('aria-label="DR inherited shared infrastructure"');
    expect(html.match(/>cmp-lz-shared-exacs-infra<\/dd>/g)).toHaveLength(2);
    const choices = html.match(/<legend[^>]*>Environment platforms<\/legend>([\s\S]*?)<\/fieldset>/)![1];
    expect(choices).not.toContain('Shared · EXACS');
    expect(choices).toContain('EXACS · Prod DR VMC');
    expect(choices).toContain('EXACS · Preprod DR VMC');
    expect(choices).toContain('10.0.240.0/21');
    expect(choices).toContain('10.0.248.0/21');
    expect(choices).toContain('cmp-lz-prod-exacs');
    expect(choices).toContain('aria-label="EXACS prod DR VCN CIDR"');
    expect(choices).toContain('aria-label="EXACS preprod DR VCN CIDR"');
    expect(choices).not.toContain('Add Exacs env');
    expect(choices).toContain('aria-label="EXACS prod DR db subnet CIDR"');
    expect(choices).toContain('aria-label="EXACS preprod DR backup subnet CIDR"');
  });
  it('offers optional RPC and shows both regional DRGs when enabled', () => {
    const model = emptyLzModel();
    const draft = { ...createDrDraft(model), region: 'eu-amsterdam-1', rpcEnabled: true };
    const html = renderToStaticMarkup(<DisasterRecoveryConfiguration name="Source" model={model} sourceLabel="Saved Landing Zone" draft={draft} onChange={() => {}} />);
    expect(html).toContain('Configure an RPC between the Home and DR DRGs?');
    expect(html).toMatch(/type="radio"[^>]*name="dr-rpc-enabled"[^>]*checked=""[^>]*value="true"/);
    expect(html).toContain('drg-fra-lz-hub');
    expect(html).toContain('drg-ams-lz-hub');
  });
  it('shows a confirmed DR environment as a matching summary with Home compartment details', () => {
    const model = emptyLzModel();
    const env = model.environments[0];
    const draft = { ...createDrDraft(model), environmentAdded: { [env.id]: true }, environmentNames: { [env.id]: 'dr' }, projectNames: { [env.id]: { [model.projects[0].id]: 'recovery' } } };
    const html = renderToStaticMarkup(<DisasterRecoveryConfiguration name="Source" model={model} sourceLabel="Saved Landing Zone" draft={draft} onChange={() => {}} />);
    expect(html).toContain('Edit env');
    expect(html).toContain('Compartment: cmp-lz-prod');
    expect(html).toContain('Compartment: cmp-lz-prod-proj1');
    expect(html).toContain('Compartment: cmp-lz-dr-recovery');
    expect(html).not.toContain('aria-label="DR VCN CIDR for prod"');
    expect(html).not.toContain('aria-label="DR environment name for prod"');
    expect(html).not.toContain('aria-label="DR project name for proj1 in prod"');
  });
  it('offers independent DR environment and project names with compartment previews', () => {
    const model = emptyLzModel();
    const draft = { ...createDrDraft(model), environmentNames: { [model.environments[0].id]: 'dr' }, projectNames: { [model.environments[0].id]: { [model.projects[0].id]: 'recovery' } } };
    const html = renderToStaticMarkup(<DisasterRecoveryConfiguration name="Source" model={model} sourceLabel="Saved Landing Zone" draft={draft} onChange={() => {}} />);
    expect(html).toContain('aria-label="DR environment name for prod"');
    expect(html).toContain('aria-label="DR project name for proj1 in prod"');
    expect(html).toContain('Compartment: cmp-lz-dr-recovery');
    expect(html).toContain('value="recovery"');
  });
  it('offers a CIDR field when preprod is added to DR', () => {
    const model = emptyLzModel();
    const draft = createDrDraft(model);
    draft.projectNetworkIds.push(`projects:${model.environments[1].id}`);
    const html = renderToStaticMarkup(<DisasterRecoveryConfiguration name="Source" model={model} sourceLabel="Saved Landing Zone" draft={draft} onChange={() => {}} />);
    expect(html).toContain('aria-label="DR VCN CIDR for preprod"');
    expect(html).toContain('Add Env');
  });
  it('replaces the confirmed region selector with matching facts and an edit action', () => {
    const model = emptyLzModel();
    const draft = { ...createDrDraft(model), region: 'eu-amsterdam-1', regionConfirmed: true };
    const html = renderToStaticMarkup(<DisasterRecoveryConfiguration name="Source" model={model} sourceLabel="Saved Landing Zone" draft={draft} onChange={() => {}} />);
    expect(html).toContain('Edit region');
    expect(html).toContain('eu-amsterdam-1');
    expect(html).not.toContain('id="dr-target-region"');
    expect(html).not.toContain('Choose a different region');
  });
  it('replaces the confirmed hub form with the comparable summary and an edit action', () => {
    const model = emptyLzModel();
    const draft = { ...createDrDraft(model), hubNetwork: createDrHubNetwork('hub_a'), hubAdded: true };
    const html = renderToStaticMarkup(<DisasterRecoveryConfiguration name="Source" model={model} sourceLabel="Saved Landing Zone" draft={draft} onChange={() => {}} />);
    expect(html).toContain('Edit hub');
    expect(html).toContain('10.0.192.0/21');
    expect(html).not.toContain('id="dr-target-hub"');
    expect(html).not.toContain('id="dr-hub-vcn"');
  });
  it('shows a read-only home beside DR region and network controls', () => {
    const model = emptyLzModel();
    const html = renderToStaticMarkup(<DisasterRecoveryConfiguration name="Source" model={model} sourceLabel="Saved Landing Zone" draft={createDrDraft(model)} onChange={() => {}} />);
    expect(html).toContain('Home region</h4>');
    expect(html).toContain('DR region</h4>');
    expect(html).toContain('One-OE');
    expect(html).toContain('Workload Extensions (Platforms)');
    expect(html).toContain('No platforms configured.');
    expect(html).not.toContain('No environment platforms configured.');
    expect(html).not.toContain('Shared platforms (0)');
    expect(html).not.toContain('<option value="eu-frankfurt-1"');
    expect(html).toContain('aria-label="DR environments"');
    expect(html).toContain('Remove prod from DR');
    expect(html).not.toContain('Remove preprod from DR');
    expect(html).toContain('Add environment');
  });
  it('offers only existing optional platforms with their source scope', () => {
    const model = emptyLzModel();
    model.sharedPlatforms = [newSharedPlatform('ocvs', [])];
    const html = renderToStaticMarkup(<DisasterRecoveryConfiguration name="Source" model={model} sourceLabel="Saved Landing Zone" draft={createDrDraft(model)} onChange={() => {}} />);
    expect(html).toContain('aria-label="OCVS Shared DR VCN CIDR"');
    expect(html).toContain('>Shared</h4>');
    expect(html).not.toContain('Home VCN:');
    const platforms = html.match(/<legend[^>]*>Environment platforms<\/legend>([\s\S]*?)<\/fieldset>/)![1];
    expect(platforms).toContain('Add to DR');
    expect(platforms).toContain('aria-pressed="false"');
  });
});
